def fill(text, v):
    n, r, b = v // 4, (v - 1) // 3, v * (v - 1) // 12
    for key, val in (('@V2@', v - 2), ('@V@', v), ('@N@', n), ('@R@', r), ('@B@', b)):
        text = text.replace(key, str(val))
    return text


def main(argv):
    """gen_cert.py OUTDIR [--audit NAME] [--certs V,V,...] V [V ...]: Cert modules for the --certs orders (default: all
    listed orders) and one audit module NAME (default Audit) covering all listed orders."""
    args = argv[1:]
    if not args:
        raise SystemExit(__doc__)
    out = Path(args.pop(0))
    audit_name, cert_orders = 'Audit', None
    while args and args[0].startswith('--'):
        opt = args.pop(0)
        if opt == '--audit':
            audit_name = args.pop(0)
        elif opt == '--certs':
            cert_orders = [int(x) for x in args.pop(0).split(',')]
        else:
            raise SystemExit(f'unknown option {opt}')
    vs = [int(x) for x in args]
    if not vs:
        raise SystemExit(__doc__)
    out.mkdir(parents=True, exist_ok=True)
    files = {f'Cert{v}.lean': fill(CERT, v) for v in (cert_orders if cert_orders is not None else vs)}
    audit = AUDIT_HEAD.replace('@IMPORTS@', '\n'.join(f'import PCTableKernelR2.Cert{v}' for v in vs))
    audit += ''.join(fill(AUDIT_ORDER, v) for v in vs) + AUDIT_PRINTS
    audit += ''.join(fill(AUDIT_ORDER_PRINTS, v) for v in vs)
    files[f'{audit_name}.lean'] = audit
    for name in files:
        if (out / name).exists():
            raise SystemExit(f'refusing to overwrite {out / name}')
    for name, text in files.items():
        with (out / name).open('x') as stream:
            stream.write(text)
        print(f'wrote {out / name}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
