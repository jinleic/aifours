#!/usr/bin/env python3
"""Generate PCTableKernelR2/Cert<v>.lean (one per order) and an audit module from one template (stdlib only).

Usage: python3 -B gen_cert.py OUTDIR V [V ...]     (refuses to overwrite)

Every Cert<v> module runs the generic checker `PC100.Kernel.certCheck` of the accepted v = 100 development
(`PC100Kernel/Check.lean`, byte copy) on the literal `cert<v>` of `PCTableKernelR2/Data<v>.lean` with `decide +kernel`, and
derives the roots `PC100.Target v`, `PC100.TargetShift v` and `PC100.TargetCounts v` from the data-independent
soundness theorem `sound_of_check` and the cycle lemmas `isFullCycle_shift`, `cycleType_shift`. Nothing order-specific
is assumed: the template differs between orders only in the numbers v, n = v/4, r = (v-1)/3 and b = v(v-1)/12.
"""
from pathlib import Path
import sys

CERT = r'''import PCTableKernelR2.Data@V@

/-!
# A point-cyclic resolution of a 2-(@V@,4,1) design: kernel-checked existence

`cert@V@` comes from `PCTableKernelR2.Data@V@`, generated by `lean-kernel/gen_lean.py` from the pinned raw certificate (its
SHA-256 is recorded there and in `cert@V@RawSha256`). Every `decide +kernel` below is evaluated by the Lean kernel (no
`native_decide`, no `Lean.ofReduceBool`). The semantic conclusions come from the data-independent theorem
`sound_of_check` (`PC100Kernel.Check`, byte copy of the accepted v = 100 module) and the cycle lemmas
`isFullCycle_shift`, `cycleType_shift`; the target notions are defined in `PC100Kernel.Target` (byte copy).
Generated by `lean-kernel/gen_cert.py` from one template for all orders.
-/

namespace PC100.Kernel

/-- Shape of the raw data: @R@ classes of @N@ blocks each, @B@ blocks in all. -/
theorem cert@V@_shape :
    cert@V@.length = @R@ ∧ (∀ c ∈ cert@V@, c.length = @N@) ∧ cert@V@.flatten.length = @B@ := by
  decide +kernel

/-- Every listed block is `a < b < c < d < @V@`: no reduction modulo @V@ happens. -/
theorem cert@V@_range :
    ∀ e ∈ cert@V@.flatten, e.1 < e.2.1 ∧ e.2.1 < e.2.2.1 ∧ e.2.2.1 < e.2.2.2 ∧ e.2.2.2 < @V@ := by
  decide +kernel

/-! The checker `certCheck v d` is the conjunction (`&&`) of four Boolean parts. Each part is evaluated by the kernel
in its own declaration (this bounds the memory of each kernel evaluation), and `cert@V@_check` assembles them. -/

theorem cert@V@_rangeOK : cert@V@.flatten.all (rangeOK @V@) = true := by
  decide +kernel

theorem cert@V@_pairsOK :
    (insertAll (cert@V@.flatten.flatMap (pairCodes @V@)) 0 == some (pairMask @V@)) = true := by
  decide +kernel

theorem cert@V@_classesOK :
    cert@V@.all (fun c => insertAll (c.flatMap pts) 0 == some (pointMask @V@)) = true := by
  decide +kernel

theorem cert@V@_shiftOK : shiftOK @V@ cert@V@ = true := by
  decide +kernel

/-- The certificate checker evaluates to `true` (assembled from the four kernel evaluations). -/
theorem cert@V@_check : certCheck @V@ cert@V@ = true := by
  simp only [certCheck, Bool.and_eq_true]
  exact ⟨⟨⟨cert@V@_rangeOK, cert@V@_pairsOK⟩, cert@V@_classesOK⟩, cert@V@_shiftOK⟩

/-- The explicit block set: the @B@ blocks listed in the raw certificate. -/
def pc@V@Blocks : Finset (Finset (Fin @V@)) := blocks @V@ cert@V@

/-- The explicit resolution: the @R@ classes listed in the raw certificate. -/
def pc@V@Classes : Finset (Finset (Finset (Fin @V@))) := classes @V@ cert@V@

theorem pc@V@Blocks_spec (X : Finset (Fin @V@)) :
    X ∈ pc@V@Blocks ↔ ∃ e ∈ cert@V@.flatten, blk @V@ e = X :=
  mem_blocks

theorem pc@V@Classes_spec (P : Finset (Finset (Fin @V@))) :
    P ∈ pc@V@Classes ↔ ∃ c ∈ cert@V@, classOf @V@ c = P :=
  mem_classes

theorem isDesign241_pc@V@ : IsDesign241 pc@V@Blocks :=
  (sound_of_check cert@V@_check).1

theorem isResolution_pc@V@ : IsResolution pc@V@Blocks pc@V@Classes :=
  (sound_of_check cert@V@_check).2.1

theorem shift_pc@V@ : IsResolutionAutomorphism pc@V@Blocks pc@V@Classes (shift @V@) :=
  (sound_of_check cert@V@_check).2.2.1

/-- `x ↦ x + 1` permutes the @V@ points in one cycle. -/
theorem isFullCycle_shift@V@ : IsFullCycle (shift @V@) :=
  isFullCycle_shift @V2@

theorem cycleType_shift@V@ : (shift @V@).cycleType = {@V@} :=
  cycleType_shift @V2@

theorem counts_pc@V@ : pc@V@Blocks.card = @B@ ∧ pc@V@Classes.card = @R@ ∧
    ∀ P ∈ pc@V@Classes, P.card = @N@ := by
  obtain ⟨-, -, -, hb, hr, hp⟩ := sound_of_check cert@V@_check
  obtain ⟨hlen, hcl, hflat⟩ := cert@V@_shape
  refine ⟨?_, ?_, ?_⟩
  · rw [pc@V@Blocks, hb, hflat]
  · rw [pc@V@Classes, hr, hlen]
  · intro P hP
    obtain ⟨c, hc, rfl⟩ := mem_classes.mp hP
    rw [hp c hc, hcl c hc]

/-- **A point-cyclic resolution of a 2-(@V@,4,1) design exists** (on the point set `Fin @V@`). -/
theorem exists_pc@V@ : Target @V@ :=
  ⟨pc@V@Blocks, isDesign241_pc@V@, pc@V@Classes, isResolution_pc@V@, shift @V@,
    isFullCycle_shift@V@, shift_pc@V@⟩

theorem exists_pc@V@_shift : TargetShift @V@ :=
  ⟨isFullCycle_shift@V@, pc@V@Blocks, pc@V@Classes, isDesign241_pc@V@, isResolution_pc@V@,
    shift_pc@V@⟩

theorem counts_pc@V@_target : TargetCounts @V@ := by
  obtain ⟨hb, hr, hp⟩ := counts_pc@V@
  refine ⟨pc@V@Blocks, pc@V@Classes, isDesign241_pc@V@, isResolution_pc@V@, shift_pc@V@, ?_, ?_, ?_⟩
  · rw [hb]
  · rw [hr]
  · intro P hP
    rw [hp P hP]

end PC100.Kernel
'''

AUDIT_HEAD = '''import PC100Kernel.Target
@IMPORTS@

/-!
# Audit: the table roots prove the data-independent targets

`PC100.Target`, `PC100.TargetShift`, `PC100.TargetCounts` and their vocabulary are defined in `PC100Kernel.Target`
(byte copy of the accepted v = 100 module), which imports no proof and no data. The theorems below restate the roots
with exactly the target types, one block per order. Generated by `lean-kernel/gen_cert.py`.
-/

namespace PCTable.Audit
'''

AUDIT_ORDER = '''
/-- Root: a 2-(@V@,4,1) design on `Fin @V@` with a point-cyclic resolution. -/
theorem root@V@ : PC100.Target @V@ := PC100.Kernel.exists_pc@V@

/-- Root: `x ↦ x + 1` is one @V@-cycle on `Fin @V@` and preserves a 2-(@V@,4,1) design and a resolution of it. -/
theorem root@V@_shift : PC100.TargetShift @V@ := PC100.Kernel.exists_pc@V@_shift

/-- Root with the counts written out: @B@ blocks, @R@ classes of @N@ blocks. -/
theorem root@V@_counts : PC100.TargetCounts @V@ := PC100.Kernel.counts_pc@V@_target

theorem root@V@_cycleType : (PC100.shift @V@).cycleType = {@V@} := PC100.Kernel.cycleType_shift@V@

theorem shift@V@_apply (x : Fin @V@) : PC100.shift @V@ x = x + 1 := rfl
'''

