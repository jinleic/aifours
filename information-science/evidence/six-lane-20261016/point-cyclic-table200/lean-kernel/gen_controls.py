#!/usr/bin/env python3
"""Generate PCTableKernelR2/Controls.lean and PCTableKernelR2/ControlFail.lean (stdlib only; refuses to overwrite).

Usage: python3 -B gen_controls.py OUTDIR

The mutation data is computed here from the pinned certificates (no number is invented):
* swap (every order): the first block B1 of CLASS 0 and the first block B2 of CLASS 1 disjoint from B1 exchange their
  smallest points x in B1 and y in B2. The pair {y, b} with b the second point of B1 is then covered twice: by the new
  block B1 - x + y and by the original block Z that covered {y, b}. Z is distinct from B1 and B2 and is unchanged.
* relabel (v = 112): the points 1 and 2 are exchanged in every block. This gives an isomorphic design and resolution
  that x -> x+1 does not preserve: the first relabelled block of CLASS 0 and its translate are recorded.
ControlFail.lean asks the kernel to accept the corrupted swap literal at 196 and the relabelled literal at 112; it must
fail to build.
"""
from pathlib import Path
import hashlib
import sys

HERE = Path(__file__).resolve().parent
LANE = HERE.parent
CERTS = {112: ('certs/v112/pc112_t1.cert', '96265b66f4495e5927224599c941993d96bed85fb3d008b7dd53b925224a440d'),
         136: ('certs/v136/pc136_t3.cert', '61874100bd9333a6df83fbbecbbc807e139d985187ddcab6919ea4f815895c56'),
         160: ('certs/v160/pc160_t3.cert', '8928dd9bd61c77da974d352f26f1980248445c5912428d943d4db3e22141a923'),
         196: ('certs/v196/pc196_t2.cert', '0828bf23d3bcd8a00a544cf7b8f1ae9e3a39279bc71a98fedd229eda5c6d8db5')}


def load(v):
    rel, sha = CERTS[v]
    raw = (LANE / rel).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == sha, v
    cls = {}
    for line in raw.decode().rstrip('\n').split('\n')[1:]:
        t = list(map(int, line.split()))
        cls.setdefault(t[0], []).append(tuple(t[1:]))
    return [cls[i] for i in range(len(cls))]


def tup(B):
    return '(' + ', '.join(map(str, B)) + ')'


def fset(B):
    return '{' + ', '.join(map(str, B)) + '}'


def swap_block(v, d):
    B1 = d[0][0]
    j = next(k for k, B in enumerate(d[1]) if not set(B) & set(B1))
    B2 = d[1][j]
    x, y = B1[0], B2[0]
    n1 = tuple(sorted(B1[1:] + (y,)))
    n2 = tuple(sorted(B2[1:] + (x,)))
    b = B1[1]
    Z = next(B for c in d for B in c if y in B and b in B)
    assert Z not in (B1, B2)
    pair = (min(y, b), max(y, b))
    return f'''
/-! ### swap, v = {v} -/

/-- The point {x} of `{tup(B1)}` (CLASS 0, entry 0) and the point {y} of `{tup(B2)}` (CLASS 1, entry {j}) exchanged. -/
def cert{v}swap : List (List RawBlock) :=
  setBlock (setBlock cert{v} 0 0 {tup(n1)}) 1 {j} {tup(n2)}

theorem swap{v}_spec :
    (cert{v}.getD 0 []).take 1 = [{tup(B1)}] ∧ ((cert{v}.getD 1 []).drop {j}).take 1 = [{tup(B2)}] := by
  decide +kernel

theorem swap{v}_pairs_fail : insertAll (cert{v}swap.flatten.flatMap (pairCodes {v})) 0 = none := by
  decide +kernel

theorem swap{v}_check_false : certCheck {v} cert{v}swap = false := by
  decide +kernel

/-- The swapped data is not a 2-({v},4,1) design: `{fset(pair)}` lies in `{fset(n1)}` and in `{fset(Z)}`. -/
theorem swap{v}_not_design : ¬ IsDesign241 (blocks {v} cert{v}swap) := by
  intro h
  have hT : ({fset(pair)} : Finset (Fin {v})).card = 2 := by decide
  obtain ⟨X, -, huniq⟩ := h.2 _ hT
  have h1 : ({fset(n1)} : Finset (Fin {v})) ∈ blocks {v} cert{v}swap :=
    mem_blocks.mpr ⟨{tup(n1)}, by decide +kernel, by decide +kernel⟩
  have h2 : ({fset(Z)} : Finset (Fin {v})) ∈ blocks {v} cert{v}swap :=
    mem_blocks.mpr ⟨{tup(Z)}, by decide +kernel, by decide +kernel⟩
  have e1 := huniq _ ⟨h1, by decide⟩
  have e2 := huniq _ ⟨h2, by decide⟩
  exact absurd (e1.trans e2.symm) (by decide)
'''


HEAD = '''import PCTableKernelR2.Cert112
import PCTableKernelR2.Cert136
import PCTableKernelR2.Cert160
import PCTableKernelR2.Cert196

/-!
# Kernel controls for the table package (generated by `lean-kernel/gen_controls.py`)

No root depends on this module. Every mutation acts on a pinned literal `cert<v>`, and every statement is proved by
kernel evaluation (`decide +kernel`) or from the definitions.
* swap (every order): one point is exchanged between a block of CLASS 0 and a disjoint block of CLASS 1. The pair
  insertion meets a pair twice, so `certCheck` is `false`; semantically the block set is not a 2-(v,4,1) design.
* relabel (v = 112): the points 1 and 2 are exchanged in every block. The range, pair and class parts of the checker
  pass, the shift part fails, and semantically `x ↦ x + 1` does not preserve the block set.
-/

namespace PCTable.Controls

open PC100 PC100.Kernel

/-- Replace block `j` of raw class `i` by `e`. -/
def setBlock (d : List (List RawBlock)) (i j : ℕ) (e : RawBlock) : List (List RawBlock) :=
  d.set i ((d.getD i []).set j e)

/-- Sort two numbers. -/
def sort2 (a b : ℕ) : ℕ × ℕ := (min a b, max a b)

/-- Sort four numbers (comparator network (0,1) (2,3) (0,2) (1,3) (1,2)). -/
def sort4 (a b c d : ℕ) : RawBlock :=
  let p := sort2 a b
  let q := sort2 c d
  let r := sort2 p.1 q.1
  let s := sort2 p.2 q.2
  let t := sort2 s.1 r.2
  (r.1, t.1, t.2, s.2)

/-- Apply a point relabelling to every raw block (re-sorting each block). -/
def relabelData (σ : ℕ → ℕ) (d : List (List RawBlock)) : List (List RawBlock) :=
  d.map (List.map fun e => sort4 (σ e.1) (σ e.2.1) (σ e.2.2.1) (σ e.2.2.2))

/-- Exchange the points `1` and `2`. -/
def swap12 (p : ℕ) : ℕ := if p = 1 then 2 else if p = 2 then 1 else p
'''


def relabel112(d):
    s12 = lambda p: 2 if p == 1 else 1 if p == 2 else p
    rel = [[tuple(sorted(s12(p) for p in B)) for B in c] for c in d]
    rs = {B for c in rel for B in c}
    first = rel[0][0]
    T = tuple(sorted((p + 1) % 112 for p in first))
    assert T not in rs
    return f'''
/-! ### relabel, v = 112 -/

/-- The points `1` and `2` exchanged in every block. -/
def cert112relabel : List (List RawBlock) := relabelData swap12 cert112

theorem relabel112_spec : (cert112relabel.getD 0 []).take 1 = [{tup(first)}] := by
  decide +kernel

theorem relabel112_range_ok : cert112relabel.flatten.all (rangeOK 112) = true := by
  decide +kernel

theorem relabel112_pairs_ok :
    insertAll (cert112relabel.flatten.flatMap (pairCodes 112)) 0 = some (pairMask 112) := by
  decide +kernel

theorem relabel112_classes_ok :
    cert112relabel.all (fun c => insertAll (c.flatMap pts) 0 == some (pointMask 112)) = true := by
  decide +kernel

theorem relabel112_shift_fail : shiftOK 112 cert112relabel = false := by
  decide +kernel

theorem relabel112_check_false : certCheck 112 cert112relabel = false := by
  decide +kernel

/-- The relabelled data is not preserved by `x ↦ x + 1`: `{fset(first)}` is a block and its translate `{fset(T)}` is
not. -/
theorem relabel112_not_shift_invariant :
    ¬ IsResolutionAutomorphism (blocks 112 cert112relabel) (classes 112 cert112relabel) (shift 112) := by
  intro h
  have hX : ({fset(first)} : Finset (Fin 112)) ∈ blocks 112 cert112relabel :=
    mem_blocks.mpr ⟨{tup(first)}, by decide +kernel, by decide +kernel⟩
  have himg : blockImage (shift 112) ({fset(first)} : Finset (Fin 112)) = {fset(T)} := by
    decide +kernel
  have hmem := Finset.mem_image_of_mem (blockImage (shift 112)) hX
  rw [h.1, himg] at hmem
  have hnot : ∀ e ∈ cert112relabel.flatten, blk 112 e ≠ {fset(T)} := by
    decide +kernel
  obtain ⟨e, he, heq⟩ := mem_blocks.mp hmem
  exact hnot e he heq
'''


FAIL = '''import PCTableKernelR2.Controls

/-!
# Negative control: this module must FAIL to build (generated by `lean-kernel/gen_controls.py`)

The kernel evaluation of `certCheck` returns `false` on the corrupted literals `cert196swap` and `cert112relabel` of
`PCTableKernelR2.Controls`, so `swap196_check_true` and `relabel112_check_true` are rejected, and nothing about the
corrupted data can be derived without `sorryAx`. No root depends on this module.
-/

namespace PCTable.Controls

open PC100 PC100.Kernel

theorem swap196_check_true : certCheck 196 cert196swap = true := by
  decide +kernel

theorem swap196_isDesign : IsDesign241 (blocks 196 cert196swap) :=
  (sound_of_check swap196_check_true).1

theorem relabel112_check_true : certCheck 112 cert112relabel = true := by
  decide +kernel

theorem relabel112_shift :
    IsResolutionAutomorphism (blocks 112 cert112relabel) (classes 112 cert112relabel) (shift 112) :=
  (sound_of_check relabel112_check_true).2.2.1

end PCTable.Controls

#print axioms PCTable.Controls.swap196_isDesign
#print axioms PCTable.Controls.relabel112_shift
'''


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    out = Path(argv[1])
    ds = {v: load(v) for v in CERTS}
    text = HEAD + ''.join(swap_block(v, ds[v]) for v in CERTS) + relabel112(ds[112]) + '\nend PCTable.Controls\n'
    files = {'Controls.lean': text, 'ControlFail.lean': FAIL}
    for name in files:
        if (out / name).exists():
            raise SystemExit(f'refusing to overwrite {out / name}')
    for name, t in files.items():
        with (out / name).open('x') as f:
            f.write(t)
        print(f'wrote {out / name} sha256 {hashlib.sha256(t.encode()).hexdigest()}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
