#!/usr/bin/env python3
"""brd_models.py -- build model specs (README 1.4/1.5) for the generic invariant BRD encoder code/brd_cnf.py.

A model is an abstract finite group G (given by permutation generators on some set X, composition g*h = "apply h,
then g"), a row module and a column module, each a disjoint union of induced monomial modules Ind_K^G(psi) for a
subgroup K (given by generating elements) and a character psi: K -> {+1,-1} (given on those generators; consistency
is checked by closure).  For Ind_K^G(psi) the points are the left cosets t_c K (transversal in order of first
appearance in a breadth-first enumeration of G); a generator x maps coset c to c' where x t_c = t_c' k, k in K, with
sign psi(k).  The spec lists, for every generator of G, its signed permutation of the v rows and of the b columns;
invariance means W[pi(i)][tau(j)] = rho(i) sigma(j) W[i][j].

Usage: brd_models.py MODEL OUT.json      (OUT created exclusively)
MODEL names: trivial-v-b-r-k-L | Z25inf-aAbB | Z5x5inf-a5b1 | Z5x5inf-a4b6 | Z13x2 | Z26neg | Dic13
Stdlib only.
"""
import json
import sys


class Group:
    def __init__(self, gens, m):
        self.m = m
        self.gens = [tuple(g) for g in gens]
        self.id = tuple(range(m))
        self.elems = [self.id]
        seen = {self.id}
        k = 0
        while k < len(self.elems):
            g = self.elems[k]
            k += 1
            for x in self.gens:
                h = self.mul(x, g)
                if h not in seen:
                    seen.add(h)
                    self.elems.append(h)
        self.order = len(self.elems)

    def mul(self, g, h):
        return tuple(g[h[i]] for i in range(self.m))

    def inv(self, g):
        r = [0] * self.m
        for i, gi in enumerate(g):
            r[gi] = i
        return tuple(r)

    def power(self, g, e):
        r = self.id
        for _ in range(e):
            r = self.mul(g, r)
        return r


def subgroup_with_char(G, kgens, kvals):
    """Closure of the subgroup generated by kgens with the character determined by kvals; raises on inconsistency."""
    chi = {G.id: 1}
    order = [G.id]
    k = 0
    while k < len(order):
        g = order[k]
        k += 1
        for x, s in zip(kgens, kvals):
            h = G.mul(g, x)
            val = chi[g] * s
            if h in chi:
                if chi[h] != val:
                    raise ValueError("inconsistent character")
            else:
                chi[h] = val
                order.append(h)
    return chi


def induced(G, kgens, kvals):
    """Return (n, actions) where actions[t] = list of (image, sign) for generator t on Ind_K^G(psi)."""
    chi = subgroup_with_char(G, kgens, kvals)
    trans, coset_of = [], {}
    for g in G.elems:
        if g in coset_of:
            continue
        c = len(trans)
        trans.append(g)
        for k in chi:
            coset_of[G.mul(g, k)] = c
    n = len(trans)
    actions = []
    for x in G.gens:
        act = []
        for c, t in enumerate(trans):
            xt = G.mul(x, t)
            c2 = coset_of[xt]
            kk = G.mul(G.inv(trans[c2]), xt)
            act.append((c2, chi[kk]))
        actions.append(act)
    return n, actions


def module(G, parts):
    """parts: list of (kgens, kvals, multiplicity).  Returns (size, actions per generator, description)."""
    total, acts, desc = 0, [[] for _ in G.gens], []
    for kgens, kvals, mult, label in parts:
        n, a = induced(G, kgens, kvals)
        for _ in range(mult):
            for t in range(len(G.gens)):
                acts[t].extend((total + img, s) for img, s in a[t])
            desc.append({"label": label, "size": n, "first_index": total})
            total += n
    return total, acts, desc


def cyclic(n):
    return Group([[(i + 1) % n for i in range(n)]], n)


def params_target():
    return [26, 130, 25, 5, 4]


def build(name):
    if name.startswith("trivial-"):
        v, b, r, k, lam = (int(x) for x in name.split("-")[1:])
        G = Group([], 1)
        rows = [([], [], v, "G/1")]
        cols = [([], [], b, "G/1")]
        return [v, b, r, k, lam], G, rows, cols
    if name.startswith("cyc"):
        # cyc{n}_r{sizes}_c{sizes}[_p{v.b.r.k.L}]: Z_n, untwisted; sizes = comma list of "s" or "sxm" (m orbits of
        # size s, s | n, orbit G/<g^s>); default parameters are the target's.
        parts = name[3:].split("_")
        n = int(parts[0])
        G = cyclic(n)
        g = G.gens[0]

        def orbits(tok):
            out = []
            for item in tok.split(","):
                s, m = (item.split("x") + ["1"])[:2]
                s, m = int(s), int(m)
                if n % s != 0:
                    raise SystemExit(f"orbit size {s} does not divide {n}")
                out.append(([G.power(g, s)], [1], m, f"Z{n}/<g^{s}>"))
            return out

        rows = orbits(parts[1][1:])
        cols = orbits(parts[2][1:])
        prm = [int(x) for x in parts[3][1:].split(".")] if len(parts) > 3 else params_target()
        return prm, G, rows, cols
    params = [26, 130, 25, 5, 4]
    if name.startswith("Z25inf-a"):
        a, bb = name[len("Z25inf-a"):].split("b")
        a, bb = int(a), int(bb)
        G = cyclic(25)
        g = G.gens[0]
        rows = [([], [], 1, "G/1 (Z25)"), (list(G.gens), [1], 1, "G/G (inf)")]
        cols = [([], [], a, "G/1"), ([G.power(g, 5)], [1], bb, "G/<5>")]
        return params, G, rows, cols
    if name.startswith("Z5x5inf-"):
        X = [(x, y) for x in range(5) for y in range(5)]
        idx = {p: i for i, p in enumerate(X)}
        g1 = [idx[((x + 1) % 5, y)] for (x, y) in X]
        g2 = [idx[(x, (y + 1) % 5)] for (x, y) in X]
        G = Group([g1, g2], 25)

        def transl(dx, dy):
            return tuple(idx[((x + dx) % 5, (y + dy) % 5)] for (x, y) in X)

        H = [transl(1, m) for m in range(5)] + [transl(0, 1)]  # H_m = <(1,m)>, H_5 = <(0,1)>
        rows = [([], [], 1, "G/1 (GF(5)^2)"), (list(G.gens), [1, 1], 1, "G/G (inf)")]
        if name == "Z5x5inf-a5b1":
            cols = [([], [], 5, "G/1"), ([H[5]], [1], 1, "G/H5, H5=<(0,1)>")]
        elif name == "Z5x5inf-a4b6":
            cols = [([], [], 4, "G/1")] + [([H[m]], [1], 1, f"G/H{m}") for m in range(6)]
        else:
            raise SystemExit(f"unknown model {name}")
        return params, G, rows, cols
    if name == "Z13x2":
        G = cyclic(13)
        rows = [([], [], 2, "G/1")]
        cols = [([], [], 10, "G/1")]
        return params, G, rows, cols
    if name == "Z26neg":
        G = cyclic(52)
        z = G.power(G.gens[0], 26)
        rows = [([z], [-1], 1, "Z52/<z>, psi(z)=-1")]
        cols = [([z], [-1], 5, "Z52/<z>, psi(z)=-1")]
        return params, G, rows, cols
    if name == "Dic13":
        # elements a^i b^e, i in Z26, e in {0,1}; b a = a^-1 b, b^2 = a^13; index 2i + e
        def mul(p, q):
            (i, e), (j, f) = p, q
            i2 = (i + (j if e == 0 else -j)) % 26
            if e == 1 and f == 1:
                return ((i2 + 13) % 26, 0)
            return (i2, e ^ f)

        X = [(i, e) for i in range(26) for e in range(2)]
        idx = {p: n for n, p in enumerate(X)}
        ga = [idx[mul((1, 0), p)] for p in X]  # left multiplication by a
        gb = [idx[mul((0, 1), p)] for p in X]  # left multiplication by b
        G = Group([ga, gb], 52)
        assert G.order == 52
        z = G.power(G.gens[0], 13)
        assert G.mul(G.gens[1], G.gens[1]) == z
        rows = [([z], [-1], 1, "Dic13/<z>, psi(z)=-1")]
        cols = [([z], [-1], 5, "Dic13/<z>, psi(z)=-1")]
        return params, G, rows, cols
    raise SystemExit(f"unknown model {name}")


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    name, out = argv[1], argv[2]
    params, G, rows, cols = build(name)
    v, b = params[0], params[1]
    nv, racts, rdesc = module(G, rows)
    nb, cacts, cdesc = module(G, cols)
    if nv != v or nb != b:
        raise SystemExit(f"module sizes {nv} rows, {nb} columns differ from v={v}, b={b}")
    spec = {"model": name, "params": params, "group_order": G.order, "row_orbits": rdesc, "col_orbits": cdesc,
            "generators": [{"rows": racts[t], "cols": cacts[t]} for t in range(len(G.gens))]}
    with open(out, "x") as f:
        json.dump(spec, f)
        f.write("\n")
    print(json.dumps({"model": name, "group_order": G.order, "rows": len(rdesc), "col_orbits": len(cdesc)}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
