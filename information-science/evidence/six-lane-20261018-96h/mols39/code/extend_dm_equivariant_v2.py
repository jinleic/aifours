import sys, json, hashlib, time, os, random, math
T0 = time.monotonic()
a = sys.argv
raw_p, raw_sha, n, gens_s, mode, BUD, outd = a[1], a[2], int(a[3]), a[4], a[5], float(a[6]), a[7]
MAXSOL = int(a[8]) if len(a) > 8 else 1000
PROBES = int(a[9]) if len(a) > 9 else 0
SEED = int(a[10]) if len(a) > 10 else 1
MODES = ('equivariant', 'free', 'free0', 'estimate-equivariant', 'estimate-free', 'estimate-free0')
if mode not in MODES: print(json.dumps({"status": "BAD_MODE", "mode": mode})); sys.exit(2)
base = mode.replace('estimate-', '')
rb = open(raw_p, 'rb').read(); h = hashlib.sha256(rb).hexdigest()
if h != raw_sha: print(json.dumps({"status": "INPUT_PIN_MISMATCH", "got": h})); sys.exit(2)
rows = [[int(t) % n for t in ln.split()] for ln in rb.decode().splitlines() if ln.strip()]
k = len(rows); cols = [tuple(r[c] for r in rows) for c in range(n)]
out = {"input_sha256": h, "n": n, "k_old": k, "mode": mode}
dm_ok = all(len({(rows[i][c] - rows[j][c]) % n for c in range(n)}) == n for i in range(k) for j in range(i + 1, k))
out["old_dm_ok"] = dm_ok
if not dm_ok or len(set(cols)) != n: out["status"] = "OLD_NOT_DM"; print(json.dumps(out)); sys.exit(3)
ident = (1, tuple(range(k)))
def act(s, c):
    mu, perm = s; pinv = [0] * k
    for x in range(k): pinv[perm[x]] = x
    return tuple((mu * c[pinv[x]]) % n for x in range(k))
def compose(p, q): return ((p[0] * q[0]) % n, tuple(p[1][q[1][x]] for x in range(k)))
if base == 'equivariant':
    gens = [(g[0] % n, tuple(g[1])) for g in json.loads(gens_s)]
    G = {ident}; fr = [ident]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = compose(g, x)
                if y not in G: G.add(y); nf.append(y)
        fr = nf
    G = sorted(G); S = set(cols)
    if not all(act(g, c) in S for g in G for c in cols):
        out["status"] = "NOT_INVARIANT"; print(json.dumps(out)); sys.exit(3)
else:
    G = [ident]
out["group_order"] = len(G)
zero = tuple([0] * k)
if base == 'free0' and zero not in set(cols):
    out["status"] = "NO_ZERO_COLUMN"; print(json.dumps(out)); sys.exit(3)
seen = set(); orbits = []
for c in sorted(cols):
    if c in seen: continue
    orb = {}
    for g in G:
        orb.setdefault(act(g, c), g)
    seen |= set(orb); orbits.append((c, orb))
options = []
for oi, (c, orb) in enumerate(orbits):
    stab = [g for g in G if act(g, c) == c]
    allowed = [w for w in range(n) if all(((g[0] - 1) * w) % n == 0 for g in stab)]
    if base == 'free0' and c == zero: allowed = [0]
    for w in allowed:
        fvals = {d: (g[0] * w) % n for d, g in orb.items()}
        items = []; ok = True; seen_it = set()
        for d, fv in fvals.items():
            for i in range(k):
                it = i * n + (d[i] - fv) % n
                if it in seen_it: ok = False; break
                seen_it.add(it); items.append(it)
            if not ok: break
        if ok: options.append((oi, w, sorted(items), fvals))
out["orbits"] = len(orbits); out["orbit_sizes"] = sorted(len(o[1]) for o in orbits); out["options"] = len(options)
NI = k * n; NO = len(orbits); NT = NI + NO
opt_items = [items + [NI + oi] for (oi, w, items, fv) in options]
item_opts = [[] for _ in range(NT)]
for idx, its in enumerate(opt_items):
    for it in its: item_opts[it].append(idx)
cnt = [len(item_opts[it]) for it in range(NT)]
covered = [False] * NT; blocked = [0] * len(options)
def select(o):
    for j in opt_items[o]: covered[j] = True
    for j in opt_items[o]:
        for o2 in item_opts[j]:
            if blocked[o2] == 0:
                for j2 in opt_items[o2]: cnt[j2] -= 1
            blocked[o2] += 1
def unselect(o):
    for j in opt_items[o]:
        for o2 in item_opts[j]:
            blocked[o2] -= 1
            if blocked[o2] == 0:
                for j2 in opt_items[o2]: cnt[j2] += 1
    for j in opt_items[o]: covered[j] = False
def choose():
    best = -1; bc = 1 << 30
    for it in range(NT):
        if not covered[it]:
            c = cnt[it]
            if c < bc:
                best, bc = it, c
                if c <= 1: break
    return best, bc
if mode.startswith('estimate-'):
    rng = random.Random(SEED); ests = []; depths = []
    while len(ests) < PROBES and time.monotonic() - T0 <= BUD:
        est = 1; w = 1; path = []
        while True:
            it, bc = choose()
            if it < 0 or bc == 0: break
            cands = [o for o in item_opts[it] if not blocked[o]]
            w *= len(cands); est += w
            o = cands[rng.randrange(len(cands))]
            select(o); path.append(o)
        depths.append(len(path)); ests.append(est)
        for o in reversed(path): unselect(o)
    m = sum(ests) / len(ests) if ests else None
    sd = math.sqrt(sum((e - m) ** 2 for e in ests) / (len(ests) - 1)) if len(ests) > 1 else None
    out.update({"status": "ESTIMATE", "probes_done": len(ests), "probes_requested": PROBES, "seed": SEED,
                "knuth_mean_nodes": m, "knuth_sd": sd, "knuth_sem": (sd / math.sqrt(len(ests))) if sd is not None else None,
                "knuth_min": min(ests) if ests else None, "knuth_max": max(ests) if ests else None,
                "mean_depth": (sum(depths) / len(depths)) if depths else None, "max_depth": max(depths) if depths else None,
                "full_depth": NO, "probes_reaching_full_depth": sum(1 for d_ in depths if d_ == NO),
                "wall_s": round(time.monotonic() - T0, 3)})
    print(json.dumps(out, sort_keys=True)); sys.exit(0)
