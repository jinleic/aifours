#!/usr/bin/env python3
"""Generate CpcwKernel/Data{v}k{k}.lean and CpcwKernel/Cert{v}k{k}.lean from a pinned raw CPCW file.

Raw format (strict): line 1 is `CPCW <v> <k>`; every further line is one codeword of k canonical
decimal numbers separated by single spaces; every line ends in `\\n`; nothing else.  The script

1. reads the raw file byte-exactly and requires its SHA-256 to equal --expect-sha256;
2. parses it (the header must read exactly `CPCW <--v> <--k>`) and re-renders the canonical text,
   requiring a byte-identical round trip, so every input byte is represented by the emitted
   literals (header numbers and codeword numbers);
3. emits the codewords verbatim, in raw order, as a Lean `List (List Nat)` (no sorting, no
   reduction modulo v, no deduplication, no repair), together with the header pair and the
   SHA-256 string, and emits the certificate module that runs the checker in the kernel.

It checks no mathematical property; the Lean kernel does (CpcwKernel.Generic, CpcwKernel.Cert*).
The number of codewords is taken from the file; the certificate module states that it equals
(v - 1) / (k * (k - 1)), which the kernel must confirm.  --leave (comma-separated, may be empty) is
the parent's recorded set of uncovered nonzero differences; it is emitted only into an audit
theorem that the kernel must also confirm, and no root depends on it.

Usage:
  python3 gen_lean.py RAW OUTDIR --v 122 --k 6 --expect-sha256 HEX --label TEXT --leave 61
"""
import argparse
import hashlib
import pathlib
import re
import sys

NUMBER = re.compile(r"0|[1-9][0-9]*")


def fail(message):
    raise SystemExit(f"gen_lean.py: {message}")


def parse(raw, v, k):
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        fail("raw file is not ASCII")
    if not text.endswith("\n"):
        fail("raw file does not end with a newline")
    lines = text[:-1].split("\n")
    if lines[0] != f"CPCW {v} {k}":
        fail(f"unexpected header {lines[0]!r}")
    blocks = []
    for lineno, line in enumerate(lines[1:], 2):
        tokens = line.split(" ")
        if len(tokens) != k or not all(NUMBER.fullmatch(t) for t in tokens):
            fail(f"line {lineno}: not {k} canonical decimal numbers: {line!r}")
        blocks.append([int(t) for t in tokens])
    if not blocks:
        fail("no codewords")
    return blocks


def render_raw(blocks, v, k):
    return (f"CPCW {v} {k}\n" + "".join(" ".join(str(x) for x in b) + "\n" for b in blocks)).encode("ascii")


def names(v, k):
    tag = f"{v}k{k}"
    return tag, f"data{tag}", f"cpcw{tag}"


def render_data(blocks, v, k, sha, size, label):
    tag, name, _ = names(v, k)
    rows = ",\n".join("  [" + ", ".join(str(x) for x in b) + "]" for b in blocks)
    return "\n".join([
        "/-",
        "GENERATED FILE - do not edit.  Produced by gen_lean.py from the raw certificate",
        f"{label} ({size} bytes, SHA-256 {sha}).",
        f"Header line `CPCW {v} {k}`.  Entry i of `{name}` is raw line i + 2, copied verbatim in raw order.",
        "Nothing is assumed about these numbers here: CpcwKernel.Generic states the checker and its",
        f"soundness theorem, and CpcwKernel.Cert{tag} runs the checker in the Lean kernel.",
        "-/",
        "namespace Cpcw.Kernel",
        "",
        "/-- SHA-256 of the raw certificate bytes, recorded by gen_lean.py (documentation only). -/",
        f'def {name}RawSha256 : String := "{sha}"',
        "",
        "/-- The header of the raw certificate: length `v` and weight `k`. -/",
        f"def {name}Header : Nat × Nat := ({v}, {k})",
        "",
        f"/-- The {len(blocks)} raw codewords of {label}, in raw order. -/",
        f"def {name} : List (List Nat) := [",
        rows,
        "]",
        "",
        "end Cpcw.Kernel",
        "",
    ])


def render_cert(blocks, v, k, sha, label, leave):
    tag, d, c = names(v, k)
    n = len(blocks)
    pairs = k * (k - 1)
    lv = "[" + ", ".join(str(x) for x in leave) + "]"
    return "\n".join([
        "import CpcwKernel.Generic",
        f"import CpcwKernel.Data{tag}",
        "",
        "/-!",
        f"# Optimal `({v}, {k}, 1)` CPCW code: kernel-checked existence",
        "",
        f"GENERATED by gen_lean.py from {label}",
        f"(SHA-256 {sha}); `{d}` comes from `CpcwKernel.Data{tag}`.",
        "Every `decide +kernel` below is evaluated by the Lean kernel (no `native_decide`, no",
        "`Lean.ofReduceBool`).  The semantic conclusion comes from the data-independent theorem",
        "`Cpcw.Kernel.isCPCW_of_check`; the target `Cpcw.IsOptimalCPCW` is defined in",
        "`CpcwKernel.Target`.  The leave theorems at the end are audit facts only; the root",
        f"`Cpcw.Kernel.exists_{c}` does not depend on them.",
        "-/",
        "",
        "namespace Cpcw.Kernel",
        "",
        f"/-- The raw certificate's own header reads `CPCW {v} {k}`. -/",
        f"theorem {d}_header : {d}Header = ({v}, {k}) := rfl",
        "",
        f"/-- Shape of the raw data: {n} codewords, each of {k} numbers below {v}. -/",
        f"theorem {d}_shape :",
        f"    {d}.length = {n} ∧ ∀ b ∈ {d}, b.length = {k} ∧ ∀ x ∈ b, x < {v} := by",
        "  decide +kernel",
        "",
        f"/-- The explicit family: entry `j` of codeword `i` is the residue modulo {v} of number `j + 1`",
        f"on raw line `i + 2`. -/",
        f"def {c} : Fin {n} → Fin {k} → Fin {v} := blockOf {v} (by decide) {k} {n} {d}",
        "",
        f"/-- No reduction happens: the residues are the raw numbers themselves. -/",
        f"theorem {c}_spec :",
        f"    ∀ i : Fin {n}, ∀ j : Fin {k}, (({c} i j : Fin {v}) : Nat) = rawAt {d} i j := by",
        "  decide +kernel",
        "",
        f"/-- The number of codewords is the optimal bound `⌊({v} - 1) / ({k} * ({k} - 1))⌋`. -/",
        f"theorem {d}_count : {n} = ({v} - 1) / ({k} * ({k} - 1)) := by decide +kernel",
        "",
        f"/-- One kernel evaluation of the check over all {n * pairs} ordered differences. -/",
        f"theorem {d}_check : check {v} {k} {n} {d} = true := by decide +kernel",
        "",
        f"theorem {c}_isCPCW : Cpcw.IsCPCW {c} :=",
        f"  isCPCW_of_check {v} {k} {n} (by decide) {d} {d}_check",
        "",
        f"/-- **An optimal `({v}, {k}, 1)` CPCW code exists:** {n} codewords, the bound",
        f"`⌊({v} - 1) / ({k} * ({k} - 1))⌋`. -/",
        f"theorem exists_{c} : ∃ B : Fin {n} → Fin {k} → Fin {v}, Cpcw.IsOptimalCPCW B :=",
        f"  ⟨{c}, {c}_isCPCW, {d}_count⟩",
        "",
        f"/-- Audit only: the nonzero residues that are not ordered differences are exactly {lv}",
        "(the parent's recorded leave), checked by the kernel over every residue. -/",
        f"theorem {d}_leave : leaveCheck {v} {k} {n} {d} {lv} = true := by decide +kernel",
        "",
        f"/-- Audit only: the exact multiset of ordered differences of `{c}`. -/",
        f"theorem {c}_counts : ∀ e : Fin {v},",
        f"    (Cpcw.diffs {c}).count e = if e.val = 0 ∨ e.val ∈ ({lv} : List Nat) then 0 else 1 :=",
        f"  count_of_leaveCheck {v} {k} {n} (by decide) {d} {lv} {d}_check {d}_leave",
        "",
        "end Cpcw.Kernel",
        "",
        "set_option pp.funBinderTypes true in",
        f"#check @Cpcw.Kernel.exists_{c}",
        f"#print axioms Cpcw.Kernel.{d}_shape",
        f"#print axioms Cpcw.Kernel.{c}_spec",
        f"#print axioms Cpcw.Kernel.{d}_count",
        f"#print axioms Cpcw.Kernel.{d}_check",
        f"#print axioms Cpcw.Kernel.{c}_isCPCW",
        f"#print axioms Cpcw.Kernel.exists_{c}",
        f"#print axioms Cpcw.Kernel.{d}_leave",
        f"#print axioms Cpcw.Kernel.{c}_counts",
        "",
    ])


def parse_leave(text):
    if text == "":
        return []
    values = text.split(",")
    if not all(NUMBER.fullmatch(t) for t in values):
        fail(f"--leave is not a comma-separated list of canonical decimals: {text!r}")
    leave = [int(t) for t in values]
    if leave != sorted(set(leave)):
        fail("--leave is not strictly increasing")
    return leave


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("raw")
    ap.add_argument("outdir")
    ap.add_argument("--v", type=int, required=True)
    ap.add_argument("--k", type=int, required=True)
    ap.add_argument("--expect-sha256", required=True)
    ap.add_argument("--label", required=True)
    ap.add_argument("--leave", required=True)
    args = ap.parse_args()
    raw = pathlib.Path(args.raw).read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != args.expect_sha256:
        fail(f"SHA-256 mismatch: {sha} != {args.expect_sha256}")
    blocks = parse(raw, args.v, args.k)
    if render_raw(blocks, args.v, args.k) != raw:
        fail("raw bytes are not the canonical rendering of the parsed codewords")
    leave = parse_leave(args.leave)
    tag = names(args.v, args.k)[0]
    out = pathlib.Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    data = render_data(blocks, args.v, args.k, sha, len(raw), args.label).encode("utf-8")
    cert = render_cert(blocks, args.v, args.k, sha, args.label, leave).encode("utf-8")
    (out / f"Data{tag}.lean").write_bytes(data)
    (out / f"Cert{tag}.lean").write_bytes(cert)
    print(f"v={args.v} k={args.k} codewords={len(blocks)} raw_bytes={len(raw)} raw_sha256={sha} "
          f"data_sha256={hashlib.sha256(data).hexdigest()} cert_sha256={hashlib.sha256(cert).hexdigest()}")


if __name__ == "__main__":
    sys.exit(main())
