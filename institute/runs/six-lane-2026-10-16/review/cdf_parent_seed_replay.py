"""Rebuild pinned CDF producer sources and replay the four frozen seeds, without trusting search logic.

All generated bytes stay in cdf-seed-parent-replay-v1. Each resulting certificate must be byte-identical
with the independently verified pinned witness, then pass the parent checker. The general-pair input
lists for 321/681 are pinned, not independently regenerated here. Reproducibility is not validity.
"""
from datetime import datetime
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time
from zoneinfo import ZoneInfo

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
LANE = ROOT / 'information-science/evidence/six-lane-20261016/cdf-k5'
OUT = HERE / 'cdf-seed-parent-replay-v1'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def stamp():
    return datetime.now(ZoneInfo('America/Los_Angeles')).isoformat()


def copy_new(source, dest):
    data = source.read_bytes()
    with dest.open('xb') as stream:
        stream.write(data)
    return {'source': str(source), 'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}


def run(args, label, timeout):
    started = time.monotonic()
    result = subprocess.run(args, cwd=OUT, capture_output=True, text=True, timeout=timeout)
    (OUT / f'{label}.stdout.txt').write_text(result.stdout)
    (OUT / f'{label}.stderr.txt').write_text(result.stderr)
    record = {'command': args, 'returncode': result.returncode, 'duration_seconds': time.monotonic() - started,
              'finished_at_pt': stamp()}
    with (OUT / f'{label}.execution.json').open('x') as stream:
        json.dump(record, stream, indent=2)
        stream.write('\n')
    if result.returncode:
        raise RuntimeError(f'{label} exited {result.returncode}; see retained output')
    return record


def main():
    OUT.mkdir(exist_ok=False)
    result = {'status': 'INCOMPLETE', 'started_at_pt': stamp(), 'driver_sha256': sha(Path(__file__)),
              'input_pins': {}, 'builds': {}, 'replays': {},
              'limits': 'One replay process at a time. Source/seed/input-list reproducibility only; all raw witnesses independently verified.'}
    try:
        run(['cc', '--version'], 'compiler-version', 30)
        for stem in ('cdf_inv3p', 'cdf_hyb3p', 'cdf_mq2'):
            src = OUT / f'{stem}.c'
            result['input_pins'][src.name] = copy_new(LANE / 'code' / src.name, src)
            build = run(['cc', '-O3', '-march=native', '-o', str(OUT / stem), str(src)], f'build-{stem}', 120)
            build['binary_sha256'] = sha(OUT / stem)
            result['builds'][stem] = build
        for name in ('gpairs_p107_k30.txt', 'gpairs_p227_k5.txt'):
            result['input_pins'][name] = copy_new(LANE / 'evidence/gpairs' / name, OUT / name)
        for v, stem, extra in (
            (501, 'cdf_inv3p', []),
            (321, 'cdf_hyb3p', ['1', '20000', '50000000', str(OUT / 'gpairs_p107_k30.txt')]),
            (621, 'cdf_mq2', ['30', '3', '50000000']),
            (681, 'cdf_hyb3p', ['1', '20000', '50000000', str(OUT / 'gpairs_p227_k5.txt')]),
        ):
            prefix = OUT / f'regenerated-{v}'
            args = [str(OUT / stem), str(v)]
            if v == 621:
                args += ['27']
            args += ['1', '600', str(prefix)] + extra
            rec = run(args, f'replay-{v}', 720)
            generated = prefix.with_suffix('.sol')
            pinned = HERE / f'cdf{v}-parent-inputs-v1' / f'cdf_{v}.txt'
            rec.update({'generated_sha256': sha(generated), 'pinned_sha256': sha(pinned),
                        'byte_identical': generated.read_bytes() == pinned.read_bytes()})
            if not rec['byte_identical']:
                raise RuntimeError(f'v={v}: regenerated bytes differ from the frozen witness')
            run([sys.executable, '-B', str(HERE / 'check_cdf_independent.py'), str(generated), str(v),
                 rec['pinned_sha256'], str(OUT / f'regenerated-{v}-parent-check.json')], f'check-{v}', 180)
            result['replays'][str(v)] = rec
            print(f'v={v}: rebuilt seed replay byte-identical; parent checker VALID', flush=True)
        result['status'] = 'FOUR_REBUILT_SEED_REPLAYS_BYTE_IDENTICAL_AND_VALID'
    except Exception as exc:
        result['status'] = 'FAILED'
        result['error'] = f'{type(exc).__name__}: {exc}'
    finally:
        result['finished_at_pt'] = stamp()
        with (OUT / 'parent-result.json').open('x') as stream:
            json.dump(result, stream, indent=2)
            stream.write('\n')
        print(json.dumps(result, indent=2), flush=True)
    return 0 if result['status'] == 'FOUR_REBUILT_SEED_REPLAYS_BYTE_IDENTICAL_AND_VALID' else 1


if __name__ == '__main__':
    raise SystemExit(main())
