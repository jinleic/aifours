"""Good colouring of an incomplete STS (derived design of a CQS) by partial parallel classes,
invariant under a prescribed abelian group R (adapted from ../../mcdsqs38/code/ppcsym.py,
sha256 ea43b344…085276).

R: list of permutations (closed group, identity included) preserving the triple set, the hole
H and fixing the anchor h ∈ H.  Class orbits: first the hole-avoiding ones (stabilizers given by
the caller, sum of indices = number of hole-avoiding classes), then one class orbit per R-orbit
of triples through h (stabilizer = that triple's stabilizer; the anchored triple is forced into
the representative class at the identity coset — lossless, since every non-avoiding class
contains exactly one triple through h).  A triple orbit may be placed in class orbit k only if
its stabilizer lies in R_k, its placed sub-orbit has no repeated point and, for hole-avoiding
k, it has no hole point.  Exactly one placement per triple orbit; at most one triple per
(class orbit, point).  Class labels: hole-avoiding classes first.
"""
from __future__ import annotations

import lane_guard  # noqa: F401

import collections

from lanelib import CNF, comp, inverse


def img(g, t):
    return tuple(sorted(g[p] for p in t))


def subgroup_from_gens(R, gens):
    """Subgroup of R generated by the given elements (all in R)."""
    e = tuple(range(len(R[0])))
    S = {e}
    frontier = [e]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                b = comp(g, a)
                if b not in S:
                    S.add(b)
                    new.append(b)
        frontier = new
    assert S <= set(R)
    return sorted(S)


def build(triples, points, hole, R, stabs, avoid_flags, strengthen=False, profile=None):
    hole = set(hole)
    stabs = [set(s) for s in stabs]
    cosets = []
    for S in stabs:
        reps, seen = [], set()
        for g in sorted(R):
            if g in seen:
                continue
            reps.append(g)
            seen.update(comp(g, s) for s in S)
        cosets.append(reps)
    tset = set(triples)
    seen, orbits = set(), []
    for t in sorted(tset):
        if t in seen:
            continue
        orb = {img(g, t) for g in R}
        assert orb <= tset, "R does not preserve the triples"
        seen |= orb
        stab = {g for g in R if img(g, t) == t}
        orbits.append((t, stab))
    cnf = CNF()
    choice = []
    cover = collections.defaultdict(list)
    for t, stab in orbits:
        opts = []
        has_hole = bool(set(t) & hole)
        for k, S in enumerate(stabs):
            if avoid_flags[k] and has_hole:
                continue
            for g in cosets[k]:
                ginv = inverse(g)
                # t lies in the class g·C_k, which is fixed by g R_k g^-1: need g^-1 Stab(t) g <= R_k
                # (for abelian R this is Stab(t) <= R_k)
                if not all(comp(comp(ginv, h), g) in S for h in stab):
                    continue
                blks = {img(comp(s, ginv), t) for s in S}
                pts = collections.Counter(p for b in blks for p in b)
                if any(c > 1 for c in pts.values()):
                    continue
                v = cnf.var()
                opts.append((v, k, g))
                for p in pts:
                    cover[(k, p)].append(v)
        cnf.exactly_one([o[0] for o in opts])
        choice.append(opts)
    for k in range(len(stabs)):
        for p in points:
            cnf.amo(cover.get((k, p), []))
    if strengthen or profile:
        cov = add_strengthening(cnf, cover, points, hole, R, stabs, cosets, avoid_flags)
        if profile == "P10":
            add_profile_p10(cnf, cover, points, hole, R, stabs, cosets, avoid_flags, cov)
    return cnf, orbits, choice, cosets, stabs


def add_strengthening(cnf, cover, points, hole, R, stabs, cosets, avoid_flags, free_cover=None, n_free=0):
    """README E7 redundant constraints (implied by counting, made explicit):
    S1  every non-avoiding class contains every hole point;
    S2  every non-hole point is missed by exactly one of the r classes.
    Class g·C_k misses p iff C_k misses g^{-1}(p).  free_cover: (c, p) -> literals of the
    symmetry-free hole-avoiding classes of the hybrid model (n_free of them)."""
    hole = set(hole)
    for k in range(len(stabs)):
        if not avoid_flags[k]:
            for q in hole:
                cnf.add(cover.get((k, q), []))
    covvar = {}

    def cov(key, lits):
        if key not in covvar:
            c = cnf.var()
            cnf.add([-c] + list(lits))
            for l in lits:
                cnf.add([-l, c])
            covvar[key] = c
        return covvar[key]

    nonhole = [p for p in points if p not in hole]
    if free_cover is None:
        reps, seen = [], set()
        for p in nonhole:
            if p in seen:
                continue
            reps.append(p)
            seen |= {g[p] for g in R}
    else:
        reps = nonhole
    for p in reps:
        lits = []
        for k in range(len(stabs)):
            for g in cosets[k]:
                q = inverse(g)[p]
                lits.append(-cov(("k", k, q), cover.get((k, q), [])))
        for c in range(n_free):
            lits.append(-cov(("f", c, p), free_cover.get((c, p), [])))
        cnf.exactly_one(lits)
    return cov


def add_profile_p10(cnf, cover, points, hole, R, stabs, cosets, avoid_flags, cov):
    """README E8 optional ansatz P10 (parent-suggested profile, NOT part of the target): every
    non-avoiding class misses exactly one non-hole point (size 26), every hole-avoiding class in a
    non-trivial orbit covers all non-hole points (size 20); the R-fixed hole-avoiding class then
    has the remaining slack (size 10 when the structure is [1,3,3,3])."""
    hole = set(hole)
    nonhole = [p for p in points if p not in hole]
    for k in range(len(stabs)):
        if not avoid_flags[k]:
            cnf.exactly_one([-cov(("k", k, p), cover.get((k, p), [])) for p in nonhole])
        elif len(cosets[k]) > 1:
            for p in nonhole:
                cnf.add(cover.get((k, p), []))


def anchored(der, pts, hole, R, anchor, avoid_stabs, strengthen=False, profile=None):
    """avoid_stabs: list of subgroups (lists of perms) for the hole-avoiding class orbits."""
    assert anchor in hole
    seen, anchor_orbits = set(), []
    for t in sorted(t for t in der if anchor in t):
        if t in seen:
            continue
        seen |= {img(g, t) for g in R}
        anchor_orbits.append((t, [g for g in R if img(g, t) == t]))
    stabs = list(avoid_stabs) + [s for _, s in anchor_orbits]
    flags = [True] * len(avoid_stabs) + [False] * len(anchor_orbits)
    cnf, orbits, choice, cosets, stb = build(der, pts, hole, R, stabs, flags, strengthen=strengthen, profile=profile)
    ident = tuple(range(len(R[0])))
    for i, (t, _) in enumerate(anchor_orbits):
        k = len(avoid_stabs) + i
        oi = next(j for j, (u, _) in enumerate(orbits) if u == t)
        forced = [o[0] for o in choice[oi] if o[1] == k and o[2] == ident]
        cnf.add([forced[0]] if forced else [])
    sizes = [len(R) // len(s) for s in stabs]
    return cnf, orbits, choice, cosets, stb, sizes


def decode(model, orbits, choice, cosets, stabs, R):
    classes = {(k, i): set() for k in range(len(stabs)) for i in range(len(cosets[k]))}
    for (t, stab), opts in zip(orbits, choice):
        sel = [o for o in opts if o[0] in model]
        assert len(sel) == 1
        _, k, g = sel[0]
        for h in R:
            x = comp(h, g)
            idx = next(i for i, c in enumerate(cosets[k]) if any(comp(c, s) == x for s in stabs[k]))
            classes[(k, idx)].add(img(h, t))
    return [sorted(v) for _, v in sorted(classes.items())]


def hybrid(der, pts, hole, R, anchor, n_avoid, strengthen=False):
    """README E5 hybrid model.  The non-avoiding classes form R-orbits anchored at `anchor`
    exactly as in anchored() (lossless).  The n_avoid hole-avoiding classes carry NO symmetry:
    a hole-free triple orbit is either placed as a whole into a non-avoiding class orbit
    (coset placement) or each of its triples is assigned individually to one of the n_avoid
    hole-avoiding classes.  The resulting colouring is R-invariant on the non-avoiding classes
    only (validity never uses R; transport uses the SQS group)."""
    assert anchor in hole
    hole = set(hole)
    seen, anchor_orbits = set(), []
    for t in sorted(t for t in der if anchor in t):
        if t in seen:
            continue
        seen |= {img(g, t) for g in R}
        anchor_orbits.append((t, [g for g in R if img(g, t) == t]))
    stabs = [set(s) for _, s in anchor_orbits]
    cosets = []
    for S in stabs:
        reps, sn = [], set()
        for g in sorted(R):
            if g in sn:
                continue
            reps.append(g)
            sn.update(comp(g, s) for s in S)
        cosets.append(reps)
    tset = set(der)
    seen, orbits = set(), []
    for t in sorted(tset):
        if t in seen:
            continue
        orb = sorted({img(g, t) for g in R})
        assert set(orb) <= tset
        seen |= set(orb)
        orbits.append((t, {g for g in R if img(g, t) == t}, orb))
    cnf = CNF()
    choice, free = [], []
    cover = collections.defaultdict(list)
    acover = collections.defaultdict(list)
    for t, stab, orb in orbits:
        opts = []
        for k, S in enumerate(stabs):
            for g in cosets[k]:
                ginv = inverse(g)
                if not all(comp(comp(ginv, hh), g) in S for hh in stab):  # g^-1 Stab(t) g <= R_k
                    continue
                blks = {img(comp(s, ginv), t) for s in S}
                pc = collections.Counter(p for b in blks for p in b)
                if any(c > 1 for c in pc.values()):
                    continue
                v = cnf.var()
                opts.append((v, k, g))
                for p in pc:
                    cover[(k, p)].append(v)
        fv = None
        tv = {}
        if not (set(t) & hole):
            fv = cnf.var()  # orbit goes to the hole-avoiding classes
            for u in orb:
                lits = []
                for c in range(n_avoid):
                    w = cnf.var()
                    tv[(u, c)] = w
                    lits.append(w)
                    for p in u:
                        acover[(c, p)].append(w)
                    cnf.add([-w, fv])
                cnf.add([-fv] + lits)          # fv -> each triple gets a class
                cnf.amo(lits)
        cnf.exactly_one([o[0] for o in opts] + ([fv] if fv else []))
        choice.append(opts)
        free.append((fv, tv))
    for k in range(len(stabs)):
        for p in pts:
            cnf.amo(cover.get((k, p), []))
    for c in range(n_avoid):
        for p in pts:
            cnf.amo(acover.get((c, p), []))
    if strengthen:
        add_strengthening(cnf, cover, pts, hole, R, [set(s) for s in stabs], cosets, [False] * len(stabs),
                          free_cover=acover, n_free=n_avoid)
    ident = tuple(range(len(R[0])))
    for i, (t, _) in enumerate(anchor_orbits):
        oi = next(j for j, (u, _, _) in enumerate(orbits) if u == t)
        forced = [o[0] for o in choice[oi] if o[1] == i and o[2] == ident]
        cnf.add([forced[0]] if forced else [])
    sizes = [len(R) // len(s) for s in stabs]
    return cnf, (orbits, choice, free, cosets, stabs, n_avoid), sizes


def decode_hybrid(model, dec, R):
    orbits, choice, free, cosets, stabs, n_avoid = dec
    avoid = [set() for _ in range(n_avoid)]
    classes = {(k, i): set() for k in range(len(stabs)) for i in range(len(cosets[k]))}
    for (t, stab, orb), opts, (fv, tv) in zip(orbits, choice, free):
        if fv is not None and fv in model:
            for (u, c), w in tv.items():
                if w in model:
                    avoid[c].add(u)
            continue
        sel = [o for o in opts if o[0] in model]
        assert len(sel) == 1
        _, k, g = sel[0]
        for h in R:
            x = comp(h, g)
            idx = next(i for i, c in enumerate(cosets[k]) if any(comp(c, s) == x for s in stabs[k]))
            classes[(k, idx)].add(img(h, t))
    return [sorted(C) for C in avoid] + [sorted(v) for _, v in sorted(classes.items())]


def verify_good_colouring(triples, points, hole, classes, r, s):
    assert len(classes) == r, "wrong number of classes"
    allt = sorted(t for C in classes for t in C)
    assert allt == sorted(triples), "colouring does not list the derived design exactly"
    pset, hole = set(points), set(hole)
    navoid = 0
    for C in classes:
        assert C, "empty class"
        ps = [p for t in C for p in t]
        assert len(ps) == len(set(ps)), "class is not a partial parallel class"
        assert set(ps) <= pset
        navoid += not (set(ps) & hole)
    assert navoid == s, f"{navoid} hole-avoiding classes, expected {s}"
    return True
