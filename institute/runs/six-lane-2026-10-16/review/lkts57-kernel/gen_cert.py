#!/usr/bin/env python3
"""Generate the Lean certificate module LktsKernel/Cert<v>.lean for a raw LKTS(v) file.

The module states one kernel-evaluated `sysOK` theorem per system, a chain of kernel-evaluated
`rankFold` segments whose intermediate accumulators are written as hexadecimal literals, and
the final semantic theorem obtained from `Kirkman.KernelCert.isLKTS_of_check`.

The accumulator literals are only claims: each segment theorem is proved by `decide +kernel`,
so a wrong literal makes the Lean build fail.  This script never decides validity.  It parses
the raw file (whose SHA-256 must match --expect-sha256) only to compute those claimed values,
and it reports, without stopping, whether its own fold met a repeated rank.

Usage:
  python3 gen_cert.py RAW OUT.lean --v 57 --name data57 --module LktsKernel.Data57 \
      --expect-sha256 HEX --group 11 --theorem-prefix lkts57
"""
import argparse
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_data import parse  # noqa: E402  (same parser as the data module)


def nat_sub(x, y):
    return x - y if x > y else 0


def rank(t):
    """Mirror of Lean `Kirkman.KernelCert.rank` (truncated natural subtraction)."""
    a, b, c = t
    return c * nat_sub(c, 1) * nat_sub(c, 2) // 6 + b * nat_sub(b, 1) // 2 + a


def comb3(v):
    return v * (v - 1) * (v - 2) // 6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("raw")
    ap.add_argument("out")
    ap.add_argument("--v", type=int, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--module", required=True)
    ap.add_argument("--expect-sha256", required=True)
    ap.add_argument("--group", type=int, required=True)
    ap.add_argument("--theorem-prefix", required=True)
    ap.add_argument("--label", required=True)
    args = ap.parse_args()

    raw = pathlib.Path(args.raw).read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != args.expect_sha256:
        raise SystemExit(f"SHA-256 mismatch: {sha} != {args.expect_sha256}")
    systems = parse(raw.decode("ascii"), args.v)
    v, n, pre = args.v, args.name, args.theorem_prefix
    nsys = len(systems)
    full = comb3(v)

    groups = [list(range(j, min(j + args.group, nsys))) for j in range(0, nsys, args.group)]
    accs = [0]
    collision = None
    acc = 0
    for g in groups:
        for i in g:
            for cls in systems[i]:
                for t in cls:
                    bit = 1 << rank(t)
                    if acc & bit and collision is None:
                        collision = (i, t)
                    acc |= bit
        accs.append(acc)

    def lit(x):
        if x == (1 << full) - 1:
            return f"(2 ^ {full} - 1)"
        return "0x" + format(x, "x") if x else "0"

    def sysl(g):
        return "[" + ", ".join(f"{n}Sys{i}" for i in g) + "]"

    L = []
    L.append(f"import LktsKernel.Generic\nimport {args.module}\n")
    L.append("/-!")
    L.append(f"# LKTS({v}): kernel-checked existence from the pinned raw certificate")
    L.append("")
    L.append(f"GENERATED by gen_cert.py from {args.label}")
    L.append(f"(SHA-256 {sha}); `{n}` comes from `{args.module}`.")
    L.append("Every `decide +kernel` below is evaluated by the Lean kernel (no `native_decide`, no")
    L.append("`Lean.ofReduceBool`).  The semantic conclusion comes from the data-independent theorem")
    L.append("`Kirkman.KernelCert.isLKTS_of_check`.  The hexadecimal accumulators of the rank-fold")
    L.append("segments are claims checked by the kernel, not assumptions.")
    L.append("-/")
    L.append("")
    L.append("namespace Kirkman.KernelCert")
    L.append("")
    L.append(f"theorem {n}_len : {n}.length = {v} - 2 := rfl")
    L.append("")
    L.append(f"/-! One kernel evaluation of `sysOK` per system (class partitions and pair partition). -/")
    L.append("")
    for i in range(nsys):
        L.append(f"theorem {n}_sys{i} : sysOK {v} (fullPairs {v}) {n}Sys{i} = true := by decide +kernel")
    L.append("")
    nest = "fun _ h => nomatch h"
    for i in reversed(range(nsys)):
        nest = f"List.forall_mem_cons.2 ⟨{n}_sys{i},\n    {nest}⟩"
    L.append(f"theorem {n}_sys : ∀ s ∈ {n}, sysOK {v} (fullPairs {v}) s = true :=")
    L.append(f"  {nest}")
    L.append("")
    L.append(f"/-! No row repeats: a rank fold over all rows, checked in {len(groups)} kernel segments. -/")
    L.append("")
    for k, g in enumerate(groups):
        L.append(f"theorem {n}_rank{k} :")
        L.append(f"    rankFold {lit(accs[k])}")
        L.append(f"      (allRows {sysl(g)}) =")
        L.append(f"      some {lit(accs[k + 1])} := by")
        L.append("  decide +kernel")
        L.append("")
    split = " ++ (".join(sysl(g) for g in groups) + ")" * (len(groups) - 1)
    chain = f"{n}_rank{len(groups) - 1}"
    for k in reversed(range(len(groups) - 1)):
        chain = f"rankFold_append _ _ _ _ _ {n}_rank{k}\n      ({chain})"
    L.append(f"theorem {n}_nodup : (allRows {n}).Nodup := by")
    L.append(f"  have e : {n} = {split} := rfl")
    L.append("  rw [e]")
    L.append("  simp only [allRows_append]")
    L.append(f"  exact nodup_of_rankFold\n    ({chain})")
    L.append("")
    L.append(f"theorem {n}_card : ({v} - 2) * (({v} - 1) / 2 * ({v} / 3)) = Nat.choose {v} 3 := by")
    L.append("  decide +kernel")
    L.append("")
    L.append(f"/-- The {nsys} constituents named by the raw certificate form a large set of Kirkman")
    L.append("triple systems, in the sense of the frozen definition `Kirkman.IsLKTS`. -/")
    L.append(f"theorem {pre}_isLKTS : IsLKTS (blocksOf {v} {n}) :=")
    L.append(f"  isLKTS_of_check {v} {n} {n}_len {n}_sys {n}_nodup {n}_card")
    L.append("")
    L.append("/-- Constituent `i` is exactly the set of genuine triples whose point set is a row of")
    L.append("KTS `i` of the raw certificate. -/")
    L.append(f"theorem {pre}_blocks_spec (i : Fin {v - 2}) (T : Triple {v}) :")
    L.append(f"    T ∈ blocksOf {v} {n} i ↔")
    L.append(f"      ∃ c : Fin {(v - 1) // 2}, ∃ r : Fin {v // 3}, T.val = rowSet {v} (rowAt {n} i c r) :=")
    L.append("  Iff.rfl")
    L.append("")
    L.append(f"/-- **LKTS({v}) exists.** -/")
    L.append(f"theorem exists_{pre} : ∃ B : Fin {v - 2} → Kirkman.Blocks {v}, Kirkman.IsLKTS B :=")
    L.append(f"  ⟨blocksOf {v} {n}, {pre}_isLKTS⟩")
    L.append("")
    L.append("end Kirkman.KernelCert")
    L.append("")
    for d in ["Kirkman.IsSTS", "Kirkman.IsParallelClass", "Kirkman.IsResolution", "Kirkman.IsKTS",
              "Kirkman.IsLKTS", "Kirkman.KernelCert.rowSet", "Kirkman.KernelCert.rowAt",
              "Kirkman.KernelCert.blocksOf"]:
        L.append(f"#print {d}")
    L.append("#check @Kirkman.KernelCert.isLKTS_of_check")
    L.append("set_option pp.funBinderTypes true in")
    L.append(f"#check @Kirkman.KernelCert.exists_{pre}")
    for d in ["isLKTS_of_check", f"{n}_sys", f"{n}_nodup", f"{n}_card", f"{pre}_isLKTS",
              f"exists_{pre}"]:
        L.append(f"#print axioms Kirkman.KernelCert.{d}")
    text = "\n".join(L) + "\n"
    pathlib.Path(args.out).write_text(text)
    print(f"v={v} systems={nsys} groups={len(groups)} final_full={accs[-1] == (1 << full) - 1} "
          f"python_rank_collision={collision} raw_sha256={sha} "
          f"out_sha256={hashlib.sha256(text.encode()).hexdigest()}")


if __name__ == "__main__":
    sys.exit(main())
