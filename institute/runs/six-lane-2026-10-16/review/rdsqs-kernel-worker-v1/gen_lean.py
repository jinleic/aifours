#!/usr/bin/env python3
"""Generate RdsqsKernel/Data{v}.lean from a pinned raw RDSQS certificate and its compact seed.

Usage: python3 -B gen_lean.py V OUT_DIR      (V in {52, 76}; refuses to overwrite OUT_DIR/Data{V}.lean)

The Lean literal `data{V}` is the raw certificate's `POINT 0` section, copied verbatim in raw
order: entry j of class i is the j-th triple line after `CLASS i` of `POINT 0`, with its three
numbers in raw order.  Nothing is sorted, repaired or reduced modulo V.  The raw file must have
its pinned SHA-256 and the section must have the exact `CLASS 0 .. CLASS k-1` layout.

`mults{V}` lists the cyclic subgroup of units generated by the seed's `multiplier_generator`
(powers g^0, g^1, ... in order), each with its inverse modulo V.  The seed JSON must have its
pinned SHA-256, its `v` and `classes_at_0` must equal the raw `POINT 0` section, and its header
must equal the raw certificate's first line.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
REVIEW = HERE.parent
INPUTS = {
    52: {'raw': 'rdsqs52-parent-inputs-v1/rdsqs52_z52_m23.txt',
         'raw_sha256': '7ae0a828b5af08b4bd9b423564981d85e3703886553638024fdc812f564989a6',
         'seed': 'rdsqs52-parent-replay-v1/rdsqs52_z52_m23_seed.json',
         'seed_sha256': 'a0fe9247f93d1f16007eff24b65c3dddf0f409c33f847f8a7382399b09dcefce'},
    76: {'raw': 'rdsqs76-parent-inputs-v1/rdsqs76_z76_m3_sample0.txt',
         'raw_sha256': '2f75b37c0439aa9f9c57861505a2e865997dd02249349b708880916d477a75aa',
         'seed': 'rdsqs76-parent-inputs-v1/rdsqs76_z76_m3_sample0_seed.json',
         'seed_sha256': '8d5860f640d1d49163496f996aad97af1e4674855cc2a1c6883327cb272ba0ad'},
}
TRIPLE = re.compile(r'(0|[1-9][0-9]*) (0|[1-9][0-9]*) (0|[1-9][0-9]*)')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def point0_section(raw_text):
    """Return (first_line_number, last_line_number, classes) of the raw POINT 0 section."""
    lines = raw_text.split('\n')
    require(lines[-1] == '' and '\r' not in raw_text, 'noncanonical line endings')
    lines = lines[:-1]
    starts = [i for i, line in enumerate(lines) if line == 'POINT 0']
    require(len(starts) == 1, 'expected exactly one POINT 0 line')
    start = starts[0]
    classes = []
    i = start + 1
    while i < len(lines) and not lines[i].startswith('POINT '):
        line = lines[i]
        if line.startswith('CLASS '):
            require(line == f'CLASS {len(classes)}', f'out-of-order class header at line {i + 1}')
            classes.append([])
        else:
            match = TRIPLE.fullmatch(line)
            require(match is not None and classes, f'invalid triple line {i + 1}: {line!r}')
            classes[-1].append(tuple(int(x) for x in match.groups()))
        i += 1
    require(i < len(lines) and lines[i] == 'POINT 1', 'POINT 0 section must be followed by POINT 1')
    return start + 1, i, classes


def subgroup(gen, v):
    elements = [1]
    while True:
        nxt = elements[-1] * gen % v
        if nxt == 1:
            return elements
        require(nxt not in elements and len(elements) < v, 'generator is not a unit')
        elements.append(nxt)


def render(v, spec, raw_bytes, first, last, classes, gen, mults, seed_bytes):
    raw_sha = hashlib.sha256(raw_bytes).hexdigest()
    seed_sha = hashlib.sha256(seed_bytes).hexdigest()
    header = raw_bytes.decode('ascii').split('\n')[0]
    rows = []
    for k, cls in enumerate(classes):
        body = ',\n    '.join(', '.join(f'({a}, {b}, {c})' for a, b, c in cls[j:j + 6])
                              for j in range(0, len(cls), 6))
        rows.append(f'  -- CLASS {k}\n  [{body}]')
    data = ',\n'.join(rows)
    mult_text = ', '.join(f'({m}, {mi})' for m, mi in mults)
    count = sum(len(c) for c in classes)
    return f'''import RdsqsKernel.Check

/-
GENERATED FILE - do not edit.  Produced by gen_lean.py from the raw certificate
review/{spec['raw']}
({len(raw_bytes)} bytes, SHA-256 {raw_sha}),
first line `{header}`.
`data{v}` is the raw `POINT 0` section (raw lines {first}-{last}), copied verbatim in raw order:
entry j of class i is the j-th triple line after `CLASS i` of `POINT 0`.
`mults{v}` lists the powers of the multiplier generator {gen} of the compact seed
review/{spec['seed']}
({len(seed_bytes)} bytes, SHA-256 {seed_sha}),
each with its inverse modulo {v}.
Nothing is assumed about these numbers here: RdsqsKernel.Check states the checker and its
soundness theorem, and RdsqsKernel.Cert{v} runs the checker in the Lean kernel.
-/

namespace Rdsqs.Kernel

/-- SHA-256 of the raw certificate bytes, recorded by gen_lean.py (documentation only). -/
def data{v}RawSha256 : String := "{raw_sha}"

/-- SHA-256 of the compact seed bytes, recorded by gen_lean.py (documentation only). -/
def data{v}SeedSha256 : String := "{seed_sha}"

/-- The {len(classes)} classes ({count} triples) of the raw `POINT 0` section, in raw order. -/
def data{v} : List (List RawTriple) := [
{data}
]

/-- The multipliers `m` (powers of the seed's generator) with their inverses `m'` mod {v}. -/
def mults{v} : List (ℕ × ℕ) := [{mult_text}]

end Rdsqs.Kernel
'''


def main(argv):
    require(len(argv) == 2, __doc__)
    v = int(argv[0])
    out_dir = Path(argv[1])
    spec = INPUTS[v]
    raw_bytes = (REVIEW / spec['raw']).read_bytes()
    require(hashlib.sha256(raw_bytes).hexdigest() == spec['raw_sha256'], 'raw certificate SHA-256 mismatch')
    seed_bytes = (REVIEW / spec['seed']).read_bytes()
    require(hashlib.sha256(seed_bytes).hexdigest() == spec['seed_sha256'], 'seed SHA-256 mismatch')
    raw_text = raw_bytes.decode('ascii')
    require(raw_text.split('\n')[1] == f'RDSQS {v}', 'raw header mismatch')
    first, last, classes = point0_section(raw_text)
    seed = json.loads(seed_bytes)
    require(seed['v'] == v, 'seed order mismatch')
    require(seed['certificate_header'] == raw_text.split('\n')[0], 'seed header differs from raw header')
    require([[tuple(t) for t in c] for c in seed['classes_at_0']] == classes,
            'seed classes_at_0 differ from the raw POINT 0 section')
    gen = seed['multiplier_generator']
    mults = [(m, pow(m, -1, v)) for m in subgroup(gen, v)]
    text = render(v, spec, raw_bytes, first, last, classes, gen, mults, seed_bytes)
    out = out_dir / f'Data{v}.lean'
    with out.open('x') as stream:
        stream.write(text)
    print(json.dumps({'written': str(out), 'sha256': hashlib.sha256(text.encode()).hexdigest(),
                      'classes': len(classes), 'triples': sum(len(c) for c in classes),
                      'raw_point0_lines': [first, last], 'mults': mults}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
