def sha(p):
    return runlib.sha_file(p)


def parse_cnf(path):
    nv = nc = None
    cls, cur = [], []
    with open(path) as f:
        for line in f:
            s = line.split()
            if not s or s[0] == "c":
                continue
            if s[0] == "p":
                assert s[1] == "cnf" and nv is None
                nv, nc = int(s[2]), int(s[3])
                continue
            for t in s:
                v = int(t)
                if v == 0:
                    cls.append(tuple(cur))
                    cur = []
                else:
                    cur.append(v)
    assert not cur
    return nv, nc, cls


def drat(cnf, prf, tag):
    r = runlib.run([DT, cnf, prf], OUT, os.path.join(OUT, "dt", tag + ".out"), os.path.join(OUT, "dt", tag + ".err"), env=env)
    with open(os.path.join(OUT, "dt", tag + ".out"), "rb") as f:
        txt = f.read().decode("utf-8", "replace")
    lines = [l.strip() for l in txt.replace("\r", "\n").split("\n")]
    r["s_lines"] = [l for l in lines if l.startswith("s ")]
    r["verified"] = ("s VERIFIED" in lines) and ("s NOT VERIFIED" not in lines)
    r["tag"] = tag
    r["cnf"], r["cnf_sha256"], r["proof"], r["proof_sha256"] = cnf, sha(cnf), prf, sha(prf)
    rec["drat_runs"].append(r)
    return r["verified"]


def unit_eval(nv, clauses, fixed):
    """fixed: var -> bool. Propagate units to a fixpoint; return (ok, assignment) where ok means every clause is satisfied
    by the completed assignment (all vars must end assigned)."""
    a = dict(fixed)
    changed = True
    while changed:
        changed = False
        for c in clauses:
            sat = False
            unassigned = []
            for l in c:
                v = abs(l)
                if v in a:
                    if a[v] == (l > 0):
                        sat = True
                        break
                else:
                    unassigned.append(l)
            if sat:
                continue
            if not unassigned:
                return False, a
            if len(unassigned) == 1:
                l = unassigned[0]
                a[abs(l)] = l > 0
                changed = True
    if len(a) != nv:
        return False, a
    return all(any(a[abs(l)] == (l > 0) for l in c) for c in clauses), a


