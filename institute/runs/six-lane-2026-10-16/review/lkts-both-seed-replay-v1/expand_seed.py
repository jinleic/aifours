#!/usr/bin/env python3
"""Independent regeneration of an LKTS(v) certificate (v from the seed, default 57) from the compact seed
(standard library only; does not import any other lane module).
Usage: expand_seed.py SEED.json OUT_CERT [COMPARE_CERT]"""
import json, sys
from collections import deque

def comp(p, q):  # apply q then p
    return tuple(p[x] for x in q)

def closure(gens, n):
    e = tuple(range(n)); seen = {e}; dq = deque([e])
    while dq:
        a = dq.popleft()
        for g in gens:
            b = comp(g, a)
            if b not in seen:
                seen.add(b); dq.append(b)
    return seen

def canon(systems):
    return sorted(tuple(sorted(tuple(sorted(tuple(sorted(b)) for b in C)) for C in S)) for S in systems)

def parse(path):
    systems = []
    for raw in open(path):
        line = raw.split('#')[0].strip()
        if not line: continue
        t = line.split()
        if t[0] == 'LKTS': continue
        if t[0] == 'KTS': systems.append([]); continue
        if t[0] == 'CLASS': systems[-1].append([]); continue
        systems[-1][-1].append(tuple(int(x) for x in t))
    return systems

seed = json.load(open(sys.argv[1]))
n = seed.get("v", 57)
G = closure([tuple(g) for g in seed["G_generators"].values()], n)
assert len(G) == seed.get("G_order", 513 if n == 57 else len(G)), len(G)
systems = []
for base in seed["bases"]:
    H = closure([tuple(g) for g in base["stabilizer_generators"]], n)
    assert H <= G
    classes = [[tuple(b) for b in C] for C in base["classes"]]
    reps, covered = [], set()
    for g in sorted(G):
        if g in covered: continue
        reps.append(g); covered |= {comp(g, h) for h in H}
    for g in reps:
        systems.append([[tuple(sorted(g[p] for p in b)) for b in C] for C in classes])
assert len(systems) == n - 2, len(systems)
with open(sys.argv[2], 'w') as f:
    f.write(seed.get("certificate_header", "# regenerated by expand_seed.py") + f"\nLKTS {n}\n")
    for k, S in enumerate(systems):
        f.write(f"KTS {k}\n")
        for c, C in enumerate(S):
            f.write(f"CLASS {c}\n")
            for b in sorted(C): f.write(f"{b[0]} {b[1]} {b[2]}\n")
print("regenerated", len(systems), "systems")
if len(sys.argv) > 3:
    same = canon(systems) == canon(parse(sys.argv[3]))
    print("canonical equality with", sys.argv[3], ":", same)
    sys.exit(0 if same else 1)
