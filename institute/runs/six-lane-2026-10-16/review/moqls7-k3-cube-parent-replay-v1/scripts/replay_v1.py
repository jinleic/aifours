#!/usr/bin/env python3
"""Parent replay of the phys-2 K3 cube certificates A_C321 and A_C411 (review/moqls7-k3-cube-parent-replay-v1).

Usage (run from bash; never under an eval deadline):
  replay_v1.py regen CUBE [CUBE ...]  regenerate and hash only, no native launch -> receipts/v1-regen-A_<CUBE>.json
  replay_v1.py selfcheck              three tiny transport self-checks of pipeline()+verdict() -> receipts/v1-X*.json
  replay_v1.py run CUBE               one instance -> receipts/v1-A_<CUBE>.pre.json, .launch.json, .json

run: brief pins and producer evidence are checked, then the pre-execution receipt (script SHA-256s) is written
exclusively; the CNF is regenerated by compose_v1.py in a subprocess (cwd and TMPDIR = desk tmp) and held in memory;
its SHA-256 is compared with the brief's value (mismatch: FAIL, nothing launched); the launch receipt records the
cadical and drat-trim SHA-256s taken at spawn and an observational lane snapshot; then cadical -q -t 5400 reads the
CNF from a pipe and writes binary DRAT to a FIFO that drat-trim -i -t 7200 reads on stdin, with the CNF on a second
pipe. A fresh free-space gate (>= 12.2e9 + projected retained growth) precedes each native Popen. SIGTERM to this
driver is a cooperative safety stop (children get SIGTERM, bounded wait, verdict UNKNOWN).
"""
import json
import os
import signal
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import k3lib_v1 as K  # noqa: E402

TAG = "v1"
SOLVER_SECONDS = 5400
CHECKER_SECONDS = 7200
LOGFD = {"fd": None}


def log(msg):
    line = "[%s] %s\n" % (K.now(), msg)
    sys.stdout.write(line)
    sys.stdout.flush()
    if LOGFD["fd"] is not None:
        os.write(LOGFD["fd"], line.encode())


def _on_term(signum, frame):
    K.STOP["requested"] = "driver SIGTERM received at %s" % K.now()


def common(mode):
    return {"mode": mode, "driver_pid": os.getpid(), "at": K.now(), "desk": K.DESK,
            "scripts_sha256": K.script_hashes(), "python": {"argv0": sys.executable, "version": sys.version,
                                                            "flags_isolated": sys.flags.isolated,
                                                            "flags_dont_write_bytecode": sys.flags.dont_write_bytecode},
            "interpreter_binary": K.binary_record(K.PY), "uname": list(os.uname()),
            "gate_rule": {"launch_threshold": K.GATE, "launch_base": K.LAUNCH_BASE,
                          "projected_retained_growth": K.PROJECTED_GROWTH, "inflight_floor": K.FLOOR,
                          "rss_stop": K.RSS_STOP, "sigterm_grace_seconds": K.GRACE}}


def mode_regen(cubes):
    pins, bad = K.pin_status()
    for cube in cubes:
        label = "%s-regen-A_%s" % (TAG, cube)
        path = os.path.join(K.DESK, "receipts", label + ".json")
        if os.path.lexists(path):
            raise SystemExit("exists: " + path)
        prod = K.producer_evidence(cube)
        row = common("regen")
        row.update({"label": label, "pins": pins, "pin_mismatch": bad, "producer": prod,
                    "gate_before_compose": K.gate("before compose subprocess (python, not native)")})
        if bad:
            row["result"] = "not run: pin mismatch"
        else:
            cnf, info = K.regenerate(cube)
            row["regen"] = K.check_regen(cube, cnf, info, prod["meta_fields"])
            row["result"] = {True: "MATCH", False: "MISMATCH", None: "NO BYTES"}[row["regen"]["cnf_hash_match"]]
            del cnf
        row["finished_at"] = K.now()
        h = K.write_json_x(path, row)
        log("%s %s receipt=%s sha256=%s" % (label, row["result"], os.path.relpath(path, K.DESK), h))


UNSAT4 = b"p cnf 2 4\n1 2 0\n1 -2 0\n-1 2 0\n-1 -2 0\n"
SAT3 = b"p cnf 2 3\n1 2 0\n1 -2 0\n-1 2 0\n"
SELFCHECKS = [("X1-UNSAT4", UNSAT4, None, "PASS"),
              ("X2-SAT3", SAT3, None, "FAIL"),
              ("X3-UNSAT4proof-vs-SAT3cnf", UNSAT4, SAT3, "FAIL")]
PARSER_CASES = [  # (checker log bytes, expected flags subset)
    (b"\rc reading proof from stdin\n\rs VERIFIED\n\rc verification time: 1.0 seconds\n",
     {"exact_verified": True, "exact_not_verified": False, "timeout_anywhere": False}),
    (b"\rc x\n\ns NOT VERIFIED\n\rc verification time: 1.0 seconds\n",
     {"exact_verified": False, "exact_not_verified": True, "not_verified_anywhere": True}),
    (b"\rc detected empty clause\ns TIMEOUT\n", {"exact_verified": False, "timeout_anywhere": True}),
    (b" s VERIFIED\n", {"exact_verified": False}),
    (b"\rs VERIFIED \n", {"exact_verified": False}),
    (b"\rs VERIFIED\r\n", {"exact_verified": True}),
]


def mode_selfcheck():
    pre_path = os.path.join(K.DESK, "receipts", TAG + "-selfcheck.pre.json")
    pre = common("selfcheck")
    pre.update({"pins": K.pin_status()[0], "checks": [[n, e] for n, _, _, e in SELFCHECKS],
                "binaries_at_spawn": {"cadical": K.binary_record(K.CADICAL), "drat-trim": K.binary_record(K.DRAT)}})
    log("selfcheck pre-execution receipt sha256=%s" % K.write_json_x(pre_path, pre))
    parser = []
    for data, want in PARSER_CASES:
        got = K.checker_flags(data)
        parser.append({"log_hex": data.hex(), "want": want, "got": got,
                       "ok": all(got[k] == v for k, v in want.items())})
    logic = {"hash_mismatch_no_run": K.verdict(False, None), "no_bytes_no_run": K.verdict(None, None)}
    rows = []
    for name, cnf, ccnf, expect in SELFCHECKS:
        label = "%s-%s" % (TAG, name)
        rec = K.pipeline(label, cnf, [K.CADICAL, "-q", "-t", "60"], 60, 60, checker_cnf=ccnf)
        v = K.verdict(True, rec)   # hash binding not applicable here; True exercises the run-time branches
        row = {"label": label, "expect": expect, "verdict": v, "matches_expectation": v == expect,
               "cnf_text": cnf.decode(), "checker_cnf_text": (ccnf or cnf).decode(), "pipeline": rec}
        h = K.write_json_x(os.path.join(K.DESK, "receipts", label + ".json"), row)
        rows.append({"label": label, "expect": expect, "verdict": v, "matches_expectation": v == expect,
                     "solver_rc": rec.get("children", {}).get("solver", {}).get("rc"),
                     "checker_rc": rec.get("children", {}).get("checker", {}).get("rc"),
                     "checker_status_lines": rec.get("checker_flags", {}).get("status_lines"),
                     "receipt_sha256": h})
        log(json.dumps(rows[-1]))
    out = {"at": K.now(), "parser_cases": parser, "parser_all_ok": all(p["ok"] for p in parser),
           "verdict_logic": logic, "verdict_logic_ok": logic == {"hash_mismatch_no_run": "FAIL",
                                                                  "no_bytes_no_run": "UNKNOWN"},
           "rows": rows, "all_match": all(r["matches_expectation"] for r in rows)}
    log("selfcheck summary sha256=%s all_match=%s parser_all_ok=%s" % (
        K.write_json_x(os.path.join(K.DESK, "receipts", TAG + "-selfcheck-summary.json"), out),
        out["all_match"], out["parser_all_ok"]))


def mode_run(cube):
    label = "%s-A_%s" % (TAG, cube)
    paths = {k: os.path.join(K.DESK, "receipts", label + s) for k, s in
             (("pre", ".pre.json"), ("launch", ".launch.json"), ("final", ".json"))}
    for p in paths.values():
        if os.path.lexists(p):
            raise SystemExit("exists: " + p)
    t0 = time.monotonic()
    pins, bad = K.pin_status()
    prod = K.producer_evidence(cube)
    pre = common("run")
    pre.update({"label": label, "cube": cube, "pins": pins, "pin_mismatch": bad, "producer": prod,
                "expected_cnf_sha256": K.EXPECTED_CNF[cube], "expected_base_cnf_sha256": K.BASE_CNF_SHA256,
                "planned": {"compose": [K.PY, "-I", "-B", os.path.join(K.SCRIPTS, "compose_v1.py"), cube],
                            "solver": [K.CADICAL, "-q", "-t", str(SOLVER_SECONDS), "/dev/fd/<cnf-pipe>",
                                       "fifo/%s.drat.fifo" % label],
                            "checker": [K.DRAT, "/dev/fd/<cnf-pipe>", "-i", "-t", str(CHECKER_SECONDS),
                                        "<stdin: fifo/%s.drat.fifo>" % label]}})
    pre_sha = K.write_json_x(paths["pre"], pre)
    log("%s pre-execution receipt sha256=%s scripts=%s" % (label, pre_sha, json.dumps(pre["scripts_sha256"])))
    final = {"label": label, "cube": cube, "encoder": "A", "pre_receipt_sha256": pre_sha,
             "started_at": pre["at"], "expected_cnf_sha256": K.EXPECTED_CNF[cube]}
    rec, regen, launch_sha = None, None, None
    if bad or not prod["consistent"]:
        final["not_launched"] = "pin mismatch %s / producer evidence inconsistent %s" % (bad, prod["checks"])
        hash_match = None
    else:
        cnf, info = K.regenerate(cube)
        regen = K.check_regen(cube, cnf, info, prod["meta_fields"])
        hash_match = regen["cnf_hash_match"]
        log("%s regenerated: sha256=%s match=%s seconds=%s" % (label, regen["cnf_sha256"], hash_match,
                                                                  info["seconds"]))
        if hash_match is not True:
            final["not_launched"] = "regenerated CNF %s" % ("hash mismatch" if hash_match is False else "missing")
        elif K.STOP["requested"]:
            final["not_launched"] = K.STOP["requested"]
            hash_match = True
        else:
            launch = {"label": label, "at": K.now(), "regen": regen,
                      "binaries_at_spawn": {"cadical": K.binary_record(K.CADICAL),
                                            "drat-trim": K.binary_record(K.DRAT)},
                      "lane_snapshot": K.lane_snapshot(), "gate_at_launch_receipt": K.gate("launch receipt")}
            launch_sha = K.write_json_x(paths["launch"], launch)
            final["binaries_at_spawn"] = launch["binaries_at_spawn"]
            log("%s launch receipt sha256=%s cadical=%s drat-trim=%s free=%d" % (
                label, launch_sha, launch["binaries_at_spawn"]["cadical"]["sha256"],
                launch["binaries_at_spawn"]["drat-trim"]["sha256"], launch["gate_at_launch_receipt"]["free_bytes"]))
            rec = K.pipeline(label, cnf, [K.CADICAL, "-q", "-t", str(SOLVER_SECONDS)], SOLVER_SECONDS,
                             CHECKER_SECONDS)
        del cnf
    pins_end, bad_end = K.pin_status()
    final.update({"launch_receipt_sha256": launch_sha, "regen": regen, "pipeline": rec,
                  "binaries_after": ({"cadical": K.binary_record(K.CADICAL), "drat-trim": K.binary_record(K.DRAT)}
                                     if rec else None),
                  "pins_end": pins_end, "pins_unchanged": pins_end == pins and not bad_end,
                  "scripts_sha256_end": K.script_hashes(),
                  "producer_solver_log_sha256": prod["receipt_fields"].get("solver_log_sha256"),
                  "solver_log_equals_producer": (rec.get("solver_log_sha256")
                                                 == prod["receipt_fields"].get("solver_log_sha256")) if rec and "solver_log_sha256" in rec else None,
                  "finished_at": K.now(), "driver_seconds": round(time.monotonic() - t0, 3)})
    final["verdict"] = K.verdict(hash_match, rec)
    final["verdict_rule"] = K.verdict.__doc__
    final["scope"] = ("Instance only: CNF regenerated from the pinned encoder A + K3 cube wrapper is UNSAT by a "
                      "streamed CaDiCaL DRAT proof checked by the parent-built drat-trim. No K3, M(7) or theorem "
                      "verdict.")
    h = K.write_json_x(paths["final"], final)
    brief = {"label": label, "verdict": final["verdict"], "cnf_hash_match": hash_match,
             "solver_rc": (rec or {}).get("children", {}).get("solver", {}).get("rc"),
             "checker_rc": (rec or {}).get("children", {}).get("checker", {}).get("rc"),
             "checker_status_lines": (rec or {}).get("checker_flags", {}).get("status_lines"),
             "safety_stop": (rec or {}).get("safety_stop_reason"), "deferred": (rec or {}).get("deferred"),
             "seconds": (rec or {}).get("pipeline_seconds"),
             "peak_aggregate_rss": (rec or {}).get("peak_sampled_aggregate_rss_bytes"),
             "free_start": (rec or {}).get("free_bytes_start"), "free_end": (rec or {}).get("free_bytes_end"),
             "receipt_sha256": h}
    log("RESULT " + json.dumps(brief))


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("regen", "selfcheck", "run"):
        raise SystemExit(__doc__)
    mode, args = sys.argv[1], sys.argv[2:]
    if mode in ("regen", "run") and (not args or any(c not in K.EXPECTED_CNF for c in args)):
        raise SystemExit("cubes must be among %s" % sorted(K.EXPECTED_CNF))
    if mode == "run" and len(args) != 1:
        raise SystemExit("run takes exactly one cube")
    signal.signal(signal.SIGTERM, _on_term)
    name = "%s-driver-%s%s.log" % (TAG, mode, "-" + "-".join(args) if args else "")
    LOGFD["fd"] = K.open_append_x(os.path.join(K.DESK, "logs", name))
    log("driver pid %d mode %s args %s" % (os.getpid(), mode, args))
    try:
        if mode == "regen":
            mode_regen(args)
        elif mode == "selfcheck":
            mode_selfcheck()
        else:
            mode_run(args[0])
    finally:
        log("driver exit")
        os.close(LOGFD["fd"])


if __name__ == "__main__":
    main()
