#!/usr/bin/env python3
"""SQS(v) invariant under Z_v ⋊ <multipliers>, derived design at 0 resolved with an
R-invariant resolution (R generated by --res-mult, R ≤ multiplier group, fixing 0).

Class structure is not guessed: if p (--anchor) is fixed by R, every class contains
exactly one triple through p, so the class orbits are in bijection with the R-orbits
of derived triples through p and the stabilizer of a class orbit equals that of its
anchor triple.  The i-th anchor orbit (sorted) is forced into the representative
class of class orbit i (lossless labelling).  --res-mult "" gives the unrestricted
anchored model.

Usage: mult_pipeline.py V OUT --mult m1,... [--res-mult r1,...] [--anchor p]
       [--samples K] [--seed0 S] [--res-timeout T] [--km-timeout T] [--workers W]
"""
import argparse
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from rdsqs_lib import (SQSKM, closure, decode_resolution, derived, kissat, resolution_cnf, transport,
                       verify_resolution, write_certificate)
import symres


def sym_model(der, pts, R, anchor):
    tset = set(der)
    seen, anchor_orbits = set(), []
    for t in sorted(t for t in der if anchor in t):
        if t in seen:
            continue
        orb = {symres.img(g, t) for g in R}
        seen |= orb
        anchor_orbits.append((t, [g for g in R if symres.img(g, t) == t]))
    stabs = [s for _, s in anchor_orbits]
    cnf, orbits, choice, cosets, stb = symres.build(der, pts, R, stabs)
    ident = tuple(range(len(R[0])))
    for i, (t, _) in enumerate(anchor_orbits):
        oi = next(j for j, (u, _) in enumerate(orbits) if u == t)
        forced = [o[0] for o in choice[oi] if o[1] == i and o[2] == ident]
        if not forced:
            cnf.add([])
        else:
            cnf.add([forced[0]])
    return cnf, orbits, choice, cosets, stb, [len(R) // len(s) for s in stabs]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("v", type=int)
    ap.add_argument("out")
    ap.add_argument("--mult", default="")
    ap.add_argument("--res-mult", default=None)
    ap.add_argument("--anchor", type=int, default=None)
    ap.add_argument("--samples", type=int, default=1)
    ap.add_argument("--seed0", type=int, default=0)
    ap.add_argument("--res-timeout", type=int, default=120)
    ap.add_argument("--km-timeout", type=int, default=600)
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args()
    v = a.v
    os.makedirs(a.out, exist_ok=True)
    mults = [int(m) for m in a.mult.split(",") if m]
    rmults = mults if a.res_mult is None else [int(m) for m in a.res_mult.split(",") if m]
    perm = lambda m: tuple((m * x) % v for x in range(v))
    gens = [tuple((x + 1) % v for x in range(v))] + [perm(m) for m in mults]
    R = closure([perm(m) for m in rmults], v) if rmults else [tuple(range(v))]
    t0 = time.time()
    M = SQSKM(v, gens)
    summ = {"v": v, "mult": mults, "res_mult": rmults, "R_order": len(R), "anchor": a.anchor,
            "km": M.summary(), "args": vars(a), "samples": []}
    print(json.dumps({"km": summ["km"], "R_order": len(R)}), flush=True)
    cnf, rv = M.cnf()
    pts = list(range(1, v))
    jobs = []
    for i in range(a.samples):
        p = os.path.join(a.out, f"km_{i}.cnf")
        sha = cnf.write(p)
        st, model, dt = kissat(p, a.km_timeout, seed=a.seed0 + i)
        rec = {"sample": i, "km_seed": a.seed0 + i, "km_cnf_sha256": sha, "km_status": st, "km_seconds": round(dt, 3)}
        summ["samples"].append(rec)
        if st != "SAT":
            print(json.dumps(rec), flush=True)
            break
        sel = [j for j, x in enumerate(rv) if x in model]
        rec["rows"] = sel
        cnf.add([-rv[j] for j in sel])
        blocks = M.blocks_of(sel)
        der = derived(blocks, 0)
        rp = os.path.join(a.out, f"res_{i}.cnf")
        if len(R) > 1:
            rc, orbits, choice, cosets, stb, osz = sym_model(der, pts, R, a.anchor)
            rec["class_orbit_sizes"] = sorted(osz)
            dec = ("sym", orbits, choice, cosets, stb)
        else:
            rc, tv = resolution_cnf(der, pts, (v - 2) // 2, anchor=a.anchor if a.anchor is not None else 1)
            dec = ("plain", tv)
        rec["res_cnf_sha256"] = rc.write(rp)
        rec["res_vars"] = rc.nv
        jobs.append((i, rp, der, blocks, dec))
    json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)

    def run(job):
        st, model, dt = kissat(job[1], a.res_timeout, seed=1, log=job[1] + ".log")
        return job, st, model, dt

    found = []
    G = None
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        for job, st, model, dt in ex.map(run, jobs):
            i, rp, der, blocks, dec = job
            rec = summ["samples"][i]
            rec["res_status"] = st
            rec["res_seconds"] = round(dt, 3)
            if st == "SAT":
                if dec[0] == "sym":
                    classes = symres.decode(model, dec[1], dec[2], dec[3], dec[4], R)
                else:
                    classes = decode_resolution(model, der, dec[1], (v - 2) // 2)
                verify_resolution(der, pts, classes)
                G = G or closure(gens, v)
                res = transport(G, {0: classes}, v)
                cert = os.path.join(a.out, f"rdsqs{v}_sample{i}.txt")
                rec["certificate_sha256"] = write_certificate(
                    cert, v, blocks, res, f"RDSQS({v}) candidate: Z{v} x| <{mults}>, R=<{rmults}>, sample {i}")
                chk = subprocess.run([sys.executable, os.path.join(HERE, "check_rdsqs.py"), cert],
                                     capture_output=True, text=True)
                rec["checker"] = json.loads(chk.stdout)["result"]
                found.append(i)
            print(json.dumps({k: rec[k] for k in rec if k != "rows"}), flush=True)
            json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)
    summ["found"] = found
    summ["total_seconds"] = round(time.time() - t0, 2)
    json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)
    print("FOUND", found, "total_seconds", summ["total_seconds"], flush=True)


if __name__ == "__main__":
    main()
