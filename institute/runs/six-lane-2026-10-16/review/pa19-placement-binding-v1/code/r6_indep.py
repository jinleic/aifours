#!/usr/bin/env python3
"""R6 parent-owned independent semantics for one-column P1 placements (stdlib only).

Shares no code with the lane enumerators extend_p1.py / extend_p1q.py / extend_b.py and does
not import networkx or nauty. The placement conditions are restated from the definitions
(lane README A3; they are necessary conditions of any valid PA(19,8,6) completion):

  * row r carries t(r) = set of P0 columns whose quad contains r, T(r) = |t(r)|;
  * a placement of one P1 column is a triple of disjoint row sets A, B (4 rows each), P (2 rows);
  * two rows of one block never already agree, i.e. never share a P0 quad;
  * e(r) = +1 on A and B, -1 on P, 0 elsewhere; with `left` further free P1 columns (each moves
    the row budget by at most one) every row needs
        T(r) + e(r) - left <= 2   and   T(r) + e(r) + left >= 2 - L.

Symmetry: placements are identified under the group generated by (i) permutations of rows with
equal P0 set, (ii) P0-column permutations preserving the multiset of row P0 sets, lifted to rows,
and (iii) the A/B swap. A placement's orbit under (i) is its count vector
{t: (a_t, b_t, p_t)} (rows of type t in A, B, P); the remaining group acts on count vectors.

Orbits are computed here by union-find over explicit group generators (not by canonical minima as
in extend_b, and not by graph isomorphism as in extend_p1/extend_p1q). Row-level controls
enumerate labeled placements directly from the row conditions, without the count-vector reduction.
"""
import itertools
from collections import Counter
from fractions import Fraction
from math import factorial


# ----------------------------------------------------------------------------- row frames
def _fill(c0, rows, empty, N):
    deg = Counter(v for t in rows for v in t)
    bad = [v for v in range(c0) if deg[v] > 4]
    if bad:
        raise ValueError("P0 column(s) %s in more than 4 listed rows" % bad)
    if any(v < 0 or v >= c0 for t in rows for v in t):
        raise ValueError("P0 column index out of range")
    rows = list(rows)
    for v in range(c0):
        rows += [frozenset([v])] * (4 - deg[v])
    rows += [frozenset()] * empty
    if len(rows) != N:
        raise ValueError("row count %d != N %d" % (len(rows), N))
    return rows


def m1_rows(c0, skel, N):
    """M1 row order: edge rows, hyperedge rows, private rows of each P0 column, empty rows."""
    rows = [frozenset(e) for e in skel["edges"]] + [frozenset(h) for h in skel["hyper"]]
    return _fill(c0, rows, skel["empty"], N)


def m2_rows(c0, types, empty, N):
    """M2 row order: listed types, private rows of each P0 column, empty rows."""
    return _fill(c0, [frozenset(t) for t in types], empty, N)


def skeleton_sanity(c0, rows):
    """Every P0 column has exactly 4 rows; listed rows have 2..3 P0 sets in the input; no two rows
    share two P0 columns (they would agree twice)."""
    deg = Counter(v for t in rows for v in t)
    out = {"column_degrees_all_4": all(deg[v] == 4 for v in range(c0)),
           "max_row_P0_set": max(len(t) for t in rows),
           "rows_sharing_two_columns": sum(1 for x, y in itertools.combinations(rows, 2) if len(x & y) >= 2)}
    out["ok"] = out["column_degrees_all_4"] and out["rows_sharing_two_columns"] == 0
    return out


# ----------------------------------------------------------------------------- symmetry
def perm_set(p, t):
    return frozenset(p[v] for v in t)


def isomorphisms(c0, rows_a, rows_b):
    """All P0-column permutations p with {p(t(r))} = {t(r')} as multisets (brute force, c0!)."""
    tb = Counter(rows_b)
    return [p for p in itertools.permutations(range(c0)) if Counter(perm_set(p, t) for t in rows_a) == tb]


def automorphisms(c0, rows):
    return isomorphisms(c0, rows, rows)


def _compose(a, b):  # a after b
    return tuple(a[x] for x in b)


def generating_set(auts, c0):
    """Greedy generating set; asserts that the generated group is exactly `auts`."""
    ident = tuple(range(c0))
    group = {ident}
    gens = []
    for g in auts:
        if g in group:
            continue
        gens.append(g)
        frontier = list(group)
        while frontier:
            nxt = []
            for x in frontier:
                for h in gens:
                    y = _compose(h, x)
                    if y not in group:
                        group.add(y)
                        nxt.append(y)
            frontier = nxt
    if group != set(auts):
        raise ValueError("automorphism list is not a group")
    return gens


def act(p, swap, v):
    return frozenset((perm_set(p, t), (c[1], c[0], c[2]) if swap else c) for t, c in v)


def transport(p, v):
    return frozenset((perm_set(p, t), c) for t, c in v)


# ----------------------------------------------------------------------------- count vectors
def budget_ok(T, e, L, left):
    return T + e - left <= 2 and T + e + left >= 2 - L


def count_vectors(rows, L, left):
    """Block-wise enumeration: multiset of types for A, then B, then P, then the e=0 rest check.
    Returns (set of count vectors, number of productions)."""
    cap = Counter(rows)
    types = sorted(cap, key=lambda t: (len(t), sorted(t)))

    def blocks(size, avail, e):
        cand = [t for t in types if avail[t] > 0 and budget_ok(len(t), e, L, left)]
        out = []

        def rec(i, need, used, chosen):
            if need == 0:
                out.append(dict(chosen))
                return
            if i == len(cand):
                return
            t = cand[i]
            if t:  # rows of a nonempty type share a quad: at most one, and disjoint from the block so far
                kmax = 0 if (t & used) else 1
            else:
                kmax = avail[t]
            for k in range(min(kmax, need), -1, -1):
                if k:
                    chosen[t] = k
                    rec(i + 1, need - k, used | t, chosen)
                    del chosen[t]
                else:
                    rec(i + 1, need, used, chosen)

        rec(0, size, frozenset(), {})
        return out

    X = set()
    produced = 0
    for A in blocks(4, cap, +1):
        rB = cap - Counter(A)
        for B in blocks(4, rB, +1):
            rP = rB - Counter(B)
            for P in blocks(2, rP, -1):
                rest = rP - Counter(P)
                if all(budget_ok(len(t), 0, L, left) for t in rest):
                    keys = set(A) | set(B) | set(P)
                    X.add(frozenset((t, (A.get(t, 0), B.get(t, 0), P.get(t, 0))) for t in keys))
                    produced += 1
    return X, produced


def vec_of(rows, A, B, P):
    v = {}
    for blk, k in ((A, 0), (B, 1), (P, 2)):
        for r in blk:
            c = list(v.get(rows[r], (0, 0, 0)))
            c[k] += 1
            v[rows[r]] = tuple(c)
    return frozenset(v.items())


def orbit_components(X, gens):
    """Union-find over X with the generators (each P0 generator, and the A/B swap)."""
    Xl = sorted(X, key=lambda v: sorted((sorted(t), c) for t, c in v))
    idx = {v: i for i, v in enumerate(Xl)}
    par = list(range(len(Xl)))

    def find(i):
        while par[i] != i:
            par[i] = par[par[i]]
            i = par[i]
        return i

    for i, v in enumerate(Xl):
        imgs = [act(g, False, v) for g in gens] + [act(tuple(range(64)), True, v)]
        for w in imgs:
            j = idx.get(w)
            if j is None:
                raise ValueError("X not closed under the symmetry group")
            a, b = find(i), find(j)
            if a != b:
                par[a] = b
    comp = {v: find(i) for i, v in enumerate(Xl)}
    return comp, len(set(comp.values()))


def burnside(X, auts):
    """Number of orbits of <auts> x <swap> on X by Burnside's lemma (exact Fraction)."""
    fixed = 0
    for p in auts:
        for s in (False, True):
            fixed += sum(1 for v in X if act(p, s, v) == v)
    return Fraction(fixed, 2 * len(auts))


# ----------------------------------------------------------------------------- row level
def row_errors(rows, L, left, A, B, P):
    N = len(rows)
    errs = []
    if not (len(A) == 4 and len(B) == 4 and len(P) == 2):
        errs.append("block sizes %d/%d/%d" % (len(A), len(B), len(P)))
    allr = list(A) + list(B) + list(P)
    if any((not isinstance(r, int)) or r < 0 or r >= N for r in allr):
        errs.append("row index out of range")
        return errs
    if len(set(allr)) != len(allr):
        errs.append("blocks not disjoint")
    for name, blk in (("A", A), ("B", B), ("P", P)):
        for x, y in itertools.combinations(blk, 2):
            if rows[x] & rows[y]:
                errs.append("%s rows %d,%d share a P0 quad" % (name, x, y))
    e = [0] * N
    for r in A:
        e[r] += 1
    for r in B:
        e[r] += 1
    for r in P:
        e[r] -= 1
    for r in range(N):
        if not budget_ok(len(rows[r]), e[r], L, left):
            errs.append("row %d budget T=%d e=%d" % (r, len(rows[r]), e[r]))
    return errs


def realize(rows, v):
    """Labeled placement with count vector v (rows of each type taken in index order)."""
    by = {}
    for r, t in enumerate(rows):
        by.setdefault(t, []).append(r)
    A, B, P = [], [], []
    for t, (a, b, p) in v:
        rs = by.get(t, [])
        if a + b + p > len(rs):
            return None
        A += rs[:a]
        B += rs[a:a + b]
        P += rs[a + b:a + b + p]
    return sorted(A), sorted(B), sorted(P)


def _multinomial(n, ks):
    r = factorial(n) // factorial(n - sum(ks))
    for k in ks:
        r //= factorial(k)
    return r


def weight_sum(X, rows):
    cap = Counter(rows)
    tot = 0
    for v in X:
        w = 1
        for t, c in v:
            w *= _multinomial(cap[t], c)
        tot += w
    return tot


def _row_level_parts(rows, L, left):
    N = len(rows)
    comp = [[x != y and not (rows[x] & rows[y]) for y in range(N)] for x in range(N)]

    def cliques(k, allowed):
        out = []

        def rec(start, chosen, mask):
            if len(chosen) == k:
                out.append(mask)
                return
            for r in range(start, N):
                if allowed[r] and all(comp[r][c] for c in chosen):
                    chosen.append(r)
                    rec(r + 1, chosen, mask | (1 << r))
                    chosen.pop()

        rec(0, [], 0)
        return out

    quads = cliques(4, [budget_ok(len(rows[r]), +1, L, left) for r in range(N)])
    pairs = cliques(2, [budget_ok(len(rows[r]), -1, L, left) for r in range(N)])
    bad_rest = 0
    for r in range(N):
        if not budget_ok(len(rows[r]), 0, L, left):
            bad_rest |= 1 << r
    return quads, pairs, bad_rest


def row_level_count(rows, L, left):
    """Number of labeled placements, enumerated at row level."""
    quads, pairs, bad_rest = _row_level_parts(rows, L, left)
    memo = {}
    tot = 0
    for A in quads:
        for B in quads:
            if A & B:
                continue
            U = A | B
            c = memo.get(U)
            if c is None:
                c = sum(1 for P in pairs if not (P & U) and not (bad_rest & ~(U | P)))
                memo[U] = c
            tot += c
    return tot


def _bits(mask):
    out = []
    while mask:
        low = mask & -mask
        out.append(low.bit_length() - 1)
        mask ^= low
    return out


def row_level_orbits(rows, L, left, auts):
    """Labeled placements (row level) and their orbits by union-find under row generators:
    adjacent transpositions within each P0 type, every automorphism lifted to rows, A/B swap.
    Returns (labeled count, #orbits under within-type permutations, #orbits under the full group,
    set of count vectors of the labeled placements)."""
    N = len(rows)
    quads, pairs, bad_rest = _row_level_parts(rows, L, left)
    lst = []
    for A in quads:
        for B in quads:
            if A & B:
                continue
            U = A | B
            for P in pairs:
                if not (P & U) and not (bad_rest & ~(U | P)):
                    lst.append((A, B, P))
    idx = {x: i for i, x in enumerate(lst)}
    by = {}
    for r, t in enumerate(rows):
        by.setdefault(t, []).append(r)
    within = []
    for rs in by.values():
        for i in range(len(rs) - 1):
            s = list(range(N))
            s[rs[i]], s[rs[i + 1]] = rs[i + 1], rs[i]
            within.append(s)
    lifted = []
    for p in auts:
        s = [None] * N
        for t, rs in by.items():
            img = by[perm_set(p, t)]
            for a, b in zip(rs, img):
                s[a] = b
        if sorted(s) != list(range(N)):
            raise ValueError("lifted automorphism is not a row permutation")
        lifted.append(s)

    def pm(s, mask):
        out = 0
        for r in _bits(mask):
            out |= 1 << s[r]
        return out

    def ncomp(perms, swap):
        par = list(range(len(lst)))

        def find(i):
            while par[i] != i:
                par[i] = par[par[i]]
                i = par[i]
            return i

        for i, (A, B, P) in enumerate(lst):
            imgs = [(pm(s, A), pm(s, B), pm(s, P)) for s in perms]
            if swap:
                imgs.append((B, A, P))
            for y in imgs:
                j = idx[y]
                a, b = find(i), find(j)
                if a != b:
                    par[a] = b
        return len({find(i) for i in range(len(lst))})

    vecs = {vec_of(rows, _bits(A), _bits(B), _bits(P)) for A, B, P in lst}
    return len(lst), ncomp(within, False), ncomp(within + lifted, True), vecs


# ----------------------------------------------------------------------------- list checks
def check_list(rows, L, left, X, comp, norb, entries):
    """entries: list of (A, B, P). Validity at row level, membership in X, orbit coverage."""
    invalid = []
    not_in_X = []
    hits = {}
    comp_of = []
    for i, (A, B, P) in enumerate(entries):
        errs = row_errors(rows, L, left, A, B, P)
        if errs:
            invalid.append([i, errs[:5]])
        v = vec_of(rows, A, B, P) if not errs else None
        c = comp.get(v) if v is not None else None
        if v is not None and c is None:
            not_in_X.append(i)
        comp_of.append(c)
        if c is not None:
            hits.setdefault(c, []).append(i)
    dups = [ix for ix in hits.values() if len(ix) > 1]
    res = {"entries": len(entries), "invalid": invalid, "not_in_X": not_in_X,
           "orbits_hit": len(hits), "orbits_total": norb, "missing_orbits": norb - len(hits),
           "duplicate_orbit_groups": dups}
    res["bijective_with_orbits"] = (not invalid and not not_in_X and not dups and len(hits) == norb
                                    and len(entries) == norb)
    return res, comp_of
