#!/usr/bin/env python3
"""
sym_depol.py -- parent-side INDEPENDENT evaluator of the coherent information
I_c(rho, D_eta^{(x)M}) = S(B) - S(RB) for inputs rho = sum_i q_i |phi_i><phi_i|
with phi_i in the symmetric subspace Sym^M (Dicke basis |M;x>, x = #ones),
D_eta(X) = eta X + (1-eta) tr(X) I/2   (p = 3(1-eta)/4).

Route (full derivation in ../README.md; no worker code was read before this
file was written):
  1. Schur-Weyl block r (spin J = M/2 - r, multiplicity m_r = C(M,r)-C(M,r-1))
     of D^{(x)M}(X) is unitarily equivalent -- with an X-independent intertwiner --
     to   c_r * S_N(tr_{2r} X),  N = M-2r,  c_r = (f(1-f))^r,  f = (1-eta)/2,
     S_N(Z) = Pi_N D^{(x)N}(Z) Pi_N.  (Contract with |u> -> |psi^->^{(x)r}|u>;
     singlets are annihilated by Pi_sym, so of (D(x)D)(singlet) = eta^2 singlet +
     (1-eta^2) I/4 only the (1-eta^2) I/4 part survives.)
  2. S_N in the Dicke basis from the 4-letter ket/bra string expansion:
       S_N(Z)[b+Q,b] = sum_l eta^(2l+Q) g_l(b) sum_y B_{N-2l-Q}(b-l, y-l) g_l(y) Z[y+Q,y]
     g_l(y)^2 = C(y+Q,l+Q) C(N-y-Q,l) / C(N,y)   (hypergeometric pmf in l),
     B_m = Sym^m([[1-f,f],[f,1-f]]) in the Dicke basis (all entries >= 0),
     generated by the positive recursion of the generating polynomial
     ((1-f)(1+pq) + f(p+q))^m.
  3. Block weights are input independent:  p_r = m_r c_r lambda0(N) tr(X),
     lambda0(N) = ((1-f)^(N+1) - f^(N+1)) / (1-2f).
  4. I_c = sum_r p_r [S(rho_r^B) - S(rho_r^RB)]   (H(p), log m_r cancel exactly).
Everything is float64 except the log-factorial table (mpmath, split hi+lo so that
signed sums of <= 9 table entries are exact).
"""
import math
import numpy as np
import mpmath


# --------------------------------------------------------------------------- helpers
class LogFact:
    """log(n!) = hi[n] + lo[n]; hi on the dyadic grid 2^-35 (exact signed sums of <=9
    entries below 2^14 in float64), lo = remainder (|lo| < 2^-36)."""

    def __init__(self, nmax, dps=50):
        mpmath.mp.dps = dps
        self.nmax = nmax
        self.hi = np.zeros(nmax + 1)
        self.lo = np.zeros(nmax + 1)
        scale = mpmath.mpf(2) ** 35
        for n in range(nmax + 1):
            v = mpmath.loggamma(n + 1)
            h = mpmath.nint(v * scale) / scale
            self.hi[n] = float(h)
            self.lo[n] = float(v - h)
        assert self.hi[-1] < 2.0 ** 14, "table too large for exact dyadic sums"

    def combo(self, plus, minus):
        Lhi = 0.0
        Llo = 0.0
        for a in plus:
            Lhi = Lhi + self.hi[a]
            Llo = Llo + self.lo[a]
        for a in minus:
            Lhi = Lhi - self.hi[a]
            Llo = Llo - self.lo[a]
        return Lhi, Llo

    def exp_half(self, plus, minus):
        Lhi, Llo = self.combo(plus, minus)
        return np.exp(0.5 * Lhi) * np.exp(0.5 * Llo)

    def logval(self, plus, minus):
        Lhi, Llo = self.combo(plus, minus)
        return Lhi + Llo


def entropy_nats(ev):
    ev = ev[ev > 0.0]
    return float(-np.sum(ev * np.log(ev)))


# --------------------------------------------------------------------------- B_m windows
class BWindows:
    """B_m = Sym^m(A), A=[[1-f,f],[f,1-f]], Dicke basis, rows k' in [0,R], cols k in [0,C].
    Positive recursion (coefficient extraction of ((1-f)(1+pq)+f(p+q))^(m+1)):
      B_{m+1}(k',k) = [ (1-f) s(k')s(k) B_m(k',k) + f t(k')s(k) B_m(k'-1,k)
                       + f s(k')t(k) B_m(k',k-1) + (1-f) t(k')t(k) B_m(k'-1,k-1) ] / (m+1)
      s(j)=sqrt(max(m+1-j,0)), t(j)=sqrt(j).
    Stores only m >= keep_from (sliding window)."""

    def __init__(self, f, R, C):
        self.f = float(f)
        self.g = 1.0 - self.f
        self.R, self.C = R, C
        self.m = 0
        B = np.zeros((R + 1, C + 1))
        B[0, 0] = 1.0
        self.cur = B
        self.store = {0: B}
        self.keep_from = 0
        self.kr = np.arange(R + 1, dtype=float)
        self.kc = np.arange(C + 1, dtype=float)
        self.tr = np.sqrt(self.kr)
        self.tc = np.sqrt(self.kc)

    def _step(self):
        m, B, f, g = self.m, self.cur, self.f, self.g
        sr = np.sqrt(np.maximum(m + 1 - self.kr, 0.0))
        sc = np.sqrt(np.maximum(m + 1 - self.kc, 0.0))
        out = g * (sr[:, None] * sc[None, :]) * B
        out[1:, :] += f * (self.tr[1:, None] * sc[None, :]) * B[:-1, :]
        out[:, 1:] += f * (sr[:, None] * self.tc[None, 1:]) * B[:, :-1]
        out[1:, 1:] += g * (self.tr[1:, None] * self.tc[None, 1:]) * B[:-1, :-1]
        out *= 1.0 / (m + 1)
        self.m = m + 1
        self.cur = out
        if self.m >= self.keep_from:
            self.store[self.m] = out

    def set_keep_from(self, mmin):
        self.keep_from = mmin
        for k in [k for k in self.store if k < mmin]:
            del self.store[k]

    def get(self, m):
        while self.m < m:
            self._step()
        return self.store[m]


def B_direct(m, kp, k, f, lf):
    """Closed form (all-positive sum) for a single entry, used only for cross-checks:
    B_m(k',k) = (1-f)^m sqrt(k!(m-k)!k'!(m-k')!) sum_j rho^(k+k'-2j)/(j!(k-j)!(k'-j)!(m-k-k'+j)!)"""
    if k > m or kp > m:
        return 0.0
    rho = f / (1 - f)
    js = np.arange(max(0, k + kp - m), min(k, kp) + 1)
    if js.size == 0:
        return 0.0
    base = 0.5 * (lf.logval([k, m - k, kp, m - kp], []))
    terms = [base + m * math.log(1 - f) + (k + kp - 2 * j) * math.log(rho)
             - lf.logval([j, k - j, kp - j, m - k - kp + j], []) for j in js]
    mx = max(terms)
    return math.exp(mx) * math.fsum(math.exp(t - mx) for t in terms)


# --------------------------------------------------------------------------- partial trace
def partial_trace_factor(phi, M, r, lf):
    """A[w, x'] = h_r(w; x'+w) * phi[x'+w], h_r(w;x)^2 = C(2r,w) C(N,x-w)/C(M,x),
    so tr_{2r}(|phi><chi|) = A_phi^T conj(A_chi) on Sym^N (Dicke basis)."""
    N = M - 2 * r
    L = len(phi) - 1                     # support x in [0, L]
    Xp = min(L, N)
    W = min(2 * r, L)
    w = np.arange(W + 1)[:, None]
    xp = np.arange(Xp + 1)[None, :]
    x = xp + w
    valid = x <= L
    xc = np.where(valid, x, 0)
    h = lf.exp_half([2 * r + 0 * xc, N + 0 * xc, xc, M - xc],
                    [w + 0 * xc, 2 * r - w + 0 * xc, xp + 0 * xc, N - xp + 0 * xc, M + 0 * xc])
    A = np.where(valid, h * np.asarray(phi)[xc], 0.0)
    return A


# --------------------------------------------------------------------------- S_N
def apply_SN(Zs, N, eta, Bget, Dout, lf):
    """Zs: (nop, X+1, X+1) operators on Sym^N (Dicke basis, support <= X <= N).
    Returns Osec (nop, X+1, Dout+1) with Osec[op,Q,b] = S_N(Z_op)[b+Q, b] for b+Q <= Dout."""
    nop, X1, _ = Zs.shape
    X = X1 - 1
    Dout = min(Dout, N)
    Zsec = np.zeros((nop, X + 1, X + 1), dtype=Zs.dtype)
    for Q in range(X + 1):
        Zsec[:, Q, :X + 1 - Q] = np.diagonal(Zs, offset=-Q, axis1=1, axis2=2)
    Osec = np.zeros((nop, X + 1, Dout + 1), dtype=Zs.dtype)
    for d in range(0, 2 * X + 1):
        m = N - d
        if m < 0:
            break
        l_lo, l_hi = max(0, d - X), d // 2
        if l_lo > l_hi:
            continue
        Kin = min(X - d + l_hi, m)
        Kout = min(Dout - d + l_hi, m)
        if Kin < 0 or Kout < 0:
            continue
        ls = np.arange(l_lo, l_hi + 1)
        Qs = d - 2 * ls
        Kmax = max(Kin, Kout)
        L2 = ls[:, None]
        Q2 = Qs[:, None]
        y = L2 + np.arange(Kmax + 1)[None, :]
        valid = (N - y - Q2 - L2) >= 0
        yc = np.where(valid, y, 0)
        Lc = np.where(valid, L2, 0) + 0 * yc
        Qc = np.where(valid, Q2, 0) + 0 * yc
        g = lf.exp_half([yc + Qc, N - yc - Qc, yc, N - yc],
                        [Lc + Qc, yc - Lc, Lc, N - yc - Qc - Lc, N + 0 * yc])
        g = np.where(valid, g, 0.0)
        npairs = ls.size
        Fin = g[None, :, :Kin + 1] * Zsec[:, Qs[:, None], y[:, :Kin + 1]]
        Fmat = Fin.reshape(nop * npairs, Kin + 1).T
        Bm = Bget(m)[:Kout + 1, :Kin + 1]
        OUT = (Bm @ Fmat).T.reshape(nop, npairs, Kout + 1)
        contrib = (eta ** d) * g[None, :, :Kout + 1] * OUT
        bidx = L2 + np.arange(Kout + 1)[None, :]
        Osec[:, Qs[:, None], bidx] += contrib
    return Osec


def assemble(Osec_lower, Osec_upper, Dout):
    """Y[b+Q,b] = Osec_lower[Q,b];  Y[b,b+Q] = conj(Osec_upper[Q,b]) (Q>0)."""
    X1 = Osec_lower.shape[0]
    Y = np.zeros((Dout + 1, Dout + 1), dtype=Osec_lower.dtype)
    for Q in range(min(X1 - 1, Dout) + 1):
        n = Dout + 1 - Q
        idx = np.arange(n)
        Y[idx + Q, idx] = Osec_lower[Q, :n]
        if Q > 0:
            Y[idx, idx + Q] = np.conj(Osec_upper[Q, :n])
    return Y


# --------------------------------------------------------------------------- weights
def log_block_weights(M, eta, lf):
    """log p_r for r = 0..floor(M/2):  p_r = m_r c_r lambda0(M-2r)  (tr X = 1)."""
    f = (1.0 - eta) / 2.0
    out = []
    for r in range(M // 2 + 1):
        N = M - 2 * r
        lm = lf.logval([M], [r, M - r]) + math.log((M - 2 * r + 1) / (M - r + 1))
        lc = r * math.log(f * (1 - f))
        ll0 = (N + 1) * math.log(1 - f) + math.log1p(-(f / (1 - f)) ** (N + 1)) - math.log(1 - 2 * f)
        out.append(lm + lc + ll0)
    return np.array(out)


# --------------------------------------------------------------------------- driver
def coherent_information(phis, qs, M, eta, Dout=None, rs=None, lf=None, verbose=False,
                         keep_blocks=False, tail_logp=-60.0):
    """phis: list of two Dicke-amplitude vectors (length <= M+1); qs: two weights.
    Returns dict with I_c (nats and bits) and per-block diagnostics."""
    assert len(phis) == 2 and len(qs) == 2
    phis = [np.asarray(p) for p in phis]
    Lsup = max(len(p) for p in phis) - 1
    phis = [np.concatenate([p, np.zeros(Lsup + 1 - len(p), dtype=p.dtype)]) for p in phis]
    cplx = any(np.iscomplexobj(p) for p in phis)
    if Dout is None:
        Dout = M
    if lf is None:
        lf = LogFact(M + 2)
    f = (1.0 - eta) / 2.0
    logp = log_block_weights(M, eta, lf)
    if rs is None:
        rs = [r for r in range(M // 2 + 1) if logp[r] > tail_logp]
    rs = sorted(rs, reverse=True)                     # ascending N for the sliding B window
    Xin = Lsup
    Bw = BWindows(f, min(Dout, M), min(Xin, M))
    q1, q2 = qs
    s12 = math.sqrt(q1 * q2)
    res = []
    for r in rs:
        N = M - 2 * r
        Bw.set_keep_from(max(0, N - 2 * min(Xin, N)))
        A = [partial_trace_factor(p, M, r, lf) for p in phis]
        Z11 = A[0].T @ np.conj(A[0])
        Z22 = A[1].T @ np.conj(A[1])
        Z12 = A[0].T @ np.conj(A[1])
        Z21 = A[1].T @ np.conj(A[0])
        Zs = np.stack([Z11, Z22, Z12, Z21])
        if not cplx:
            Zs = Zs.real
        Dr = min(Dout, N)
        Osec = apply_SN(Zs, N, eta, Bw.get, Dr, lf)
        Y11 = assemble(Osec[0], Osec[0], Dr)
        Y22 = assemble(Osec[1], Osec[1], Dr)
        Y12 = assemble(Osec[2], Osec[3], Dr)
        YB = q1 * Y11 + q2 * Y22
        YRB = np.block([[q1 * Y11, s12 * Y12], [s12 * np.conj(Y12.T), q2 * Y22]])
        t = float(np.real(np.trace(YB)))
        t_exact = math.exp(logp[r] - (lf.logval([M], [r, M - r]) + math.log((M - 2 * r + 1) / (M - r + 1))
                                      + r * math.log(f * (1 - f))))
        evB = np.linalg.eigvalsh(YB / t)
        evRB = np.linalg.eigvalsh(YRB / t)
        SB, SRB = entropy_nats(evB), entropy_nats(evRB)
        rec = dict(r=r, N=N, logp=float(logp[r]), p=float(math.exp(logp[r])),
                   SB=SB, SRB=SRB, dS=SB - SRB,
                   trace_window=t, trace_exact_lambda0=t_exact,
                   deficit=1.0 - t / t_exact,
                   min_evB=float(evB.min()), min_evRB=float(evRB.min()),
                   diag_tail=float(np.real(np.diag(YB))[-1] / t))
        if keep_blocks:
            rec['YB'] = YB / t
            rec['YRB'] = YRB / t
        res.append(rec)
        if verbose:
            print("r=%4d N=%5d p=%.3e dS=% .12e deficit=% .2e" % (r, N, rec['p'], rec['dS'], rec['deficit']),
                  flush=True)
    res.sort(key=lambda d: d['r'])
    Ic = math.fsum(d['p'] * d['dS'] for d in res)
    covered = math.fsum(d['p'] for d in res)
    total = math.fsum(math.exp(v) for v in logp)
    return dict(M=M, eta=eta, Dout=Dout, Xin=Xin, Ic_nats=Ic, Ic_bits=Ic / math.log(2),
                p_covered=covered, p_total_allr=total, p_excluded=max(0.0, 1.0 - covered),
                blocks=res)
