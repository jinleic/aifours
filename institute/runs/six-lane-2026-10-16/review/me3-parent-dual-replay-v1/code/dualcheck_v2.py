class Ctx:
    """Constants for a given T (kappa = 1/(1+T) must exceed 1/2)."""

    def __init__(self, T):
        self.T = T
        self.kq = 1 / (1 + T)
        if not self.kq > fmpq(1, 2):
            raise ValueError("kappa <= 1/2")
        self.K = arb(self.kq)
        self.C0 = (2 * self.K - 1).sqrt()
        self.PI = arb.pi()
        self.TWOPI = 2 * self.PI
        self.HALFPI = self.PI / 2
        self.IC_P = acb(ONE, self.C0)
        self.IC_M = acb(ONE, -self.C0)
        self.IU = acb(ZERO, ONE)


