EVAL = {"LW": ev_LW, "G": ev_G, "LD1": ev_LD1, "LD2": ev_LD2, "C": ev_SWC, "B": ev_SWB}


def skip_ok(C, kind, box, tag):
    if kind == "G":
        return skip_G(box, tag)
    if kind == "LD2":
        return skip_LD2(C, box, tag)
    return False


def split_dims(cell, wts, n):
    """Split coordinate sequence for a cell (depends only on depth: widths halve deterministically)."""
    sc = [(cell[i][1] - cell[i][0]) * wts[i] for i in range(3)]
    dims = []
    for _ in range(n):
        best = 0
        for i in (1, 2):
            if sc[i] > sc[best]:
                best = i
        dims.append(best)
        sc[best] = sc[best] / 2
    return dims


def leaf_box(cell, dims, path):
    k = [0, 0, 0]
    m = [0, 0, 0]
    for t, ch in enumerate(path):
        i = dims[t]
        k[i] = 2 * k[i] + (1 if ch == "1" else 0)
        m[i] += 1
    out = []
    for i in range(3):
        lo, hi = cell[i]
        wd = hi - lo
        den = 1 << m[i]
        out.append((lo + wd * fmpq(k[i], den), lo + wd * fmpq(k[i] + 1, den)))
    return tuple(out)


def is_successor(prev, cur):
    k = len(prev.rstrip("1"))
    if k == 0:
        return False
    q = prev[:k - 1]
    if not cur.startswith(q + "1"):
        return False
    rest = cur[k:]
    return rest.count("0") == len(rest)


def certify(ev, C, box, depth, dims, extra_left):
    """Returns (n_leaves, {method: count}, extra_depth_used) or None."""
    ok, how = ev(C, box)
    if ok:
        return 1, {how: 1}, 0
    if extra_left <= 0:
        return None
    i = dims[depth]
    lo, hi = box[i]
    mid = (lo + hi) / 2
    b0, b1 = list(box), list(box)
    b0[i], b1[i] = (lo, mid), (mid, hi)
    r0 = certify(ev, C, tuple(b0), depth + 1, dims, extra_left - 1)
    if r0 is None:
        return None
    r1 = certify(ev, C, tuple(b1), depth + 1, dims, extra_left - 1)
    if r1 is None:
        return None
    meth = dict(r0[1])
    for k_, v_ in r1[1].items():
        meth[k_] = meth.get(k_, 0) + v_
    return r0[0] + r1[0], meth, 1 + max(r0[2], r1[2])


def load_chart(spec, chart):
    cs = spec["charts"][chart]
    kind, dom = DOMAINS[chart]
    problems = []
    if cs["kind"] != kind:
        problems.append("kind %r != expected %r" % (cs["kind"], kind))
    bps = [[Q(v) for v in dim] for dim in cs["breakpoints"]]
    for i in range(3):
        if any(not (bps[i][j] < bps[i][j + 1]) for j in range(len(bps[i]) - 1)):
            problems.append("breakpoints of dim %d not strictly increasing" % i)
        if bps[i][0] != Q(dom[i][0]) or bps[i][-1] != Q(dom[i][1]):
            problems.append("dim %d range [%s, %s] != claimed [%s, %s]" % (i, bps[i][0], bps[i][-1], dom[i][0], dom[i][1]))
    for k_, v_ in PARAMS.get(chart, {}).items():
        if k_ not in cs.get("params", {}) or Q(cs["params"][k_]) != Q(v_):
            problems.append("param %s != %s" % (k_, v_))
    wts = [Q(w) for w in cs["split_weights"]]
    if any(not (w > 0) for w in wts):
        problems.append("nonpositive split weight")
    cells = []
    for a in range(len(bps[0]) - 1):
        for b in range(len(bps[1]) - 1):
            for c in range(len(bps[2]) - 1):
                cells.append(((bps[0][a], bps[0][a + 1]), (bps[1][b], bps[1][b + 1]), (bps[2][c], bps[2][c + 1])))
    return kind, cells, wts, int(cs["max_depth"]), problems


def run_lines(lines, chart, spec, C, cell_lo, cell_hi, extra_depth, sub_write, progress=None, max_errors=200,
              ev_override=None):
    """Stream leaf lines. Returns result dict (tiling audit for all cells; evaluation for cells in [cell_lo, cell_hi))."""
    kind, cells, wts, maxdepth, problems = load_chart(spec, chart)
    ev = ev_override if ev_override is not None else EVAL[kind]
    ncell = len(cells)
    if cell_hi is None or cell_hi > ncell:
        cell_hi = ncell
    errors = []
    failures = []

    def err(msg):
        if len(errors) < max_errors:
            errors.append(msg)

    def fail(rec):
        failures.append(rec if len(failures) < max_errors else None)

    counts = {}
    table = {}
    subdiv = {"leaves": 0, "subleaves": 0, "max_extra_depth": 0, "methods": {}}
    skip_checked = 0
    evaluated = 0
    nlines = 0
    maxd = 0
    cur = -1
    prev = None
    dims = None
    t0 = time.time()
    for raw in lines:
        nlines += 1
        parts = raw.split()
        if len(parts) != 3:
            err("line %d malformed" % nlines)
            continue
        try:
            ci = int(parts[0])
        except ValueError:
            err("line %d bad cell" % nlines)
            continue
        path = "" if parts[1] == "-" else parts[1]
        out = parts[2]
        if parts[1] != "-" and (path.count("0") + path.count("1") != len(path) or not path):
            err("line %d bad path %r" % (nlines, parts[1]))
            continue
        counts[out] = counts.get(out, 0) + 1
        if ci != cur:
            if cur >= 0 and prev is not None and prev.count("1") != len(prev):
                err("cell %d ends at %r: gap (incomplete tiling)" % (cur, prev))
            if ci != cur + 1:
                err("cell order: %d follows %d" % (ci, cur))
            if not (0 <= ci < ncell):
                err("cell index %d out of range" % ci)
                cur, prev = ci, path
                continue
            cur = ci
            if path.count("0") != len(path):
                err("cell %d starts at %r: gap (first leaf not leftmost)" % (ci, path))
            dims = split_dims(cells[ci], wts, maxdepth + extra_depth + 1)
        else:
            if not is_successor(prev, path):
                err("cell %d: %r does not follow %r (gap or overlap)" % (ci, path, prev))
        prev = path
        maxd = max(maxd, len(path))
        if not (0 <= ci < ncell):
            continue
        if len(path) > maxdepth:
            err("cell %d path %r deeper than max_depth %d" % (ci, path, maxdepth))
            fail({"cell": ci, "path": path, "outcome": out, "why": "deeper than max_depth"})
            continue
        if not (cell_lo <= ci < cell_hi):
            continue
        box = leaf_box(cells[ci], dims, path)
        evaluated += 1
        if out.startswith("SKIP:"):
            if skip_ok(C, kind, box, out):
                skip_checked += 1
                key = (out, "skip-rule-ok")
            else:
                key = (out, "INVALID-SKIP")
                fail({"cell": ci, "path": path or "-", "outcome": out, "why": "skip rule false",
                      "box": [[str(a_), str(b_)] for a_, b_ in box]})
        elif out.startswith("CERT:"):
            r = certify(ev, C, box, len(path), dims, extra_depth)
            if r is None:
                key = (out, "UNPROVED")
                fail({"cell": ci, "path": path or "-", "outcome": out, "why": "no test passed",
                      "box": [[str(a_), str(b_)] for a_, b_ in box]})
            elif r[0] == 1:
                key = (out, next(iter(r[1])))
            else:
                key = (out, "subdivided")
                subdiv["leaves"] += 1
                subdiv["subleaves"] += r[0]
                subdiv["max_extra_depth"] = max(subdiv["max_extra_depth"], r[2])
                for k_, v_ in r[1].items():
                    subdiv["methods"][k_] = subdiv["methods"].get(k_, 0) + v_
                sub_write("%d %s %s %d %d %s\n" % (ci, path or "-", out, r[0], r[2],
                                                   ",".join("%s=%d" % kv for kv in sorted(r[1].items()))))
        else:
            key = (out, "FAIL-LABEL")
            fail({"cell": ci, "path": path or "-", "outcome": out, "why": "non-certificate label"})
        table[key] = table.get(key, 0) + 1
        if progress and evaluated % 500000 == 0:
            progress(evaluated, time.time() - t0)
    if cur >= 0 and prev is not None and prev.count("1") != len(prev):
        err("cell %d ends at %r: gap (incomplete tiling)" % (cur, prev))
    if cur != ncell - 1:
        err("last cell %d != %d (missing cells)" % (cur, ncell - 1))
    return {
        "chart": chart, "kind": kind, "cells": ncell, "evaluated_cells": [cell_lo, cell_hi],
        "lines": nlines, "max_depth_seen": maxd, "spec_problems": problems,
        "tiling_errors": errors,
        "claimed_counts": counts,
        "verification_table": {"%s -> %s" % k_: v_ for k_, v_ in sorted(table.items())},
        "evaluated_leaves": evaluated, "skip_rule_ok": skip_checked,
        "subdivision": subdiv, "n_failures": len(failures),
        "failures_first": [f for f in failures if f is not None][:max_errors],
        "eval_seconds": round(time.time() - t0, 2),
    }


def sha256_file(path):
    h = hashlib.sha256()
    n = 0
    with open(path, "rb") as fh:
        while True:
            b = fh.read(1 << 20)
            if not b:
                break
            h.update(b)
            n += len(b)
    return h.hexdigest(), n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pin", required=True)
    ap.add_argument("--chart", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--sub-log", required=True)
    ap.add_argument("--log", required=True)
    ap.add_argument("--cells", default=None)
    ap.add_argument("--extra-depth", type=int, default=12)
    ap.add_argument("--T", default="11/50")
    a = ap.parse_args()
    t_start = time.time()
    logf = open(a.log, "x")

    def log(*xs):
        logf.write(" ".join(str(x) for x in xs) + "\n")
        logf.flush()

    pin = json.load(open(a.pin))
    ent = pin["charts"][a.chart]
    res = {"tool": "dualcheck_v2.py", "tool_sha256": sha256_file(os.path.abspath(__file__))[0],
           "flint": flint.__version__, "prec": PREC, "T": a.T, "argv": sys.argv[1:],
           "pin": {"path": a.pin, "sha256": sha256_file(a.pin)[0]},
           "started": time.strftime("%Y-%m-%dT%H:%M:%S%z")}
    log("start", res["started"], a.chart)
    bind = {}
    for key in ("spec", "leaves", "dual", "post_receipt"):
        sh, nb = sha256_file(ent[key]["path"])
        bind[key] = {"path": ent[key]["path"], "sha256": sh, "bytes": nb, "pinned": ent[key]["sha256"],
                     "match": sh == ent[key]["sha256"]}
    post = json.load(open(ent["post_receipt"]["path"]))
    outs = post["outputs_sha256"]
    rel_leaves = [k for k in outs if k.endswith("/leaves.txt.gz")]
    rel_dual = [k for k in outs if k.endswith("/dual.json")]
    bind["post_receipt_binds_leaves"] = (len(rel_leaves) == 1
                                         and outs[rel_leaves[0]]["sha256"] == bind["leaves"]["sha256"]
                                         and outs[rel_leaves[0]]["bytes"] == bind["leaves"]["bytes"])
    bind["post_receipt_binds_dual"] = (len(rel_dual) == 1 and outs[rel_dual[0]]["sha256"] == bind["dual"]["sha256"])
    bind["post_receipt_exit_code"] = post.get("exit_code")
    res["binding"] = bind
    if not all(bind[k]["match"] for k in ("spec", "leaves", "dual", "post_receipt")):
        res["verdict"] = "INPUT-MISMATCH"
        with open(a.out, "x") as fh:
            json.dump(res, fh, indent=1)
        log("INPUT-MISMATCH")
        raise SystemExit(2)
    spec = json.load(open(ent["spec"]["path"]))
    dual = json.load(open(ent["dual"]["path"]))
    C = Ctx(Q(a.T))
    if a.cells:
        lo_s, hi_s = a.cells.split(":")
        cell_lo, cell_hi = int(lo_s), int(hi_s)
    else:
        cell_lo, cell_hi = 0, None
    hasher = hashlib.sha256()

    def lines():
        with gzip.open(ent["leaves"]["path"], "rb") as fh:
            for bline in fh:
                hasher.update(bline)
                yield bline.decode("ascii")

    def progress(n, sec):
        log("progress", a.chart, n, round(sec, 1), time.strftime("%H:%M:%S"))

    with gzip.GzipFile(fileobj=open(a.sub_log, "xb"), mode="wb", mtime=0) as sub:
        r = run_lines(lines(), a.chart, spec, C, cell_lo, cell_hi, a.extra_depth,
                      lambda s_: sub.write(s_.encode()), progress)
    res.update(r)
    res["leaf_lines_sha256"] = hasher.hexdigest()
    res["leaf_lines_sha256_claimed"] = dual.get("leaf_lines_sha256")
    res["leaf_lines_match"] = res["leaf_lines_sha256"] == dual.get("leaf_lines_sha256")
    res["claimed_counts_match_dual"] = r["claimed_counts"] == dual.get("counts")
    res["dual_certificate_ok_claim"] = dual.get("certificate_ok")
    sh2, nb2 = sha256_file(ent["leaves"]["path"])
    res["leaves_rehash_after"] = {"sha256": sh2, "bytes": nb2, "unchanged": sh2 == bind["leaves"]["sha256"]}
    full = (cell_lo == 0 and r["evaluated_cells"][1] == r["cells"])
    ok = (not r["spec_problems"] and not r["tiling_errors"] and r["n_failures"] == 0 and res["leaf_lines_match"]
          and res["claimed_counts_match_dual"] and res["leaves_rehash_after"]["unchanged"]
          and bind["post_receipt_binds_leaves"] and bind["post_receipt_binds_dual"] and post.get("exit_code") == 0)
    res["scope_full_chart"] = full
    res["verdict"] = ("PASS" if ok else "FAIL") if full else ("CHUNK-PASS" if ok else "CHUNK-FAIL")
    res["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    res["wall_seconds"] = round(time.time() - t_start, 2)
    with open(a.out, "x") as fh:
        json.dump(res, fh, indent=1)
    log("RESULT", res["verdict"], json.dumps(r["subdivision"]), res["finished"])
    logf.close()
    print("RESULT", json.dumps({k: res[k] for k in ("chart", "verdict", "lines", "evaluated_leaves", "n_failures",
                                                     "wall_seconds")}), flush=True)


if __name__ == "__main__":
    main()
