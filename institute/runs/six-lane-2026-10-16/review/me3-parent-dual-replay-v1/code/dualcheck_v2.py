def Q(x):
    x = str(x).strip()
    if "/" in x:
        a, b = x.split("/")
        return fmpq(int(a), int(b))
    return fmpq(int(x))


def I(lo, hi):
    if lo == hi:
        return arb(lo)
    return arb(lo).union(arb(hi))


ONE = arb(1)
ZERO = arb(0)

