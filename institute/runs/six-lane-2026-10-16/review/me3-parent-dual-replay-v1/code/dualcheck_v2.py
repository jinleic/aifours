# forward-mode jets (value + gradient in 3 variables) for mean-value-form enclosures
class J:
    __slots__ = ("v", "g")

    def __init__(self, v, g):
        self.v = v
        self.g = g

    def __add__(a, b):
        if type(b) is J:
            ag, bg = a.g, b.g
            return J(a.v + b.v, (ag[0] + bg[0], ag[1] + bg[1], ag[2] + bg[2]))
        return J(a.v + b, a.g)

    __radd__ = __add__

    def __sub__(a, b):
        if type(b) is J:
            ag, bg = a.g, b.g
            return J(a.v - b.v, (ag[0] - bg[0], ag[1] - bg[1], ag[2] - bg[2]))
        return J(a.v - b, a.g)

    def __rsub__(a, b):
        ag = a.g
        return J(b - a.v, (-ag[0], -ag[1], -ag[2]))

    def __neg__(a):
        ag = a.g
        return J(-a.v, (-ag[0], -ag[1], -ag[2]))

    def __mul__(a, b):
        if type(b) is J:
            ag, bg, av, bv = a.g, b.g, a.v, b.v
            return J(av * bv, (ag[0] * bv + av * bg[0], ag[1] * bv + av * bg[1], ag[2] * bv + av * bg[2]))
        ag = a.g
        return J(a.v * b, (ag[0] * b, ag[1] * b, ag[2] * b))

    __rmul__ = __mul__

    def __truediv__(a, b):
        if type(b) is J:
            inv = ONE / b.v
            qv = a.v * inv
            ag, bg = a.g, b.g
            return J(qv, ((ag[0] - qv * bg[0]) * inv, (ag[1] - qv * bg[1]) * inv, (ag[2] - qv * bg[2]) * inv))
        inv = ONE / b
        ag = a.g
        return J(a.v * inv, (ag[0] * inv, ag[1] * inv, ag[2] * inv))

    def __rtruediv__(a, b):
        inv = ONE / a.v
        qv = b * inv
        f = -qv * inv
        ag = a.g
        return J(qv, (ag[0] * f, ag[1] * f, ag[2] * f))

    @property
    def real(self):
        return J(self.v.real, tuple(x.real for x in self.g))

    @property
    def imag(self):
        return J(self.v.imag, tuple(x.imag for x in self.g))

    def log(self):
        v = self.v
        return J(v.log(), tuple(x / v for x in self.g))


def jvars(s, d, w):
    return (J(s, (ONE, ZERO, ZERO)), J(d, (ZERO, ONE, ZERO)), J(w, (ZERO, ZERO, ONE)))


def mids_halfwidths(box):
    m = [(lo + hi) / 2 for lo, hi in box]
    h = [arb((hi - lo) / 2) for lo, hi in box]
    return m, h


def mvf_upper(fmid, jet, h):
    """Ball whose upper end bounds f over the box: f(mid) + sum |df/dx_i (box)| * h_i."""
    g = jet.g
    return fmid + abs(g[0]) * h[0] + abs(g[1]) * h[1] + abs(g[2]) * h[2]


def mvf_lower(fmid, jet, h):
    g = jet.g
    return fmid - abs(g[0]) * h[0] - abs(g[1]) * h[1] - abs(g[2]) * h[2]


# ----------------------------------------------------------------------------------------------------------------
# W(s, xi) = Q_T(theta(1+xi))/Q_T(theta), theta = s/(1-s), zz = 1/(1+xi)   (derivation-v1.md section 2)
def wcoef(C, s):
    one_s = 1 - s
    s2 = s * s
    N1 = C.K * s2 - 2 * s * one_s + 2 * one_s * one_s
    return C.K * s2 / N1, -2 * s * one_s / N1, 2 * one_s * one_s / N1


def Wfun(C, s, zz):
    w1, w2, w3 = wcoef(C, s)
    return zz * (w1 + zz * (w2 + zz * w3))


# ---------------------------------------------------------------- LW: nu = 1/omega in [0, 1/640], SMALL only
def ev_LW(C, box):
    (sl, sh), (dl, dh), (nl, nh) = box
    s, d, nu = I(sl, sh), I(dl, dh), I(nl, nh)
    zz = acb(nu) / acb(nu * (1 + d), -ONE)
    W = Wfun(C, s, zz)
    if abs(W) < (-C.TWOPI * arb(dh) * arb(nh)).exp():
        return True, "small"
    return False, "lw"


# ---------------------------------------------------------------- G: SMALL / RADIAL (+MVF) / TRIANGLE
def branch_holds(W, br):
    if br == "up":
        return W.imag > 0
    if br == "down":
        return W.imag < 0
    if br == "left":
        return W.real < 0
    return False


def pick_branch(W):
    for br in ("up", "down", "left"):
        if branch_holds(W, br):
            return br
    return None


def alpha_on(C, W, br):
    """A continuous argument of W on the branch region (values in [0, 2pi) for up/down/left)."""
    if br == "up":
        return arb.atan2(W.imag, W.real)
    if br == "down":
        return arb.atan2(W.imag, W.real) + C.TWOPI
    if br == "left":
        return C.PI + (W.imag / W.real).atan()
    if br == "principal":      # controls only: may be negative, never certified without alpha >= 0
        return arb.atan2(W.imag, W.real)
    raise ValueError(br)


def g_point_W(C, sq, dq, wq):
    z = acb(1 + arb(dq), -arb(wq))
    return Wfun(C, arb(sq), ONE / z)


def logabs_hull(W):
    """Ball containing log|w| for every w in the acb ball W, from rigorous lower/upper bounds of |w|.
    (v1 used log(abs(W)); abs(W) = |mid| +- rad can have a negative lower end even when W excludes 0 -> NaN.)
    Returns None if the lower bound of |W| is not certified positive."""
    lo, hi = W.abs_lower(), W.abs_upper()
    if not (lo > 0):
        return None
    return lo.log().union(hi.log())


def g_radial_mvf(C, box, br, s, d, w, z, la, alpha):
    """MVF bound of F = omega*log|W| + delta*alpha on a fixed branch; True iff certified F < 0 on the box.
    la = ball containing log|W| on the box (logabs_hull)."""
    K = C.K
    one_s = 1 - s
    s2 = s * s
    q = K * s2 * z * z - 2 * s * one_s * z + 2 * one_s * one_s
    N1 = K * s2 - 2 * s * one_s + 2 * one_s * one_s
    qz = 2 * K * s2 * z - 2 * s * one_s
    qs = 2 * K * s * z * z - 2 * (1 - 2 * s) * z - 4 * one_s
    N1s = 2 * K * s - 2 * (1 - 2 * s) - 4 * one_s
    L = qz / q - 3 / z             # d log W / d xi
    Ls = qs / q - N1s / N1         # d log W / d s
    dFs = w * Ls.real + d * Ls.imag
    dFd = w * L.real + alpha + d * L.imag
    dFw = la + w * L.imag - d * L.real
    m, h = mids_halfwidths(box)
    WM = g_point_W(C, m[0], m[1], m[2])
    if not branch_holds(WM, br):
        return False
    laM = logabs_hull(WM)
    if laM is None:
        return False
    FM = arb(m[2]) * laM + arb(m[1]) * alpha_on(C, WM, br)
    bound = FM + abs(dFs) * h[0] + abs(dFd) * h[1] + abs(dFw) * h[2]
    return bound < 0


def theta1_float(r):
    """Heuristic only (choice of the TRIANGLE vertex): root in (pi, 2pi) of cos u - r sin u = exp(-r u)."""
    if r <= 0:
        return 2 * math.pi
    lo, hi = math.pi, 2 * math.pi
    for _ in range(100):
        mid = 0.5 * (lo + hi)
        if math.cos(mid) - r * math.sin(mid) - math.exp(-r * mid) < 0:
            lo = mid
        else:
            hi = mid
    return lo


def g_triangle(C, box, d, w, W):
    """W = a + b*V, V = exp(-r th) e^{i th}, r = delta/omega, any rational th > 0 with sin th != 0."""
    (sl, sh), (dl, dh), (wl, wh) = box
    r = d / w
    cands = []
    for rr in (float((dl + dh) / 2) / float((wl + wh) / 2), float(dl) / float(wh), float(dh) / float(wl)):
        th = fmpq(int(math.floor(theta1_float(rr) * 10000)), 10000)
        if th > 0 and th not in cands:
            cands.append(th)
    for th in cands:
        t = arb(th)
        sn, cs = t.sin(), t.cos()
        if not (sn < 0 or sn > 0):
            continue
        e = (r * t).exp()
        b = W.imag * e / sn
        a = W.real - W.imag * cs / sn
        ab = W.real + W.imag * (e - cs) / sn
        if b >= 0 and a >= 0 and ab <= 1:
            return True
    return False


def ev_G(C, box, force_branch=None):
    (sl, sh), (dl, dh), (wl, wh) = box
    s, d, w = I(sl, sh), I(dl, dh), I(wl, wh)
    z = acb(1 + d, -w)
    W = Wfun(C, s, ONE / z)
    aW = abs(W)
    if force_branch is None:
        if aW < (-C.TWOPI * arb(dh) / arb(wl)).exp():
            return True, "small"
        br = pick_branch(W)
    else:
        br = force_branch
        if br != "principal" and not branch_holds(W, br):
            return False, "branch-condition-false"
    if br is not None:
        alpha = alpha_on(C, W, br)
        nonneg = (br in ("up", "down", "left")) or (alpha >= 0)
        if not nonneg:
            return False, "alpha-negative"
        la = logabs_hull(W)
        if la is not None:
            F = w * la + d * alpha
            if F < 0:
                return True, "radial"
            if g_radial_mvf(C, box, br, s, d, w, z, la, alpha):
                return True, "radial-mvf"
    if force_branch is None and g_triangle(C, box, d, w, W):
        return True, "triangle"
    return False, "g"


def skip_G(box, tag):
    (sl, sh), (dl, dh), (wl, wh) = box
    if tag != "SKIP:in-primal-P":
        return False
    return wh <= 40 and wl >= fmpq(1, 5) and dh <= 3 * wl


# ---------------------------------------------------------------- LD1 / LD2 (delta >= 64)
def ld_tests(C, bl, b, aW, P, Pb_fn, fac):
    """Common LD logic.  arg W = beta + arg P (positive factor); ratio delta/omega = (1-d)/tan(beta) <= fac/tan(beta).
    Returns method name or None."""
    bl_ok = bl > 0 and arb(bl) < C.HALFPI
    if bl_ok:
        tl = arb(bl).tan()
        if aW < (-fac * C.TWOPI / tl).exp():          # alpha = Arg+ W in [0, 2pi)
            return "fallback"
    if P.real > 0:
        if bl == 0:
            Jv = (Pb_fn() / P).imag                   # d/dbeta Arg P on the box
            U = 1 + Jv
            if U >= 0 and aW < (-fac * U).exp():
                return "mvt0"
        elif bl_ok:
            alpha = b + (P.imag / P.real).atan()
            if alpha >= 0 and aW < (-fac * alpha / tl).exp():
                return "principal"
    return None


def ev_LD1(C, box, force=None):
    (sl, sh), (dl, dh), (bl, bh) = box
    if arb(bl) > C.HALFPI:
        return True, "vacuous-beta"
    s, d, b = I(sl, sh), I(dl, dh), I(bl, bh)
    cb, sb = b.cos(), b.sin()
    e1 = acb(cb, sb)
    zeta = d * cb * e1
    w1, w2, w3 = wcoef(C, s)
    P = w1 + zeta * (w2 + zeta * w3)
    aW = abs(zeta * P)
    fac = 1 - arb(dl)
    if force == "principal-minus-2pi":      # controls only: a wrong (negative) argument branch
        if not (bl > 0 and arb(bl) < C.HALFPI and P.real > 0):
            return False, "branch-condition-false"
        alpha = b + (P.imag / P.real).atan() - C.TWOPI
        if not (alpha >= 0):
            return False, "alpha-negative"
        if aW < (-fac * alpha / arb(bl).tan()).exp():
            return True, "principal-minus-2pi"
        return False, "ld1"

    def Pb():
        return (w2 + 2 * w3 * zeta) * C.IU * d * e1 * e1

    m = ld_tests(C, bl, b, aW, P, Pb, fac)
    if m:
        return True, m
    return False, "ld1"


def ev_LD2(C, box):
    (xl, xh), (rl, rh), (bl, bh) = box
    if arb(bl) > C.HALFPI:
        return True, "vacuous-beta"
    x, rt, b = I(xl, xh), I(rl, rh), I(bl, bh)
    s = x * rt
    one_s = 1 - s
    omx = 1 - x
    N1 = C.K * s * s - 2 * s * one_s + 2 * one_s * one_s
    e1 = acb(b.cos(), b.sin())
    e2 = e1 * e1
    Ph = (C.K * x * x - 2 * x * omx * one_s * e1 + 2 * one_s * one_s * omx * omx * e2) / N1
    aW = omx * rt * rt * rt * abs(Ph)

    def Pb():
        return C.IU * (-2 * x * omx * one_s * e1 + 4 * one_s * one_s * omx * omx * e2) / N1

    m = ld_tests(C, bl, b, aW, Ph, Pb, ONE)
    if m:
        return True, m
    return False, "ld2"


def skip_LD2(C, box, tag):
    (xl, xh), (rl, rh), (bl, bh) = box
    if tag == "SKIP:skip-s":
        return xl * rl > fmpq(1, 16)
    if tag == "SKIP:skip-d":
        return arb((1 - xh) * rl) > arb(bl).cos() / 65
    return False


# ---------------------------------------------------------------- SWC: power series of g = log W around xi = 0
def swc_series(C, s, d, w, N):
    one_s = 1 - s
    s2 = s * s
    N1 = C.K * s2 - 2 * s * one_s + 2 * one_s * one_s
    p = (s * one_s * C.IC_P - C.K * s2) / N1
    cs = []
    pj = p
    for j in range(1, N + 1):
        cs.append((pj.real * (-2) + 3 * (-1) ** j) / arb(j))
        pj = pj * p
    w2 = w * w
    X, U = ONE, ZERO
    Us = [U]
    for _ in range(N):
        X, U = d * X - w2 * U, X + d * U
        Us.append(U)
    Psi = ZERO
    for j in range(2, N + 1):
        Psi = Psi - cs[j - 1] * Us[j - 1]
    Ig = ZERO
    for j in range(1, N + 1):
        Ig = Ig - cs[j - 1] * Us[j]
    return Psi, Ig


def swc_tails(C, box, N):
    (sl, sh), (dl, dh), (wl, wh) = box
    s = I(sl, sh)
    one_s = 1 - s
    N1 = C.K * s * s - 2 * s * one_s + 2 * one_s * one_s
    B = C.K * s * s / N1
    rho = arb(B.upper()).sqrt()
    x = (arb(dh) * arb(dh) + arb(wh) * arb(wh)).sqrt()
    rx = rho * x
    if not (rx < 1 and x < 1):
        return None
    tP = 2 * rho * rho * rx ** (N - 1) / (1 - rx) + 3 * x ** (N - 1) / (1 - x)
    tI = 2 * rho * rx ** N / (1 - rx) + 3 * x ** N / (1 - x)
    return tP, tI


def ev_SWC(C, box, N=20, tail_scale=None):
    (sl, sh), (dl, dh), (wl, wh) = box
    t = swc_tails(C, box, N)
    if t is None:
        return False, "radius"
    tP, tI = t
    if tail_scale is not None:        # controls only (weakened tail)
        tP, tI = tP * tail_scale, tI * tail_scale
    s, d, w = I(sl, sh), I(dl, dh), I(wl, wh)
    Psi, Ig = swc_series(C, s, d, w, N)
    ok_p = (Psi + tP) < 0
    ok_i = (Ig - tI) > 0
    if ok_p and ok_i:
        return True, "series"
    m, h = mids_halfwidths(box)
    PsiJ, IgJ = swc_series(C, *jvars(s, d, w), N)
    PsiM, IgM = swc_series(C, arb(m[0]), arb(m[1]), arb(m[2]), N)
    if not ok_p:
        ok_p = (mvf_upper(PsiM, PsiJ, h) + tP) < 0
    if not ok_i:
        ok_i = (mvf_lower(IgM, IgJ, h) - tI) > 0
    if ok_p and ok_i:
        return True, "series-mvf"
    return False, "swc"


# ---------------------------------------------------------------- SWB: Taylor expansion in omega at real delta
def swb_g(C, s, d):
    one_s = 1 - s
    s2 = s * s
    z = 1 + d
    q = C.K * s2 * z * z - 2 * s * one_s * z + 2 * one_s * one_s
    N1 = C.K * s2 - 2 * s * one_s + 2 * one_s * one_s
    qz = 2 * C.K * s2 * z - 2 * s * one_s
    qzz = 2 * C.K * s2
    r1 = qz / q
    g0 = (q / N1).log() - 3 * z.log()
    g1 = r1 - 3 / z
    g2 = qzz / q - r1 * r1 + 3 / (z * z)
    g3 = -3 * r1 * qzz / q + 2 * r1 * r1 * r1 - 6 / (z * z * z)
    return g0, g1, g2, g3


def swb_M(C, box):
    """Upper bounds M4, M5 of |g''''|, |g'''''| on {delta - i y : delta in box, 0 <= y <= omega_h}, s in box."""
    (sl, sh), (dl, dh), (wl, wh) = box
    s, d = I(sl, sh), I(dl, dh)
    one_s = 1 - s
    Z = acb(1 + d, -I(fmpq(0), wh))
    D1 = C.K * s * Z - one_s * C.IC_P
    D2 = C.K * s * Z - one_s * C.IC_M
    L1, L2 = D1.abs_lower(), D2.abs_lower()
    if not (L1 > 0 and L2 > 0):
        return None
    ks = C.K * arb(sh)
    v1, v2 = ks / L1, ks / L2
    iz = ONE / (1 + arb(dl))
    M4 = 6 * (v1 ** 4 + v2 ** 4 + 3 * iz ** 4)
    M5 = 24 * (v1 ** 5 + v2 ** 5 + 3 * iz ** 5)
    return M4, M5


def swb_parts(C, s, d, w):
    g0, g1, g2, g3 = swb_g(C, s, d)
    w2 = w * w
    S = (g0 - d * g1) + w2 * (-g2 / 2 + d * g3 / 6)
    Im = -g1 + w2 * g3 / 6
    return S, Im


def ev_SWB(C, box, rem_scale=None):
    (sl, sh), (dl, dh), (wl, wh) = box
    MM = swb_M(C, box)
    if MM is None:
        return False, "M"
    M4, M5 = MM
    wh4 = arb(wh) ** 4
    E = wh4 * (M4 / 24 + arb(dh) * M5 / 120)
    Rb = wh4 * M5 / 120
    if rem_scale is not None:         # controls only (weakened remainder)
        E, Rb = E * rem_scale, Rb * rem_scale
    s, d, w = I(sl, sh), I(dl, dh), I(wl, wh)
    S, Im = swb_parts(C, s, d, w)
    ok_p = (S + E) < 0
    ok_i = (Im - Rb) > 0
    if ok_p and ok_i:
        return True, "taylor"
    m, h = mids_halfwidths(box)
    SJ, ImJ = swb_parts(C, *jvars(s, d, w))
    SM, ImM = swb_parts(C, arb(m[0]), arb(m[1]), arb(m[2]))
    if not ok_p:
        ok_p = (mvf_upper(SM, SJ, h) + E) < 0
    if not ok_i:
        ok_i = (mvf_lower(ImM, ImJ, h) - Rb) > 0
    if ok_p and ok_i:
        return True, "taylor-mvf"
    return False, "swb"


