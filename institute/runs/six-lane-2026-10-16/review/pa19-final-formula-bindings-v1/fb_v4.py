class TokenRefused(RuntimeError):
    pass


class _Alarm(BaseException):
    """BaseException so that a bounded lock wait cannot be swallowed by an `except Exception` handler."""


def _alarm(signum, frame):
    raise _Alarm()


def tok_count():
    with open(TOK / 'COUNT') as f:
        return max(0, int(f.read().split()[0]))


def bounded_flock(fd, max_wait):
    """One blocking LOCK_EX interrupted by SIGALRM at max_wait (no polling); returns waited seconds."""
    import fcntl
    t0 = time.time()
    old = signal.signal(signal.SIGALRM, _alarm)
    signal.setitimer(signal.ITIMER_REAL, max(0.001, max_wait))
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
    except _Alarm:
        raise TokenRefused('lock wait exceeded %.0f s' % max_wait)
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)
    return round(time.time() - t0, 1)


class Token:
    """token_ro.py (8e069589) semantics: an EXISTING t<i> (i < COUNT) opened O_RDONLY + exclusive flock, never
    written; each admitted token tried once non-blocking, then ONE blocking wait on t0 bounded by max_wait."""

    def __init__(self, max_wait=TOKEN_WAIT_MAX):
        self.max_wait, self.fd, self.name, self.acquired_at, self.waited_s = max_wait, None, None, None, None

    def __enter__(self):
        import fcntl
        t0 = time.time()
        n = tok_count()
        if n < 1:
            raise TokenRefused('COUNT=%d: no token admitted' % n)
        for i in range(n):
            p = TOK / ('t%d' % i)
            if not p.is_file():
                raise TokenRefused('token file missing: %s' % p)
            fd = os.open(p, os.O_RDONLY)
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                os.close(fd)
                continue
            self.fd, self.name = fd, 't%d' % i
            break
        if self.fd is None:
            fd = os.open(TOK / 't0', os.O_RDONLY)
            try:
                bounded_flock(fd, self.max_wait - (time.time() - t0))
            except TokenRefused:
                os.close(fd)
                raise
            self.fd, self.name = fd, 't0'
        if int(self.name[1:]) >= tok_count():
            self.__exit__()
            raise TokenRefused('COUNT dropped below held token index')
        self.acquired_at = now()
        self.waited_s = round(time.time() - t0, 1)
        return self

    def __exit__(self, *a):
        import fcntl
        if self.fd is not None:
            fcntl.flock(self.fd, fcntl.LOCK_UN)
            os.close(self.fd)
            self.fd = None
        return False


def disk_gate(projected):
    fb = free_bytes()
    need = max(NORMAL_GATE, BASE_FREE + projected + RECEIPT_MARGIN) + projected
    return fb, need, fb >= need


# ----------------------------------------------------------------------------- record rules
def parse_name(fn):
    m = SINGLE.match(fn)
    if m:
        lo = int(m.group(1))
        return 'single', lo, lo, m.group(2) or ''
    m = BATCH.match(fn)
    if m:
        return 'batch', int(m.group(1)), int(m.group(2)), m.group(3) or ''
    return None


def canonical_name(kind, lo, hi, suf):
    s = ('_' + suf) if suf else ''
    return ('f%05d%s.json' % (lo, s)) if kind == 'single' else ('batch_%05d_%05d%s.json' % (lo, hi, s))


def structural(fam, tag, fname, rec, n, lo, hi, rev_map, map_kind):
    """Identity checks of one chosen record against its path, the frozen index map and the pinned list size n.
    Returns (checks, kind, suffix, indices or None)."""
    c = OrderedDict()
    pn = parse_name(fname)
    c['canonical_filename'] = pn is not None and fname == canonical_name(*pn)
    if pn is None:
        return c, None, None, None
    kind, flo, fhi, suf = pn
    c['filename_range_equals_index_map'] = (flo, fhi) == (lo, hi)
    c['map_kind_equals_filename_kind'] = MAP_KIND.get((kind, suf)) == map_kind
    c['tag_field_equals_dir'] = rec.get('tag') == tag
    if kind == 'single':
        field = ('full_index' if fam == 'a3' else 'sub_index') if suf in ('', 'exact') else 'index'
        v = rec.get(field)
        c['index_field_equals_filename'] = type(v) is int and v == flo
        if suf == 'r3':
            c['rerun_kind_field'] = rec.get('kind') == ('a3' if fam == 'a3' else 'part')
        idxs = [flo]
    else:
        ind = rec.get('indices')
        c['indices_explicit_and_equal_filename_range'] = (isinstance(ind, list) and len(ind) >= 1
                                                          and all(type(x) is int for x in ind)
                                                          and ind == list(range(flo, fhi + 1)))
        if suf == 'r3':
            c['rerun_index_field_equals_stem'] = rec.get('index') == 'batch_%05d_%05d' % (flo, fhi)
            c['rerun_kind_field'] = rec.get('kind') == 'partbatch'
        idxs = list(range(flo, fhi + 1))
    c['indices_within_pinned_list'] = n is not None and 0 <= idxs[0] and idxs[-1] < n
    enc = EXPECT_ENCODER.get((fam, kind, suf))
    c['declared_encoder_expected'] = enc is not None and rec.get('encoder') == enc
    rv = rec.get('stream_check_revision')
    c['revision_equals_index_map'] = type(rv) is int and rv == rev_map
    c['serializer_revision_pinned'] = rv in SERIALIZER_OF_REV
    if suf in RERUN_RUNNERS:
        c['rerun_runner_and_revision_expected'] = (rec.get('runner'), rv) in RERUN_RUNNERS[suf]
    cs = rec.get('cnf_sha256')
    c['recorded_cnf_sha256_wellformed'] = isinstance(cs, str) and HEX64.match(cs) is not None
    c['recorded_cnf_bytes_positive_int'] = type(rec.get('cnf_bytes')) is int and rec.get('cnf_bytes') > 0
    return c, kind, suf, idxs


def rebuild(mods, sers, kind, enc, rev, spec, E, idxs):
    """The production call (run_hard4-9/12/14/15, rerun_exact/rerun5/rerun_batch12/15; identical to R8
    bind_subcases.build / incremental_bind.regen): returns (bytes, info, inputs_unmutated, call label)."""
    ser = sers[rev]
    if kind == 'single':
        m = mods[ENC_MOD[enc]]
        sub = dict(spec)
        sub['placed'] = E['full'][idxs[0]]
        before = jdigest([spec, sub['placed']])
        F, X, info = m.build(sub)
        b = ser(F)
        return b, info, before == jdigest([spec, sub['placed']]), '%s.build + %s.cnf_bytes_of' % (
            enc[:-3], SERIALIZER_OF_REV[rev])
    if enc != 'encode_partbatch.py':
        raise KeyError(enc)
    pls = [E['full'][i] for i in idxs]
    before = jdigest([spec, pls])
    F, X, sel = mods['encode_partbatch'].build(spec, pls)
    b = ser(F)
    return b, None, before == jdigest([spec, pls]), 'encode_partbatch.build + %s.cnf_bytes_of' % SERIALIZER_OF_REV[rev]


def coverage(chosen, n):
    """chosen: list of [path, sha, lo, hi, ...]. Exact set-union coverage of range(n)."""
    cov = bytearray(n) if n and n > 0 else bytearray()
    out_of_range, overlaps = 0, 0
    for ch in chosen:
        lo, hi = ch[2], ch[3]
        for i in range(lo, hi + 1):
            if 0 <= i < n:
                if cov[i]:
                    overlaps += 1
                cov[i] = 1
            else:
                out_of_range += 1
    holes = [i for i in range(n)] if not cov else [i for i in range(n) if not cov[i]]
    return {'n': n, 'records': len(chosen), 'holes': len(holes), 'first_holes': holes[:5], 'out_of_range': out_of_range,
            'overlapping_indices': overlaps,
            'complete': bool(n and n > 0 and not holes and not out_of_range)}


