    res['prior_receipt'] = pr['receipt']
    res['status'] = ('PRIOR_R8_PASS' if pr['kind'] == 'R8' else 'PRIOR_INC001_V2_PASS') if ok else 'UNRESOLVED'
    if not ok:
        res['reason'] = 'record bytes changed against the reused parent receipt hash'
    return res


