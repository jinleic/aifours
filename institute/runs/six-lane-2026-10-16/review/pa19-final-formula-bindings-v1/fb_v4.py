class Ctx:
    def __init__(self, pins, mods=None, sers=None):
        self.pins = pins
        self.mods, self.sers = mods, sers
        self._case = None
        self._case_tag = None

    def case(self, tag):
        """(spec object, list object E, list sha) for a split case, re-read and re-hashed against pins."""
        if self._case_tag == tag:
            return self._case
        cp = self.pins['split_cases'][tag]
        sb = (S_IN / cp['spec']['path']).read_bytes()
        spec = json.loads(sb) if sha(sb) == cp['spec']['S_sha256'] and cp['spec']['bound'] else None
        eb = (L / cp['list']['path']).read_bytes()
        eh = sha(eb)
        E = json.loads(eb) if eh == cp['list']['sha256'] else None
        self._case, self._case_tag = (spec, E, eh), tag
        return self._case


def evaluate(ctx, job, ov=None):
    """One chosen split record -> result dict. ov: in-memory overlay used only by the controls."""
    ov = ov or {}
    res = OrderedDict([('i', job['i']), ('case', job['case']), ('path', ov.get('path', job['path']))])
    checks = OrderedDict()
    cp = ctx.pins['split_cases'][job['case']]
    try:
        data = (L / res['path']).read_bytes()
    except FileNotFoundError:
        res['status'], res['reason'] = 'UNRESOLVED', 'record_missing'
        return res
    res['rec_sha'] = sha(data)
    want_sha = ov.get('pinned_rec_sha', job['rec_sha'])
    checks['record_sha_equals_pinned'] = res['rec_sha'] == want_sha
    if not checks['record_sha_equals_pinned']:
        res['checks_false'] = ['record_sha_equals_pinned']
        res['status'], res['reason'] = 'UNRESOLVED', 'record_changed_or_wrong_record'
        return res
    try:
        rec = json.loads(data)
    except ValueError:
        res['status'], res['reason'] = 'UNRESOLVED', 'record_unparseable'
        return res
    if 'rec' in ov:
        rec = ov['rec'](copy.deepcopy(rec))
    spec, E, eh = ctx.case(job['case'])
    if 'list' in ov:
        E, eh = ov['list']
    pinned_list = ov.get('pinned_list_sha', cp['list']['sha256'])
    checks['spec_bytes_bound'] = spec is not None
    checks['list_sha_equals_pinned'] = E is not None and eh == pinned_list
    n = len(E['full']) if E is not None else None
    lo, hi = ov.get('lohi', (job['lo'], job['hi']))
    st, kind, suf, idxs = structural(cp['fam'], job['case'], res['path'].rsplit('/', 1)[1], rec, n, lo, hi,
                                     job['rev'], job['map_kind'])
    checks.update(st)
    res['kind'], res['suf'] = kind, suf
    res['rec'] = [rec.get('cnf_sha256'), rec.get('cnf_bytes')]
    enc = ov.get('encoder', rec.get('encoder'))
    if 'indices' in ov:
        idxs = ov['indices']
    res['enc'], res['rev'] = enc, rec.get('stream_check_revision')
    res['runner'] = rec.get('runner')
    if idxs is not None:
        res['lo_hi_n'] = [idxs[0], idxs[-1], len(idxs)]
        if kind == 'batch':
            res['idx_digest'] = jdigest(idxs)
    bad = [k for k, v in checks.items() if v is False]
    if bad and not ov.get('force_rebuild'):
        res['checks_false'] = bad
        res['status'] = classify(bad)
        return res
    t = time.perf_counter()
    try:
        b, info, unmut, call = rebuild(ctx.mods, ctx.sers, kind, enc, res['rev'], spec, E, idxs)
    except Exception as ex:  # encoder refused the inputs: never a PASS
        res['checks_false'] = bad + ['rebuild_possible']
        res['status'], res['reason'] = 'UNRESOLVED', 'rebuild not possible: %r' % (ex,)
        return res
    res['build_s'] = round(time.perf_counter() - t, 3)
    nv, nc = header(b)
    res['gen'] = [sha(b), len(b), nv, nc]
    res['call'] = call
    del b
    checks['inputs_not_mutated_by_encoder'] = unmut
    checks['cnf_sha256_equal'] = res['gen'][0] == rec.get('cnf_sha256')
    checks['cnf_bytes_equal'] = res['gen'][1] == rec.get('cnf_bytes')
    if info is not None and 'leave' in rec:
        checks['leave_vector_equal'] = info.get('leave') == rec.get('leave')
    if suf == 'r3':
        stem = ('f%05d.json' % idxs[0]) if kind == 'single' else res['path'].rsplit('/', 1)[1][:-len('_r3.json')] + '.json'
        op = res['path'].rsplit('/', 1)[0] + '/' + stem
        try:
            od = (L / op).read_bytes()
            orec = json.loads(od)
        except (FileNotFoundError, ValueError):
            orec, od = None, None
        checks['rerun_original_present'] = orec is not None
        if orec is not None:
            res['orig'] = [op, sha(od), orec.get('cnf_sha256'), orec.get('status')]
            checks['rerun_recorded_cnf_equal_original'] = (orec.get('encoder') == rec.get('encoder')
                                                           and orec.get('cnf_sha256') == rec.get('cnf_sha256')
                                                           and orec.get('cnf_bytes') == rec.get('cnf_bytes'))
            if kind == 'batch':
                checks['rerun_indices_equal_original'] = orec.get('indices') == rec.get('indices')
    bad = [k for k, v in checks.items() if v is False]
    res['checks_false'] = bad
    if not bad:
        res['status'] = 'PASS' if cp['list']['parent_bound'] else 'FORMULA_EQUAL_LIST_PENDING'
    else:
        res['status'] = classify(bad)
    return res


INPUT_CHECKS = ('spec_bytes_bound', 'list_sha_equals_pinned')


def classify(bad):
    """FAIL_INPUT_BINDING (spec/list not the pinned bytes) > FAIL_STRUCTURAL (identity/index/encoder fields) >
    MISMATCH (only formula checks false: rebuilt bytes differ from the record)."""
    if any(k in INPUT_CHECKS for k in bad):
        return 'FAIL_INPUT_BINDING'
    if all(k in FORMULA_CHECKS or k == 'rerun_original_present' for k in bad):
        return 'MISMATCH'
    return 'FAIL_STRUCTURAL'


def evaluate_prior(job):
    """Already parent-bound record: counted only if its bytes are unchanged against the pinned hash, which equals
    the hash in the reused parent receipt (R8 sample PASS or inc-001 + ms06-binding-v2)."""
    res = OrderedDict([('i', job['i']), ('case', job['case']), ('path', job['path'])])
    try:
        h = sha((L / job['path']).read_bytes())
    except FileNotFoundError:
        res['status'], res['reason'] = 'UNRESOLVED', 'record_missing'
        return res
    res['rec_sha'] = h
    pr = job['prior']
    ok = h == job['rec_sha'] == pr['receipt_record_sha256']
