def cmd_lists(args):
    import fcntl
    pins, jobs = load_pins(args, parse_jobs=False)  # v3: lean driver RSS -> larger child share of the 5 GiB cap
    chunk = int(args['--chunk'])
    chunk_guard = time.monotonic() + CHUNK_SECONDS - SHUTDOWN_RESERVE
    run_guard = RUN_WALL_DEADLINE - SHUTDOWN_RESERVE
