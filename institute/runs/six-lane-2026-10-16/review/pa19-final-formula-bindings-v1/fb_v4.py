def write_x(path, data):
    old = signal.pthread_sigmask(signal.SIG_BLOCK, {signal.SIGTERM})
    try:
        with open(path, 'xb') as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
    finally:
        signal.pthread_sigmask(signal.SIG_SETMASK, old)
    return len(data)


