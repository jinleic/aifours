LIST_KEYS = {'source', 'raw', 'num_full', 'full'}


def compare_lists(tag, stored, replay):
    """Documented comparator: byte equality, else parsed equality of ALL four fields with identical key sets
    (source must equal '<tag>.json' on both sides; no field is ignored). Order of `full` is significant."""
    out = OrderedDict([('stored_sha256', sha(stored)), ('replay_sha256', sha(replay)), ('stored_bytes', len(stored)),
                       ('replay_bytes', len(replay))])
    if out['stored_sha256'] == out['replay_sha256']:
        out['verdict'] = 'BYTE_EQUAL'
        return out
    try:
        a, b = json.loads(stored), json.loads(replay)
    except ValueError as ex:
        out['verdict'], out['reason'] = 'MISMATCH', 'unparseable: %r' % (ex,)
        return out
    diffs = []
    if not (isinstance(a, dict) and isinstance(b, dict) and set(a) == LIST_KEYS and set(b) == LIST_KEYS):
        diffs.append('key_set')
    else:
        for k in ('source', 'raw', 'num_full'):
            if a[k] != b[k]:
                diffs.append(k)
        if a['source'] != tag + '.json' or b['source'] != tag + '.json':
            diffs.append('source_not_production_basename')
        if not (isinstance(a['full'], list) and isinstance(b['full'], list)):
            diffs.append('full_type')
        else:
            if len(a['full']) != len(b['full']):
                diffs.append('full_length')
            first = next((j for j, (x, y) in enumerate(zip(a['full'], b['full'])) if x != y), None)
            if first is not None:
                diffs.append('full_entry')
                out['first_differing_index'] = first
            if a['num_full'] != len(a['full']) or b['num_full'] != len(b['full']):
                diffs.append('num_full_vs_length')
    out['differences'] = diffs
    out['verdict'] = 'SEMANTIC_EQUAL_ALL_FIELDS' if not diffs else 'MISMATCH'
    return out


