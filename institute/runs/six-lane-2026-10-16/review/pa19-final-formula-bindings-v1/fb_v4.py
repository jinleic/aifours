def load_pins(args, parse_jobs=True):
    want = args.get('--pins')
    b = PINS.read_bytes()
    if sha(b) != want:
        raise SystemExit('pins-v1.json sha %s != --pins %s' % (sha(b), want))
    pins = json.loads(b)
    jb = JOBS.read_bytes()
    if sha(jb) != pins['jobs_file']['sha256']:
        raise SystemExit('jobs file changed')
    jobs = [json.loads(x) for x in gzip.decompress(jb).decode().splitlines()] if parse_jobs else None
    del jb
    for k, (p, w) in REF.items():
        if sha_file(p)[0] != w:
            raise SystemExit('reference changed after pin: %s' % k)
    return pins, jobs


