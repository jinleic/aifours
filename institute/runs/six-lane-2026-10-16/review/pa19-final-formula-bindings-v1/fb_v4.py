class _Sink:
    def __init__(self):
        self.parts = []

    def write(self, s):
        self.parts.append(s)
        return len(s)

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


SENTINEL = '<fb_v1 in-memory CNF sink>'


def e1_write_bytes(e1, F):
    """Run the pinned encode_e1.CNF.write unchanged with its module-global open() shadowed by an in-memory text
    sink (production run_cases.py called F.write(cnf_path)); no file is opened."""
    sink = _Sink()
    calls = []

    def fake_open(path, mode='r', *a, **k):
        calls.append([path, mode])
        if path != SENTINEL or mode != 'w' or a or k:
            raise RuntimeError('unexpected open(%r, %r)' % (path, mode))
        return sink
    e1.open = fake_open
    try:
        F.write(SENTINEL)
    finally:
        del e1.open
    if calls != [[SENTINEL, 'w']]:
        raise RuntimeError('unexpected open calls %r' % calls)
    return ''.join(sink.parts).encode('ascii')


