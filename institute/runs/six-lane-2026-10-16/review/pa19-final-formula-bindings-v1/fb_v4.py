    log('controls: %d/%d as expected; controls-v1.json sha %s' % (sum(c['as_expected'] for c in out), len(out),
                                                                  sha_file(HERE / 'controls-v1.json')[0]))
    print(json.dumps({'all_as_expected': res['all_as_expected'], 'count': len(out),
                      'unexpected': [c for c in out if not c['as_expected']]}, indent=1)[:6000])


