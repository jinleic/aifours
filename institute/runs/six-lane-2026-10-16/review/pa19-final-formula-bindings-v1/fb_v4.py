def load_module(name, path, want):
    """Execute the exact pinned bytes as module `name` (no bytecode cache is read or written)."""
    b = Path(path).read_bytes()
    h = sha(b)
    if h != want:
        raise SystemExit('pinned source mismatch: %s %s != %s' % (path, h, want))
    mod = types.ModuleType(name)
    mod.__file__ = str(path)
    sys.modules[name] = mod
    exec(compile(b, str(path), 'exec'), mod.__dict__)
    return mod


