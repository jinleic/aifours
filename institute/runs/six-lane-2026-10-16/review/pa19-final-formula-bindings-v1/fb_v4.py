def read_gz_lines(p):
    out = []
    try:
        with gzip.open(p, 'rt') as f:
            for line in f:
                if line.endswith('\n'):
                    out.append(json.loads(line))
    except (EOFError, OSError, ValueError):
        pass
    return out


