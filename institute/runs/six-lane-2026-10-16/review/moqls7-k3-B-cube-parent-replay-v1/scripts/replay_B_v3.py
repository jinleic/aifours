#!/usr/bin/env python3
"""Parent replay driver for phys-2 K3 cube certificates, encoder B (review/moqls7-k3-B-cube-parent-replay-v1), v3.

v3 = replay_B_v2.py with the import bumped to bklib_v2 (adds the B_C411 item pin) and one addition: the regen mode
takes an optional '--tag TAG' and then writes receipts/regen-ITEM-TAG.json and logs/driver-regen-ITEM-TAG.log. This is
needed because receipts/regen-B_C411.json was spent by a free-space-gate deferral at 07:12:31. Without a tag the regen
mode is unchanged.
  replay_B_v3.py regen ITEM [--tag TAG]   (TAG: [A-Za-z0-9]+)

v2 = replay_B_v1.py plus one change: the run mode takes an attempt LABEL (ITEM-<suffix>, never equal to ITEM) and
derives every run receipt, log, FIFO and the expected supervisor record from LABEL instead of ITEM, so a new
attempt never collides with an earlier attempt's exclusive files. Everything else (pins, limits, transport,
verdict rule, regen and selfcheck modes) is unchanged.

Usage (from bash or launch_B_v2.py; never under an eval deadline):
  replay_B_v2.py regen ITEM               regenerate and hash only, no native launch -> receipts/regen-ITEM.json
  replay_B_v2.py selfcheck                three tiny transport self-checks + in-memory parser/logic cases
                                          -> receipts/selfcheck.pre.json, selfcheck-X*.json, selfcheck-summary.json
  replay_B_v2.py run ITEM --label LABEL --rss-stop N
                                          one instance, only under supervise_r3.py (launch_B_v2.py)
                                          -> receipts/LABEL.pre.json, LABEL.launch.json, LABEL.driver.json

run: refuses unless started by the pinned supervise_r3.py (K3_SUPERVISOR_* environment, parent pid) and unless the
self-check summary is all OK. Pins and producer evidence are checked; the pre-execution receipt (script SHA-256s)
is written exclusively; the CNF is regenerated by compose_B_v1.py in a subprocess and held in memory; its SHA-256 is
compared with the pin (mismatch: STOP, nothing launched, UNKNOWN); the launch receipt records kissat and drat-trim
SHA-256s at spawn; then kissat -q -f --time=5400 reads the CNF from a pipe and writes binary DRAT to a desk FIFO that
the parent drat-trim (-i -t 9000) reads on stdin, with the CNF on a second pipe. A fresh free-space gate
(>= 12.2e9 + projected growth) precedes each native Popen. SIGTERM to this driver is a cooperative safety stop
(own children get SIGTERM, bounded wait, verdict UNKNOWN). Verdicts: PASS only if every strict condition holds,
otherwise UNKNOWN.
"""
import json
import re
import os
import signal
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bklib_v2 as K  # noqa: E402

SOLVER_SECONDS = 5400
CHECKER_SECONDS = 9000
BACKSTOP_SECONDS = CHECKER_SECONDS + 300
SELF_SECONDS = 60
SELF_BACKSTOP = 180
SELF_RSS_STOP = 1 << 30
LOGFD = {"fd": None}


def solver_prefix(seconds):
    return [K.KISSAT, "-q", "-f", "--time=%d" % seconds]


def log(msg):
    line = "[%s] %s\n" % (K.now(), msg)
    sys.stdout.write(line)
    sys.stdout.flush()
    if LOGFD["fd"] is not None:
        os.write(LOGFD["fd"], line.encode())


def _on_term(signum, frame):
    K.STOP["requested"] = "driver %s received at %s" % (signal.Signals(signum).name, K.now())


def common(mode):
    return {"mode": mode, "driver_pid": os.getpid(), "parent_pid": os.getppid(), "at": K.now(), "desk": K.DESK,
            "scripts_sha256": K.script_hashes(),
            "python": {"argv0": sys.executable, "version": sys.version, "flags_isolated": sys.flags.isolated,
                       "flags_dont_write_bytecode": sys.flags.dont_write_bytecode},
            "interpreter_binary": K.binary_record(K.PY), "uname": list(os.uname()),
            "supervisor_env": {k: os.environ.get(k) for k in ("K3_SUPERVISOR_PID", "K3_SUPERVISOR_SCRIPT",
                                                               "K3_SUPERVISOR_RECORD")},
            "gate_rule": {"launch_threshold": K.GATE, "launch_base": K.LAUNCH_BASE,
                          "projected_retained_growth": K.PROJECTED_GROWTH, "inflight_floor": K.FLOOR,
                          "sigterm_grace_seconds": K.GRACE}}


def mode_regen(item, tag=None):
    label = "regen-" + item + ("-" + tag if tag else "")
    path = os.path.join(K.RECEIPTS, label + ".json")
    if os.path.lexists(path):
        raise SystemExit("exists: " + path)
    pins, bad = K.pin_status()
    prod = K.producer_evidence(item)
    row = common("regen")
    row.update({"label": label, "item": item, "pins": pins, "pin_mismatch": bad, "producer": prod,
                "gate_before_compose": K.gate("before compose subprocess (python, not native)")})
    if bad or not prod["consistent"] or not row["gate_before_compose"]["pass"]:
        row["result"] = "not run: pin mismatch %s / producer consistent %s / gate %s" % (
            bad, prod["consistent"], row["gate_before_compose"]["pass"])
    else:
        cnf, info = K.regenerate(item)
        row["regen"] = K.check_regen(item, cnf, info, prod["meta_fields"])
        row["result"] = {True: "MATCH", False: "MISMATCH", None: "NO BYTES"}[row["regen"]["cnf_hash_match"]]
        del cnf
    row["scripts_sha256_end"] = K.script_hashes()
    row["finished_at"] = K.now()
    h = K.write_json_x(path, row)
    log("%s %s receipt=%s sha256=%s" % (label, row["result"], os.path.relpath(path, K.DESK), h))
    return 0 if row["result"] == "MATCH" else 1


UNSAT4 = b"p cnf 2 4\n1 2 0\n1 -2 0\n-1 2 0\n-1 -2 0\n"
SAT3 = b"p cnf 2 3\n1 2 0\n1 -2 0\n-1 2 0\n"
SELFCHECKS = [("X1-UNSAT4", UNSAT4, None, "strict PASS"),
              ("X2-SAT3", SAT3, None, "solver rc 10 ['s SATISFIABLE'] and checker rejects"),
              ("X3-UNSAT4proof-vs-SAT3cnf", UNSAT4, SAT3, "solver rc 20 ['s UNSATISFIABLE'] and checker rejects")]
PARSER_CASES = [  # (log bytes, expected status lines, NOT VERIFIED anywhere, TIMEOUT anywhere)
    (b"\rc reading proof from stdin\n\rs VERIFIED\n\rc verification time: 1.0 seconds\n", ["s VERIFIED"], False,
     False),
    (b"\rc x\n\ns NOT VERIFIED\n\rc verification time: 1.0 seconds\n", ["s NOT VERIFIED"], True, False),
    (b"\rc detected empty clause\ns TIMEOUT\n", ["s TIMEOUT"], False, True),
    (b" s VERIFIED\n", [], False, False),
    (b"\rs VERIFIED \n", ["s VERIFIED "], False, False),
    (b"\rs VERIFIED\r\n", ["s VERIFIED"], False, False),
    (b"\rs VERIFIED\n\rs VERIFIED\n", ["s VERIFIED", "s VERIFIED"], False, False),
    (b"\rs VERIFIED\n\rc TIMEOUT reached\n", ["s VERIFIED"], False, True),
    (b"s UNSATISFIABLE\n", ["s UNSATISFIABLE"], False, False),
    (b"s SATISFIABLE\nv 1 2 0\n", ["s SATISFIABLE"], False, False),
]


def synthetic_rec():
    n, h = len(UNSAT4), K.sha_bytes(UNSAT4)
    w = {"complete": True, "written": n, "sha256": h, "thread_alive_after_join": False}
    return {"children": {"solver": {"rc": 20}, "checker": {"rc": 0}},
            "writers": {"solver_cnf": dict(w), "checker_cnf": dict(w)},
            "solver_flags": K.log_flags(b"s UNSATISFIABLE\n"), "checker_flags": K.log_flags(b"\rs VERIFIED\n"),
            "safety_stop_reason": None, "sigterm_sent": [], "driver_signal": None}


def logic_cases():
    n, h = len(UNSAT4), K.sha_bytes(UNSAT4)
    muts = {
        "baseline_all_true": lambda r: None,
        "checker_two_verified_lines": lambda r: r.update(checker_flags=K.log_flags(b"\rs VERIFIED\n\rs VERIFIED\n")),
        "checker_rc_1": lambda r: r["children"]["checker"].update(rc=1),
        "solver_rc_10": lambda r: r["children"]["solver"].update(rc=10),
        "solver_two_unsat_lines": lambda r: r.update(solver_flags=K.log_flags(b"s UNSATISFIABLE\ns UNSATISFIABLE\n")),
        "timeout_text_in_checker": lambda r: r.update(checker_flags=K.log_flags(b"\rs VERIFIED\nc TIMEOUT\n")),
        "feed_short_by_one": lambda r: r["writers"]["solver_cnf"].update(written=n - 1),
        "feed_sha_differs": lambda r: r["writers"]["checker_cnf"].update(sha256="0" * 64),
        "feed_incomplete": lambda r: r["writers"]["checker_cnf"].update(complete=False),
        "sigterm_sent": lambda r: r.update(sigterm_sent=[{"child": "solver"}]),
        "safety_stop": lambda r: r.update(safety_stop_reason="test"),
        "driver_signal": lambda r: r.update(driver_signal="test"),
        "grace_exceeded": lambda r: r.update(grace_exceeded="test"),
        "deferred": lambda r: r.update(deferred="test"),
        "checker_not_reaped": lambda r: r["children"].pop("checker"),
        "writer_thread_alive": lambda r: r["writers"]["solver_cnf"].update(thread_alive_after_join=True),
    }
    out = {}
    for name, f in muts.items():
        r = synthetic_rec()
        f(r)
        c = K.strict_checks(r, h, h, n, n)
        out[name] = {"all_true": all(c.values()), "false": [k for k, v in c.items() if not v]}
    ok = out["baseline_all_true"]["all_true"] and all(not v["all_true"] for k, v in out.items()
                                                       if k != "baseline_all_true")
    return out, ok


def expectation_met(name, rec, ccnf, cnf):
    s = (rec.get("children") or {}).get("solver") or {}
    checks = K.strict_checks(rec, K.sha_bytes(cnf), K.sha_bytes(ccnf), len(cnf), len(ccnf))
    plumbing = all(checks[k] for k in ("not_deferred", "solver_feed_complete_and_equal",
                                       "checker_feed_complete_and_equal", "no_safety_stop", "no_sigterm_sent",
                                       "no_driver_signal", "all_children_reaped", "writer_threads_finished"))
    sl = (rec.get("solver_flags") or {}).get("status_lines")
    if name == "X1-UNSAT4":
        return all(checks.values()), checks
    if name == "X2-SAT3":
        return plumbing and s.get("rc") == 10 and sl == ["s SATISFIABLE"] and K.checker_rejected(rec), checks
    return plumbing and s.get("rc") == 20 and sl == ["s UNSATISFIABLE"] and K.checker_rejected(rec), checks


def mode_selfcheck():
    pre_path = os.path.join(K.RECEIPTS, "selfcheck.pre.json")
    pre = common("selfcheck")
    pins, bad = K.pin_status()
    pre.update({"pins": pins, "pin_mismatch": bad, "checks": [[n, e] for n, _, _, e in SELFCHECKS],
                "binaries_at_spawn": {"kissat": K.binary_record(K.KISSAT), "drat-trim": K.binary_record(K.DRAT)},
                "solver_prefix": solver_prefix(SELF_SECONDS), "checker_seconds": SELF_SECONDS,
                "backstop_seconds": SELF_BACKSTOP, "rss_stop": SELF_RSS_STOP})
    log("selfcheck pre-execution receipt sha256=%s" % K.write_json_x(pre_path, pre))
    if bad:
        raise SystemExit("pin mismatch: %s" % bad)
    parser = []
    for data, want_lines, want_nv, want_to in PARSER_CASES:
        got = K.log_flags(data)
        parser.append({"log_hex": data.hex(), "want": [want_lines, want_nv, want_to], "got": got,
                       "ok": (got["status_lines"] == want_lines and got["not_verified_anywhere"] == want_nv
                              and got["timeout_anywhere"] == want_to)})
    logic, logic_ok = logic_cases()
    rows = []
    for name, cnf, ccnf, expect in SELFCHECKS:
        label = "selfcheck-" + name
        ccnf = ccnf or cnf
        rec = K.pipeline(label, cnf, solver_prefix(SELF_SECONDS), SELF_SECONDS, SELF_BACKSTOP, SELF_RSS_STOP,
                         checker_cnf=ccnf)
        met, checks = expectation_met(name, rec, ccnf, cnf)
        row = {"label": label, "expect": expect, "expectation_met": met, "strict_checks": checks,
               "cnf_text": cnf.decode(), "checker_cnf_text": ccnf.decode(), "pipeline": rec}
        h = K.write_json_x(os.path.join(K.RECEIPTS, label + ".json"), row)
        rows.append({"label": label, "expect": expect, "expectation_met": met,
                     "solver_rc": (rec.get("children") or {}).get("solver", {}).get("rc"),
                     "checker_rc": (rec.get("children") or {}).get("checker", {}).get("rc"),
                     "solver_status_lines": (rec.get("solver_flags") or {}).get("status_lines"),
                     "checker_status_lines": (rec.get("checker_flags") or {}).get("status_lines"),
                     "solver_log_sha256": rec.get("solver_log_sha256"),
                     "checker_log_sha256": rec.get("checker_log_sha256"), "receipt_sha256": h})
        log(json.dumps(rows[-1]))
    after = {"kissat": K.binary_record(K.KISSAT), "drat-trim": K.binary_record(K.DRAT)}
    out = {"at": K.now(), "parser_cases": parser, "parser_all_ok": all(p["ok"] for p in parser),
           "logic_cases": logic, "logic_ok": logic_ok, "rows": rows,
           "all_expectations_met": all(r["expectation_met"] for r in rows),
           "binaries_after": after,
           "binaries_unchanged": all(after[k]["sha256"] == pre["binaries_at_spawn"][k]["sha256"] for k in after),
           "scripts_sha256_end": K.script_hashes()}
    out["all_ok"] = (out["parser_all_ok"] and out["logic_ok"] and out["all_expectations_met"]
                     and out["binaries_unchanged"])
    h = K.write_json_x(os.path.join(K.RECEIPTS, "selfcheck-summary.json"), out)
    log("selfcheck summary sha256=%s all_ok=%s parser=%s logic=%s expectations=%s" % (
        h, out["all_ok"], out["parser_all_ok"], out["logic_ok"], out["all_expectations_met"]))
    return 0 if out["all_ok"] else 1


def supervised_by_pinned_supervisor(label):
    env = {k: os.environ.get(k) for k in ("K3_SUPERVISOR_PID", "K3_SUPERVISOR_SCRIPT", "K3_SUPERVISOR_RECORD")}
    want_record = os.path.join(K.RECEIPTS, label + ".supervisor.json")
    return {"env": env, "parent_pid": os.getppid(), "expected_record": want_record,
            "ok": (env["K3_SUPERVISOR_PID"] == str(os.getppid()) and env["K3_SUPERVISOR_SCRIPT"] == K.SUPERVISOR
                   and env["K3_SUPERVISOR_RECORD"] == want_record)}


def observed_outcome(hash_match, rec):
    if hash_match is not True:
        return "not launched: regenerated CNF %s" % ("hash mismatch (STOP)" if hash_match is False else "missing")
    if rec is None:
        return "not launched"
    if rec.get("deferred"):
        return "deferred: %s" % rec["deferred"]
    s = (rec.get("children") or {}).get("solver", {}).get("rc")
    cl = (rec.get("checker_flags") or {}).get("status_lines")
    if rec.get("safety_stop_reason"):
        return "safety stop: %s" % rec["safety_stop_reason"]
    if s == 10:
        return "solver reported SATISFIABLE (rc 10): contradicts the producer's UNSAT claim; parent attention"
    if s != 20:
        return "solver rc %r (no UNSAT answer)" % s
    if cl == ["s NOT VERIFIED"]:
        return "checker rejected the proof (s NOT VERIFIED)"
    if cl and any("TIMEOUT" in x for x in cl):
        return "checker timeout"
    return "solver rc 20; checker status lines %r" % (cl,)


def mode_run(item, label, rss_stop):
    sup = supervised_by_pinned_supervisor(label)
    if not sup["ok"]:
        raise SystemExit("refusing to run unsupervised: %r" % sup)
    if not (K.MIN_CAP <= rss_stop <= K.CAP_MAX):
        raise SystemExit("rss stop %d outside [%d, %d]" % (rss_stop, K.MIN_CAP, K.CAP_MAX))
    summary_path = os.path.join(K.RECEIPTS, "selfcheck-summary.json")
    with open(summary_path) as f:
        summary = json.load(f)
    if summary.get("all_ok") is not True:
        raise SystemExit("self-check summary is not all OK")
    it = K.ITEMS[item]
    paths = {k: os.path.join(K.RECEIPTS, label + s) for k, s in
             (("pre", ".pre.json"), ("launch", ".launch.json"), ("final", ".driver.json"))}
    for p in paths.values():
        if os.path.lexists(p):
            raise SystemExit("exists: " + p)
    t0 = time.monotonic()
    pins, bad = K.pin_status()
    prod = K.producer_evidence(item)
    pre = common("run")
    pre.update({"label": label, "item": item, "pins": pins, "pin_mismatch": bad, "producer": prod,
                "supervision": sup, "rss_stop": rss_stop, "selfcheck_summary_sha256": K.sha_file(summary_path),
                "expected_cnf_sha256": it["cnf_sha256"], "expected_base_cnf_sha256": it["base_cnf_sha256"],
                "planned": {"compose": [K.PY, "-I", "-B", os.path.join(K.SCRIPTS, "compose_B_v1.py"), it["cube"]],
                            "solver": solver_prefix(SOLVER_SECONDS) + ["/dev/fd/<cnf-pipe>",
                                                                       "fifo/%s.drat.fifo" % label],
                            "checker": [K.DRAT, "/dev/fd/<cnf-pipe>", "-i", "-t", str(CHECKER_SECONDS),
                                        "<stdin: fifo/%s.drat.fifo>" % label],
                            "backstop_seconds": BACKSTOP_SECONDS}})
    pre_sha = K.write_json_x(paths["pre"], pre)
    log("%s pre-execution receipt sha256=%s scripts=%s" % (label, pre_sha, json.dumps(pre["scripts_sha256"])))
    final = {"label": label, "item": item, "encoder": it["encoder"], "cube": it["cube"],
             "pre_receipt_sha256": pre_sha, "started_at": pre["at"], "expected_cnf_sha256": it["cnf_sha256"]}
    rec, regen, launch_sha, cnf_len, bins_spawn = None, None, None, None, None
    hash_match = None
    g0 = K.gate("before compose subprocess (python, not native)")
    final["gate_before_compose"] = g0
    if bad or not prod["consistent"]:
        final["not_launched"] = "pin mismatch %s / producer evidence inconsistent %s" % (bad, prod["checks"])
    elif not g0["pass"]:
        final["not_launched"] = "free-space gate failed before compose"
    elif K.STOP["requested"]:
        final["not_launched"] = K.STOP["requested"]
    else:
        cnf, info = K.regenerate(item)
        regen = K.check_regen(item, cnf, info, prod["meta_fields"])
        hash_match = regen["cnf_hash_match"]
        cnf_len = regen["cnf_bytes"]
        log("%s regenerated: sha256=%s match=%s bytes=%s seconds=%s" % (label, regen["cnf_sha256"], hash_match,
                                                                       cnf_len, info["seconds"]))
        if hash_match is not True:
            final["not_launched"] = "STOP: regenerated CNF %s" % ("hash mismatch" if hash_match is False
                                                                  else "missing")
        elif K.STOP["requested"]:
            final["not_launched"] = K.STOP["requested"]
        else:
            bins_spawn = {"kissat": K.binary_record(K.KISSAT), "drat-trim": K.binary_record(K.DRAT)}
            launch = {"label": label, "at": K.now(), "regen": regen, "binaries_at_spawn": bins_spawn,
                      "gate_at_launch_receipt": K.gate("launch receipt")}
            launch_sha = K.write_json_x(paths["launch"], launch)
            log("%s launch receipt sha256=%s kissat=%s drat-trim=%s free=%d" % (
                label, launch_sha, bins_spawn["kissat"]["sha256"], bins_spawn["drat-trim"]["sha256"],
                launch["gate_at_launch_receipt"]["free_bytes"]))
            rec = K.pipeline(label, cnf, solver_prefix(SOLVER_SECONDS), CHECKER_SECONDS, BACKSTOP_SECONDS, rss_stop)
        del cnf
    pins_end, bad_end = K.pin_status()
    bins_after = ({"kissat": K.binary_record(K.KISSAT), "drat-trim": K.binary_record(K.DRAT)}
                  if bins_spawn else None)
    conditions = {"cnf_hash_match": hash_match is True, "supervised_by_pinned_supervisor": sup["ok"],
                  "pins_equal_at_start_and_end": pins_end == pins and not bad and not bad_end,
                  "binaries_equal_pins_at_spawn": bool(bins_spawn) and all(
                      bins_spawn[k]["sha256"] == K.BIN_PINS[p] for k, p in (("kissat", K.KISSAT),
                                                                           ("drat-trim", K.DRAT))),
                  "binaries_unchanged_spawn_to_after": bool(bins_spawn) and bool(bins_after) and all(
                      bins_spawn[k]["sha256"] == bins_after[k]["sha256"] for k in bins_spawn),
                  "drat_trim_is_not_lane_build": bool(bins_spawn) and bins_spawn["drat-trim"]["sha256"] != K.LANE_DRAT_SHA256,
                  "pipeline_ran": rec is not None}
    if rec is not None:
        conditions.update(K.strict_checks(rec, it["cnf_sha256"], it["cnf_sha256"], cnf_len, cnf_len))
    verdict = "PASS" if all(conditions.values()) else "UNKNOWN"
    final.update({"launch_receipt_sha256": launch_sha, "regen": regen, "pipeline": rec,
                  "binaries_at_spawn": bins_spawn, "binaries_after": bins_after, "pins_end": pins_end,
                  "conditions": conditions, "failed_conditions": [k for k, v in conditions.items() if not v],
                  "verdict": verdict, "observed_outcome": observed_outcome(hash_match, rec),
                  "scripts_sha256_end": K.script_hashes(),
                  "producer_solver_log_sha256": prod["receipt_fields"].get("solver_log_sha256"),
                  "solver_log_equals_producer": (rec.get("solver_log_sha256")
                                                 == prod["receipt_fields"].get("solver_log_sha256")) if rec else None,
                  "finished_at": K.now(), "driver_seconds": round(time.monotonic() - t0, 3),
                  "scope": ("Instance only: the CNF regenerated from the pinned encoder B + K3 cube wrapper (SHA-256 "
                            "equal to the pin) is UNSAT by a streamed kissat binary DRAT proof checked by the "
                            "parent-built drat-trim, if and only if verdict is PASS. No K3, M(7), coverage, bridge "
                            "or theorem verdict.")})
    h = K.write_json_x(paths["final"], final)
    brief = {"label": label, "verdict": verdict, "failed_conditions": final["failed_conditions"],
             "observed_outcome": final["observed_outcome"], "cnf_hash_match": hash_match,
             "solver_rc": (rec or {}).get("children", {}).get("solver", {}).get("rc"),
             "checker_rc": (rec or {}).get("children", {}).get("checker", {}).get("rc"),
             "solver_status_lines": ((rec or {}).get("solver_flags") or {}).get("status_lines"),
             "checker_status_lines": ((rec or {}).get("checker_flags") or {}).get("status_lines"),
             "safety_stop": (rec or {}).get("safety_stop_reason"), "seconds": (rec or {}).get("pipeline_seconds"),
             "peak_aggregate_rss": (rec or {}).get("peak_sampled_aggregate_rss_bytes"),
             "driver_receipt_sha256": h}
    log("RESULT " + json.dumps(brief))
    return 0


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("regen", "selfcheck", "run"):
        raise SystemExit(__doc__)
    mode, args = sys.argv[1], sys.argv[2:]
    rss_stop, label, tag = None, None, None
    if mode == "regen" and (len(args) not in (1, 3) or args[0] not in K.ITEMS or (len(args) == 3 and (
            args[1] != "--tag" or not re.fullmatch(r"[A-Za-z0-9]+", args[2])))):
        raise SystemExit("regen takes one item among %s and an optional --tag TAG" % sorted(K.ITEMS))
    if mode == "regen" and len(args) == 3:
        tag = args[2]
    if mode == "selfcheck" and args:
        raise SystemExit("selfcheck takes no arguments")
    if mode == "run":
        if (len(args) != 5 or args[0] not in K.ITEMS or args[1] != "--label" or args[3] != "--rss-stop"
                or not args[4].isdigit()):
            raise SystemExit("usage: run ITEM --label LABEL --rss-stop N")
        label, rss_stop = args[2], int(args[4])
        if not (re.fullmatch(r"[A-Za-z0-9_.-]+", label) and label.startswith(args[0] + "-")):
            raise SystemExit("LABEL must be ITEM-<suffix> of [A-Za-z0-9_.-]")
    signal.signal(signal.SIGTERM, _on_term)
    signal.signal(signal.SIGINT, _on_term)
    name = "driver-%s%s.log" % (mode, "-" + (label or args[0] + ("-" + tag if tag else "")) if args else "")
    LOGFD["fd"] = K.open_append_x(os.path.join(K.LOGS, name))
    log("driver pid %d ppid %d mode %s args %s" % (os.getpid(), os.getppid(), mode, args))
    rc = 1
    try:
        if mode == "regen":
            rc = mode_regen(args[0], tag)
        elif mode == "selfcheck":
            rc = mode_selfcheck()
        else:
            rc = mode_run(args[0], label, rss_stop)
    finally:
        log("driver exit rc %d" % rc)
        os.close(LOGFD["fd"])
    sys.exit(rc)


if __name__ == "__main__":
    main()
