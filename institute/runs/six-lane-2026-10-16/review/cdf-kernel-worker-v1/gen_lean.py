#!/usr/bin/env python3
"""Generate CdfKernel/Data{v}.lean and CdfKernel/Cert{v}.lean from a pinned raw CDF certificate.

Raw format (strict): line 1 is `CDF <v> 5`; every further line is one base block of five
canonical decimal numbers separated by single spaces; every line ends in `\\n`; nothing else.
The script

1. reads the raw file byte-exactly and requires its SHA-256 to equal --expect-sha256;
2. parses it and re-renders the canonical text, requiring a byte-identical round trip, so every
   input byte is represented by the emitted literals (header numbers and block numbers);
3. emits the blocks verbatim, in raw order, as a Lean `List (List Nat)` (no sorting, no
   reduction modulo v, no deduplication, no repair), together with the header pair and the
   SHA-256 string, and emits the certificate module that runs the checker in the kernel.

It checks no mathematical property; the Lean kernel does (CdfKernel.Generic, CdfKernel.Cert{v}).

Usage:
  python3 gen_lean.py RAW OUTDIR --v 321 --expect-sha256 HEX --label TEXT
"""
import argparse
import hashlib
import pathlib
import re
import sys

NUMBER = re.compile(r"0|[1-9][0-9]*")


def fail(message):
    raise SystemExit(f"gen_lean.py: {message}")


def parse(raw, v):
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        fail("raw file is not ASCII")
    if not text.endswith("\n"):
        fail("raw file does not end with a newline")
    lines = text[:-1].split("\n")
    if lines[0] != f"CDF {v} 5":
        fail(f"unexpected header {lines[0]!r}")
    blocks = []
    for lineno, line in enumerate(lines[1:], 2):
        tokens = line.split(" ")
        if len(tokens) != 5 or not all(NUMBER.fullmatch(t) for t in tokens):
            fail(f"line {lineno}: not five canonical decimal numbers: {line!r}")
        blocks.append([int(t) for t in tokens])
    if not blocks:
        fail("no blocks")
    return blocks


def render_raw(blocks, v):
    return (f"CDF {v} 5\n" + "".join(" ".join(str(x) for x in b) + "\n" for b in blocks)).encode("ascii")


def render_data(blocks, v, sha, size, label):
    name = f"data{v}"
    rows = ",\n".join("  [" + ", ".join(str(x) for x in b) + "]" for b in blocks)
    return "\n".join([
        "/-",
        "GENERATED FILE - do not edit.  Produced by gen_lean.py from the raw certificate",
        f"{label} ({size} bytes, SHA-256 {sha}).",
        f"Header line `CDF {v} 5`.  Entry i of `{name}` is raw line i + 2, copied verbatim in raw order.",
        "Nothing is assumed about these numbers here: CdfKernel.Generic states the checker and its",
        f"soundness theorem, and CdfKernel.Cert{v} runs the checker in the Lean kernel.",
        "-/",
        "namespace Cdf.Kernel",
        "",
        "/-- SHA-256 of the raw certificate bytes, recorded by gen_lean.py (documentation only). -/",
        f'def {name}RawSha256 : String := "{sha}"',
        "",
        "/-- The header of the raw certificate: order `v` and block size `k`. -/",
        f"def {name}Header : Nat × Nat := ({v}, 5)",
        "",
        f"/-- The {len(blocks)} raw base blocks of {label}, in raw order. -/",
        f"def {name} : List (List Nat) := [",
        rows,
        "]",
        "",
        "end Cdf.Kernel",
        "",
    ])


def render_cert(blocks, v, sha, label):
    n = len(blocks)
    d = f"data{v}"
    c = f"cdf{v}"
    return "\n".join([
        "import CdfKernel.Generic",
        f"import CdfKernel.Data{v}",
        "",
        "/-!",
        f"# Cyclic `({v}, 5, 1)` difference family: kernel-checked existence",
        "",
        f"GENERATED by gen_lean.py from {label}",
        f"(SHA-256 {sha}); `{d}` comes from `CdfKernel.Data{v}`.",
        "Every `decide +kernel` below is evaluated by the Lean kernel (no `native_decide`, no",
        "`Lean.ofReduceBool`).  The semantic conclusion comes from the data-independent theorem",
        "`Cdf.Kernel.isCDF_of_check`; the target `Cdf.IsCDF` is defined in `CdfKernel.Target`.",
        "-/",
        "",
        "namespace Cdf.Kernel",
        "",
        f"/-- The raw certificate's own header reads `CDF {v} 5`. -/",
        f"theorem {d}_header : {d}Header = ({v}, 5) := rfl",
        "",
        f"/-- Shape of the raw data: {n} blocks, each of five numbers below {v}. -/",
        f"theorem {d}_shape :",
        f"    {d}.length = {n} ∧ ∀ b ∈ {d}, b.length = 5 ∧ ∀ x ∈ b, x < {v} := by",
        "  decide +kernel",
        "",
        f"/-- The explicit family: entry `j` of block `i` is the residue modulo {v} of number `j + 1`",
        f"on raw line `i + 2`. -/",
        f"def {c} : Fin {n} → Fin 5 → Fin {v} := blockOf {v} (by decide) {n} {d}",
        "",
        f"/-- No reduction happens: the residues are the raw numbers themselves. -/",
        f"theorem {c}_spec : ∀ i : Fin {n}, ∀ j : Fin 5, (({c} i j : Fin {v}) : Nat) = rawAt {d} i j := by",
        "  decide +kernel",
        "",
        f"/-- The number of ordered differences matches the number of nonzero residues. -/",
        f"theorem {d}_count : 20 * {n} + 1 = {v} := by decide +kernel",
        "",
        "/-- One kernel evaluation of the coverage check. -/",
        f"theorem {d}_cover : coverMask {v} {n} {d} = fullMask {v} := by decide +kernel",
        "",
        f"theorem {c}_isCDF : Cdf.IsCDF {c} :=",
        f"  isCDF_of_check {v} {n} (by decide) {d} {d}_count {d}_cover",
        "",
        f"/-- **A cyclic `({v}, 5, 1)` difference family exists.** -/",
        f"theorem exists_{c} : ∃ B : Fin {n} → Fin 5 → Fin {v}, Cdf.IsCDF B :=",
        f"  ⟨{c}, {c}_isCDF⟩",
        "",
        "end Cdf.Kernel",
        "",
        "set_option pp.funBinderTypes true in",
        f"#check @Cdf.Kernel.exists_{c}",
        f"#print axioms Cdf.Kernel.{d}_shape",
        f"#print axioms Cdf.Kernel.{c}_spec",
        f"#print axioms Cdf.Kernel.{d}_count",
        f"#print axioms Cdf.Kernel.{d}_cover",
        f"#print axioms Cdf.Kernel.{c}_isCDF",
        f"#print axioms Cdf.Kernel.exists_{c}",
        "",
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("raw")
    ap.add_argument("outdir")
    ap.add_argument("--v", type=int, required=True)
    ap.add_argument("--expect-sha256", required=True)
    ap.add_argument("--label", required=True)
    args = ap.parse_args()
    raw = pathlib.Path(args.raw).read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != args.expect_sha256:
        fail(f"SHA-256 mismatch: {sha} != {args.expect_sha256}")
    blocks = parse(raw, args.v)
    if render_raw(blocks, args.v) != raw:
        fail("raw bytes are not the canonical rendering of the parsed blocks")
    out = pathlib.Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    data = render_data(blocks, args.v, sha, len(raw), args.label).encode("utf-8")
    cert = render_cert(blocks, args.v, sha, args.label).encode("utf-8")
    (out / f"Data{args.v}.lean").write_bytes(data)
    (out / f"Cert{args.v}.lean").write_bytes(cert)
    print(f"v={args.v} blocks={len(blocks)} raw_bytes={len(raw)} raw_sha256={sha} "
          f"data_sha256={hashlib.sha256(data).hexdigest()} cert_sha256={hashlib.sha256(cert).hexdigest()}")


if __name__ == "__main__":
    sys.exit(main())
