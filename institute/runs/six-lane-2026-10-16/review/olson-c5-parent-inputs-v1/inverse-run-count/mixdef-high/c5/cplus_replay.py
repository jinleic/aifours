#!/usr/bin/env python3
"""cplus_replay.py -- [F] literal replay of c5/proof-Cplus.md (Theorem C+) on the 7 c3 "hyp" words (task OlsonRunCount5, T4).

Usage: python3 cplus_replay.py MUT NV
For every hyp word (regenerated by c5/map5.cpp: out/map5_p11.txt, out/map5_p13.txt) and every integer vector x with
sum x = p and singleton bounds lambda({t}) <= x_t <= p - lambda({t}^c) (random, local-search near-feasible and structured
vectors), the case analysis of Theorem C (c3/proof-C-r1.md Sec. 2) with the refined step (B1+) is followed literally and
must output a proper pattern Q with X_Q < lambda(Q) (a violated constraint of (0.2)); lambda is recomputed for the final Q
by an independent slow routine from the explicit runs (general Lemma H formula with B, kappa, beta).  Every intermediate
claim is asserted: (1.1), (1.2), (1.3), Z nonempty and proper, Case A ((A-i) or (A-ii), deletion drops), Case B ((2.1)-(2.3),
(B1+) |X_o| >= 2 Delta + 1, the block structure m(Q) = m(Z) + Delta + 1, (M), (Fl), (P)).
MUT = 0: real run.  MUT = 1: |S| = Delta instead of Delta + 1 (must break (M) in every Case B instance).
MUT = 2: final test against lambda(Q) - 1 (window shrunk by one): some kills must be lost.
Necessity count (all MUT): Case B instances with |X_o| <= 2 Delta + 1, where the c3 step (B1) (|X_o| >= 2 Delta + 2) fails.
Part 2 (usage: python3 cplus_replay.py MUT NV NW): the implication (0.2) => contradiction of Theorem C+ does not use (H), so
it is replayed on random item-(iii) words (own generator, anti runs in one block, words outside Theorem C included).
"""
import sys, json, random, time
import numpy as np

def words():
    out = []
    for f in ('out/map5_p11.txt', 'out/map5_p13.txt'):
        for line in open(f):
            if '"hypword"' in line: out.append(json.loads(line))
    return out

def slow_lambda(p, d, l, B, kappa, members):
    k = len(d); inQ = [False] * k
    for i in members: inQ[i] = True
    D = sum(d[i] for i in range(k) if inQ[i])
    m = sum(1 for i in range(k) if inQ[i] and not inQ[i - 1])
    beta = sum(1 for i in range(k) if inQ[i] != inQ[i - 1] and l[i - 1] % 2 == 0)   # S_(i-1) between runs i-1, i
    return min(p - m + 1, D + B - kappa + m - beta, (D + B) // 2 + 1)

class Wd:
    def __init__(self, w):
        self.p = w['p']; self.a = w['a']; self.b = w['b']; self.l = w['l']
        self.k = len(self.a); k = self.k
        self.d = [x - y for x, y in zip(self.a, self.b)]
        self.B = sum(self.b); self.A = sum(self.a); H = sum(x // 2 for x in self.l)
        self.kappa = self.p - 1 - H; self.kB = self.kappa - self.B
        self.R = self.A + self.B; self.E = self.R - k; self.D = self.A - self.B
        self.aligned = [t for t in range(k) if self.b[t] == 0]
        self.anti = [t for t in range(k) if self.a[t] == 0]
        self.pairs = [t for t in range(k) if self.a[t] == 1 and self.b[t] == 1]
        assert len(self.aligned) + len(self.anti) + len(self.pairs) == k
        self.nev = sum(1 for t in range(k) if self.d[t] % 2 == 0)
        self.nev_al = sum(1 for t in self.aligned if self.a[t] % 2 == 0)
        self.nev_an = sum(1 for t in self.anti if self.b[t] % 2 == 0)
        self.npr = len(self.pairs)
        N = 1 << k
        idx = np.arange(N, dtype=np.int64)
        self.M = ((idx[:, None] >> np.arange(k)) & 1).astype(np.int64)
        Dq = self.M @ np.array(self.d, dtype=np.int64)
        rot = ((idx << 1) | (idx >> (k - 1))) & (N - 1)
        m = np.array([bin(int(v)).count('1') for v in (idx & ~rot & (N - 1))], dtype=np.int64)
        self.mq = m
        lam = np.minimum(np.minimum(self.p - m + 1, Dq + self.B - self.kappa + m), (Dq + self.B) // 2 + 1)
        self.lam = lam
        self.proper = (idx != 0) & (idx != N - 1)
        self.single_lo = [int(lam[1 << t]) for t in range(k)]
        self.single_hi = [self.p - int(lam[(N - 1) ^ (1 << t)]) for t in range(k)]
    def nviol(self, x):
        X = self.M @ np.array(x, dtype=np.int64)
        return int(np.count_nonzero((X < self.lam) & self.proper))
    def blocks(self, Q):
        k = self.k
        return sum(1 for i in range(k) if (i in Q) and ((i - 1) % k not in Q))

def fl(a, b): return a // b
def cl(a, b): return -((-a) // b)

def procedure(W, x, MUT, stats):
    p, k, kB, B = W.p, W.k, W.kB, W.B
    d = W.d
    assert sum(x) == p
    bh = [2 * x[t] - d[t] for t in range(k)]
    c = [d[t] - x[t] for t in range(k)]
    f = [fl(d[t] - 1, 2) for t in range(k)]
    eps = [c[t] - f[t] for t in range(k)]
    K = kB + W.nev / 2
    assert sum(bh) == 2 * p - W.D == k - 2 * kB
    assert sum(eps) == K
    Z = set(t for t in range(k) if bh[t] <= 0); Nn = set(range(k)) - Z
    for t in Z: assert x[t] <= fl(d[t], 2) and c[t] >= cl(d[t], 2) and eps[t] >= 1 and x[t] <= c[t]
    for t in Nn: assert bh[t] >= 1 + (1 if d[t] % 2 == 0 else 0) and eps[t] <= 0
    s = sum(bh[t] - 1 for t in Nn); sur = -sum(eps[t] for t in Nn)
    nodd_Z = sum(1 for t in Z if d[t] % 2 != 0)
    assert sum(bh[t] for t in Z) == len(Z) - 2 * kB - s and len(Z) + nodd_Z <= 2 * kB + s
    assert sum(eps[t] for t in Z) == K + sur
    assert 0 < len(Z) < k
    mZ = W.blocks(Z); cZ = sum(c[t] for t in Z)
    Phi = lambda Q: sum(c[t] for t in Q) + W.blocks(Q)
    if Phi(Z) >= kB + 1:
        if W.nev_al <= 4:
            stats['A-i'] = stats.get('A-i', 0) + 1
            Q = set(Z)
            XQ = sum(x[t] for t in Q)
            assert XQ + W.blocks(Q) <= p
        else:
            assert 2 * kB <= p
            stats['A-ii'] = stats.get('A-ii', 0) + 1
            for t in Z: assert c[t] <= max(kB - 1, cl(d[t] - B, 2) - 1, d[t] - p) <= p - kB - 1
            Q = set(Z)
            while Phi(Q) > p:
                # delete a run with at most one neighbour in Q
                cand = [t for t in Q if ((t - 1) % k not in Q) or ((t + 1) % k not in Q)]
                t = cand[0]
                before = Phi(Q); Q.discard(t)
                assert before - Phi(Q) <= c[t] + 1 <= p - kB
            assert Phi(Q) >= kB + 1 and len(Q) > 0
        kind = 'A'
        XQ = sum(x[t] for t in Q)
        assert Phi(Q) >= kB + 1 and sum(bh[t] for t in Q) <= B and XQ + W.blocks(Q) <= p
    else:
        Delta = kB - Phi(Z)
        DZ = sum(d[t] for t in Z)
        assert 2 * Delta == (len(Z) - DZ - s) - 2 * mZ                          # (2.1)
        assert Delta == -sum(f[t] for t in Z) - mZ - W.nev / 2 - sur           # (2.2)
        assert Delta <= kB - 1 - sum(cl(d[t], 2) for t in Z)                   # (2.3)
        X = [u for u in W.aligned if u not in Z and eps[u] == 0 and ((u - 1) % k not in Z) and ((u + 1) % k not in Z)]
        Xo = [u for u in X if W.a[u] % 2 == 1]
        assert len(X) >= k - kB - 2 * B + 2 * Delta + W.npr / 2 + W.nev_al / 2  # displayed bound of (B1)
        assert len(Xo) >= 2 * Delta + 1, '(B1+) fails'                          # refined (B1+)
        if len(Xo) <= 2 * Delta + 1: stats['c3_B1_would_fail'] = stats.get('c3_B1_would_fail', 0) + 1
        Xs = set(Xo); S = []
        for u in sorted(Xo):
            if (u - 1) % k in Xs and ((u - 1) % k) in S: continue
            # every other run of each maximal block: take u unless its predecessor in the block was taken
            S.append(u)
        # re-select properly: walk each maximal block from its start
        S = []
        starts = [u for u in Xo if (u - 1) % k not in Xs]
        for st in starts:
            u = st; i = 0
            while u in Xs:
                if i % 2 == 0: S.append(u)
                u = (u + 1) % k; i += 1
        assert len(S) >= Delta + 1
        size = Delta + 1 if MUT != 1 else Delta
        S = S[:size]
        for u in S: assert ((u - 1) % k not in S) and ((u + 1) % k not in S)
        Q = set(Z) | set(S)
        assert W.blocks(Q) == mZ + len(S)
        XQ = sum(x[t] for t in Q)
        okM = Phi(Q) >= kB + 1; okFl = sum(bh[t] for t in Q) <= B; okP = XQ + W.blocks(Q) <= p
        if MUT == 1:
            if not okM: stats['MUT1_M_broken'] = stats.get('MUT1_M_broken', 0) + 1
        else:
            assert okM and okFl and okP, ('B2', okM, okFl, okP)
        kind = 'B'
    # final: X_Q < lambda(Q) with the independent slow lambda
    members = sorted(Q); comp = [t for t in range(k) if t not in Q]
    assert 0 < len(members) < k
    lamQ = slow_lambda(p, d, W.l, B, W.kappa, members)
    if MUT == 2: lamQ -= 1
    XQ = sum(x[t] for t in Q)
    return kind, XQ < lamQ

def gen_vectors(W, rnd, NV):
    k, p = W.k, W.p
    lo, hi = W.single_lo, W.single_hi
    vecs = []
    def random_feasible():
        while True:
            x = [rnd.randint(lo[t], hi[t]) for t in range(k)]
            diff = p - sum(x)
            order = list(range(k)); rnd.shuffle(order)
            for t in order:
                if diff > 0:
                    step = min(diff, hi[t] - x[t]); x[t] += step; diff -= step
                elif diff < 0:
                    step = min(-diff, x[t] - lo[t]); x[t] -= step; diff += step
            if diff == 0: return x
    # 1/3 random, 2/3 local-search local minima (near-feasible)
    for i in range(NV):
        x = random_feasible()
        if i % 3 != 0:
            cur = W.nviol(x)
            improved = True
            while improved:
                improved = False
                pairs = [(i1, j1) for i1 in range(k) for j1 in range(k) if i1 != j1]
                rnd.shuffle(pairs)
                for (i1, j1) in pairs:
                    if x[i1] - 1 < lo[i1] or x[j1] + 1 > hi[j1]: continue
                    x[i1] -= 1; x[j1] += 1
                    v = W.nviol(x)
                    if v < cur: cur = v; improved = True; break
                    x[i1] += 1; x[j1] -= 1
            vecs.append(('localmin', x, cur))
        else:
            vecs.append(('random', x, None))
    return vecs

# ---------------- Part 2: stress test of the refined step on random item-(iii) words (independent of (H)) -------------
class Wg:
    """a general word without the 2^k tables (singleton bounds and the final check via slow_lambda)."""
    def __init__(self, p, a, b, l):
        self.p, self.a, self.b, self.l = p, a, b, l
        self.k = k = len(a)
        self.d = [x - y for x, y in zip(a, b)]
        self.B = sum(b); self.A = sum(a); H = sum(x // 2 for x in l)
        self.kappa = p - 1 - H; self.kB = self.kappa - self.B
        self.R = self.A + self.B; self.E = self.R - k; self.D = self.A - self.B
        self.aligned = [t for t in range(k) if b[t] == 0]
        self.anti = [t for t in range(k) if a[t] == 0]
        self.pairs = [t for t in range(k) if a[t] == 1 and b[t] == 1]
        self.nev = sum(1 for t in range(k) if self.d[t] % 2 == 0)
        self.nev_al = sum(1 for t in self.aligned if a[t] % 2 == 0)
        self.npr = len(self.pairs)
        self.single_lo = [slow_lambda(p, self.d, l, self.B, self.kappa, [t]) for t in range(k)]
        self.single_hi = [p - slow_lambda(p, self.d, l, self.B, self.kappa, [s for s in range(k) if s != t]) for t in range(k)]
    def blocks(self, Q):
        k = self.k
        return sum(1 for i in range(k) if (i in Q) and ((i - 1) % k not in Q))

def item_iii(W):
    p, k = W.p, W.k
    return (all(x % 2 == 1 for x in W.l) and p + 1 <= k <= 2 * p - 2 and W.R <= 2 * p - 3
            and all(x == 0 or y == 0 or (x == 1 and y == 1) for x, y in zip(W.a, W.b))
            and 1 <= W.B <= W.kappa - 1 and W.B <= W.A <= 2 * p - 1 and sum(W.l) + W.R == 4 * p - 2
            and not (k == p + 1 and W.kB == 1))

def random_word(rnd, p):
    """item-(iii) word biased to many even aligned runs (an independent generator, not map3's)."""
    while True:
        k = rnd.randint(p + 1, 2 * p - 3)
        kmin, kmax = max(k - p, 2), (k - 3) // 2
        if kmin > kmax: continue
        kappa = rnd.randint(kmin, kmax)
        B = rnd.randint(1, kappa - 1)
        R = 2 * p - k + 2 * kappa; A = R - B
        if A < B or A > 2 * p - 1: continue
        n0 = rnd.randint(0, min(2, B)); Bp = B - n0
        na = 0 if Bp == 0 else rnd.randint(1, min(Bp, k - n0 - 1))
        nal = k - n0 - na
        Ap = A - n0
        if nal < 1 or Ap < nal: continue
        ca = [1] * nal
        extra = Ap - nal
        while extra > 0:                      # prefer turning length-1 runs into length-2 runs (even aligned runs)
            ones = [i for i in range(nal) if ca[i] == 1]
            if ones and rnd.random() < 0.8: ca[rnd.choice(ones)] += 1
            else: ca[rnd.randrange(nal)] += 1
            extra -= 1
        cb = [1] * na
        for _ in range(Bp - na): cb[rnd.randrange(na)] += 1
        kinds = [0] * nal + [1] * na + [2] * n0
        rnd.shuffle(kinds)
        a, b = [], []; ia = ib = 0
        for t in range(k):
            if kinds[t] == 0: a.append(ca[ia]); b.append(0); ia += 1
            elif kinds[t] == 1: a.append(0); b.append(cb[ib]); ib += 1
            else: a.append(1); b.append(1)
        H = p - 1 - kappa
        l = [1] * k
        for _ in range(H): l[rnd.randrange(k)] += 2
        W = Wg(p, a, b, l)
        if item_iii(W): return W

def caseinfo(W, x):
    """(case, margin) with margin = |X_o| - 2 Delta in Case B (None in Case A)."""
    k, d, kB = W.k, W.d, W.kB
    bh = [2 * x[t] - d[t] for t in range(k)]
    c = [d[t] - x[t] for t in range(k)]
    f = [fl(d[t] - 1, 2) for t in range(k)]
    Z = set(t for t in range(k) if bh[t] <= 0)
    if not (0 < len(Z) < k): return ('degenerate', None)
    Phi = sum(c[t] for t in Z) + W.blocks(Z)
    if Phi >= kB + 1: return ('A', None)
    Delta = kB - Phi
    X = [u for u in W.aligned if u not in Z and c[u] - f[u] == 0 and ((u - 1) % k not in Z) and ((u + 1) % k not in Z)]
    Xo = [u for u in X if W.a[u] % 2 == 1]
    return ('B', len(Xo) - 2 * Delta)

def random_word_block(rnd, p):
    """as random_word, but the anti runs and pairs form ONE contiguous block (so that Case B with one defect block occurs)."""
    while True:
        W = random_word(rnd, p)
        k = W.k
        nonal = [t for t in range(k) if W.b[t] > 0]
        al = [t for t in range(k) if W.b[t] == 0]
        order = nonal + al
        a = [W.a[t] for t in order]; b = [W.b[t] for t in order]
        sh = rnd.randrange(k)
        a = a[sh:] + a[:sh]; b = b[sh:] + b[:sh]
        l = W.l[:]; rnd.shuffle(l)
        W2 = Wg(p, a, b, l)
        if item_iii(W2): return W2

def caseB_vector(W, rnd):
    """baseline x (bh = 1 for odd d, 2 for even d, i.e. eps = 0) on aligned runs, minimal-c defects on anti runs/pairs,
    then random unit corrections (non-defect bumps x + 1, deeper defects x - 1) to reach sum p; None if bounds forbid."""
    k, p, d = W.k, W.p, W.d
    lo, hi = W.single_lo, W.single_hi
    x = [0] * k
    for t in range(k):
        if W.b[t] > 0:                       # anti run or pair: defect, bh = 2x - d <= 0 (odd d: <= -1)
            x[t] = (d[t] - 1) // 2 if d[t] % 2 != 0 else d[t] // 2
        else:
            x[t] = (d[t] + 1) // 2 if d[t] % 2 != 0 else d[t] // 2 + 1
        x[t] = min(max(x[t], lo[t]), hi[t])
    diff = p - sum(x)
    guard = 0
    while diff != 0 and guard < 10000:
        guard += 1
        t = rnd.randrange(k)
        if diff > 0 and x[t] + 1 <= hi[t] and (W.b[t] == 0 or rnd.random() < 0.2): x[t] += 1; diff -= 1
        elif diff < 0 and x[t] - 1 >= lo[t] and (W.b[t] > 0 or rnd.random() < 0.2): x[t] -= 1; diff += 1
    return x if diff == 0 else None

def part2(MUT, NW, NV, seed):
    """per prime p in (11, 13, 17, 19): NW item-(iii) words with all anti runs/pairs in one block, 2kB <= p and the
    (ii+) count condition s0 := (k - kB - 2B) + (n_pr - n_ev,al)/2 >= 1, two thirds of them with s0 < 2 (where the c3
    step (B1) can fail); NV vectors each (two thirds targeted at Case B, one third random with singleton bounds)."""
    rnd = random.Random(seed)
    tot = {'words': 0, 'words_outside_thmC': 0, 'words_s0_lt_2': 0, 'vectors': 0, 'kills': 0, 'nokill': 0,
           'assert_failures': 0, 'caseA': 0, 'caseB': 0, 'caseB_margin_1_c3_B1_fails': 0, 'MUT1_M_broken': 0}
    hist = {}
    ex = []
    for p in (11, 13, 17, 19):
        made = 0; tries = 0
        while made < NW and tries < 400000:
            tries += 1
            W = random_word_block(rnd, p)
            s0 = (W.k - W.kB - 2 * W.B) + (W.npr - W.nev_al) / 2
            if not (2 * W.kB <= p and s0 >= 1): continue
            if s0 >= 2 and made % 3 != 0: continue
            made += 1; tot['words'] += 1
            if s0 < 2: tot['words_s0_lt_2'] += 1
            if not (W.nev_al <= 4 or (2 * W.kB <= p and W.nev_al <= 2 * W.kB + 2)): tot['words_outside_thmC'] += 1
            lo, hi = W.single_lo, W.single_hi
            for v in range(NV):
                if v % 3 != 2:
                    x = caseB_vector(W, rnd)
                    if x is None: continue
                else:
                    if sum(lo) > p or sum(hi) < p: continue
                    x = [rnd.randint(lo[t], hi[t]) for t in range(W.k)]
                    diff = p - sum(x)
                    order = list(range(W.k)); rnd.shuffle(order)
                    for t in order:
                        if diff > 0: st = min(diff, hi[t] - x[t]); x[t] += st; diff -= st
                        elif diff < 0: st = min(-diff, x[t] - lo[t]); x[t] -= st; diff += st
                stats = {}
                tot['vectors'] += 1
                try:
                    kind, kill = procedure(W, x, MUT, stats)
                    tot['case' + kind] += 1
                    if kill: tot['kills'] += 1
                    else: tot['nokill'] += 1
                    if kind == 'B':
                        cs, mg = caseinfo(W, x)
                        hist[mg] = hist.get(mg, 0) + 1
                        if mg <= 1: tot['caseB_margin_1_c3_B1_fails'] += 1
                    tot['MUT1_M_broken'] += stats.get('MUT1_M_broken', 0)
                except AssertionError as e:
                    tot['assert_failures'] += 1
                    if len(ex) < 4: ex.append((p, W.a, W.b, x, str(e)[:80]))
    tot['caseB_margin_histogram'] = sorted(hist.items())
    return tot, ex

def main():
    MUT = int(sys.argv[1]); NV = int(sys.argv[2]); NW = int(sys.argv[3]) if len(sys.argv) > 3 else 60
    rnd = random.Random(5005 + MUT)
    t0 = time.time()
    print('== cplus_replay.py MUT=%d NV=%d NW=%d start %s' % (MUT, NV, NW, time.strftime('%Y-%m-%dT%H:%M:%S')), flush=True)
    print('-- Part 1: the 7 hyp words of the c3 samples', flush=True)
    for wi, w in enumerate(words()):
        W = Wd(w)
        cond = (2 * (W.k - W.kB - 2 * W.B) + W.npr - 2 >= W.nev_al) and (2 * W.kB <= W.p)
        forced = (sum(W.single_lo) == W.p)
        stats = {}; kills = 0; nokill = 0; asserts = []; minviol = None
        for (tag, x, nv) in gen_vectors(W, rnd, NV):
            if nv is not None: minviol = nv if minviol is None else min(minviol, nv)
            try:
                kind, kill = procedure(W, x, MUT, stats)
                stats[kind] = stats.get(kind, 0) + 1
                if kill: kills += 1
                else: nokill += 1
            except AssertionError as e:
                asserts.append(str(e)[:80])
        print(json.dumps({'word': wi, 'p': W.p, 'k': W.k, 'kB': W.kB, 'B': W.B, 'n_ev_al': W.nev_al, 'n_pr': W.npr,
                          'hyp_C+': cond, 'x_forced_to_d': forced, 'vectors': NV, 'kills': kills, 'nokill': nokill,
                          'assert_failures': len(asserts), 'assert_examples': asserts[:3], 'stats': stats,
                          'min_violations_localsearch': minviol, 't': round(time.time() - t0, 1)}), flush=True)
    print('-- Part 2: random item-(iii) words with 2kB <= p and the (ii+) count condition (no (H) needed for the implication)', flush=True)
    tot, ex = part2(MUT, NW, NV, 7007 + MUT)
    print(json.dumps({'part2': tot, 'first_failures': ex}), flush=True)
    print('== end %.1f s' % (time.time() - t0), flush=True)

if __name__ == '__main__':
    main()
