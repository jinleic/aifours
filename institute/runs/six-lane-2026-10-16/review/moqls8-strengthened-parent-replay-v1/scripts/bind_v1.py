def die(msg):
    raise SystemExit("ABORT: %s" % msg)


def sha_bytes(b):
    return hashlib.sha256(b).hexdigest()


def sha_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def now():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def load_v1():
    """Execute the pinned bytes of the prior desk's replay_v1.py as a module (its main() does not run)."""
    src = read_bytes(V1_SCRIPT)
    if sha_bytes(src) != PINNED[V1_SCRIPT]:
        die("replay_v1.py sha256 differs from the pin")
    mod = types.ModuleType("replay_v1_pinned")
    mod.__file__ = V1_SCRIPT
    exec(compile(src, V1_SCRIPT, "exec"), mod.__dict__)
    return mod


def main(argv):
    if len(argv) != 2:
        die(__doc__)
    out = os.path.abspath(argv[1])
    if not out.startswith(DESK + "/") or os.path.lexists(out):
        die("output path must be new and inside the desk")
    if os.environ.get("TMPDIR") != TMP + "/":
        die("TMPDIR must be %s/" % TMP)
    os.chdir(TMP)
    t0 = time.monotonic()
    started = now()
    mismatches = []

    def expect(cond, what):
        if not cond:
            mismatches.append(what)
        return bool(cond)

    # --- pins
    pinned = []
    raw = {}
    for path, exp in PINNED.items():
        raw[path] = read_bytes(path)
        got = sha_bytes(raw[path])
        pinned.append({"path": path, "expected_sha256": exp, "sha256": got, "ok": got == exp})
        if got != exp:
            die("pin mismatch %s: %s" % (path, got))
    nf_text = raw[NF_R2].decode("utf-8")
    for frag in ("M_s can be imposed by126 negative binary clauses for i=2..7 and1≤c<d≤7:",
                 "NOT g_s((0,c),(i,0)) OR NOT g_s((0,d),(i,0)).",
                 "A source leaf5740268clauses would become5740394clauses."):
        if frag not in nf_text:
            die("normal form r2 section-5 fragment missing: " + frag)
    nf_check_text = raw[NF_CHECK].decode("utf-8")
    nf_lines = nf_check_text.split("\n")
    for frag in NF_FRAGMENTS:
        if frag not in nf_lines:
            die("parent check script tail fragment missing: " + frag)
    nf_res = json.loads(raw[NF_RESULT])
    if not (nf_res.get("status") == "PASS" and nf_res.get("script_sha256") == PINNED[NF_CHECK]
            and nf_res.get("name_map_sha256") == MAP_SHA and nf_res.get("manifest_sha256") == MANIFEST_SHA):
        die("parent normal-form RESULT fields")
    nf_fp = {int(k): v["ordered_bytes_sha256"] for k, v in nf_res["mononomial_clause_checks"].items()}
    if nf_fp != TAIL_FP or any(v["clauses"] != 126 for v in nf_res["mononomial_clause_checks"].values()):
        die("parent RESULT fingerprints differ from the brief")
    bres = json.loads(raw[BIND_RESULT])
    bleaves = {x["id"]: x["cnf_sha256"] for x in bres["leaves"]}
    worker = json.loads(raw[WORKER_HASHES])

    # --- step 1: source leaves exactly as the prior desk regenerated them
    v1 = load_v1()
    if v1.LEAF_HEADER != LEAF_HEADER or v1.PINS[v1.MAP_REL] != MAP_SHA or v1.PINS[v1.MANIFEST_REL] != MANIFEST_SHA:
        die("replay_v1 constants")
    ctx = v1.load_inputs(lambda msg: print("replay_v1.load_inputs: " + msg, flush=True))
    body = ctx["body"]
    body_len = len(body)
    body_lines = body.count(b"\n")
    if body_lines != BODY_CLAUSES or not body.endswith(b" 0\n"):
        die("weak body line count %d" % body_lines)
    manifest = json.loads(read_bytes(os.path.join(LANE, v1.MANIFEST_REL)))
    mleaves = {c["id"]: c for c in manifest["cases"]}
    leaves = {}
    for template in sorted({t for _f, t, _s in FORMULAS}):
        case = ctx["cases"][template]
        ub = case["unit_bytes"]
        h = hashlib.sha256(LEAF_HEADER)
        h.update(body)
        h.update(ub)
        hx = h.hexdigest()
        n = len(LEAF_HEADER) + body_len + len(ub)
        ok = (hx == case["cnf_sha256"] == bleaves[template] == mleaves[template]["cnf_sha256"]
              and n == case["cnf_bytes"] and ub.count(b"\n") == UNIT_CLAUSES
              and mleaves[template]["cnf_clauses"] == LEAF_CLAUSES and mleaves[template]["cnf_vars"] == NVARS)
        if not ok:
            die("source leaf recomputation " + template)
        leaves[template] = {"cnf_sha256": hx, "cnf_bytes": n, "parent_binding_result_cnf_sha256": bleaves[template],
                            "manifest_cnf_sha256": mleaves[template]["cnf_sha256"], "units": case["units"],
                            "supports_row2to7": case["supports"], "unit_lines_sha256": sha_bytes(ub),
                            "unit_lines_bytes": len(ub), "equal_parent_binding_and_manifest": True}

    # --- step 2: M_s tails from the bound name map
    map_raw = read_bytes(os.path.join(LANE, v1.MAP_REL))
    if sha_bytes(map_raw) != MAP_SHA:
        die("name map sha256")
    gmap = json.loads(map_raw)
    names = gmap["vars"]
    parsed = {}
    for key, v in names.items():
        k = json.loads(key)
        if k[0] == "g":
            parsed[(k[1], tuple(k[2]), tuple(k[3]))] = v
    if len(parsed) != 7840 or gmap["meta"]["vars"] != NVARS or gmap["meta"]["cnf_sha256"] != ctx["info"]["source_cnf_sha256"]:
        die("name map binding")
    tails, tail_info = {}, {}
    for s in (2, 3, 4, 5):
        clauses, rows, affine = [], [], True
        for i in range(2, 8):
            for c, d in itertools.combinations(range(1, 8), 2):
                a = names[json.dumps(["g", s, [0, c], [i, 0]])]
                b = names[json.dumps(["g", s, [0, d], [i, 0]])]
                if parsed[(s, (0, c), (i, 0))] != a or parsed[(s, (0, d), (i, 0))] != b:
                    die("name map key forms disagree")
                if not (1 <= a <= NVARS and 1 <= b <= NVARS and a != b):
                    die("tail variable range")
                affine = affine and a == 1568 * (s - 1) + 49 * c + 7 * i - 6 and b == 1568 * (s - 1) + 49 * d + 7 * i - 6
                cl = tuple(sorted((-a, -b)))
                clauses.append(cl)
                rows.append([i, c, d, a, b, "%d %d 0" % cl])
        if len(clauses) != TAIL_CLAUSES or len(set(clauses)) != TAIL_CLAUSES or not all(x < 0 and y < 0 for x, y in clauses):
            die("tail clause set s=%d" % s)
        tb = "".join("%d %d 0\n" % cl for cl in clauses).encode("ascii")
        tx = sha_bytes(tb)
        expect(tx == TAIL_FP[s] == nf_fp[s], "tail s=%d sha256 %s != parent fingerprint %s" % (s, tx, TAIL_FP[s]))
        tails[s] = tb
        tail_info[str(s)] = {"sha256": tx, "bytes": len(tb), "clauses": len(clauses),
                             "parent_result_fingerprint": nf_fp[s], "brief_fingerprint": TAIL_FP[s],
                             "equal_parent_fingerprint": tx == nf_fp[s] == TAIL_FP[s],
                             "variables": sorted({-x for cl in clauses for x in cl}),
                             "affine_check_v_eq_1568(s-1)+49c+7i-6": affine,
                             "derivation_rows_i_c_d_a_b_line": rows}

    # --- step 3: composition, step 4: worker comparison
    m = re.match(br"^p cnf (\d+) (\d+)\n$", LEAF_HEADER)
    derived_header = b"p cnf %d %d\n" % (int(m.group(1)), int(m.group(2)) + TAIL_CLAUSES)
    if derived_header != STRONG_HEADER:
        die("derived strengthened header")
    wformulas = {f["id"]: f for f in worker["formulas"]}
    worker_file_checks = {
        "proof_r2_sha256_equals_normal_form_pin": worker.get("proof_r2_sha256") == PINNED[NF_R2],
        "source_manifest_sha256_equals_pin": worker.get("source_manifest_sha256") == MANIFEST_SHA,
        "name_map_sha256_equals_pin": worker.get("name_map_sha256") == MAP_SHA,
        "weak_base_sha256_equals_parent_regenerated": worker.get("weak_base_sha256") == ctx["info"]["weak_base_sha256"],
        "formula_ids_equal": sorted(wformulas) == sorted(f for f, _t, _s in FORMULAS),
    }
    for k, v in worker_file_checks.items():
        expect(v, "worker file field " + k)
    formulas = []
    for fid, template, s in FORMULAS:
        ub = ctx["cases"][template]["unit_bytes"]
        tb = tails[s]
        h = hashlib.sha256(STRONG_HEADER)
        h.update(body)
        h.update(ub)
        base = h.copy()
        h.update(tb)
        hx = h.hexdigest()
        nbytes = len(STRONG_HEADER) + body_len + len(ub) + len(tb)
        nclauses = body_lines + ub.count(b"\n") + tb.count(b"\n")
        first, rest = tb.split(b"\n", 1)
        lits = first.split(b" ")
        mutant = b"%d %s %s\n" % (-int(lits[0]), lits[1], lits[2]) + rest
        mh = base.copy()
        mh.update(mutant)
        if mh.hexdigest() == hx:
            die("tail mutation not detected " + fid)
        w = wformulas.get(fid, {})
        cmp = {
            "cnf_sha256_equals_worker_planned": hx == w.get("CNF_sha256_PLANNED"),
            "cnf_sha256_equals_brief_worker_value": hx == WORKER_EXPECTED[fid],
            "bytes_equal_worker_expected_stream_bytes": nbytes == w.get("expected_stream_bytes_PLANNED"),
            "header_equal": STRONG_HEADER.decode() == w.get("header"),
            "variables_equal": NVARS == w.get("variables"),
            "clauses_equal": nclauses == w.get("clauses") == LEAF_CLAUSES + TAIL_CLAUSES,
            "source_template_equal": w.get("source_template") == template,
            "monomial_square_equal": w.get("monomial_square") == s,
            "source_leaf_sha256_equal": w.get("source_leaf_sha256") == leaves[template]["cnf_sha256"],
            "unit_tail_sha256_equal": w.get("unit_tail_sha256") == sha_bytes(ub),
            "M_tail_sha256_equal": w.get("M_tail_sha256") == sha_bytes(tb),
            "original_unit_count_equal": w.get("original_unit_count") == UNIT_CLAUSES,
            "appended_binary_clauses_equal": w.get("appended_binary_clauses") == TAIL_CLAUSES,
        }
        for k, v in cmp.items():
            expect(v, "%s: %s" % (fid, k))
        formulas.append({"id": fid, "source_template": template, "monomial_square": s,
                         "parent_composed_cnf_sha256": hx, "parent_composed_bytes": nbytes,
                         "clauses_counted": nclauses, "variables": NVARS, "header": STRONG_HEADER.decode(),
                         "composition": ["header p cnf 509915 5740394 (%d B)" % len(STRONG_HEADER),
                                         "weak body unchanged (%d B, %d clauses, sha256 %s)"
                                         % (body_len, body_lines, ctx["info"]["body_sha256"]),
                                         "42 unit lines unchanged (%d B, sha256 %s)" % (len(ub), sha_bytes(ub)),
                                         "M_%d tail (%d B, 126 clauses, sha256 %s)" % (s, len(tb), sha_bytes(tb))],
                         "source_leaf_cnf_sha256": leaves[template]["cnf_sha256"],
                         "tail_mutation_check": {"mutation": "first tail literal sign-flipped",
                                                 "mutant_cnf_sha256": mh.hexdigest(), "differs": True},
                         "worker": {k: w.get(k) for k in ("CNF_sha256_PLANNED", "expected_stream_bytes_PLANNED", "header",
                                                          "variables", "clauses", "source_leaf_sha256",
                                                          "unit_tail_sha256", "M_tail_sha256", "ordering")},
                         "brief_worker_value": WORKER_EXPECTED[fid], "comparison": cmp,
                         "all_equal": all(cmp.values())})
        print("%s parent %s bytes %d worker %s equal=%s" % (fid, hx, nbytes, w.get("CNF_sha256_PLANNED"),
                                                            all(cmp.values())), flush=True)
    status = "MATCH" if not mismatches else "MISMATCH"
    result = {
        "schema": "moqls8-strengthened-parent-binding/1", "status": status, "mismatches": mismatches,
        "started_at": started, "desk": DESK, "scope": SCOPE,
        "script": {"path": SCRIPT_REL, "sha256": sha_file(SCRIPT)},
        "python": {"executable": sys.executable, "version": sys.version.split()[0], "flags": "-I -B"},
        "inputs_pinned": pinned,
        "normal_form_r2_section5_fragments_present": True,
        "parent_check_script_tail_fragments_present": list(NF_FRAGMENTS),
        "parent_check_result": {"path": NF_RESULT, "status": nf_res["status"], "at": nf_res.get("at"),
                                "fingerprints": {str(k): v for k, v in sorted(nf_fp.items())},
                                "name_map_sha256": nf_res["name_map_sha256"],
                                "manifest_sha256": nf_res["manifest_sha256"]},
        "source_leaf_regeneration": {
            "method": "exec of the pinned replay_v1.py bytes (sha256 %s) as a module; load_inputs() called exactly as "
                      "the prior desk did; leaf hashes then recomputed here from the returned body and unit bytes"
                      % PINNED[V1_SCRIPT],
            "replay_v1_load_inputs_info": ctx["info"], "leaves": leaves},
        "name_map": {"path": os.path.join(LANE, v1.MAP_REL), "sha256": MAP_SHA, "g_entries": len(parsed),
                     "meta_vars": gmap["meta"]["vars"], "meta_cnf_sha256": gmap["meta"]["cnf_sha256"]},
        "tail_derivation": {
            "rule": "for s in (2,3,4,5): for i in 2..7: for (c,d) in itertools.combinations(1..7, 2): "
                    "a = vars[json.dumps(['g',s,[0,c],[i,0]])], b = vars[json.dumps(['g',s,[0,d],[i,0]])]; "
                    "clause = tuple(sorted((-a,-b))); line = '%d %d 0\\n' % clause (ASCII, LF)",
            "serialization": "literals ascending within each clause (so -b before -a, since b > a), single spaces, "
                             "terminating ' 0', LF; clauses in i, then (c,d) lexicographic order",
            "tails": tail_info},
        "composition_rule": "header 'p cnf 509915 5740268' -> 'p cnf 509915 5740394' (clause count + 126, variable "
                            "count unchanged); weak body and the 42 unit lines unchanged and in place; the M_s tail "
                            "appended after the last unit line",
        "worker_file": {"path": WORKER_HASHES, "sha256": PINNED[WORKER_HASHES], "use": "comparison target only",
                        "schema": worker.get("schema"), "generator_sha256": worker.get("generator_sha256"),
                        "freeze_sha256": worker.get("freeze_sha256"), "producer_sha256": worker.get("producer_sha256"),
                        "coverage_status": worker.get("coverage_status"), "file_checks": worker_file_checks},
        "formulas": formulas,
        "cnf_or_proof_bytes_written_to_disk": False, "native_tools_started": 0,
        "peak_rss_bytes_self": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        "seconds": round(time.monotonic() - t0, 2), "written_at": now()}
    with open(out, "x") as f:
        json.dump(result, f, indent=1)
        f.write("\n")
    print("BINDING %s status %s sha256 %s" % (out, status, sha_file(out)), flush=True)
    for x in mismatches:
        print("MISMATCH " + x, flush=True)
    if mismatches:
        raise SystemExit(2)


if __name__ == "__main__":
    main(sys.argv)
