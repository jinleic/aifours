def check_char(wrong_coefficient=False, gram=1):
    basis, matrix, poly = matrix_and_char(wrong_coefficient, gram)
    require(poly == expected_char(), 'wrong_contraction_characteristic')
    return basis, matrix, poly


def intended_failure(name, operation, expected):
    try:
        operation()
    except Rejected as exc:
        require(str(exc) == expected, 'unexpected_mutation_reason:' + name)
        return {'name': name, 'reason': str(exc)}
    raise Rejected('mutation_accepted:' + name)


