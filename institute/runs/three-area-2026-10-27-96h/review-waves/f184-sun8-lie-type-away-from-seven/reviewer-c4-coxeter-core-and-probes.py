# ---------------- Part B: length convention in (I2) ----------------
def relative_data(typ, n, sigma):
    S, mul, I = matrix_coxeter(cartan(typ, n))
    N, tab, inv, L, Sidx = build(S, mul, I)
    # sigma acts on W via s_i -> s_sigma(i); compute action by words
    elems = list(range(N))
    # BFS words
    word = {0: ()}
    frontier = [0]
    while frontier:
        nxt = []
        for x in frontier:
            for i, s in enumerate(Sidx):
                y = tab[s][x]
                if y not in word:
                    word[y] = (i,) + word[x]; nxt.append(y)
        frontier = nxt
    def sig(x):
        y = 0
        for i in word[x]:
            y = tab[y][Sidx[sigma[i]]]
        return y
    fixed = [x for x in elems if sig(x) == x]
    # orbits of simple reflections
    seen = set(); orbits = []
    for i in range(n):
        if i not in seen:
            O = []; j = i
            while j not in O:
                O.append(j); j = sigma[j]
            seen |= set(O); orbits.append(tuple(sorted(O)))
    # s_O = longest element of W_O
    def close(gens):
        H = {0}; fr = [0]
        while fr:
            nx = []
            for h in fr:
                for g in gens:
                    x = tab[g][h]
                    if x not in H:
                        H.add(x); nx.append(x)
            fr = nx
        return H
    sO = []
    for O in orbits:
        WO = close([Sidx[i] for i in O])
        sO.append(max(WO, key=lambda x: L[x]))
    # relative length via BFS over W^sigma with generators sO
    rl = {0: 0}; fr = [0]
    while fr:
        nx = []
        for x in fr:
            for g in sO:
                y = tab[g][x]
                if y not in rl:
                    rl[y] = rl[x] + 1; nx.append(y)
        fr = nx
    gen_ok = set(rl) == set(fixed)
    return dict(N=N, tab=tab, L=L, Sidx=Sidx, fixed=fixed, orbits=orbits, sO=sO, rl=rl, gen_ok=gen_ok, close=close)

def bruhat_sums(D, keepJ):
    """Sum over cosets of W^sigma_J in W^sigma: minimal-abs-length rep; returns (abs-poly, rel-poly)."""
    tab, L, rl = D["tab"], D["L"], D["rl"]
    WJ = D["close"]([D["sO"][k] for k in keepJ]) if keepJ else {0}
    seen = set(); absp = {}; relp = {}
    for w in D["fixed"]:
        if w in seen:
            continue
        coset = {tab[w][j] for j in WJ}
        seen |= coset
        mrep = min(coset, key=lambda x: L[x])
        absp[L[mrep]] = absp.get(L[mrep], 0) + 1
        relp[rl[mrep]] = relp.get(rl[mrep], 0) + 1
    to_list = lambda d: [d.get(i, 0) for i in range(max(d) + 1)]
    return to_list(absp), to_list(relp)

def pm(a, b):
    r = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            r[i + j] += x * y
    return r

