# ---------------- Coxeter groups as permutation/matrix groups ----------------
def cartan(typ, n):
    A = [[0] * n for _ in range(n)]
    for i in range(n):
        A[i][i] = 2
    def link(i, j, aij=-1, aji=-1):
        A[i][j] = aij; A[j][i] = aji
    if typ == 'A':
        for i in range(n - 1): link(i, i + 1)
    elif typ == 'B':
        for i in range(n - 2): link(i, i + 1)
        link(n - 2, n - 1, -2, -1)
    elif typ == 'D':
        for i in range(n - 2): link(i, i + 1)
        link(n - 3, n - 1)
    elif typ == 'E':
        link(0, 2); link(2, 3); link(1, 3)
        for i in range(3, n - 1): link(i, i + 1)
    elif typ == 'F':
        link(0, 1); link(1, 2, -2, -1); link(2, 3)
    elif typ == 'G':
        link(0, 1, -1, -3)
    return A

def matrix_coxeter(A):
    n = len(A)
    S = []
    for i in range(n):
        M = [[(1 if r == c else 0) for c in range(n)] for r in range(n)]
        for j in range(n):
            M[i][j] -= A[i][j]
        S.append(tuple(tuple(r) for r in M))
    def mul(X, Y):
        return tuple(tuple(sum(X[r][k] * Y[k][c] for k in range(n)) for c in range(n)) for r in range(n))
    I = tuple(tuple(1 if r == c else 0 for c in range(n)) for r in range(n))
    return S, mul, I

def perm_coxeter_dihedral(m):
    # Action on vertices plus edge midpoints (2m points), faithful even for m=2.
    N = 2 * m
    s = tuple((-i) % N for i in range(N))
    t = tuple((2 - i) % N for i in range(N))
    def mul(X, Y):  # X after Y
        return tuple(X[Y[i]] for i in range(N))
    return [s, t], mul, tuple(range(N))

def build(S, mul, I):
    """BFS: elements with lengths; index table for multiplication."""
    length = {I: 0}; order = [I]; frontier = [I]
    while frontier:
        nxt = []
        for X in frontier:
            for s in S:
                Y = mul(s, X)
                if Y not in length:
                    length[Y] = length[X] + 1; order.append(Y); nxt.append(Y)
        frontier = nxt
    idx = {X: i for i, X in enumerate(order)}
    N = len(order)
    tab = [[idx[mul(order[a], order[b])] for b in range(N)] for a in range(N)]
    inv = [next(b for b in range(N) if tab[a][b] == 0) for a in range(N)]
    L = [length[X] for X in order]
    Sidx = [idx[s] for s in S]
    return N, tab, inv, L, Sidx

def all_subgroups(N, tab):
    def close(gens):
        H = {0}; frontier = [0]
        gens = list(gens)
        while frontier:
            nxt = []
            for h in frontier:
                for g in gens:
                    x = tab[g][h]
                    if x not in H:
                        H.add(x); nxt.append(x)
            frontier = nxt
        return frozenset(H)
    cyc = {close([g]) for g in range(N)}
    subs = set(cyc) | {frozenset([0])}
    frontier = list(subs)
    while frontier:
        nxt = []
        for K in frontier:
            for C in cyc:
                if not C <= K:
                    J = close(list(K) + list(C))
                    if J not in subs:
                        subs.add(J); nxt.append(J)
        frontier = nxt
    return subs, close

def coxeter_core_test(label, S, mul, I):
    N, tab, inv, L, Sidx = build(S, mul, I)
    subs, close = all_subgroups(N, tab)
    std = {}
    for r in range(len(Sidx) + 1):
        for J in itertools.combinations(range(len(Sidx)), r):
            std[frozenset(J)] = close([Sidx[j] for j in J]) if J else frozenset([0])
    stdset = set(std.values())
    def P(Wp):
        for w in Wp:
            for s in Sidx:
                if L[tab[s][w]] < L[w]:
                    if tab[tab[inv[w]][s]][w] not in Wp:
                        return False
        return True
    satisfying = [K for K in subs if P(K)]
    nonstd_satisfying = [K for K in satisfying if K not in stdset]
    std_all_satisfy = all(P(K) for K in stdset)
    # J recovered as W' n S
    J_ok = all(std[frozenset(j for j, s in enumerate(Sidx) if s in K)] == K for K in satisfying)
    rec = {"|W|": N, "num_subgroups": len(subs), "num_standard_parabolics": len(stdset),
           "num_subgroups_with_P": len(satisfying), "nonstandard_with_P": len(nonstd_satisfying),
           "standard_all_have_P": std_all_satisfy, "J=W'nS_recovers": J_ok,
           "num_nonstandard_subgroups_violating_P": len(subs) - len(satisfying)}
    ok = (not nonstd_satisfying) and std_all_satisfy and J_ok and len(satisfying) == len(stdset)
    check(f"A:Coxeter core {label}", ok, rec)
    return rec, N, tab, inv, L, Sidx, close

