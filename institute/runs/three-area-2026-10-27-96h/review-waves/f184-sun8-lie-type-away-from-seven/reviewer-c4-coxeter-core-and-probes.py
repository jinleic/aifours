def is_even(p):
    seen = [False] * len(p); sign = 1
    for i in range(len(p)):
        if not seen[i]:
            j = i; c = 0
            while not seen[j]:
                seen[j] = True; j = p[j]; c += 1
            if c % 2 == 0:
                sign = -sign
    return sign == 1
