# ---------------- Part C: 2E6 orbit -> Levi pairing ----------------
def trim(p):
    p = list(p)
    while p and p[-1] == 0:
        p.pop()
    return p
def xm(n, c):
    p = [0] * (n + 1); p[n] = 1; p[0] -= c
    return trim(p)
def prod(ps):
    r = [1]
    for p in ps:
        r = trim(pm(r, p))
    return r
def pdiv(a, b):
    a = trim(a); b = trim(b); r = a[:]; q = [0] * max(len(a) - len(b) + 1, 1)
    while r and len(r) >= len(b):
        c = r[-1] // b[-1]; k = len(r) - len(b); q[k] = c
        for i, bi in enumerate(b):
            r[k + i] -= c * bi
        r = trim(r)
    return trim(q), r
def orbit_fixed_poly(A, O, sigma):
    n = len(A)
    start = tuple(1 if j in O else 0 for j in range(n))
    seen = {start}; frontier = [start]; fixc = []
    while frontier:
        fixc.append(sum(1 for mu in frontier if all(mu[sigma[j]] == mu[j] for j in range(n))))
        nxt = []
        for lam in frontier:
            for i in range(n):
                c = lam[i]
                if c > 0:
                    mu = tuple(lam[j] - c * A[i][j] for j in range(n))
                    if mu not in seen:
                        seen.add(mu); nxt.append(mu)
        frontier = nxt
    return trim(fixc)
