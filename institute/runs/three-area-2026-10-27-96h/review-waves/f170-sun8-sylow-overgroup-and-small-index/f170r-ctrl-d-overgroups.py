def factor(n):
    f = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


class Group:
    def __init__(self, mul, e):
        self.mul = mul
        self.e = e

    def closure(self, gens, limit):
        seen = {self.e}
        frontier = [self.e]
        while frontier:
            nxt = []
            for x in frontier:
                for g in gens:
                    y = self.mul(x, g)
                    if y not in seen:
                        seen.add(y)
                        nxt.append(y)
            if len(seen) > limit:
                return None
            frontier = nxt
        return frozenset(seen)

    def power(self, x, k):
        r = self.e
        b = x
        while k:
            if k & 1:
                r = self.mul(r, b)
            b = self.mul(b, b)
            k >>= 1
        return r

    def order_of(self, x, cap):
        y = x
        k = 1
        while y != self.e:
            y = self.mul(y, x)
            k += 1
            if k > cap:
                return None
        return k


def overgroup_analysis(G, elems, x, Gorder, limit):
    """All proper overgroups of P=<x>; return (P, proper overgroups, maximal ones)."""
    P = G.closure([x], Gorder)
    plist = list(P)
    marked = set()
    reps = []
    for g in elems:
        if g in marked:
            continue
        reps.append(g)
        for a in plist:
            ag = G.mul(a, g)
            for b in plist:
                marked.add(G.mul(ag, b))
    assert len(marked) == Gorder
    over = {}
    for g in reps:
        S = G.closure([x, g], limit)
        if S is not None:
            over.setdefault(S, [x, g])
    changed = True
    while changed:
        changed = False
        items = list(over.items())
        for (A, ga), (B, gb) in itertools.combinations(items, 2):
            if A <= B or B <= A:
                continue
            S = G.closure(ga + gb, limit)
            if S is not None and S not in over:
                over[S] = ga + gb
                changed = True
    props = list(over.keys())
    maximal = [A for A in props if not any(A < B for B in props)]
    return P, len(reps), props, maximal


def psl2(q):
    inv = {a: pow(a, -1, q) for a in range(1, q)}

    def norm(m):
        n = tuple((-v) % q for v in m)
        return min(m, n)

    def mul(m, n):
        a, b, c, d = m
        e, f, g, h = n
        return norm(((a * e + b * g) % q, (a * f + b * h) % q, (c * e + d * g) % q, (c * f + d * h) % q))

    els = set()
