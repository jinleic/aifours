RGRAPH_PS = os.path.join(HERE, "rv161-dfz-src/rv161-bcdrv/RGraph.ps")


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def clock():
    return subprocess.run(["/bin/date", "+%Y-%m-%dT%H:%M:%S%z"], capture_output=True, text=True).stdout.strip()


def parse_dfz_fourcopy_list():
    raw = open(DFZ_TEX, "rb").read()
    assert hashlib.sha256(raw).hexdigest() == DFZ_TEX_SHA
    lines = raw.decode("latin-1").split("\n")
    start = next(i for i, s in enumerate(lines) if s.startswith(r"\section{Inequalities Using Four Copy Variables"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith(r"\end{enumerate}"))
    items = {}
    for ln in range(start, end):
        m = re.match(r"\\item ((?:\d+ ){9})(.*)$", lines[ln])
        if m:
            tup = tuple(int(x) for x in m.group(1).split())
            items.setdefault(tup, []).append((ln + 1, m.group(2).strip()))
    return items, start + 1, end + 1


def main():
    t0 = clock()
    rec = {"reviewer_script": "rv161_cert_check.py", "script_sha256": sha(__file__),
           "lib_sha256": sha(os.path.join(HERE, "rv161_lib.py")), "clock_start": t0}

    # DFZ list (source transcription)
    items, s_ln, e_ln = parse_dfz_fourcopy_list()
    rec["dfz_fourcopy_section_lines"] = [s_ln, e_ln]
    rec["dfz_fourcopy_items"] = sum(len(v) for v in items.values())
    used = {(2, 5, 2, 1, 2, 0, 0, 2, 0), (3, 7, 2, 2, 3, 0, 0, 3, 2), (3, 5, 6, 2, 3, 0, 0, 3, 0)}
    rec["dfz_used_items_in_source"] = {" ".join(map(str, t)): items.get(t) for t in sorted(used)}
    assert all(t in items for t in used)

    # Graph from source figure
    E_R = L.parse_rgraph_edges(RGRAPH_PS)
    E_Rm, gchk = L.graph_checks(E_R)
    rec["graph_checks"] = gchk
    rec["Rminus_edges"] = sorted(sorted(e) for e in E_Rm)
    assert gchk["Rminus_edges"] == 26 and all(v for k, v in gchk.items() if k not in ("R_edges", "Rminus_edges"))
    N = L.neighbourhoods(E_Rm)
    NB = {L.NUMV[v]: frozenset(L.NUMV[u] for u in N[v]) for v in N}
    auts = L.automorphisms(E_Rm)
    rec["aut_Rminus_order"] = len(auts)
    rec["aut_Rminus_elements"] = [[a[v] for v in range(1, 11)] for a in auts]
    rec["aut_R_order"] = len(L.automorphisms(E_R))
    gen0 = {1: 8, 2: 10, 3: 7, 4: 6, 5: 9, 6: 3, 7: 4, 8: 1, 9: 2, 10: 5}
    gen1 = {1: 1, 2: 5, 3: 6, 4: 7, 5: 2, 6: 3, 7: 4, 8: 8, 9: 9, 10: 10}
    assert gen0 in auts and gen1 in auts
    # group generated by gen0, gen1
    seen, frontier = {tuple(range(1, 11))}, [tuple(range(1, 11))]
    while frontier:
        nf = []
        for p in frontier:
            for g in (gen0, gen1):
                q = tuple(g[p[v - 1]] for v in range(1, 11))
                if q not in seen:
                    seen.add(q)
                    nf.append(q)
        frontier = nf
    rec["generated_group_order"] = len(seen)
    assert len(seen) == 8
    letter = lambda g: {L.NUMV[v]: L.NUMV[g[v]] for v in g}  # noqa: E731
    gens = {0: letter(gen0), 1: letter(gen1)}

    allowed_lists = {tuple(L.BRANCHVARS[b]) for b in L.BRANCHVARS} | {tuple(L.ORIG)} | {
        tuple(L.ORIG + ["s'%d" % k]) for k in range(3)}
    base_ctx = dict(NB=NB, gens=gens, conv=dict(L.CONV), allowed_lists=allowed_lists, dfz_tuples=used)

    certs = {}
    for key, (fn, h, claimed) in CERTS.items():
        raw = open(EVD + fn, "rb").read()
        assert hashlib.sha256(raw).hexdigest() == h
        certs[key] = json.loads(raw)
        res = L.check_certificate(certs[key], base_ctx)
        res["claimed_bound"] = claimed
        res["bound_matches_claim"] = res["cap_sum"] == claimed == certs[key]["bound"]
        res["PASS"] = (res["residual_nonzero_coordinates"] == 0 and res["sign_violations"] == 0
                       and res["bound_matches_claim"])
        res["sha256"] = h
        res["rows"] = len(certs[key]["multipliers"])
        rec["positive_" + key] = res

    # Uniqueness of the generator assignment (informational): all ordered pairs of nontrivial automorphisms.
    nontriv = [a for a in auts if any(a[v] != v for v in a)]
    zero_pairs = []
    for a in nontriv:
        for b in nontriv:
            ctx = dict(base_ctx, gens={0: letter(a), 1: letter(b)})
            if L.check_certificate(certs["cert1_10834_1619"], ctx)["residual_nonzero_coordinates"] == 0:
                zero_pairs.append([[a[v] for v in range(1, 11)], [b[v] for v in range(1, 11)]])
    rec["cert1_generator_pairs_with_zero_residual"] = zero_pairs

    neg = {}
    c1 = certs["cert1_10834_1619"]
    # N1 identity: double one cap multiplier
    m1 = json.loads(json.dumps(c1))
    for m in m1["multipliers"]:
        if m["row"][0] == "cap":
            m["multiplier"] = str(2 * Fraction(m["multiplier"]))
            break
    r = L.check_certificate(m1, base_ctx)
    neg["N1_doubled_cap_multiplier"] = dict(expected="IDENTITY_FAIL", residual_nonzero=r["residual_nonzero_coordinates"],
                                            cap_sum=r["cap_sum"], rejected=r["residual_nonzero_coordinates"] > 0)
    # N2 sign: duplicate one cmi row with +t and -t (identity stays exact, sign rule must reject)
    m2 = json.loads(json.dumps(c1))
    row = next(m["row"] for m in m2["multipliers"] if m["row"][0] == "cmi")
    m2["multipliers"] += [{"row": row, "multiplier": "1/1619"}, {"row": row, "multiplier": "-1/1619"}]
    r = L.check_certificate(m2, base_ctx)
    neg["N2_positive_multiplier_on_cmi"] = dict(expected="SIGN_FAIL_WITH_EXACT_IDENTITY",
                                                residual_nonzero=r["residual_nonzero_coordinates"],
                                                sign_violations=r["sign_violations"],
                                                rejected=r["sign_violations"] > 0 and r["residual_nonzero_coordinates"] == 0)
    # N3 graph: use R (edge 9-10 present) for the FD rows
    NR = L.neighbourhoods(E_R)
    NBR = {L.NUMV[v]: frozenset(L.NUMV[u] for u in NR[v]) for v in NR}
    r = L.check_certificate(c1, dict(base_ctx, NB=NBR))
    neg["N3_graph_R_instead_of_Rminus"] = dict(expected="IDENTITY_FAIL_AT_FD_ROWS_9_10",
                                               residual_nonzero=r["residual_nonzero_coordinates"],
                                               sample=r["residual_sample"],
                                               rejected=r["residual_nonzero_coordinates"] > 0)
    # N4 DFZ strengthening: a -> a+1 on the 3 7 2 2 3 0 0 3 2 instance
    m4 = json.loads(json.dumps(c1))
    for m in m4["multipliers"]:
        if m["row"][0] == "dfz" and m["row"][1] == [3, 7, 2, 2, 3, 0, 0, 3, 2]:
            m["row"][1] = [4, 7, 2, 2, 3, 0, 0, 3, 2]
    strengthened = (4, 7, 2, 2, 3, 0, 0, 3, 2)
    r = L.check_certificate(m4, dict(base_ctx, dfz_tuples=used | {strengthened}))
    neg["N4_strengthened_dfz_tuple"] = dict(expected="IDENTITY_FAIL_AND_NOT_IN_DFZ_LIST",
                                            in_dfz_list=strengthened in items,
                                            residual_nonzero=r["residual_nonzero_coordinates"],
                                            rejected=(strengthened not in items) and r["residual_nonzero_coordinates"] > 0)
    # N5 generators swapped
    r = L.check_certificate(c1, dict(base_ctx, gens={0: gens[1], 1: gens[0]}))
    neg["N5_generators_swapped"] = dict(expected="IDENTITY_FAIL", residual_nonzero=r["residual_nonzero_coordinates"],
                                        rejected=r["residual_nonzero_coordinates"] > 0)
    # N6 cert2 with the branch-1 DFZ row removed
    c2 = certs["cert2_977_146"]
    m6 = json.loads(json.dumps(c2))
    m6["multipliers"] = [m for m in m6["multipliers"] if m["row"][0] != "dfzb"]
    r = L.check_certificate(m6, base_ctx)
    neg["N6_cert2_without_branch1_dfz_row"] = dict(expected="IDENTITY_FAIL",
                                                   residual_nonzero=r["residual_nonzero_coordinates"],
                                                   rejected=r["residual_nonzero_coordinates"] > 0)
    rec["negative_controls"] = neg
    rec["all_negative_controls_rejected"] = all(v["rejected"] for v in neg.values())
    rec["clock_end"] = clock()
    out = os.path.join(HERE, "rv161-cert-check-receipt.json")
    with open(out, "x") as f:
        json.dump(rec, f, indent=1, sort_keys=True)
        f.write("\n")
    print(json.dumps({k: rec[k] for k in ("clock_start", "clock_end", "aut_Rminus_order", "generated_group_order",
                                          "all_negative_controls_rejected")}, indent=1))
    for key in CERTS:
        p = rec["positive_" + key]
        print(key, "PASS" if p["PASS"] else "FAIL", p["residual_nonzero_coordinates"], p["sign_violations"], p["cap_sum"])
    for k, v in neg.items():
        print(k, v["rejected"])
    print("zero-residual generator pairs:", len(zero_pairs))


if __name__ == "__main__":
    main()
