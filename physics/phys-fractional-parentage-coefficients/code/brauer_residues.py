"""Can a Q(v)-rational orthonormal basis of a two-dimensional spin-2 multiplicity family
L = 2v - k (k = 6, 8, ...) have Bao-Li-type CFPs?

K = Q(v).  For x in V (Q(v)-span of the family states), cfp(x/|x|; d)^2 = b_d(x)^2 C_d / q(x)
with C_d a product of linear factors (multiplicity_obstruction.py).  So some (equivalently
every) nonzero CFP of x/|x| into a multiplicity-free daughter is of Bao-Li type
(square * constant * product of linear polynomials) iff q(x) lies in L * K*^2, where L is
generated by Q* and the linear polynomials.  With q = <q11, q11*Delta> (q11 = q(phi1),
Delta = det G), q represents c iff the quaternion algebra A_c = (c*q11, -Delta) splits over K;
necessary: every residue (tame symbol) of A_c vanishes.

Steps (all exact):
 1. non-linear irreducible pi with odd valuation in q11 (or in Delta): A_c has residue
    (-Delta mod pi) (resp. depending on c) -- checked with multiplicity_obstruction.is_square_mod;
 2. P = rational places (roots of linear factors, and infinity) where -Delta has odd
    valuation; for c = c0 * prod_{s in S}(v - s), S a subset of P, the residues at P are
    c0 * R_S(r); a suitable c0 exists iff all R_S(r) coincide (bimultiplicativity);
 3. a linear factor (v - s), s not in P, may occur in c only if -Delta(s) is a nonzero
    rational square (else the residue at s is nontrivial): search s of small height and
    s = n/4, |n| <= 10^6.
Run: $PY code/brauer_residues.py [k] [height]     (k in {6, 8, 9, 10, 11}; default 6, 60)
"""
import itertools
import sys
from math import gcd, isqrt

import sympy as sp

from multiplicity_obstruction import family_gram, is_square_mod, square_free_part
from top_family_symbolic import v


def sqclass(r):
    """Square-free integer representative of a nonzero rational (exact input required)."""
    assert isinstance(r, (int, sp.Rational)) and not isinstance(r, sp.Float), ("inexact input", r)
    r = sp.Rational(r)
    n = r.p * r.q
    out = -1 if n < 0 else 1
    for p, e in sp.factorint(abs(n)).items():
        if e % 2:
            out *= p
    return out


def val_unit(expr, r):
    num, den = sp.fraction(sp.together(expr))
    pn, pd = sp.Poly(num, v), sp.Poly(den, v)
    if r == 'inf':
        return -(pn.degree() - pd.degree()), sp.Rational(pn.LC()) / sp.Rational(pd.LC())
    a = 0
    lin = sp.Poly(v - r, v)
    while pn.eval(r) == 0:
        pn = sp.div(pn, lin)[0]
        a += 1
    while pd.eval(r) == 0:
        pd = sp.div(pd, lin)[0]
        a -= 1
    return a, sp.Rational(pn.eval(r)) / sp.Rational(pd.eval(r))


def tame(x, y, r):
    """Tame symbol {x, y} at the degree-1 place r: (-1)^(ab) u^b w^(-a), exact rationals."""
    a, u = val_unit(x, r)
    b, w = val_unit(y, r)
    sign = -1 if (a * b) % 2 else 1          # integer parity: no float from (-1)**negative
    return sqclass(sp.Integer(sign) * u ** b * w ** (-a))


def _regression_pole_case():
    """Codex-reported case (k = 6): {v + 1/2, -Delta} at v = -1/2 has valuations (1, -1) and
    exact value 32768/800415, square class 30 (a float sign once gave a wrong class)."""
    delta6 = (v - 5) * (v - 4) * (v - 3) * (v - 2) * (2 * v - 5) * (4 * v - 9) * (4 * v - 7) * (4 * v - 5) / (
        18432 * (2 * v + 1))
    assert tame(v + sp.Rational(1, 2), -delta6, sp.Rational(-1, 2)) == 30


_regression_pole_case()


def odd_linear_places(expr):
    """Rational roots of linear factors with odd multiplicity, plus 'inf' if the degree is odd."""
    _, facs = square_free_part(expr)
    places = []
    for fac in facs:
        P = sp.Poly(fac, v)
        if P.degree() == 1:
            a, b = P.all_coeffs()
            places.append(sp.Rational(-b, a))
    num, den = sp.fraction(sp.together(expr))
    if (sp.Poly(num, v).degree() - sp.Poly(den, v).degree()) % 2:
        places.append('inf')
    return places


def residue_hits(x0, y, places):
    """Subsets S of the finite places and c0 with all residues of (c0 prod_S (v-s) x0, y) trivial.

    places: every rational place where x0 or y has odd valuation (plus 'inf' if relevant).
    c0 contributes c0^(v_r(y)): at places with v_r(y) odd the residues must all equal c0,
    at places with v_r(y) even they must be trivial."""
    finite = [r for r in places if r != 'inf']
    yodd = {r: val_unit(y, r)[0] % 2 == 1 for r in places}
    base = {r: tame(x0, y, r) for r in places}
    gens = {s: {r: tame(v - s, y, r) for r in places} for s in finite}
    # Weil reciprocity for every generator (v - s): its residues vanish outside `places`
    # (y has only linear factors in all uses here), so their product must be a square.
    if all(sp.Poly(p, v).degree() == 1 for p in square_free_part(y)[1]):
        for s in finite:
            assert sqclass(sp.prod(list(gens[s].values()))) == 1, ("reciprocity fails for", s)
    hits = []
    for eps in itertools.product((0, 1), repeat=len(finite)):
        res = dict(base)
        for s, e in zip(finite, eps):
            if e:
                res = {r: sqclass(res[r] * gens[s][r]) for r in places}
        odd_vals = {res[r] for r in places if yodd[r]}
        if len(odd_vals) <= 1 and all(res[r] == 1 for r in places if not yodd[r]):
            hits.append(([s for s, e in zip(finite, eps) if e], odd_vals.pop() if odd_vals else 1))
    return base, hits


def extra_places(y, places, height, quarter_bound):
    num, den = sp.fraction(sp.together(y))
    a = [int(c) for c in sp.Poly(num, v).all_coeffs()]
    b = [int(c) for c in sp.Poly(den, v).all_coeffs()]
    assert all(sp.Rational(c).q == 1 for c in sp.Poly(num, v).all_coeffs() + sp.Poly(den, v).all_coeffs())

    def hom(coeffs, p, q):
        d = len(coeffs) - 1
        return sum(c * p ** (d - i) * q ** i for i, c in enumerate(coeffs))

    def is_sq(p, q):
        val = hom(a, p, q) * hom(b, p, q) * q ** ((len(a) - 1 + len(b) - 1) % 2)
        return val > 0 and isqrt(val) ** 2 == val

    skip = set(r for r in places if r != 'inf')
    small = [sp.Rational(p, q) for q in range(1, height + 1) for p in range(-height * q, height * q + 1)
             if gcd(p, q) == 1 and sp.Rational(p, q) not in skip and hom(b, p, q) != 0 and is_sq(p, q)]
    quarter = [n for n in range(-quarter_bound, quarter_bound + 1)
               if sp.Rational(n, 4) not in skip and hom(b, n, 4) != 0 and is_sq(n, 4)]
    return small, quarter


def main(k=6, height=60):
    _, _, _, q00, q01, q11, disc = family_gram(k)
    print(f"family k = {k}: q11 = {sp.factor(q11)};  disc = {sp.factor(disc)}")
    return analyze(q11, disc, height)


def analyze(q11, disc, height=60):
    """Residue analysis for the binary form <q11, q11*disc> over Q(v); returns the hit list."""
    y = -disc
    # step 1: non-linear places (status: True = residue trivial, False = obstruction there,
    # None = undecided / not handled)
    nonlin_ok = True
    for name, a in (("q(phi1)", q11), ("disc", disc)):
        for pi in square_free_part(a)[1]:
            if sp.Poly(pi, v).degree() >= 2:
                if name == "disc":
                    print(f"  disc has odd non-linear factor {pi}: residue depends on c (not handled)")
                    nonlin_ok = None
                    continue
                sq, cert = is_square_mod(y, pi)
                word = {True: "is a square", False: "is NOT a square", None: "is UNDECIDED"}[sq]
                print(f"  residue at {pi}: -disc {word} mod pi [{cert}]")
                if sq is False and nonlin_ok is not None:
                    nonlin_ok = False
                elif sq is None:
                    nonlin_ok = None
    if nonlin_ok is False:
        print("  => obstruction already at a non-linear place: q represents no c in L (unconditional)")
    elif nonlin_ok is None:
        print("  => non-linear places not fully decided; conclusions below are about linear places only")
    py = odd_linear_places(y)
    px = odd_linear_places(q11)
    # every rational root (any multiplicity) of q11 or -disc, plus infinity: a factor (v - s)
    # of c at such s is handled by the tame symbols below; any other s needs -disc(s) square.
    places = []
    for expr in (y, q11):
        num, den = sp.fraction(sp.together(expr))
        for poly in (num, den):
            for fac, _ in sp.factor_list(sp.Poly(poly, v))[1]:
                if fac.degree() == 1:
                    a, b = fac.all_coeffs()
                    r = sp.Rational(-b, a)
                    if r not in places:
                        places.append(r)
    places.append('inf')
    print(f"  rational places with odd valuation: -disc {py}; q11 {px}; all rational places used: "
          f"{len(places) - 1} finite + inf")
    small, quarter = extra_places(y, places, height, 10 ** 6)
    extras = sorted(set(small) | {sp.Rational(n, 4) for n in quarter})
    print(f"  extra places s (not above) with -disc(s) a nonzero square: height <= {height}: {small};"
          f" s = n/4, |n| <= 10^6: {quarter}")
    places = places[:-1] + extras + ['inf']
    base, hits = residue_hits(q11, y, places)
    print(f"  residues of (q11, -disc): {base}")
    assert sqclass(sp.prod([x for x in base.values()])) == 1 or nonlin_ok is not True, "reciprocity"
    lin_ctrl = sp.prod([v - s for s in py[:2] if s != 'inf']) * 3
    _, ctrl = residue_hits(lin_ctrl, y, places)
    assert ctrl, "positive control failed"
    print(f"  controls OK (reciprocity product square; linear-type control {lin_ctrl} hit)")
    print(f"  subsets S of the {len(places) - 1} finite places (incl. extras {extras}) with all residues"
          f" trivial for some c0: {len(hits)} {hits[:5]}")
    return hits


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 6, int(sys.argv[2]) if len(sys.argv) > 2 else 60)
