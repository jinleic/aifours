#!/usr/bin/env python3
"""Bounded, sequential FIFO-DRAT certification; encoder mathematics are unchanged.

Two busy processes per instance: solver and drat-trim. The Python parent monitors.
Every retained CNF is regenerated by the pinned encoder; the CNF and both complete
logs are hashed. Proof bytes are streamed to the checker, not stored. Scratch
CNF is reused; evidence and used FIFOs are never overwritten or removed.

Usage: gram_certify_r4.py CLASSES OUTDIR INSTANCE... [--solver-seconds 1800]
       [--checker-seconds 3600]
Instances: k2A:0, k2B:0, k3A, k3B. No implicit expansion or unbounded solve.
"""
import argparse
import ctypes
import datetime
import hashlib
import json
import os
import subprocess
import sys
import struct
import time

import gram_enc
from k2_classes import square_from_key

HERE = os.path.dirname(os.path.abspath(__file__))
LANE = os.path.dirname(HERE)
CHECKER = os.path.join(LANE, "env", "drat-trim", "drat-trim")
SCRATCH = os.path.join(LANE, "explore", "scratch")


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def now():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


# macOS SDK sys/proc_info.h: PROC_PIDTASKINFO = 4; proc_taskinfo is 96
# bytes, with pti_resident_size (uint64_t) at byte offset 8. Read memory
# from this waiting parent, without launching an extra sampling process.
LIBPROC = ctypes.CDLL("/usr/lib/libproc.dylib", use_errno=True)
LIBPROC.proc_pidinfo.argtypes = (ctypes.c_int, ctypes.c_int, ctypes.c_uint64,
                               ctypes.c_void_p, ctypes.c_int)
LIBPROC.proc_pidinfo.restype = ctypes.c_int


def rss(pid):
    buf = ctypes.create_string_buffer(96)
    n = LIBPROC.proc_pidinfo(pid, 4, 0, buf, len(buf))
    return struct.unpack_from("=Q", buf.raw, 8)[0] if n == len(buf) else 0


def monitor(solve, check, wall_seconds):
    peak, reason = 0, None
    t0 = time.monotonic()
    while solve.poll() is None or check.poll() is None:
        current = rss(os.getpid()) + rss(solve.pid) + rss(check.pid)
        peak = max(peak, current)
        st = os.statvfs(LANE)
        if current > 3584 * 1024 * 1024:
            reason = "aggregate RSS safety threshold 3.5 GiB"
        elif st.f_bavail * st.f_frsize < 12000000000:
            reason = "global free-space floor"
        elif time.monotonic() - t0 > wall_seconds:
            reason = "combined native-child wall-clock cap"
        if reason:
            for child in (solve, check):
                if child.poll() is None:
                    child.terminate()
            stop = time.monotonic() + 30
            while any(c.poll() is None for c in (solve, check)):
                if time.monotonic() >= stop:
                    raise RuntimeError("SIGTERM wait exceeded; no SIGKILL sent")
                time.sleep(0.1)
            break
        time.sleep(0.25)
    return peak, reason


def make_cnf(instance, rows, path, seconds):
    kind, sep, idx = instance.partition(":")
    if kind not in ("k2A", "k2B", "k3A", "k3B"):
        raise ValueError("Unknown instance: " + instance)
    if kind.startswith("k2"):
        if not sep or not idx.isdigit() or int(idx) >= len(rows):
            raise ValueError("Invalid class index: " + instance)
        L = square_from_key(rows[int(idx)][0])
    elif sep:
        raise ValueError("K3 instance has no index")
    if kind.endswith("A"):
        F, _ = gram_enc.build(2 if kind == "k2A" else 3,
                              L if kind == "k2A" else None,
                              True, kind == "k3A", None)
        with open(path, "w") as f:
            f.write(F.text())
        return ["cadical", "-q", "-t", str(seconds), path]
    args = ["--squares", "3", "--heavy", "--sym"]
    if kind == "k2B":
        lpath = os.path.join(SCRATCH, "cert_r4_L.json")
        with open(lpath, "w") as f:
            json.dump(L, f)
        args = ["--squares", "2", "--net-L", lpath, "--heavy"]
    subprocess.run(["/usr/bin/python3", "-B", os.path.join(HERE, "gram_encB.py")]
                   + args + ["--out", path], check=True, capture_output=True)
    return ["kissat", "-q", "-f", "--time=%d" % seconds, path]


def certify(instance, rows, outdir, solver_seconds, checker_seconds, pins):
    if os.statvfs(LANE).f_bavail * os.statvfs(LANE).f_frsize < 12000000000:
        raise RuntimeError("Global free-space floor reached")
    label = instance.replace(":", "_")
    cnf = os.path.join(SCRATCH, "cert_r4_current.cnf")
    receipt = os.path.join(outdir, label + ".json")
    fifo = os.path.join(outdir, label + ".drat.fifo")
    solver_log = os.path.join(outdir, label + ".solver.log")
    checker_log = os.path.join(outdir, label + ".checker.log")
    for path in (receipt, fifo, solver_log, checker_log):
        if os.path.exists(path):
            raise FileExistsError(path)
    solver = make_cnf(instance, rows, cnf, solver_seconds)
    cnf_hash = sha(cnf)
    os.mkfifo(fifo)
    start = now()
    t0 = time.monotonic()
    # Files, not pipes: verbose checker progress cannot fill a pipe and deadlock
    # the solver while the parent is waiting on the other child.
    if not rss(os.getpid()):
        raise RuntimeError("Native RSS sampler unavailable")
    with open(solver_log, "x") as sl, open(checker_log, "x") as cl:
        solve = subprocess.Popen(solver + [fifo], stdout=sl,
                                 stderr=subprocess.STDOUT)
        # Named-proof auto-detection closes/reopens its input and consumes bytes
        # on a FIFO. Stdin with explicit binary mode never probes or reopens.
        with open(fifo, "rb") as proof:
            check = subprocess.Popen([CHECKER, cnf, "-i", "-t", str(checker_seconds)],
                                     stdin=proof, stdout=cl, stderr=subprocess.STDOUT)
        peak_rss, stop_reason = monitor(solve, check, solver_seconds + checker_seconds + 120)
    with open(checker_log) as f:
        lines = [line.strip() for line in f.read().replace("\r", "\n").splitlines()]
    verified = (stop_reason is None and solve.returncode == 20 and check.returncode == 0
                and "s VERIFIED" in lines and "s NOT VERIFIED" not in lines
                and "s TIMEOUT" not in lines)
    record = {"instance": instance, "started_at": start, "finished_at": now(),
              "seconds": round(time.monotonic() - t0, 3), "pins": pins,
              "cnf_sha256": cnf_hash, "solver_command": solver + [fifo],
              "solver_rc": solve.returncode, "checker_rc": check.returncode,
              "solver_log_sha256": sha(solver_log),
              "checker_log_sha256": sha(checker_log),
              "checker_status_lines": [line for line in lines if line.startswith("s ")],
              "verified_unsat": verified, "proof_storage": "FIFO-only; replay from pinned CNF generator",
              "peak_sampled_aggregate_rss_bytes": peak_rss, "rss_sample_period_seconds": 0.25,
              "rss_abort_threshold_bytes": 3584 * 1024 * 1024, "safety_stop_reason": stop_reason,
              "solver_seconds": solver_seconds, "checker_seconds": checker_seconds}
    with open(receipt, "x") as f:
        json.dump(record, f, indent=2)
        f.write("\n")
    print(json.dumps({k: record[k] for k in ("instance", "seconds", "solver_rc", "checker_rc", "verified_unsat")}), flush=True)
    return verified


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("classes")
    ap.add_argument("outdir")
    ap.add_argument("instances", nargs="+")
    ap.add_argument("--solver-seconds", type=int, default=1800)
    ap.add_argument("--checker-seconds", type=int, default=3600)
    a = ap.parse_args()
    if not 1 <= a.solver_seconds <= 3600 or not 1 <= a.checker_seconds <= 3600:
        raise ValueError("Each native child gets at most 3600 seconds")
    os.makedirs(SCRATCH, exist_ok=True)
    os.makedirs(a.outdir, exist_ok=True)
    pins = {name: sha(os.path.join(HERE, name)) for name in
            ("gram_enc.py", "gram_encB.py", "gram_certify_r4.py", "k2_classes.py")}
    pins["classfile"] = sha(a.classes)
    pins["drat-trim"] = sha(CHECKER)
    pins["drat-trim.c"] = sha(CHECKER + ".c")
    with open(a.classes) as f:
        rows = [line.split() for line in f if line.strip()]
    for instance in a.instances:
        if not certify(instance, rows, a.outdir, a.solver_seconds, a.checker_seconds, pins):
            raise SystemExit("Certification stopped: unverified instance " + instance)


if __name__ == "__main__":
    main()
