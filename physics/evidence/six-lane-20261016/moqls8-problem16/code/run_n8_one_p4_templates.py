"""Strict16-case weakened-F pass, authorised ONLY after all13 old-F attempts.
Separate ledger and formula identity; no oldc112 proof imported. Each formula
is regenerated by the frozen four-ALO deletion producer and streamed only.
Native solver900s/checker<=3600s, no retry, aggregate6GiB; fresh12.2e9+growth
launch gate per case. Restricted receipts do NOT assert the target theorem:
both mathematical reviews, parent disposition and replay remain mandatory.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
EXPECTED=[p+'-'+b for p in('P0','P1') for b in('B1','B2','B3','B4','B5','B6')]+['P2-C1','P2-C2','P2-C3','P2-C4']
OLD_EXPECTED=[x for x in EXPECTED if x not in('P0-B6','P1-B6','P2-C4')]
WEAK_SHA='374d6fb46ab2a1f7a77bdf6699aa67792c126b2e2dcdf65ad37074be9fc5eeb9'
SOURCE_SHA='6ecb77a779170635830c4c7c488c3e0eb434ee249fb2b1c81dc2625c4183469b'
BRIDGE_SHA='c391a67ab7cb468c2500dd4fc0d565fa4e104b97777a5bab668ed5fdc82ebbb3'
STRONG_SHA='f77c061947aa64d1107736d27723373ccc9e02633dd099c1a58cf9d77a2c0b71'


def sha(b): return hashlib.sha256(b).hexdigest()


def load(name):
    s=importlib.util.spec_from_file_location(name,ROOT/'code'/str(name+'.py'))
    m=importlib.util.module_from_spec(s); s.loader.exec_module(m); return m


def write_new(path,obj):
    raw=json.dumps(obj,indent=1).encode()
    with path.open('xb') as f: f.write(raw)
    return sha(raw)


def old_pass_gate():
    src=(ROOT/'evidence/k5_column_templates_v1/MANIFEST.json').read_bytes()
    if sha(src)!=STRONG_SHA: raise RuntimeError('old instance manifest changed')
    cases={x['id']:x for x in json.loads(src)['cases'] if x['run_required']}
    path=ROOT/'evidence/k5_column_template_runs_v1/RESULTS.jsonl'
    if not path.exists(): raise SystemExit('DEFERRED:13 old-F attempts must finish before weakened-F execution')
    raw=path.read_bytes(); rows=[json.loads(x) for x in raw.splitlines() if x.strip()]
    if len(rows)!=13 or {x['id'] for x in rows}!=set(OLD_EXPECTED):
        raise SystemExit('DEFERRED:13 old-F attempts are not all complete')
    for r in rows:
        x=cases[r['id']]
        if r.get('base_cnf_sha256')!=SOURCE_SHA or r.get('units')!=x['units'] or r.get('cnf_sha256')!=x['cnf_sha256']:
            raise RuntimeError('old pass receipt identity mismatch')
    return {'file':str(path),'sha256':sha(raw),'attempts':13}


def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--manifest',required=True); ap.add_argument('--outdir',required=True)
    a=ap.parse_args(); t0=time.monotonic(); out=Path(a.outdir)
    free=shutil.disk_usage(ROOT).free
    if free<12_200_000_000: raise SystemExit('DEFERRED: fresh12.2e9 gate failed; wait for parent')
    old_gate=old_pass_gate()
    out.mkdir(exist_ok=True)
    F=load('n8_one_p4_formula'); C=load('k5_cover'); R=load('k5_resplit_r2')
    raw=Path(a.manifest).read_bytes(); m=json.loads(raw); mh=sha(raw)
    if m.get('schema')!='n8-one-p4-template-manifest/1' or m.get('source_base_cnf_sha256')!=SOURCE_SHA \
       or m.get('base_cnf_sha256')!=WEAK_SHA or m.get('bridge_note_sha256')!=BRIDGE_SHA or m.get('run_cases')!=EXPECTED \
       or m.get('run_all_c112_templates') is not True or m.get('H3_used') is not False:
        raise RuntimeError('weakened manifest identity/case list mismatch')
    if m['producer_sha256']!=sha((ROOT/'code/n8_one_p4_formula.py').read_bytes()):
        raise RuntimeError('frozen weakened producer changed')
    base,recipe=F.build()
    if base.sha!=WEAK_SHA or base.nv!=509915 or base.nc!=5740226: raise RuntimeError('regenerated weakened base differs')
    cases={x['id']:x for x in m['cases']}
    if len(m['cases'])!=16 or len(cases)!=16 or set(cases)!=set(EXPECTED): raise RuntimeError('missing/duplicate case')
    for i,x in cases.items():
        regen=[v if co in S else -v for row,S in enumerate(x['supports_row2to7'],start=2)
               for co,v in enumerate(C.CHAIN[row-1],start=1)]
        if regen!=x['units'] or len(regen)!=42 or len({abs(v) for v in regen})!=42 \
           or x['cnf_sha256']!=base.leaf_sha(regen) or x['cnf_clauses']!=5740268 \
           or x.get('excluded_by_imported_c112') is not False or x.get('run_required') is not True:
            raise RuntimeError('weakened case unit/formula identity differs')
    def identity(r):
        x=cases.get(r.get('id'))
        return (x is not None and r.get('manifest_sha256')==mh and r.get('base_cnf_sha256')==WEAK_SHA
                and r.get('units')==x['units'] and r.get('cnf_sha256')==x['cnf_sha256']
                and r.get('source_base_cnf_sha256')==SOURCE_SHA)
    results=out/'RESULTS.jsonl'; recs={}; line_hash={}
    if results.exists():
        for line in results.read_bytes().splitlines():
            if not line.strip(): continue
            r=json.loads(line)
            if not identity(r) or r['id'] in recs or r.get('strict_ok') is not C.strict_ok(r):
                raise RuntimeError('stale/duplicate/misclassified weakened receipt')
            recs[r['id']]=r; line_hash[r['id']]=sha(line)
    versions=sorted(out.glob('LEDGER.v*.json'))
    if versions:
        lb=versions[-1].read_bytes(); L=json.loads(lb); lh=sha(lb)
        if L['manifest_sha256']!=mh or L['base_cnf_sha256']!=WEAK_SHA or set(L['cases'])!=set(EXPECTED):
            raise RuntimeError('ledger belongs to different formula/cases')
        for i,x in L['cases'].items():
            if x['units']!=cases[i]['units'] or x['cnf_sha256']!=cases[i]['cnf_sha256']:
                raise RuntimeError('ledger case identity mismatch')
    else:
        L={'schema':'n8-one-p4-semantic-template-ledger/1','version':1,'prev_sha256':None,
           'manifest_sha256':mh,'base_cnf_sha256':WEAK_SHA,'source_base_cnf_sha256':SOURCE_SHA,
           'bridge_note_sha256':BRIDGE_SHA,'old13_order_gate':old_gate,
           'claim':'restricted formula results only; n8 theorem pending both reviews and parent replay',
           'cases':{i:{'units':cases[i]['units'],'cnf_sha256':cases[i]['cnf_sha256'],
                       'state':'UNSTARTED','evidence':None} for i in EXPECTED}}
        lh=write_new(out/'LEDGER.v001.json',L)
    def update(i,r,hs):
        nonlocal L,lh
        st='STRICT_UNSAT' if C.strict_ok(r) else 'UNKNOWN'; ev={'file':'RESULTS.jsonl','line_sha256':hs}
        if L['cases'][i]['state']!='UNSTARTED':
            if L['cases'][i]['state']!=st or L['cases'][i]['evidence']!=ev: raise RuntimeError('ledger/receipt differs')
            return
        L=copy.deepcopy(L); L['prev_sha256']=lh; L['version']+=1
        L['cases'][i].update(state=st,evidence=ev)
        L['all_16_strict']=all(x['state']=='STRICT_UNSAT' for x in L['cases'].values())
        L['writer_sha256']=sha(Path(__file__).read_bytes()); lh=write_new(out/('LEDGER.v%03d.json'%L['version']),L)
    for i,r in recs.items(): update(i,r,line_hash[i])
    if any(x['state']!='UNSTARTED' and i not in recs for i,x in L['cases'].items()): raise RuntimeError('ledger receipt missing')
    cad=Path(shutil.which('cadical')).resolve()
    meta={'argv':sys.argv,'script_sha256':sha(Path(__file__).read_bytes()),'manifest_sha256':mh,
          'producer_sha256':m['producer_sha256'],'pipeline_sha256':sha((ROOT/'code/k5_resplit_r2.py').read_bytes()),
          'strict_predicate_sha256':sha((ROOT/'code/k5_cover.py').read_bytes()),'base_cnf_sha256':WEAK_SHA,
          'cadical_binary':str(cad),'cadical_sha256':sha(cad.read_bytes()),
          'cadical_version':subprocess.run([str(cad),'--version'],capture_output=True,text=True).stdout.strip(),'seed':'default',
          'drat_trim_binary':R.DT,'drat_trim_sha256':sha(Path(R.DT).read_bytes()),
          'solver_limit':900,'checker_limit_max':3600,'aggregate_rss_limit':6*2**30,'chunk_wall_cap':10400,
          'launch_floor':12_200_000_000,'projected_retained_growth_max':10_000_000,
          'start':datetime.now().astimezone().isoformat(),'old13_order_gate':old_gate,'deletion_recipe':recipe}
    write_new(out/('META.%d.json'%int(time.time())),meta)
    fifos=tuple(str(out/('w0.%s.fifo'%x)) for x in('cnf_s','cnf_c','proof'))
    for f in fifos:
        if not Path(f).exists(): os.mkfifo(f)
    for i in EXPECTED:
        if i in recs: continue
        remaining=int(10400-(time.monotonic()-t0)); free=shutil.disk_usage(out).free
        if free<12_200_000_000 or remaining<960:
            write_new(out/('DEFERRED.%d.json'%int(time.time())),{'before_case':i,'free':free,'remaining':remaining})
            break
        x=cases[i]; n=1
        while(out/(i+'.a%d.solver.log'%n)).exists(): n+=1
        tag=i+'.a%d'%n
        r={'id':i,'manifest_sha256':mh,'base_cnf_sha256':WEAK_SHA,'source_base_cnf_sha256':SOURCE_SHA,
           'units':x['units'],'attempt':1,'tag':tag,'H3_used':False,'parent_semantic_acceptance_pending':True}
        r.update(R.certify(tag,x['units'],base.nv,base.nc,base.body,str(out),fifos,900,6*2**30,
                           checker_limit=min(3600,remaining-60)))
        if not identity(r): raise RuntimeError('streamed weakened CNF differs from manifest')
        r['strict_ok']=C.strict_ok(r); line=json.dumps(r).encode()
        with results.open('ab') as f: f.write(line+b'\n')
        update(i,r,sha(line)); recs[i]=r
        print(json.dumps({'id':i,'strict_ok':r['strict_ok'],'seconds':r['secs'],
                          'ledger_version':L['version'],'ledger_sha256':lh}),flush=True)
    print(json.dumps({'ledger_version':L['version'],'ledger_sha256':lh,
          'counts':{s:sum(x['state']==s for x in L['cases'].values()) for s in('UNSTARTED','STRICT_UNSAT','UNKNOWN')},
          'all_16_strict':all(x['state']=='STRICT_UNSAT' for x in L['cases'].values()),
          'not_a_target_exclusion_claim':True}),flush=True)


if __name__=='__main__': main()
