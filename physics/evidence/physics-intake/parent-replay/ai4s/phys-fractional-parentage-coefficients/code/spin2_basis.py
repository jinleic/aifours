"""Spin-2 bosons: SO(5) > SO(3) harmonic highest-weight states labelled by covariants of
the binary quartic.

Highest-weight vectors (S+ psi = 0) of Sym(C^5) are the semi-invariants of the binary
quartic form; they are generated by f (deg 1, L 2), H (deg 2, L 2), T (deg 3, L 3),
i (deg 2, L 0) and j (deg 3, L 0) with the single syzygy T^2 = poly(f, H, i, j).
i is the SO(5)-invariant pair P+, so the seniority-v harmonic highest-weight vectors of
total spin L have the basis
    phi(v, e, L) = harmonic projection of f^a H^b T^c j^e,
    lambda = v - 3e,  a = L - lambda,  c = (2 lambda - L) mod 2,  b = (2 lambda - L - 3c)/2,
which exists iff lambda <= L <= 2 lambda and L != 2 lambda - 1  (the Chacon-Moshinsky-Sharp
labels: e = n_Delta).  Orthonormal basis: Gram-Schmidt in order e = 0, 1, 2, ...
(this module checks linear independence and spanning against the null space).
"""
from __future__ import annotations

from flint import fmpq

from fpc_core import SpinBosons


def labels(v, L):
    """Allowed e values (missing label n_Delta) for SO(5) irrep (v,0) and spin L."""
    out = []
    for e in range(v // 3 + 1):
        lam = v - 3 * e
        if lam <= L <= 2 * lam and L != 2 * lam - 1:
            out.append(e)
    return out


def exponents(v, e, L):
    lam = v - 3 * e
    a = L - lam
    c = (2 * lam - L) % 2
    b = (2 * lam - L - 3 * c) // 2
    assert a >= 0 and b >= 0
    return a, b, c


class Spin2:
    def __init__(self):
        self.B = SpinBosons(2)
        B = self.B
        (self.H,) = B.hw_harmonic_basis(2, 2)
        (self.T,) = B.hw_harmonic_basis(3, 3)
        (self.J,) = B.hw_harmonic_basis(3, 0)
        self.F = {(0, 0, 0, 0, 1): fmpq(1)}
        # fix phases: leading (lexicographically largest) monomial coefficient positive
        for name in ("H", "T", "J"):
            p = getattr(self, name)
            lead = max(p)
            if p[lead] < 0:
                setattr(self, name, {a: -c for a, c in p.items()})
        self._pow = {}
        self._cache = {}

    def power(self, name, k):
        key = (name, k)
        if key not in self._pow:
            base = {"F": self.F, "H": self.H, "T": self.T, "J": self.J}[name]
            if k == 0:
                self._pow[key] = {(0, 0, 0, 0, 0): fmpq(1)}
            else:
                self._pow[key] = self.B.mul(self.power(name, k - 1), base)
        return self._pow[key]

    def covariant_monomial(self, v, e, L):
        a, b, c = exponents(v, e, L)
        B = self.B
        p = B.mul(self.power("F", a), self.power("H", b))
        if c:
            p = B.mul(p, self.T)
        if e:
            p = B.mul(p, self.power("J", e))
        return p

    def raw_basis(self, v, L):
        """Harmonic projections phi(v, e, L) for e in labels(v, L) (not orthogonal)."""
        return [(e, self.B.harm_proj(self.covariant_monomial(v, e, L), v)) for e in labels(v, L)]

    def orthogonal_basis(self, v, L, order="asc"):
        """[(e, psi)] Gram-Schmidt of the projected covariants, in order of e ascending
        ("asc", default) or descending ("desc": most trios first)."""
        key = (v, L, order)
        if key in self._cache:
            return self._cache[key]
        B = self.B
        out = []
        raw = self.raw_basis(v, L)
        for e, phi in (raw if order == "asc" else raw[::-1]):
            w = dict(phi)
            for _, u in out:
                cf = B.inner(u, w) / B.norm2(u)
                for a, x in u.items():
                    y = w.get(a, fmpq(0)) - cf * x
                    if y == 0:
                        w.pop(a, None)
                    else:
                        w[a] = y
            if not w:
                raise ValueError(f"projected covariants dependent at v={v}, L={L}, e={e}")
            out.append((e, w))
        self._cache[key] = out
        return out
