#!/usr/bin/env python3
"""Generate the chunked k = 3, T = 128 certificate modules.

  gen_k3_tables.py data <eval-output>             writes lean/KSatUpper/K3Data.lean
  gen_k3_tables.py checks <table-chunk> <terms>   writes the K3Check* modules, CertificatesK3 (rows
                                                  A, B) and CertificatesK3Controls (rows C, D), and
                                                  prints the module names in build order

Measured on 2026-10-16 (archive/k3-chunk-probes): 16 table entries in one `decide` peaked at
3.8 GB including the ~2.7 GB import base; 16 top entries, and the full vertex sum from literal
tables, exceeded the 4 GiB cap. Tables are therefore checked in chunks of `<table-chunk>` entries,
and the alternating moments `momentLower` are materialized and checked in chunks of at most
`<terms>` summands. Literals are data only; each one is re-proved by a separate `decide +kernel`.
"""
import pathlib
import sys

FORMAL = pathlib.Path(__file__).resolve().parents[1]
KS = FORMAL / 'lean' / 'KSatUpper'
U = '239949/250000'
N = 256
ROWS = {
    'A': dict(alpha='2667/625', role='cert', eps='1/500000', thm='cert_42672'),
    'B': dict(alpha='213359/50000', role='cert', eps='1/2000000', thm='cert_426718'),
    'C': dict(alpha='42671/10000', role='control', thm='control_42671_low'),
    'D': dict(alpha='426717/100000', role='control', thm='control_426717_low'),
}
HDR = ['set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', '']
IMP = ['import KSatUpper.K3Data', 'import KSatUpper.TrialDataK3']


def q(n, d):
    return f'(({n} : ℚ) / {d})'


def edge_name(r):
    return f'edgeLo{r}' if ROWS[r]['role'] == 'cert' else f'edgeUp{r}'


def parse(path):
    data = {r: {'T': {}, 'M': {}} for r in ROWS}
    for line in pathlib.Path(path).read_text().splitlines():
        p = line.split()
        if len(p) < 3 or p[0] not in ROWS:
            continue
        r, kind = p[0], p[1]
        if kind in ('T', 'M'):
            data[r][kind][int(p[2])] = p[3:]
        elif kind in ('Elo', 'Ehi'):
            data[r][kind] = p[2:4]
    for r in ROWS:
        assert len(data[r]['T']) == 129 and len(data[r]['M']) == 129, r
        assert 'Elo' in data[r] and 'Ehi' in data[r], r
    return data


def write_data(data):
    out = ['import KSatUpper.NumericalCriterionTables', '',
           '/-! Materialized dyadic literals for the k = 3, T = 128 certificates and controls,',
           'generated by `tools/gen_k3_tables.py` from the evaluation `audit/GenK3Tables.lean`.',
           'They are data only: each table entry, alternating moment, edge bound and final value is',
           're-proved from its defining computation by a separate `decide +kernel`, so no literal is',
           'trusted. -/', '', 'namespace KSatUpper.K3Data', '']
    for r, row in ROWS.items():
        d = data[r]
        out.append(f'/-- Entries `j ≤ 128` of '
                   f'`NumericalCriterion.table TrialDataK3.trialT128 2 ({row["alpha"]}) 128`. -/')
        out.append(f'def tbl{r} : List (ℚ × ℚ) := [')
        out.append(',\n'.join(f'  ({q(*d["T"][j][:2])}, {q(*d["T"][j][2:4])})'
                              for j in range(129)) + ']')
        out.append('')
        out.append(f'/-- `VertexEnclosures.momentLower (lowerOf tbl{r}) (upperOf tbl{r}) k`, `k ≤ 128`. -/')
        out.append(f'def mom{r} : List ℚ := [')
        out.append(',\n'.join(f'  {q(*d["M"][k][:2])}' for k in range(129)) + ']')
        out.append('')
        e, how = (d['Elo'], 'down') if row['role'] == 'cert' else (d['Ehi'], 'up')
        out.append(f'/-- `edgeLower trialT128 2 {N} ({U})` rounded {how} on the grid `2^-96`. -/')
        out.append(f'def {edge_name(r)} : ℚ := {q(*e)}')
        out.append('')
    out.append('end KSatUpper.K3Data')
    (KS / 'K3Data.lean').write_text('\n'.join(out) + '\n')


def table_chunks(size):
    return [(lo, min(lo + size, 129)) for lo in range(0, 129, size)]


def moment_chunks(terms):
    chunks, lo, acc = [], 0, 0
    for k in range(129):
        if acc + k + 1 > terms and k > lo:
            chunks.append((lo, k))
            lo, acc = k, 0
        acc += k + 1
    chunks.append((lo, 129))
    return chunks


def module(name, imports, doc, body):
    text = imports + ['', f'/-! {doc} -/', ''] + HDR + [
        f'namespace KSatUpper.{name}', '', 'open K3Data NumericalCriterion TrialDataK3', ''] + body + [
        '', f'end KSatUpper.{name}']
    (KS / f'{name}.lean').write_text('\n'.join(text) + '\n')


def chain(prefix, cs, var):
    lines = [f'  intro {var} h{var}']
    for i, (lo, hi) in enumerate(cs):
        prev = '(Nat.zero_le _)' if i == 0 else f'h{i - 1}'
        if i < len(cs) - 1:
            lines += [f'  rcases Nat.lt_or_ge {var} {hi} with h | h{i}',
                      f'  · exact {prefix}{i}.chunk {var} h {prev}']
        else:
            lines += [f'  exact {prefix}{i}.chunk {var} (by omega) {prev}']
    return lines


def row_modules(r, size, terms):
    row, a = ROWS[r], ROWS[r]['alpha']
    mods = []
    for i, (lo, hi) in enumerate(table_chunks(size)):
        module(f'K3CheckTable{r}{i}', IMP, f'Kernel check of the entries `{lo} ≤ j < {hi}` of `K3Data.tbl{r}`.', [
            f'theorem chunk : ∀ j, j < {hi} → {lo} ≤ j →',
            f'    bounds trialT128 2 ({a}) j = tbl{r}.getD j (0, 0) := by', '  decide +kernel'])
        mods.append(f'K3CheckTable{r}{i}')
    for i, (lo, hi) in enumerate(moment_chunks(terms)):
        module(f'K3CheckMom{r}{i}', IMP, f'Kernel check of the moments `{lo} ≤ k < {hi}` of `K3Data.mom{r}`.', [
            f'theorem chunk : ∀ k, k < {hi} → {lo} ≤ k →',
            f'    VertexEnclosures.momentLower (lowerOf tbl{r}) (upperOf tbl{r}) k = mom{r}.getD k 0 := by',
            '  decide +kernel'])
        mods.append(f'K3CheckMom{r}{i}')
    rel = (f'{edge_name(r)} ≤ edgeLower trialT128 2 {N} ({U})' if row['role'] == 'cert'
           else f'edgeLower trialT128 2 {N} ({U}) ≤ {edge_name(r)}')
    module(f'K3CheckEdge{r}', IMP, f'Kernel check of the edge literal `K3Data.{edge_name(r)}`.',
           [f'theorem edge : {rel} := by', '  decide +kernel'])
    mods.append(f'K3CheckEdge{r}')
    val = f'vertexOf 128 (fun k => mom{r}.getD k 0) +\n      (-((2 : ℕ) : ℚ)) * ({a}) * {edge_name(r)}'
    stmt = (f'theorem value : {val} ≤ -{row["eps"]} := by' if row['role'] == 'cert'
            else f'theorem value : 0 < {val} := by')
    module(f'K3CheckValue{r}', IMP, f'Kernel evaluation of the certificate value from `K3Data.mom{r}` '
           f'and `K3Data.{edge_name(r)}`.', [stmt, '  decide +kernel'])
    mods.append(f'K3CheckValue{r}')
    return mods


def assembly(r, size, terms):
    row, a = ROWS[r], ROWS[r]['alpha']
    body = [f'theorem table{r} : ∀ j, j ≤ 128 →',
            f'    bounds trialT128 2 ({a}) j = tbl{r}.getD j (0, 0) := by']
    body += chain(f'K3CheckTable{r}', table_chunks(size), 'j') + ['']
    body += [f'theorem mom{r}_all : ∀ k, k ≤ 128 →',
             f'    VertexEnclosures.momentLower (lowerOf tbl{r}) (upperOf tbl{r}) k = mom{r}.getD k 0 := by']
    body += chain(f'K3CheckMom{r}', moment_chunks(terms), 'k') + ['']
    lemma = 'certUpper_le_of_tables' if row['role'] == 'cert' else 'le_certUpper_of_tables'
    concl = (f'certUpper trialT128 2 ({a}) 128 {N} ({U}) ≤ -{row["eps"]}' if row['role'] == 'cert'
             else f'0 < certUpper trialT128 2 ({a}) 128 {N} ({U})')
    final = (f'  exact h.trans K3CheckValue{r}.value' if row['role'] == 'cert'
             else f'  exact lt_of_lt_of_le K3CheckValue{r}.value h')
    body += [f'theorem {row["thm"]} :', f'    {concl} := by',
             f'  have h := {lemma} trialT128 2 ({a}) (by norm_num) 128 {N} ({U}) tbl{r}',
             f'    table{r} K3CheckEdge{r}.edge',
             f'  rw [vertexUpper_eq_vertexOf 128 _ _ (fun k => mom{r}.getD k 0) mom{r}_all] at h',
             final, '']
    return body


def write_checks(size, terms):
    order = []
    for group, rows, doc in [
            ('CertificatesK3', 'AB', 'Random 3-SAT certificates at 4.2672 and 4.26718'),
            ('CertificatesK3Controls', 'CD', 'Same-law controls at 4.2671 and 4.26717 (positive values)')]:
        mods, body = [], []
        for r in rows:
            mods += row_modules(r, size, terms)
            body += assembly(r, size, terms)
        order += mods
        module(group, ['import KSatUpper.NumericalCriterionTables'] + IMP + [f'import KSatUpper.{m}' for m in mods],
               f'{doc} for the six-atom law `TrialDataK3.trialT128` (`T = 128`, edge\n'
               f'truncation `N = {N}`), assembled from bounded kernel checks: every table chunk, moment\n'
               'chunk, edge bound and final value is a separate small `decide +kernel` in a `K3Check*`\n'
               'module. The statements are those of the superseded monolithic module\n'
               '(`archive/k3-monolithic-12GiB/CertificatesK3.lean`), whose single `decide` per\n'
               'certificate peaked at about 12 GB of memory.', body[:-1])
        order.append(group)
    print('\n'.join(order))


if __name__ == '__main__':
    if sys.argv[1] == 'data':
        write_data(parse(sys.argv[2]))
    elif sys.argv[1] == 'checks':
        write_checks(int(sys.argv[2]), int(sys.argv[3]))
