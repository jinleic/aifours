#!/usr/bin/env python3
"""hyprun.py -- [F] driver for target T4 (c5, task OlsonRunCount5).
Reads the hyp words regenerated by map5 (out/map5_p11.txt, out/map5_p13.txt), checks their item-(iii) membership from the
explicit run data (all reflection runs odd, k >= p + 1, R <= 2p - 3, runs pure (a_t b_t = 0) or (1,1)-pairs, 1 <= B <= kappa - 1,
B <= A <= 2p - 1, not ZSI-B since kB >= 2 or k >= p + 2), reports the Theorem C quantities (n_ev,al, n_pr, the refined (B1)
count bound) and runs ./hypdfs on each word with shrink = 0 (the real windows) and shrink = 1, 2 (mutation controls:
smaller windows, avoiders expected to appear).  Positive/negative cross-checks on all-singleton W(p, kB) words
(c3/out/famdfs_W_high.txt: no avoider in W(11, 5..7), W(13, 6..9)).
Every hypdfs call is a separate process run to completion (no timeouts; tiny instances).
"""
import json, subprocess, sys, time

def words():
    out = []
    for f in ('out/map5_p11.txt', 'out/map5_p13.txt'):
        for line in open(f):
            if '"hypword"' in line: out.append(json.loads(line))
    return out

def run(p, a, b, l, shrink):
    cmd = ['./hypdfs', str(p), ','.join(map(str, a)), ','.join(map(str, b)), ','.join(map(str, l)), str(shrink)]
    return json.loads(subprocess.run(cmd, capture_output=True, text=True, check=True).stdout)

def main():
    print('== hyprun.py start', time.strftime('%Y-%m-%dT%H:%M:%S'), flush=True)
    ws = words()
    print('hyp words regenerated:', len(ws), flush=True)
    for i, w in enumerate(ws):
        p, a, b, l = w['p'], w['a'], w['b'], w['l']
        k = len(a); A = sum(a); B = sum(b); R = A + B; H = sum(x // 2 for x in l); kappa = p - 1 - H; kB = kappa - B
        pure = all(x == 0 or y == 0 or (x == 1 and y == 1) for x, y in zip(a, b))
        npr = sum(1 for x, y in zip(a, b) if x == 1 and y == 1)
        nev_al = sum(1 for x, y in zip(a, b) if y == 0 and x % 2 == 0)
        member = (all(x % 2 == 1 for x in l) and k >= p + 1 and k <= 2 * p - 2 and R <= 2 * p - 3 and pure and 1 <= B <= kappa - 1
                  and B <= A <= 2 * p - 1 and sum(l) + R == 4 * p - 2 and not (k == p + 1 and kB == 1))
        b1 = (k - kB - 2 * B) + npr / 2 - nev_al / 2
        res = [run(p, a, b, l, s) for s in (0, 1, 2)]
        print(json.dumps({'word': i, 'p': p, 'k': k, 'kB': kB, 'B': B, 'kappa': kappa, 'E': R - k, 'n_ev_al': nev_al, 'n_pr': npr,
                          'item_iii_member': member, 'thmC_hyp_(i)_or_(ii)': nev_al <= 4 or (2 * kB <= p and nev_al <= 2 * kB + 2),
                          'B1_bound_k-kB-2B+npr/2-nev/2': b1,
                          'avoider_shrink0': res[0]['avoider'], 'checks0': res[0]['checks'],
                          'avoider_shrink1': res[1]['avoider'], 'avoider_shrink2': res[2]['avoider'],
                          'hypdfs_kappa_kB': (res[0]['kappa'], res[0]['kB']), 'all_odd': res[0]['all_odd']}), flush=True)
    # cross-checks on all-singleton W(p, kB): anti run first, reflection runs l_0 = 2(p - 2 - kB) + 1, others 1
    for (p, kB) in [(11, 5), (11, 6), (11, 7), (13, 6), (13, 7), (13, 8), (13, 9)]:
        k = p + 1 + kB
        a = [0] + [1] * (k - 1); b = [1] + [0] * (k - 1); l = [2 * (p - 2 - kB) + 1] + [1] * (k - 1)
        r0 = run(p, a, b, l, 0); r1 = run(p, a, b, l, 1)
        print(json.dumps({'crosscheck_W': (p, kB), 'avoider_shrink0': r0['avoider'], 'checks0': r0['checks'], 'avoider_shrink1': r1['avoider'],
                          'kB_seen': r0['kB']}), flush=True)
    print('== hyprun.py end', time.strftime('%Y-%m-%dT%H:%M:%S'), flush=True)

if __name__ == '__main__':
    main()
