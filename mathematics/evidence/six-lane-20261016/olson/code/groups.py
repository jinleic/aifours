#!/usr/bin/env python3
"""Finite group tables for the ordered-Olson lane.

Every group is built as a concrete permutation group (closure of explicit
generators), so the multiplication table is derived from composition of
permutations, not from a hand-written presentation formula.  Element 0 is the
identity.  Convention: table[a][b] = index of (a*b) where (a*b)(x) = a(b(x))
is NOT used; we use left-to-right product a then b acting on the right:
x^(ab) = (x^a)^b.  Any fixed convention gives a group isomorphic to the
generated one; the search only needs a genuine group table.

Usage: python3 groups.py NAME OUTFILE   (writes "n\n" then n rows)
       python3 groups.py --list
"""
import itertools
import json
import sys


def compose(p, q):
    """x^(pq) = (x^p)^q for permutations given as tuples."""
    return tuple(q[p[i]] for i in range(len(p)))


def closure(gens):
    deg = len(gens[0])
    e = tuple(range(deg))
    elems = [e]
    seen = {e}
    frontier = [e]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = compose(x, g)
                if y not in seen:
                    seen.add(y)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems


def table_of(elems):
    idx = {x: i for i, x in enumerate(elems)}
    return [[idx[compose(a, b)] for b in elems] for a in elems]


def cyc(n, k=1, deg=None):
    deg = deg or n
    return tuple(((i + k) % n) if i < n else i for i in range(deg))


def perm_from_cycles(deg, cycles):
    p = list(range(deg))
    for c in cycles:
        for i, x in enumerate(c):
            p[x] = c[(i + 1) % len(c)]
    return tuple(p)


def direct(*perm_lists):
    """Direct product of permutation generator lists on disjoint points."""
    degs = [len(gs[0]) for gs in perm_lists]
    total = sum(degs)
    out = []
    off = 0
    for gs, d in zip(perm_lists, degs):
        for g in gs:
            p = list(range(total))
            for i in range(d):
                p[off + i] = off + g[i]
            out.append(tuple(p))
        off += d
    return out


def dihedral_gens(m):
    r = tuple((i + 1) % m for i in range(m))
    s = tuple((-i) % m for i in range(m))
    return [r, s]


def cyclic_gens(n):
    return [tuple((i + 1) % n for i in range(n))]


def affine_gens(p, mult_gens):
    """Subgroups of AGL(1,p): x->x+1 and x->a x for a in mult_gens."""
    t = tuple((i + 1) % p for i in range(p))
    gens = [t]
    for a in mult_gens:
        gens.append(tuple((a * i) % p for i in range(p)))
    return gens


def regular_gens_from_table(tab, gens_idx):
    """Right-regular representation of a group given by a table."""
    n = len(tab)
    return [tuple(tab[x][g] for x in range(n)) for g in gens_idx]


def dicyclic_gens(m):
    """Dic_m of order 4m as permutations: right-regular rep of the
    presentation-free model {(a,b): a in Z_2m, b in {0,1}} built as a
    subgroup of GL_2 over Z[zeta]? Simpler: realise as permutations of
    Z_2m x {0,1} induced by left multiplication in the group
    x=r (order 2m), y with y^2=r^m, y r y^-1 = r^-1.  We build it as the
    group generated by two permutations of the 4m formal words, checked by
    closure size (must equal 4m) and axioms afterwards."""
    q = 2 * m
    # elements r^a y^b, b in {0,1}; multiplication rule:
    def mul(u, v):
        a, b = u
        c, d = v
        if b == 0:
            return ((a + c) % q, d)
        # y r^c = r^-c y
        if d == 0:
            return ((a - c) % q, 1)
        # r^a y r^c y = r^(a-c) y^2 = r^(a-c+m)
        return ((a - c + m) % q, 0)
    elems = [(a, b) for b in (0, 1) for a in range(q)]
    idx = {x: i for i, x in enumerate(elems)}
    # right multiplication permutations (a genuine action: x -> x*g)
    def rperm(g):
        return tuple(idx[mul(x, g)] for x in elems)
    return [rperm((1, 0)), rperm((0, 1))]


def quaternion8_gens():
    return dicyclic_gens(2)


def build(name):
    if name.startswith('C') and name[1:].isdigit():
        return closure(cyclic_gens(int(name[1:])))
    if name.startswith('D') and name[1:].isdigit():
        # D2m notation: D10 means order 10
        order = int(name[1:])
        assert order % 2 == 0
        return closure(dihedral_gens(order // 2))
    if name.startswith('Dic') and name[3:].isdigit():
        return closure(dicyclic_gens(int(name[3:])))
    if name == 'Q8':
        return closure(quaternion8_gens())
    if name == 'A4':
        return closure([perm_from_cycles(4, [(0, 1, 2)]), perm_from_cycles(4, [(0, 1), (2, 3)])])
    if name == 'S4':
        return closure([perm_from_cycles(4, [(0, 1, 2, 3)]), perm_from_cycles(4, [(0, 1)])])
    if name == 'S3':
        return closure([perm_from_cycles(3, [(0, 1, 2)]), perm_from_cycles(3, [(0, 1)])])
    if name == 'F21':  # C7 x| C3
        return closure(affine_gens(7, [2]))
    if name == 'F20':  # C5 x| C4
        return closure(affine_gens(5, [2]))
    if name == 'F42':
        return closure(affine_gens(7, [3]))
    if name == 'C3xS3':
        return closure(direct(cyclic_gens(3), dihedral_gens(3)))
    if name == 'C2xS3':
        return closure(direct(cyclic_gens(2), dihedral_gens(3)))
    if name == 'Dih9':  # generalized dihedral of C3xC3
        # points Z3xZ3 as 9 points; translations and inversion
        pts = [(a, b) for a in range(3) for b in range(3)]
        ix = {p: i for i, p in enumerate(pts)}
        t1 = tuple(ix[((a + 1) % 3, b)] for a, b in pts)
        t2 = tuple(ix[(a, (b + 1) % 3)] for a, b in pts)
        inv = tuple(ix[((-a) % 3, (-b) % 3)] for a, b in pts)
        return closure([t1, t2, inv])
    if name == 'C3xC3':
        return closure(direct(cyclic_gens(3), cyclic_gens(3)))
    if name == 'C2xC2':
        return closure(direct(cyclic_gens(2), cyclic_gens(2)))
    if name == 'C5xS3':
        return closure(direct(cyclic_gens(5), dihedral_gens(3)))
    if name == 'C3xD10':
        return closure(direct(cyclic_gens(3), dihedral_gens(5)))
    if name == 'SL23':
        # SL(2,3) acting on nonzero vectors of F3^2 (8 points)
        vecs = [(a, b) for a in range(3) for b in range(3) if (a, b) != (0, 0)]
        ix = {v: i for i, v in enumerate(vecs)}
        def mat(M):
            return tuple(ix[((M[0][0] * a + M[0][1] * b) % 3, (M[1][0] * a + M[1][1] * b) % 3)] for a, b in vecs)
        return closure([mat(((1, 1), (0, 1))), mat(((1, 0), (1, 1)))])
    if name == 'C4xS3':
        return closure(direct(cyclic_gens(4), dihedral_gens(3)))
    if name == 'C3xQ8':
        return closure(direct(cyclic_gens(3), quaternion8_gens()))
    if name == 'C3xD8':
        return closure(direct(cyclic_gens(3), dihedral_gens(4)))
    raise SystemExit('unknown group ' + name)


def validate(tab):
    n = len(tab)
    assert all(tab[0][a] == a and tab[a][0] == a for a in range(n)), 'identity'
    for a in range(n):
        assert sorted(tab[a]) == list(range(n)), 'row latin'
        assert sorted(tab[x][a] for x in range(n)) == list(range(n)), 'col latin'
    for a, b, c in itertools.product(range(n), repeat=3):
        assert tab[tab[a][b]][c] == tab[a][tab[b][c]], 'assoc'
    return True


def main():
    if sys.argv[1] == '--list':
        print('C<n> D<2m> Dic<m> Q8 A4 S4 S3 F20 F21 F42 C3xS3 C2xS3 Dih9 C3xC3 C5xS3 C3xD10 SL23 C4xS3 C3xQ8 C3xD8')
        return
    name, out = sys.argv[1], sys.argv[2]
    elems = build(name)
    assert elems[0] == tuple(range(len(elems[0])))
    tab = table_of(elems)
    validate(tab)
    with open(out, 'w') as f:
        f.write(f"{len(tab)}\n")
        for row in tab:
            f.write(' '.join(map(str, row)) + '\n')
    meta = {'name': name, 'order': len(tab), 'degree': len(elems[0]),
            'elements': [list(x) for x in elems]}
    with open(out + '.json', 'w') as f:
        json.dump(meta, f)
    print(name, len(tab))


if __name__ == '__main__':
    main()
