#!/usr/bin/env python3
"""Exact classification of all-odd k-block words at length N over D_(2p) (rotation slice, 2026-10-18).

Statement S(k, N, p): every word of length N whose maximal-constant-block representation (any representation with
possibly empty rotation runs) has k blocks, ALL odd, and which avoids identity 2p-subwords, has rotation values in
one {c, -c}, c != 0.  Representation-based (GRX, notes-GRX-v1.md); for all-odd blocks the GRX conditions depend on
the block lengths only through F, so the enumeration is over: F (k <= F, F = k mod 2), the rotation multiset Y of
size R = N - F, its distribution into k ordered runs (X_1..X_k), and theta in Z_p^k with sum 0.
Exactness: Y is generated by a pruned DFS over value multiplicities using ONLY the zero pattern (z = +, a GRX
condition, hence necessary); every remaining datum is decided by the full GRX criterion over all 2^(k-1) patterns.
Every non-rigid avoiding datum is turned into an explicit word (l = (F-k+1, 1, ..., 1)) and re-checked by rawdp
(fresh raw DP) before being reported; a sample of rigid avoiders is re-checked the same way (positive control),
and for every avoiding datum one mutated word (an explicit identity 2p-index set forced) must be rejected.
Usage: kblock_exact_v1.py p N k [max_report]
"""
import itertools, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rawdp  # noqa: E402


def rotm(m, s, p, full):
    s %= p
    return ((m << s) | (m >> (p - s))) & full if s else m


def neg(m, p):
    out = m & 1
    for v in range(1, p):
        if (m >> v) & 1:
            out |= 1 << (p - v)
    return out


def profile(counts, p, maxm):
    """counts[v] multiplicities -> list prof[m] = bitmask of size-m sub-multiset sums."""
    full = (1 << p) - 1
    prof = [0] * (maxm + 1)
    prof[0] = 1
    for v in range(p):
        c = counts[v]
        if not c:
            continue
        new = prof[:]
        for L in range(maxm + 1):
            m = prof[L]
            if not m:
                continue
            acc = m
            for j in range(1, c + 1):
                if L + j > maxm:
                    break
                acc = rotm(acc, v, p, full)
                new[L + j] |= acc
        prof = new
    return prof


def ydfs(p, R, lo, hi):
    """All multiplicity vectors of size R with no zero-sum of even length in [lo, hi]."""
    out = []
    full = (1 << p) - 1
    maxL = min(hi, R)

    def bad(prof):
        return any((prof[L] & 1) for L in range(max(lo, 1), maxL + 1) if L % 2 == 0)

    def rec(v, left, counts, prof):
        if v == p - 1:
            c = left
            cnt = counts + [c]
            pr = prof
            if c:
                new = pr[:]
                for L in range(maxL + 1):
                    m = pr[L]
                    if not m:
                        continue
                    acc = m
                    for j in range(1, c + 1):
                        if L + j > maxL:
                            break
                        acc = rotm(acc, v, p, full)
                        new[L + j] |= acc
                pr = new
            if not bad(pr):
                out.append(cnt)
            return
        for c in range(0, left + 1):
            pr = prof
            if c:
                new = pr[:]
                for L in range(maxL + 1):
                    m = pr[L]
                    if not m:
                        continue
                    acc = m
                    for j in range(1, c + 1):
                        if L + j > maxL:
                            break
                        acc = rotm(acc, v, p, full)
                        new[L + j] |= acc
                pr = new
                if bad(pr):
                    break  # more copies of v only add zero-sums
            rec(v + 1, left - c, counts + [c], pr)

    prof0 = [0] * (maxL + 1)
    prof0[0] = 1
    rec(0, R, [], prof0)
    return out


def rigid(counts, p):
    vals = [v for v in range(p) if counts[v]]
    if 0 in vals:
        return False
    return len(vals) <= 1 or (len(vals) == 2 and (vals[0] + vals[1]) % p == 0)


def distributions(counts, k):
    per = []
    for v, c in enumerate(counts):
        if c:
            per.append([(v, comp) for comp in compositions(c, k)])
    for choice in itertools.product(*per):
        runs = [[0] * len(counts) for _ in range(k)]
        for v, comp in choice:
            for i in range(k):
                runs[i][v] += comp[i]
        yield runs


def compositions(n, k):
    if k == 1:
        yield (n,)
        return
    for a in range(n + 1):
        for rest in compositions(n - a, k - 1):
            yield (a,) + rest


def word_of(runs, F, k, theta, p):
    ls = [F - k + 1] + [1] * (k - 1)
    y, prev = [0] * k, 0
    for i in range(k):
        y[i] = (prev - theta[i]) % p
        prev = y[i]
    w = []
    for i in range(k):
        for v in range(p):
            w += [('r', v)] * runs[i][v]
        w += [('s', y[i])] * ls[i]
    return w


def main():
    p, N, k = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
    max_report = int(sys.argv[4]) if len(sys.argv) > 4 else 20
    full = (1 << p) - 1
    pats = [(1,) + t for t in itertools.product((1, -1), repeat=k - 1)]
    summary = {'p': p, 'N': N, 'k': k, 'Y_pass': 0, 'data_checked': 0, 'avoid_rigid': 0, 'avoid_nonrigid': 0,
               'dp_confirmed_nonrigid': 0, 'dp_rigid_checked': 0, 'dp_rigid_fail': 0, 'mutants_rejected': 0,
               'mutants_total': 0}
    reports = []
    import random
    rng = random.Random(1)
    for F in range(k, N + 1, 2):
        R = N - F
        H = (F - k) // 2
        if H > p - 1:
            break
        lo = 2 * p - 2 * H
        Ys = ydfs(p, R, lo, 2 * p)
        summary['Y_pass'] += len(Ys)
        for counts in Ys:
            isr = rigid(counts, p)
            for runs in distributions(counts, k):
                profs = [profile(r, p, R) for r in runs]
                negs = [[neg(m, p) for m in pr] for pr in profs]
                W = []
                for z in pats:
                    comb = [1] + [0] * R
                    for i in range(k):
                        pr = profs[i] if z[i] == 1 else negs[i]
                        new = [0] * (R + 1)
                        for a in range(R + 1):
                            if not comb[a]:
                                continue
                            for b in range(len(pr)):
                                if a + b > R or not pr[b]:
                                    continue
                                mb = pr[b]
                                acc = 0
                                ma = comb[a]
                                for s in range(p):
                                    if (ma >> s) & 1:
                                        acc |= rotm(mb, s, p, full)
                                new[a + b] |= acc
                        comb = new
                    Phi = sum(1 for i in range(k) if z[i] != z[(i + 1) % k])
                    Cmax = F - (k - Phi)
                    wm = 0
                    for C in range(Phi, Cmax + 1, 2):
                        m = 2 * p - C
                        if 0 <= m <= R:
                            wm |= comb[m]
                    W.append(wm)
                for th in itertools.product(range(p), repeat=k - 1):
                    theta = list(th) + [(-sum(th)) % p]
                    summary['data_checked'] += 1
                    ok = True
                    for z, wm in zip(pats, W):
                        T = sum(theta[i] for i in range(k) if z[i] == 1) % p
                        if (wm >> T) & 1:
                            ok = False
                            break
                    if not ok:
                        continue
                    w = word_of(runs, F, k, theta, p)
                    if isr:
                        summary['avoid_rigid'] += 1
                        if rng.random() < 0.05:
                            summary['dp_rigid_checked'] += 1
                            summary['dp_rigid_fail'] += rawdp.has_identity(w, p, 2 * p)
                    else:
                        summary['avoid_nonrigid'] += 1
                        conf = not rawdp.has_identity(w, p, 2 * p)
                        summary['dp_confirmed_nonrigid'] += conf
                        if len(reports) < max_report:
                            reports.append({'F': F, 'runs': runs, 'theta': theta, 'dp_avoider': conf,
                                            'word': rawdp.fmt(w)})
                    if rng.random() < 0.05:
                        idx = sorted(rng.sample(range(len(w)), 2 * p))
                        mw = list(w)
                        v, e = rawdp.product(mw, idx[:-1], p)
                        mw[idx[-1]] = ('r' if e == 1 else 's', (-e * v) % p)
                        summary['mutants_total'] += 1
                        summary['mutants_rejected'] += rawdp.has_identity(mw, p, 2 * p)
    for r in reports:
        print(json.dumps(r), flush=True)
    print(json.dumps(summary), flush=True)


if __name__ == '__main__':
    main()
