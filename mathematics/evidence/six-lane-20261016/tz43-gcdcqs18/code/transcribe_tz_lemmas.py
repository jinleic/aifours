TEXT_ITEM = re.compile(r"\{([^{}]*)\}")  # {0, 1, 2, a}
TEX_ITEM = re.compile(r"\\\{(.*?)\\\}")  # \{0, 1, 2, $a$\}


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def load(source, encoding, crlf):
    """Pinned source -> (sha256, lines) with lines[n] = LF line n."""
    rel, pinned = source
    with open(os.path.join(LANE, rel), "rb") as f:
        data = f.read()
    if sha256(data) != pinned:
        raise SystemExit("%s: sha256 %s is not the pinned %s" % (rel, sha256(data), pinned))
    if crlf:
        assert data.count(b"\r") == data.count(b"\r\n") == data.count(b"\n"), rel + ": not uniformly CRLF"
    else:
        assert b"\r" not in data, rel + ": unexpected CR"
    raw = data.split(b"\n")
    if crlf:
        raw = [r[:-1] if r.endswith(b"\r") else r for r in raw]
    return sha256(data), [None] + [r.decode(encoding) for r in raw]


def check_anchors(lines, anchors, route):
    for n, expected in anchors:
        if lines[n] != expected:
            raise SystemExit("%s anchor LF %d: expected %r, found %r" % (route, n, expected, lines[n]))
    return [[n, s] for n, s in anchors]


def text_row(line, label):
    """Items {p, q, ...} of one pdftotext line; nothing but the label and blanks may remain."""
    s = line[1:] if line.startswith("\x0c") else line
    if label is not None:
        head, found, s = s.partition(label)
        assert found and not head.strip(), (label, line)
    items = [tuple(tok.strip() for tok in m.split(",")) for m in TEXT_ITEM.findall(s)]
    assert items and not TEXT_ITEM.sub("", s).strip(), line
    return items


def tex_row(line, label):
    """Items \\{p, q, ...\\} of one tabular row ending in a row break; only '&' and blanks may remain."""
    assert line.endswith("\\\\"), line
    s = line[:-2]
    if label is not None:
        head, found, s = s.partition(label)
        assert found and not head.strip(), (label, line)
    items = []
    for m in TEX_ITEM.findall(s):
        toks = [tok.strip() for tok in m.split(",")]
        items.append(tuple(tok[1:-1] if len(tok) > 2 and tok[0] == tok[-1] == "$" else tok for tok in toks))
    assert items and set(TEX_ITEM.sub("", s)) <= {"&", " "}, line
    return items


def text_rows(T, lo, hi, label):
    return [text_row(T[n], label if n == lo else None) for n in range(lo, hi + 1)]


def tex_rows(X, lo, hi, label):
    return [tex_row(X[n], label if n == lo else None) for n in range(lo, hi + 1)]


def cut_parts(rows, lo, sizes):
    """Cut the reading-order items of the printed lines lo, lo+1, ... into parts of the given sizes; every
    cut must fall on a line boundary.  Returns the parts and their [first LF, last LF]."""
    ends, pos = set(), 0
    for row in rows:
        pos += len(row)
        ends.add(pos)
    flat = [(lo + i, it) for i, row in enumerate(rows) for it in row]
    assert sum(sizes) == len(flat), (sizes, len(flat))
    parts, spans, pos = [], [], 0
    for size in sizes:
        chunk = flat[pos:pos + size]
        pos += size
        assert pos in ends, "a part would end inside a printed line"
        parts.append([it for _, it in chunk])
        spans.append([chunk[0][0], chunk[-1][0]])
    return parts, spans


def tex_parts(X, lo, hi, label):
    """Appendix A tabulars: every part is a row, a \\smallskip line and a second row."""
    assert (hi - lo + 1) % 3 == 0
    parts, spans = [], []
    for n in range(lo, hi + 1, 3):
        assert X[n + 1] == "\\smallskip", n + 1
        parts.append(tex_row(X[n], label if n == lo else None) + tex_row(X[n + 2], None))
        spans.append([n, n + 2])
    return parts, spans


