def flat(lst):
    if all(not isinstance(e, (list, dict)) for e in lst):
        return len(lst) < 2 or not all(isinstance(e, str) for e in lst)
    return all(isinstance(e, list) and all(isinstance(q, int) for q in e) for e in lst)


def dump(o, ind=0):
    """JSON text: dicts and nested lists one element per line, flat lists on one line."""
    pad = "  " * ind
    if isinstance(o, dict):
        body = ",\n".join("%s  %s: %s" % (pad, json.dumps(k), dump(v, ind + 1)) for k, v in o.items())
        return "{\n" + body + "\n" + pad + "}"
    if isinstance(o, list) and not flat(o):
        return "[\n" + ",\n".join(pad + "  " + dump(e, ind + 1) for e in o) + "\n" + pad + "]"
    return json.dumps(o)


def as_json(doc):
    text = dump(doc) + "\n"
    assert json.loads(text) == doc
    return text.encode("ascii")


