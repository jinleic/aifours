        status = {}
        for rel, data in outputs:
            path = os.path.join(LANE, rel)
            if not os.path.exists(path):
                status[rel] = "ABSENT"
            else:
                with open(path, "rb") as f:
                    status[rel] = "EQUAL" if f.read() == data else "DIFFERENT"
        summary["replay"] = status
        print(json.dumps(summary, indent=1))
        sys.exit(0 if all(s == "EQUAL" for s in status.values()) else 1)
