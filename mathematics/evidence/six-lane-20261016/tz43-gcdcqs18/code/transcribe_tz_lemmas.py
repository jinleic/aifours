def agreement(rt, rx, names):
    """Compare the ordered token lists of both routes; stop at the first difference."""
    result = {}
    for key, name in names:
        a, b = rt[key], rx[key]
        if a != b:
            i = next((i for i, (p, q) in enumerate(zip(a, b)) if p != q), min(len(a), len(b)))
            raise SystemExit("text and TeX differ for %s at item %d: %r / %r" % (name, i, a[i:i + 1], b[i:i + 1]))
        result[name] = True
    result["identical_ordered_lists"] = all(result.values())
    return result


def point(tok, below, labels):
    if tok in labels:
        return labels[tok]
    assert tok.isdigit() and str(int(tok)) == tok and int(tok) < below, tok
    return int(tok)


def to_points(items, size, below, labels):
    out = [[point(tok, below, labels) for tok in it] for it in items]
    assert all(len(p) == size == len(set(p)) for p in out), items
    return out


def sigma31(p, k):
    """(0 1 ... 31)(32 33) to the power k."""
    return (p + k) % 32 if p < 32 else (p if k % 2 == 0 else 65 - p)


def sigma37(p, k):
    """(0 1 ... 9)(10 11 ... 19) to the power k."""
    return (p + k) % 10 if p < 10 else 10 + (p - 10 + k) % 10


def orbit_blocks(base, act, order):
    blocks = set()
    for b in base:
        orbit = {tuple(sorted(act(p, k) for p in b)) for k in range(order)}
        assert len(orbit) == order and not orbit & blocks, ("short or repeated orbit", b)
        blocks |= orbit
    return sorted(blocks)


def assert_derived(blocks, x, classes):
    """Every printed triple T at x has x not in T and T union {x} a block."""
    bset = set(blocks)
    for cls in classes:
        for tr in cls:
            assert x not in tr and tuple(sorted(tr + [x])) in bset, (x, tr)


def transport(classes, act, k):
    return [[sorted(act(p, k) for p in tr) for tr in cls] for cls in classes]


def missed_group(cls, groups):
    pts = {p for tr in cls for p in tr}
    missed = [k for k, g in enumerate(groups) if not pts.intersection(g)]
    assert len(missed) == 1, ("FRAME label undefined", missed, cls)
    return missed[0]


def chi_prime(v):
    """(1.1) of the source for v = 1, 3 (mod 6), v not in {7, 13}."""
    if v % 6 == 3:
        return (v - 1) // 2
    assert v % 6 == 1 and v not in (7, 13), v
    return (v + 1) // 2


def fmt(pts):
    return " ".join(str(p) for p in pts)


