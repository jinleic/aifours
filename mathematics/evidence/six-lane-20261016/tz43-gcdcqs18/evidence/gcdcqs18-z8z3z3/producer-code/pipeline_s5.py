#!/usr/bin/env python3
"""README A4: gcDCQS(18^4 : 2) pipeline in the model Z8 x Z3^2 (numpy + kissat; structure as pipeline_s3/s4).

Group points (a, z1, z2) in Z8 x Z3 x Z3 -> label 9a + 3 z1 + z2 (0..71), group = a mod 4, stems 72, 73.
Generators: t8 (a -> a + 1, swaps the stems), t31, t32 (z1 + 1, z2 + 1; stems fixed) and optionally the power
S^k of the Singer cycle S: (z1, z2) -> (z1 - z2, z1 + z2) (multiplication by 1 + i in GF(9) = GF(3)[i], order 8;
no element of order 3, so no fixed sub-CQS(6^4:2) — README Lemma F′ does not apply; stems fixed).  Lemma I is
re-checked on every element.  KM by code/cqs_km_s.py (kissat, native limit); colouring at the representative 0
with R = Stab(0) (generated by S^k), anchor = stem 72; transport by the least element; stem frames = orbits of
the kernel translations {0,4} x Z3^2 (preserve groups, regular on each group, fix the stems: Lemma K).
Usage: pipeline_s5.py OUT [--sk K] [--avoid SPEC] [--samples N] [--seed0 S] [--km-timeout T] [--col-timeout T]
       [--col-seed S] [--strengthen] [--profile P10] [--no-solve] [--stop-on-first] [--model-from LOG]"""
import lane_guard  # noqa: F401

import argparse
import collections
import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lane_guard import fresh_dir, xopen  # noqa: E402
from lanelib import closure, gcsts_params, kissat, model_satisfies, parse_status  # noqa: E402
from cqs_km_s import CQSKMS  # noqa: E402
import colour_model as cm  # noqa: E402
from pipeline_s import derived  # noqa: E402
from pipeline_s2 import cyclic_subgroup, lemma_i_violations  # noqa: E402

N, v, g = 72, 74, 18


def lab(a, z1, z2):
    return 9 * (a % 8) + 3 * (z1 % 3) + (z2 % 3)


def dec(p):
    return p // 9, (p % 9) // 3, p % 3


def perm(f, swap):
    return tuple([lab(*f(*dec(p))) for p in range(N)] + ([73, 72] if swap else [72, 73]))


def cert_text(r, s, blocks, col, frames, header):
    L = [f"# {header}", f"GCDCQS {v} 4 {g} 2", f"COLOURS {r}", f"HOLEFREE {s}", "GROUPS"]
    L += [" ".join(str(p) for p in range(N) if dec(p)[0] % 4 == i) for i in range(4)]
    L += ["STEM", "72 73", "BLOCKS"]
    L += [" ".join(map(str, b)) for b in sorted(tuple(sorted(b)) for b in blocks)]
    for y in range(N):
        L.append(f"POINT {y}")
        for j, C in enumerate(col[y]):
            L.append(f"CLASS {j}")
            L += [" ".join(map(str, t)) for t in C]
    for a in (72, 73):
        L.append(f"STEMPOINT {a}")
        for k, C in frames[a]:
            L.append(f"FRAME {k}")
            L += [" ".join(map(str, t)) for t in C]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--sk", type=int, default=0, help="use S^k as multiplier generator (0 = none)")
    ap.add_argument("--avoid", default=None)
    ap.add_argument("--samples", type=int, default=1)
    ap.add_argument("--seed0", type=int, default=0)
    ap.add_argument("--km-timeout", type=int, default=600)
    ap.add_argument("--col-timeout", type=int, default=600)
    ap.add_argument("--col-seed", type=int, default=1)
    ap.add_argument("--strengthen", action="store_true")
    ap.add_argument("--profile", default=None)
    ap.add_argument("--no-solve", action="store_true")
    ap.add_argument("--stop-on-first", action="store_true")
    ap.add_argument("--model-from", default=None)
    ap.add_argument("--excl36", action="store_true",
                    help="README A4 note: forbid the KM rows containing a block {0, 36, (a,z), (a,-z)} (S^4-invariant "
                         "2+2 blocks through 0 and its S^4-fixed group mate 36), impossible with an R-invariant "
                         "colouring at 0 when S^4 is in R")
    a = ap.parse_args()
    fresh_dir(a.out)
    prog = xopen(os.path.join(a.out, "progress.jsonl"))

    def log(rec):
        prog.write(json.dumps(rec) + "\n")
        prog.flush()
        print(json.dumps(rec), flush=True)

    group_of = [dec(p)[0] % 4 for p in range(N)] + [-1, -1]
    gens = [perm(lambda a_, z1, z2: (a_ + 1, z1, z2), True), perm(lambda a_, z1, z2: (a_, z1 + 1, z2), False),
            perm(lambda a_, z1, z2: (a_, z1, z2 + 1), False)]
    if a.sk:
        def S(a_, z1, z2):
            for _ in range(a.sk):
                z1, z2 = (z1 - z2) % 3, (z1 + z2) % 3
            return a_, z1, z2
        gens.append(perm(S, False))
    G = closure(gens, v)
    Hk = closure([perm(lambda a_, z1, z2: (a_ + 4, z1, z2), False), perm(lambda a_, z1, z2: (a_, z1 + 1, z2), False),
                  perm(lambda a_, z1, z2: (a_, z1, z2 + 1), False)], v)
    assert len(Hk) == 18
    nbad = lemma_i_violations(G, group_of, (72, 73))
    r, s = gcsts_params(v - 1, g + 1)
    x, anchor = 0, 72
    R = [e for e in G if e[x] == x]
    assert all(e[anchor] == anchor for e in R)
    info = {"model": "Z8xZ3^2", "sk": a.sk, "group_order": len(G), "R_order": len(R), "lemma_I_violating_elements": nbad,
            "r": r, "s": s}
    if nbad:
        log({**info, "stop": "Lemma I"})
        return
    toks = a.avoid.split(";") if a.avoid else [str(len(R))] * (s % len(R)) + ["1"] * ((s - s % len(R)) // len(R))
    stabs = [cyclic_subgroup(R, int(t)) for t in toks]
    assert sum(len(R) // len(st) for st in stabs) == s, f"avoid {toks} does not give {s} classes"
    info["avoid"] = ";".join(toks)
    t0 = time.time()
    km = CQSKMS(v, group_of, gens)
    summ = {**info, "km": km.summary(), "km_build_seconds": round(time.time() - t0, 2), "args": vars(a),
            "samples": [], "certificates": []}
    log({**info, "km": summ["km"], "km_build_seconds": summ["km_build_seconds"]})
    cnf, rv = km.cnf()
    if a.excl36:
        import numpy as np
        from lanelib import rank
        cand = []
        for aa in (1, 2, 3, 5, 6, 7):
            for z1 in range(3):
                for z2 in range(3):
                    if (z1, z2) != (0, 0):
                        cand.append(sorted([0, 36, lab(aa, z1, z2), lab(aa, -z1, -z2)]))
        labs_bad = set(km.LQ[rank(np.array(cand, dtype=np.int64))].tolist())
        nex = 0
        for j, (lb, _) in enumerate(km.rows):
            if lb in labs_bad:
                cnf.add([-rv[j]])
                nex += 1
        summ["excl36_rows_forbidden"] = nex
        log({"excl36_rows_forbidden": nex})
    for i in range(a.samples):
        p = os.path.join(a.out, f"km_{i}.cnf")
        sha = cnf.write(p)
        st, model, dt = kissat(p, a.km_timeout, seed=a.seed0 + i, log=p + ".log")
        rec = {"sample": i, "km_seed": a.seed0 + i, "km_cnf_sha256": sha, "km_vars": cnf.nv,
               "km_clauses": len(cnf.clauses), "km_status": st, "km_seconds": round(dt, 3)}
        summ["samples"].append(rec)
        if st != "SAT":
            log(rec)
            break
        sel = [j for j, xx in enumerate(rv) if xx in model]
        rec["rows"] = sel
        cnf.add([-rv[j] for j in sel])
        blocks = km.blocks_of(sel)
        rec["blocks"] = len(blocks)
        rec["block_types"] = dict(collections.Counter(
            "+".join(str(c) for c in sorted(collections.Counter(group_of[q] for q in b).values(), reverse=True))
            for b in blocks))
        der = derived(blocks, x)
        hole = [q for q in range(v) if (group_of[q] == group_of[x] or group_of[q] == -1) and q != x]
        pts = [q for q in range(v) if q != x]
        rc, orbits, choice, cosets, stb, sizes = cm.anchored(der, pts, hole, R, anchor, stabs, strengthen=a.strengthen,
                                                             profile=a.profile)
        cp = os.path.join(a.out, f"col_{i}.cnf")
        csha = rc.write(cp)
        rec.update({"triple_orbits": len(orbits), "class_orbit_sizes": sizes, "col_cnf_sha256": csha,
                    "col_vars": rc.nv, "col_clauses": len(rc.clauses)})
        log({kk: rec[kk] for kk in rec if kk != "rows"})
        if a.no_solve:
            continue
        if a.model_from:
            cst, cmodel = parse_status(open(a.model_from).read())
            assert cst == "SAT" and model_satisfies(cp, cmodel), "retained model does not satisfy the rebuilt CNF"
            cdt = 0.0
        else:
            cst, cmodel, cdt = kissat(cp, a.col_timeout, seed=a.col_seed, log=cp + ".log")
        rec.update({"col_status": cst, "col_seconds": round(cdt, 3)})
        log({"sample": i, "col_status": cst, "col_seconds": round(cdt, 3)})
        if cst != "SAT":
            continue
        classes = cm.decode(cmodel, orbits, choice, cosets, stb, R)
        cm.verify_good_colouring(der, pts, hole, classes, r, s)
        col = {}
        for e in G:
            y = e[x]
            if y not in col:
                col[y] = [sorted(tuple(sorted(e[q] for q in t)) for t in C) for C in classes]
        assert sorted(col) == list(range(N))
        frames = {}
        for al in (72, 73):
            dset = set(derived(blocks, al))
            fr = []
            while dset:
                t = min(dset)
                orb = {tuple(sorted(e[q] for q in t)) for e in Hk}
                assert orb <= dset
                dset -= orb
                fr.append((({0, 1, 2, 3} - {group_of[q] for q in t}).pop(), sorted(orb)))
            frames[al] = sorted(fr)
        cert = os.path.join(a.out, f"gcdcqs18_4_2_z8z3z3_sk{a.sk}_s{i}.txt")
        text = cert_text(r, s, blocks, col, frames,
                         f"gcDCQS(18^4:2) candidate, model Z8 x Z3^2 (t8 swaps the stems), multiplier S^{a.sk}, "
                         f"group order {len(G)}, KM sample {i} (seed {a.seed0 + i}), colouring seed {a.col_seed}, avoid {info['avoid']}")
        with xopen(cert) as fh:
            fh.write(text)
        crt = {"sample": i, "certificate": cert, "sha256": hashlib.sha256(text.encode()).hexdigest()}
        chk = subprocess.run([sys.executable, os.path.join(HERE, "check_gcdcqs_s.py"), cert], capture_output=True, text=True)
        crt["route1"] = json.loads(chk.stdout)["result"]
        crt["route2"] = subprocess.run([os.path.join(HERE, "bin", "check_gcdcqs_s_c"), cert], capture_output=True,
                                       text=True).stdout.strip()
        summ["certificates"].append(crt)
        log(crt)
        if a.stop_on_first and crt["route1"] == "PASS":
            break
    summ["total_seconds"] = round(time.time() - t0, 2)
    with xopen(os.path.join(a.out, "summary.json")) as fh:
        json.dump(summ, fh, indent=1)
    print("DONE", json.dumps({"certificates": summ["certificates"], "total_seconds": summ["total_seconds"]}), flush=True)


if __name__ == "__main__":
    main()
