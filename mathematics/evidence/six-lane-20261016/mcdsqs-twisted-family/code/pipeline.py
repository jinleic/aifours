#!/usr/bin/env python3
"""SQS(v) invariant under Z_v ⋊ <multipliers> (Kramer–Mesner), derived design at 0 coloured
with chi'(v-1) PARTIAL parallel classes, R-invariantly (R generated by --res-mult, R <= the
multiplier group, fixing 0 and the anchor), then translated to every point.

Adapted from ../../rdsqs52/code/mult_pipeline.py (sha256 09753950…2337).  Class structure
(README Lemma B): one class orbit per R-orbit of anchored triples (forced, lossless) plus
ncol - deg(anchor) R-invariant classes missing the anchor.  --res-mult "" (or R trivial)
gives the plain anchored colouring model.

Usage: pipeline.py V OUT --mult m1,... [--res-mult r1,...] [--anchor p] [--samples K]
       [--seed0 S] [--col-timeout T] [--km-timeout T] [--workers W]
"""
import argparse
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))


def _deletion_disabled(*args, **kwargs):
    raise RuntimeError("file deletion is disabled in this lane (no-deletion rule); retain every file")


# no-deletion guard (2026-10-17 incident fix): every KM / colouring CNF and log is retained
os.remove = os.unlink = os.rmdir = os.removedirs = _deletion_disabled
sys.path.insert(0, HERE)
from mcdsqs_lib import (SQSKM, chi_index, closure, colouring_cnf, decode_colouring, derived, kissat,
                        mult_perm, shift_perm, transport, verify_colouring, write_certificate)
import ppcsym


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("v", type=int)
    ap.add_argument("out")
    ap.add_argument("--mult", default="")
    ap.add_argument("--res-mult", default=None)
    ap.add_argument("--anchor", type=int, default=None)
    ap.add_argument("--samples", type=int, default=1)
    ap.add_argument("--seed0", type=int, default=0)
    ap.add_argument("--col-timeout", type=int, default=60)
    ap.add_argument("--km-timeout", type=int, default=600)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--affine", default=None,
                    help="generators m:b,... of y -> m*y+b (replaces translation + --mult; R1b); "
                         "transport then uses the least g in the generated group with g(0)=x")
    a = ap.parse_args()
    v = a.v
    ncol = chi_index(v - 1)
    anchor = v // 2 if a.anchor is None else a.anchor
    if os.path.exists(a.out) and os.listdir(a.out):
        sys.exit(f"refusing to write into non-empty {a.out}: every run gets a fresh directory (no overwrite)")
    os.makedirs(a.out, exist_ok=True)
    mults = [int(m) for m in a.mult.split(",") if m]
    rmults = mults if a.res_mult is None else [int(m) for m in a.res_mult.split(",") if m]
    if a.affine:
        aff = [tuple(int(z) for z in s.split(":")) for s in a.affine.split(",")]
        gens = [tuple((m * y + b) % v for y in range(v)) for m, b in aff]
    else:
        gens = [shift_perm(1, v)] + [mult_perm(m, v) for m in mults]
    R = closure([mult_perm(m, v) for m in rmults], v) if rmults else [tuple(range(v))]
    assert all(g[0] == 0 and g[anchor] == anchor for g in R), "R must fix 0 and the anchor"
    G = closure(gens, v)
    assert set(R) <= set(G), "R must lie in the SQS group"
    Gtr = G if a.affine else sorted(shift_perm(b, v) for b in range(v))
    t0 = time.time()
    M = SQSKM(v, gens)
    summ = {"v": v, "ncol": ncol, "mult": mults, "res_mult": rmults, "R_order": len(R), "anchor": anchor,
            "km": M.summary(), "args": vars(a), "samples": []}
    print(json.dumps({"km": summ["km"], "R_order": len(R), "ncol": ncol}), flush=True)
    cnf, rv = M.cnf()
    pts = list(range(1, v))
    jobs = []
    for i in range(a.samples):
        p = os.path.join(a.out, f"km_{i}.cnf")
        sha = cnf.write(p)
        st, model, dt = kissat(p, a.km_timeout, seed=a.seed0 + i)
        rec = {"sample": i, "km_seed": a.seed0 + i, "km_cnf_sha256": sha, "km_status": st, "km_seconds": round(dt, 3)}
        summ["samples"].append(rec)
        if st != "SAT":
            print(json.dumps(rec), flush=True)
            break
        sel = [j for j, x in enumerate(rv) if x in model]
        rec["rows"] = sel
        cnf.add([-rv[j] for j in sel])
        blocks = M.blocks_of(sel)
        der = derived(blocks, 0)
        deg = sum(1 for t in der if anchor in t)
        rp = os.path.join(a.out, f"col_{i}.cnf")
        if len(R) > 1:
            rc, orbits, choice, cosets, stb, osz = ppcsym.anchored(der, pts, R, anchor, ncol - deg)
            rec["class_orbit_sizes"] = osz
            rec["triple_orbits"] = len(orbits)
            dec = ("sym", orbits, choice, cosets, stb)
        else:
            rc, tv = colouring_cnf(der, pts, ncol, anchor)
            dec = ("plain", tv)
        rec["col_cnf_sha256"] = rc.write(rp)
        rec["col_vars"] = rc.nv
        rec["col_clauses"] = len(rc.clauses)
        jobs.append((i, rp, der, blocks, dec))
    json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)

    def run(job):
        st, model, dt = kissat(job[1], a.col_timeout, seed=1, log=job[1] + ".log")
        return job, st, model, dt

    found = []
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        for job, st, model, dt in ex.map(run, jobs):
            i, rp, der, blocks, dec = job
            rec = summ["samples"][i]
            rec["col_status"] = st
            rec["col_seconds"] = round(dt, 3)
            if st == "SAT":
                if dec[0] == "sym":
                    classes = ppcsym.decode(model, dec[1], dec[2], dec[3], dec[4], R)
                else:
                    classes = decode_colouring(model, der, dec[1], ncol)
                verify_colouring(der, pts, classes, ncol)
                rec["class_sizes_at_0"] = [len(C) for C in classes]
                col = transport(Gtr, {0: classes}, v)
                cert = os.path.join(a.out, f"mcdsqs{v}_sample{i}.txt")
                grp = f"G=<{a.affine}> (y->m*y+b), |G|={len(G)}" if a.affine else f"Z{v} x| <{mults}>"
                rec["certificate_sha256"] = write_certificate(
                    cert, v, ncol, blocks, col,
                    f"mcDSQS({v}) candidate: {grp}, R=<{rmults}>, anchor {anchor}, sample {i}")
                chk = subprocess.run([sys.executable, os.path.join(HERE, "check_mcdsqs.py"), cert],
                                     capture_output=True, text=True)
                rec["checker"] = json.loads(chk.stdout)["result"]
                found.append(i)
            # failed / unknown colouring CNFs are retained (no cleanup)
            print(json.dumps({k: rec[k] for k in rec if k != "rows"}), flush=True)
            json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)
    summ["found"] = found
    summ["total_seconds"] = round(time.time() - t0, 2)
    json.dump(summ, open(os.path.join(a.out, "summary.json"), "w"), indent=1)
    print("FOUND", found, "total_seconds", summ["total_seconds"], flush=True)


if __name__ == "__main__":
    main()
