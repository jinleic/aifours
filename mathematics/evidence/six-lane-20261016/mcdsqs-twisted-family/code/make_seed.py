#!/usr/bin/env python3
"""Extract the compact seed (header, affine group generators, the classes at point 0 in file
order) from an MCDSQS certificate built over an affine point-transitive group.
Usage: make_seed.py CERT GENS RES_GEN OUT.json   (GENS like 1:2,3:1; RES_GEN recorded only)"""
import json
import sys

cert, gens, rgen, out = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
header = None
v = r = None
classes = []
cur = None
for raw in open(cert):
    line = raw.rstrip("\n")
    if header is None and line.startswith("#"):
        header = line
    s = line.split("#")[0].strip()
    if not s:
        continue
    t = s.split()
    if t[0] == "MCDSQS":
        v = int(t[1]); continue
    if t[0] == "COLOURS":
        r = int(t[1]); continue
    if t[0] == "POINT":
        if cur is not None:
            break
        cur = int(t[1]); assert cur == 0; continue
    if t[0] == "CLASS" and cur == 0:
        classes.append([]); continue
    if cur == 0:
        classes[-1].append([int(x) for x in t])
seed = {"v": v, "colours": r, "certificate_header": header,
        "group_generators": gens.split(","), "colouring_multiplier_generator": rgen,
        "classes_at_0": classes,
        "rule": "G = group generated by y -> m*y+b (m:b in group_generators), elements as image tuples, "
                "sorted; blocks = sorted set of g({0} ∪ t) over g in G, t in classes_at_0; colouring at x "
                "= g_x(classes_at_0), g_x the least g in G with g(0) = x (class order kept, triples sorted)"}
json.dump(seed, open(out, "w"))
print("classes", len(classes), "triples", sum(len(C) for C in classes))
