"""Core permutation-group and orbit utilities for the LKTS(57) lane.

Standard library + numpy only.  Points are 0..n-1.  A permutation is a tuple
(or numpy array) p with p[x] = image of x.  Composition convention:
compose(p, q)[x] = p[q[x]]  (apply q first, then p).
"""
from __future__ import annotations

import itertools
from collections import deque

import numpy as np


def compose(p, q):
    return tuple(p[x] for x in q)


def inverse(p):
    inv = [0] * len(p)
    for i, x in enumerate(p):
        inv[x] = i
    return tuple(inv)


def identity(n):
    return tuple(range(n))


def perm_order(p):
    n = len(p)
    seen = [False] * n
    o = 1
    from math import gcd
    for s in range(n):
        if not seen[s]:
            L = 0
            x = s
            while not seen[x]:
                seen[x] = True
                x = p[x]
                L += 1
            o = o * L // gcd(o, L)
    return o


def fixed_points(p):
    return [x for x, y in enumerate(p) if x == y]


def closure(gens, n, limit=10**6):
    """All elements of the group generated by gens (BFS on right mult)."""
    e = identity(n)
    seen = {e}
    q = deque([e])
    gens = [tuple(g) for g in gens]
    while q:
        a = q.popleft()
        for g in gens:
            b = compose(g, a)
            if b not in seen:
                seen.add(b)
                if len(seen) > limit:
                    raise RuntimeError("group too large")
                q.append(b)
    return sorted(seen)


def subgroup(gens, n):
    return closure(gens, n)


# ---------------------------------------------------------------- triples
def triple_index_tables(n):
    """Return (triples array T[k]=(a,b,c) a<b<c, id lookup dict as 3D array)."""
    trip = np.array(list(itertools.combinations(range(n), 3)), dtype=np.int32)
    tid = -np.ones((n, n, n), dtype=np.int32)
    for k, (a, b, c) in enumerate(trip):
        for x, y, z in itertools.permutations((a, b, c)):
            tid[x, y, z] = k
    return trip, tid


def pair_index_tables(n):
    pairs = np.array(list(itertools.combinations(range(n), 2)), dtype=np.int32)
    pid = -np.ones((n, n), dtype=np.int32)
    for k, (a, b) in enumerate(pairs):
        pid[a, b] = k
        pid[b, a] = k
    return pairs, pid


def triple_images(G, trip, tid):
    """img[g, k] = id of image of triple k under element g."""
    Garr = np.array(G, dtype=np.int32)
    a, b, c = trip[:, 0], trip[:, 1], trip[:, 2]
    img = tid[Garr[:, a], Garr[:, b], Garr[:, c]]
    return img


def pair_images(G, pairs, pid):
    Garr = np.array(G, dtype=np.int32)
    return pid[Garr[:, pairs[:, 0]], Garr[:, pairs[:, 1]]]


def orbits_from_images(img):
    """img: (|G|, m) array. Return orbit label per item (label = min item)."""
    rep = img.min(axis=0)
    # rep[k] = min over g of g(k) is the orbit minimum since G is a group
    return rep


def orbit_lists(rep):
    orbits = {}
    for k, r in enumerate(rep.tolist()):
        orbits.setdefault(r, []).append(k)
    return orbits
