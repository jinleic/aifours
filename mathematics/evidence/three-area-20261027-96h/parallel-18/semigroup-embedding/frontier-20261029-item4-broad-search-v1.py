"""Item4 evidence search with a self-checking host certificate for each source.

For each family (band B with involutive automorphism a, C2-labelled CS actor D=M[C2;I,L;P]), the
script samples 2-generated subsemigroups S of the physical product P(B,D) and keeps those that are
regular, have a pure actor, are RRL (every local idempotent band right regular), and contain distinct
same-fibre R-related idempotents.  For each kept S it builds a band H as follows: take a 4-generated
right-seminormal band F (built from (I)/(D) normal forms on 4 letters), and quotient it by the
C2-invariant congruence generated by all source-host equations.  It then VERIFIES directly on the
quotient table:
- associativity, idempotence and the right-seminormal identity xyxzxy=xzxy;
- that the letter swap induces an involutive automorphism;
- every equation beta(st)=beta(s)*alpha^{w(s,t)}(beta(t));
- separation of every same-fibre R-pair.
Correctness of the reported hosts therefore does not depend on F being free.  If H collapsed a pair,
that would be inconclusive unless F were free; the script reports such cases as COLLAPSE.
All arithmetic is exact integer table work."""
import json,random,sys,time
from itertools import product
def red(w):
    n=len(w)
    for k in range(n-1):
        if w[k]==w[k+1]:return w[:k+1]+w[k+2:]
    for k in range(1,n-1):
        B=set(w[k+1:])
        if w[k-1] in B and w[k] in B:return w[:k]+w[k+1:]
    return None
def nf(w):
    while True:
        u=red(w)
        if u is None:return w
        w=u
def base_band():
    els={};todo=[(l,) for l in range(4)]
    for t in todo:els.setdefault(t,len(els))
    i=0
    while i<len(todo):
        x=todo[i];i+=1
        for l in range(4):
            y=nf(x+(l,))
            if y not in els:els[y]=len(els);todo.append(y)
    words=todo;n=len(words)
    tab=[[els[nf(words[x]+words[y])] for y in range(n)] for x in range(n)]
    aut=[els[nf(tuple((1,0,3,2)[l] for l in w))] for w in words]
    return tab,aut,n
FT,FA,FN=base_band()
def certify(M,act,gens,P):
    N=len(M)
    rep={gens[0]:(0,),gens[1]:(1,)};todo=[gens[0],gens[1]];i=0
    while i<len(todo):
        x=todo[i];i+=1
        for k in (0,1):
            y=M[x][gens[k]]
            if y not in rep:rep[y]=rep[x]+(k,);todo.append(y)
    if len(rep)<N:return None
    def beta(s):
        w=rep[s];v=0;prev=None;x=None
        for k in w:
            g=gens[k]
            if prev is not None:v^=act[prev][1]^P[act[prev][2]][act[g][0]]
            l=2*k+v;x=l if x is None else FT[x][l];prev=g
        return x
    bet=[beta(s) for s in range(N)]
    par=list(range(FN))
    def find(a):
        while par[a]!=a:par[a]=par[par[a]];a=par[a]
        return a
    def uni(a,b):
        a,b=find(a),find(b)
        if a!=b:par[a]=b
    for s in range(N):
        for t in range(N):
            w=act[s][1]^P[act[s][2]][act[t][0]]
            bt=FA[bet[t]] if w else bet[t]
            uni(bet[M[s][t]],FT[bet[s]][bt]);uni(FA[bet[M[s][t]]],FA[FT[bet[s]][bt]])
    changed=True
    while changed:
        changed=False;cl={}
        for x in range(FN):cl.setdefault(find(x),[]).append(x)
        for mem in cl.values():
            x0=mem[0]
            for x in mem[1:]:
                for l in range(4):
                    for a,b in ((FT[x0][l],FT[x][l]),(FT[l][x0],FT[l][x])):
                        a,b=find(a),find(b)
                        if a!=b:par[a]=b;changed=True
                a,b=find(FA[x0]),find(FA[x])
                if a!=b:par[a]=b;changed=True
    roots=sorted({find(x) for x in range(FN)});ix={r:k for k,r in enumerate(roots)};n=len(roots)
    rep_el={}
    for x in range(FN):rep_el.setdefault(ix[find(x)],x)
    H=[[ix[find(FT[rep_el[a]][rep_el[b]])] for b in range(n)] for a in range(n)]
    al=[ix[find(FA[rep_el[a]])] for a in range(n)]
    R=range(n)
    assert all(H[x][x]==x for x in R)
    assert all(H[H[x][y]][z]==H[x][H[y][z]] for x in R for y in R for z in R)
    assert all(H[H[H[H[H[x][y]][x]][z]][x]][y]==H[H[H[x][z]][x]][y] for x in R for y in R for z in R)
    assert all(al[al[x]]==x for x in R) and all(al[H[x][y]]==H[al[x]][al[y]] for x in R for y in R)
    hb=[ix[find(b)] for b in bet]
    for s in range(N):
        for t in range(N):
            w=act[s][1]^P[act[s][2]][act[t][0]]
            assert hb[M[s][t]]==H[hb[s]][al[hb[t]] if w else hb[t]]
    E=[x for x in range(N) if M[x][x]==x]
    Rp=[(e,f) for e in E for f in E if e<f and act[e]==act[f] and M[e][f]==f and M[f][e]==e]
    coll=[(e,f) for e,f in Rp if hb[e]==hb[f]]
    return n,len(Rp),coll
def adjoin1(T):
    n=len(T);return [[y if x==n else (x if y==n else T[x][y]) for y in range(n+1)] for x in range(n+1)]
B5=[[0,2,2,4,4],[0,1,2,1,4],[0,2,2,2,4],[0,3,2,3,4],[0,4,2,4,4]];SW5=[0,3,4,1,2]
RB22=[[2*(x//2)+(y%2) for y in range(4)] for x in range(4)]
FAMS={'B5 sw':(B5,SW5),'B5^1 sw':(adjoin1(B5),SW5+[5]),'RB22^1 rowswap':(adjoin1(RB22),[2,3,0,1,4]),
 'RB22^1 bothswap':(adjoin1(RB22),[3,2,1,0,4]),'RB22^1 colswap':(adjoin1(RB22),[1,0,3,2,4])}
ACTORS={'D8':((0,0),(0,1)),'P3a':((0,0,0),(0,1,0),(0,0,1)),'P3b':((0,0,0),(0,1,1),(0,1,0)),'P23':((0,0,0),(0,1,1))}
def localbands_RRB(M):
    N=len(M);E=[x for x in range(N) if M[x][x]==x]
    for e in E:
        L=[f for f in E if M[e][f]==f and M[f][e]==f]
        for x in L:
            for y in L:
                if M[M[x][y]][x]!=M[y][x]:return False
    return True
def run(seed,per):
    random.seed(seed);out=[];t0=time.time()
    for an,P in ACTORS.items():
        ni,nl=len(P[0]),len(P)
        for bn,(T,a) in FAMS.items():
            els=[(b,(i,g,l)) for b in range(len(T)) for i in range(ni) for g in range(2) for l in range(nl)]
            ixe={x:k for k,x in enumerate(els)}
            def mul(x,y):
                b,(i,g,l)=x;c,(j,h,m)=y;w=g^P[l][j]
                return ixe[(T[b][a[c] if w else c],(i,w^h,m))]
            tab=[[mul(x,y) for y in els] for x in els]
            seen=set();kept=0;coll=0;tried=0;sizes=[];bands=[]
            while tried<4000 and kept<per:
                tried+=1;g=random.sample(range(len(els)),2)
                S=set(g);todo=list(g)
                while todo:
                    x=todo.pop()
                    for y in list(S):
                        for z in (tab[x][y],tab[y][x]):
                            if z not in S:S.add(z);todo.append(z)
                S=sorted(S)
                if len(S)>150 or tuple(S) in seen:continue
                seen.add(tuple(S));pos={s:k for k,s in enumerate(S)}
                M=[[pos[tab[x][y]] for y in S] for x in S];act=[els[s][1] for s in S];N=len(M)
                if not all(any(M[M[x][y]][x]==x for y in range(N)) for x in range(N)):continue
                if not all((M[x][x]==x)==(act[x][1]==P[act[x][2]][act[x][0]]) for x in range(N)):continue
                if not localbands_RRB(M):continue
                r=certify(M,act,[pos[x] for x in g],P)
                if r is None or r[1]==0:continue
                kept+=1;sizes.append(N);bands.append(r[0])
                if r[2]:coll+=1;print('COLLAPSE',an,bn,N,r[2])
            out.append({'actor':an,'band':bn,'tried':tried,'certified_sources':kept,'collapses':coll,
                        'source_sizes':[min(sizes),max(sizes)] if sizes else None,'host_band_sizes':[min(bands),max(bands)] if bands else None})
            print(an,bn,'tried',tried,'certified',kept,'collapses',coll,'t',round(time.time()-t0,1),flush=True)
    return out
