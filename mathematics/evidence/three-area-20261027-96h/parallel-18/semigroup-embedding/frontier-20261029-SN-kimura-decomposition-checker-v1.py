"""Exact finite controls for the seminormal Kimura-type decomposition (the universal statement is the
written proof in the companion packet).  Builds the free band F3 (Green-Rees normal forms), checks it
is SN (it is the 3-generated free SN band), computes the least LEFTSN congruence lambda and least
RIGHTSN congruence rho from the local identities, and checks lambda <= R, rho <= L, lambda ∩ rho = Δ,
lambda = congruence generated by local R-pairs, and the same properties on ALL principal quotients."""
from itertools import product
import sys
def fb_key(w):
 c=frozenset(w)
 if len(c)==1:return w[0]
 seen=set();i=0
 while True:
  seen.add(w[i])
  if len(seen)==len(c):break
  i+=1
 seen=set();j=len(w)-1
 while True:
  seen.add(w[j])
  if len(seen)==len(c):break
  j-=1
 return (c,fb_key(w[:i]),w[i],w[j],fb_key(w[j+1:]))
def fb_rep(k):
 if isinstance(k,str):return k
 c,k0,a,b,k1=k;return fb_rep(k0)+a+b+fb_rep(k1)
order=[fb_key(g) for g in 'abc'];seen=set(order);changed=True
while changed:
 changed=False
 for x in list(order):
  for y in list(order):
   k=fb_key(fb_rep(x)+fb_rep(y))
   if k not in seen:seen.add(k);order.append(k);changed=True
ix={k:i for i,k in enumerate(order)};N=len(order);R=range(N)
T=[[ix[fb_key(fb_rep(x)+fb_rep(y))] for y in order] for x in order]
assert N==159 and all(T[x][x]==x for x in R)
assert all(T[T[x][y]][z]==T[x][T[y][z]] for x,y,z in product(R,repeat=3))
def mm(*xs):
 r=xs[0]
 for x in xs[1:]:r=T[r][x]
 return r
# SN via the equivalent local-regular form at every e (exeye ze form needs 4 variables; use exact
# local check: every local monoid eF3e satisfies x y x z x = x y z x).
for e in R:
 loc=sorted({mm(e,x,e) for x in R})
 assert all(mm(x,y,x,z,x)==mm(x,y,z,x) for x,y,z in product(loc,repeat=3))
def cong(base,pairs):
 par=list(range(N))
 def root(x):
  while par[x]!=x:par[x]=par[par[x]];x=par[x]
  return x
 todo=list(pairs)+[(x,base[x]) for x in R if base[x]!=x]
 while todo:
  a,b=todo.pop();ra,rb=root(a),root(b)
  if ra==rb:continue
  par[rb]=ra
  for z in R:todo.append((T[a][z],T[b][z]));todo.append((T[z][a],T[z][b]))
 return [root(x) for x in R]
ident=list(R)
lam=cong(ident,[(mm(e,x,e,y,e,x,e),mm(e,x,e,y,e)) for e,x,y in product(R,repeat=3)])
rho=cong(ident,[(mm(e,x,e,y,e,x,e),mm(e,y,e,x,e)) for e,x,y in product(R,repeat=3)])
Rr=lambda x,y:T[x][y]==y and T[y][x]==x
Lr=lambda x,y:T[x][y]==x and T[y][x]==y
assert all(Rr(x,y) for x,y in product(R,repeat=2) if lam[x]==lam[y])
assert all(Lr(x,y) for x,y in product(R,repeat=2) if rho[x]==rho[y])
