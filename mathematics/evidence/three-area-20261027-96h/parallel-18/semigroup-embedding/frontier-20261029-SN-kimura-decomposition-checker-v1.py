locR=[(x,y) for e,x,y in product(R,repeat=3) if mm(e,x,e)==x and mm(e,y,e)==y and x!=y and Rr(x,y)]
lam2=cong(ident,locR)
assert all((lam[x]==lam[y])==(lam2[x]==lam2[y]) for x,y in product(R,repeat=2))
print('PASS F3: 159 elements, SN, |F3/lam|=%d |F3/rho|=%d, lam<=R, rho<=L, lam∩rho=Δ, lam=<local R-pairs>'%(len(set(lam)),len(set(rho))))
fails=0
for a in R:
 for b in range(a+1,N):
  th=cong(ident,[(a,b)]);L=cong(lam,[(a,b)]);Rh=cong(rho,[(a,b)])
  if any(L[x]==L[y] and Rh[x]==Rh[y] and th[x]!=th[y] for x in R for y in range(x+1,N)):fails+=1
assert fails==0
