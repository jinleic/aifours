#!/usr/bin/env python3
"""Actual L6 primitive maps on every both-small pair in {1,2,3,4}^2.

The ideal generated by TWO seed modules is the SUM of their full one-seed
ideals, with overlaps retained and reduced, not assumed disjoint. The existing
one-seed ideal coefficient spaces do not depend on the absent opposite seed.
Rebuild their full sum in both source and target, check ALL source-ideal
basis derivatives at the actual pair, and compute the full actual primitive
quotient map. This is finite exact linear algebra, not a rank extrapolation.
Independent replay must regenerate the BOTH-seed ideal from literal PBW and
adjoint words rather than accept component records as correctness premises.
"""
import argparse
import hashlib
import importlib.util
import json
from fractions import Fraction as Q
from functools import lru_cache
from pathlib import Path

ROOT=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('original_coordinate_actions',ROOT/'frontier-20261028-level6-coordinate-row-quotient.py')
original=importlib.util.module_from_spec(spec)
spec.loader.exec_module(original)
levi=original.levi
lift=original.lift
flint=original.flint
CATALOG=original.CATALOG


def encode(v):
    return {w:str(c) for w,c in sorted(v.items()) if c}


def decode(rows):
    return [{w:Q(c) for w,c in row.items() if Q(c)} for row in rows]


def word_ideals_to_coordinates(rows):
    result=[]
    for row in rows:
        vector={tuple(map(int,w)):Q(c) for w,c in row.items() if Q(c)}
        co=original.ideals.decompose(vector)
        result.append({''.join(map(str,w)):c for w,c in co.items()})
    return result


def publish(path,record):
    with path.open('x') as stream:
        json.dump(record,stream,indent=2)
        stream.write('\n')
    return {'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}


def load_components(manifest):
    components={}
    for item in manifest['components']:
        key=(item['fixed_parameter'],item['fixed_value'])
        entries={}
        for pin in item['families']:
            raw=(ROOT/pin['file']).read_bytes()
            assert hashlib.sha256(raw).hexdigest()==pin['sha256']
            C=json.loads(raw)
            if 'parts' in C:
                records=[]
                for p in C['parts']:
                    body=(ROOT/p['file']).read_bytes()
                    assert hashlib.sha256(body).hexdigest()==p['sha256']
                    records.append(json.loads(body))
            else:
                records=C['records']
            for e in records:
                ab=tuple(e['degree'][:2])
                assert ab not in entries
                if 'source_ideal_lyndon_coordinate_rows' in e:
                    source=decode(e['source_ideal_lyndon_coordinate_rows'])
                    target=decode(e['target_ideal_lyndon_coordinate_rows'])
                else:
                    source=word_ideals_to_coordinates(e['source_ideal_rows'])
                    target=word_ideals_to_coordinates(e['target_ideal_rows'])
                assert len(source)==e['full_source_ideal_dimension'] and len(target)==e['full_target_ideal_dimension']
                entries[ab]=(source,target)
        assert set(entries)==set(CATALOG)
        components[key]=entries
    assert set(components)=={(side,value) for side in ('r','s') for value in (1,2,3,4)}
    return components


def full_sum(left,right):
    generators=list(left)+list(right)
    labels=sorted({w for v in generators for w in v})
    space=lift.Span()
    if not labels:
        return space
    M=flint.fmpq_mat([[flint.fmpq(v[w].numerator,v[w].denominator) if w in v else 0 for w in labels] for v in generators])
    R,rank=M.rref(inplace=True)
    for i in range(rank):
        row={w:Q(int(R[i,j].numerator),int(R[i,j].denominator)) for j,w in enumerate(labels) if R[i,j]}
        assert row and row[min(row)]==1 and min(row) not in space.rows
        space.rows[min(row)]=row
    assert len(space)==rank
    for row in generators:
        assert not space.reduce(row), 'input ideal component escaped the full sum'
    return space


@lru_cache(None)
def original_action(word,g,r,s):
    tuple_word=tuple(map(int,word))
    out=original.operator_word(tuple_word,g,r,s)
    return {''.join(map(str,w)):c for w,c in out.items()}


def image(v,g,r,s):
    out={}
    for word,c in v.items():
        for w,b in original_action(word,g,r,s).items():
            out[w]=out.get(w,Q(0))+c*b
            if not out[w]:
                del out[w]
    return out


def combine(vectors,co):
    out={}
    for i,c in co.items():
        for w,b in vectors[int(i)].items():
            out[w]=out.get(w,Q(0))+Q(c)*b
            if not out[w]:
                del out[w]
    return out


def free_data(pins,r,s):
    data={}
    for pin in pins:
        raw=(ROOT/pin['file']).read_bytes()
        assert hashlib.sha256(raw).hexdigest()==pin['sha256']
        P=json.loads(raw)
        a,b,n=P['degree']
        assert n==6
        words=P['source_words']
        assert len(words)==len(set(words))==original.weight_dimension(a,b)
        assert words==sorted(words)
        for word in words:
            w=tuple(map(int,word))
            assert lift.is_lyndon(w) and levi.degree(w)==(a,b,6)
        vectors=[{words[int(i)]:Q(c) for i,c in co.items() if Q(c)} for co in P['horizontal_kernel_coefficients']]
        independent=lift.Span()
        for v in vectors:
            assert independent.add(v) is not None
            assert not image(v,'f1',r,s) and not image(v,'f2',r,s)
        assert len(vectors)==original.lowest_multiplicity(a,b)
        data[a,b]=(vectors,pin)
    assert set(data)==set(CATALOG)
    return data


def run_case(r,s,ab,components,free):
    a,b=ab
    source_left,target_left=components['r',r][ab]
    source_right,target_right=components['s',s][ab]
    I=full_sum(source_left,source_right)
    T=full_sum(target_left,target_right)
    vectors,pin=free[ab]
    quotient=lift.Span()
    for row in I.rows.values():
        quotient.add(row)
    chosen=[]
    retained=[]
    for j,v in enumerate(vectors):
        if quotient.add(v) is not None:
            chosen.append(v)
            retained.append(j)
    for row in I.rows.values():
        assert not T.reduce(image(row,'f3',r,s)), 'actual BOTH-seed source ideal does not descend'
    columns=[T.reduce(image(v,'f3',r,s)) for v in chosen]
    rank=lift.Span()
    for v in columns:
        rank.add(v)
    k=len(chosen)
    result={'degree':[a,b,6],'r':r,'s':s,'coordinate_basis':'standard monic Lyndon bracket coordinates, not tensor-word coefficients',
            'free_pencil':pin,'free_primitive_dimension':len(vectors),'full_source_ideal_dimension':len(I),'full_target_ideal_dimension':len(T),
            'source_component_dimensions':[len(source_left),len(source_right)],'target_component_dimensions':[len(target_left),len(target_right)],
            'source_ideal_lyndon_coordinate_rows':[encode(v) for v in I.rows.values()],
            'target_ideal_lyndon_coordinate_rows':[encode(v) for v in T.rows.values()],
            'retained_free_primitive_indices':retained,'actual_primitive_quotient_dimension':k,'actual_D3_rank':len(rank),
            'all_source_ideal_basis_derivatives_checked_at_actual_pair':True,
            'source_quotient_completeness':'full free primitive basis and finite-sl3 complete reducibility; no component disjointness assumed'}
    if not k:
        result['status']='ZERO_ACTUAL_PRIMITIVE_SOURCE'
    elif len(rank)==k:
        selected=sorted(rank.rows)
        matrix=[[v.get(w,Q(0)) for v in columns] for w in selected]
        determinant=flint.fmpq_mat([[flint.fmpq(c.numerator,c.denominator) for c in row] for row in matrix]).det()
        assert determinant
        result.update({'selected_target_lyndon_coordinates':selected,'matrix':[[str(c) for c in row] for row in matrix],
                       'exact_nonzero_determinant':str(determinant),'status':'FULL_ACTUAL_BOTH_SEED_PRIMITIVE_RANK'})
    else:
        kernels=lift.kernel_with_coefficients(columns)
        witnesses=[]
        for co in kernels:
            v=combine(chosen,co)
            assert v and I.reduce(v) and not T.reduce(image(v,'f3',r,s))
            assert not image(v,'f1',r,s) and not image(v,'f2',r,s)
            witnesses.append({'retained_source_coefficients':{str(i):str(c) for i,c in co.items()},'nonzero_quotient_representative_lyndon_coordinates':encode(v)})
        result.update({'status':'EXACT_ACTUAL_PRIMITIVE_KERNEL_CANDIDATES','kernel_candidates':witnesses})
    return result


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--r',type=int,choices=[1,2,3,4],required=True)
    ap.add_argument('--s-values',type=int,nargs='+',default=[1,2,3,4])
    ap.add_argument('--component-sha256',required=True)
    args=ap.parse_args()
    assert args.s_values and len(args.s_values)==len(set(args.s_values)) and all(s in (1,2,3,4) for s in args.s_values)
    raw=(ROOT/'frontier-20261028-level6-both-small-component-inputs-v1.json').read_bytes()
    assert hashlib.sha256(raw).hexdigest()==args.component_sha256
    manifest=json.loads(raw)
    components=load_components(manifest)
    free=free_data(manifest['free_pencils'],args.r,args.s_values[0])
    aggregate=[]
    for s in args.s_values:
        parts=[]
        statuses=[]
        for ab in CATALOG:
            path=ROOT/f'frontier-20261028-level6-r{args.r}s{s}-corner-part-{ab[0]}{ab[1]}-v1.json'
            if path.exists():
                raise FileExistsError(path)
            e=run_case(args.r,s,ab,components,free)
            parts.append(publish(path,e))
            statuses.append(e['status'])
            print('ACTUAL BOTH-SEED CORNER',args.r,s,ab,'I',e['full_source_ideal_dimension'],'T',e['full_target_ideal_dimension'],
                  'P',e['actual_primitive_quotient_dimension'],'rank',e['actual_D3_rank'],e['status'],flush=True)
        output=ROOT/f'frontier-20261028-level6-r{args.r}s{s}-corner-family-v1.json'
        record={'owner':'MathKacMoody-2','r':args.r,'s':s,'component_manifest_sha256':args.component_sha256,'types':[list(ab) for ab in CATALOG],
                'parts':parts,'free_horizontal_membership_completeness_checked_once_parameter_independent':True,
                'status':'ALL_FIFTEEN_ACTUAL_BOTH_SEED_TYPES_FULL_RANK' if all(status in ('ZERO_ACTUAL_PRIMITIVE_SOURCE','FULL_ACTUAL_BOTH_SEED_PRIMITIVE_RANK') for status in statuses) else 'EXACT_KERNEL_CANDIDATES_RECORDED',
                'limits':'named actual free-Levi/PBW and finite-sl3 completeness inputs; whole both-seed ideal and operator replay pending. Not formal/kernel, parent, independent-model or novelty acceptance.'}
        aggregate.append(publish(output,record))
        print('WROTE',output.name,flush=True)
    print('DONE both-small r',args.r,'pairs',len(aggregate),flush=True)


if __name__=='__main__':
    main()
