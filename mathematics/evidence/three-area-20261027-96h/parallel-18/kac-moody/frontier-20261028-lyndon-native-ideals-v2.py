#!/usr/bin/env python3
"""Full one-seed Serre ideals v2, retaining and checking faithful Lyndon coordinates.

Representation change only: the bounded initial Levi seed module Q is generated
with the existing exact module engine. For n>m, the ideal generated by an
l-stable Q subset L_m(V) has I_n=[V,I_(n-1)]: nested V brackets generate its
free-Lie ideal (Jacobi), and these spaces are already l-stable since V and Q
are l-modules. Hence no repeated higher-level Levi-closure queue is needed.
All generator degree coordinates are nonnegative, so componentwise truncation
cannot lose a path into the requested bound.

Each finite span is reduced over Q in the MONIC LYNDON coordinate basis with
FLINT, then expanded back to ordinary word coefficients. Returned rows have
exact unit leading words, so their quotient projection uses the same elementary
triangular semantics as the older tensor-word Span. No solver, approximation,
source omission, or replacement of an actual quotient by a free source.

This helper is restricted to at most one active node3 seed through the bound,
as in fixed-r/s>=6 row families. Both-seed corners need their own construction.
"""
import argparse
import hashlib
import importlib.util
import json
import sys
from fractions import Fraction as Q
from pathlib import Path

ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'frontier-20261028-fastalgebra'))
import flint

sp=importlib.util.spec_from_file_location('word_engine',ROOT/'frontier-20261028-levi-lie-engine.py')
levi=importlib.util.module_from_spec(sp)
sp.loader.exec_module(levi)
lift=levi.lift
BRACKETS={}
LAST_TRACE=[]


def standard(word):
    if word not in BRACKETS:
        BRACKETS[word]=lift.lyndon_bracket(word)
    return BRACKETS[word]


def decompose(vector):
    rem={w:Q(c) for w,c in vector.items() if c}
    coords={}
    while rem:
        word=min(rem)
        assert lift.is_lyndon(word), 'non-Lie leading word'
        c=rem[word]
        coords[word]=coords.get(word,Q(0))+c
        for w,b in standard(word).items():
            rem[w]=rem.get(w,Q(0))-c*b
            if not rem[w]:
                del rem[w]
    return {w:c for w,c in coords.items() if c}


def expand(coords):
    result={}
    for word,c in coords.items():
        for w,b in standard(word).items():
            result[w]=result.get(w,Q(0))+c*b
    return {w:c for w,c in result.items() if c}


class WordSpace:
    def __init__(self,rows=(),coordinate_rows=None):
        self.rows={}
        self.coordinate_rows={}
        for index,row in enumerate(rows):
            assert row
            pivot=min(row)
            assert row[pivot]==1 and pivot not in self.rows
            self.rows[pivot]=row
            coordinates=coordinate_rows[index] if coordinate_rows is not None else decompose(row)
            assert min(coordinates)==pivot and coordinates[pivot]==1
            self.coordinate_rows[pivot]=coordinates

    def coordinate_reduce(self,vector):
        result=dict(vector)
        for pivot,row in sorted(self.coordinate_rows.items()):
            c=result.get(pivot,Q(0))
            if c:
                for w,b in row.items():
                    result[w]=result.get(w,Q(0))-c*b
                    if not result[w]:
                        del result[w]
        return result

    def __len__(self):
        return len(self.rows)

    def reduce(self,vector):
        result=dict(vector)
        for pivot,row in sorted(self.rows.items()):
            c=result.get(pivot,Q(0))
            if c:
                for w,b in row.items():
                    result[w]=result.get(w,Q(0))-c*b
                    if not result[w]:
                        del result[w]
        return result


def batch_space(vectors,degree):
    if not vectors:
        return WordSpace()
    coordinates=[decompose(v) for v in vectors]
    words=sorted({w for c in coordinates for w in c})
    if not words:
        return WordSpace()
    index={w:j for j,w in enumerate(words)}
    M=flint.fmpq_mat(len(coordinates),len(words))
    for i,co in enumerate(coordinates):
        for w,c in co.items():
            M[i,index[w]]=flint.fmpq(c.numerator,c.denominator)
    R,rank=M.rref(inplace=True)
    rows=[]
    coordinate_rows=[]
    for i in range(rank):
        co={}
        for j,w in enumerate(words):
            c=R[i,j]
            if c:
                co[w]=Q(int(c.numerator),int(c.denominator))
        row=expand(co)
        assert min(row)==min(co) and row[min(row)]==1
        rows.append(row)
        coordinate_rows.append(co)
    area=WordSpace(rows,coordinate_rows)
    # Every decompose() call already checked the exact identity by reducing
    # its original word vector to zero. Expand() defines the output word rows.
    # Therefore this independent triangular test in the faithful monic Lyndon
    # coordinate basis is EQUIVALENT to word containment, without re-expanding
    # dense word rows for every raw generator.
    for co in coordinates:
        assert not area.coordinate_reduce(co), 'generated coordinate vector escaped native span'
    LAST_TRACE.append({'degree':list(degree),'raw_generators':len(vectors),'Lyndon_coordinate_columns':len(words),'rank':rank})
    return area


def ideal_bases(bound,r,s):
    global LAST_TRACE
    LAST_TRACE=[]
    active=[(j,p) for j,p in ((1,r),(2,s)) if p+1<=bound[2] and lift.fits((*levi.WEIGHTS[j],p+1),bound)]
    if not active:
        return {}
    if len(active)!=1:
        raise ValueError('one active node3 seed required')
    j,power=active[0]
    m=power+1
    # This call has no higher-level bracket generation: the seed is already at
    # the bound's top level. It constructs the entire initial Levi module.
    initial=levi.ideal_bases((bound[0],bound[1],m),r,s)
    spaces={d:WordSpace(list(area.rows.values())) for d,area in initial.items() if d[2]==m}
    for n in range(m+1,bound[2]+1):
        generated={}
        for d,area in list(spaces.items()):
            if d[2]!=n-1:
                continue
            for row in area.rows.values():
                for letter,(a,b) in enumerate(levi.WEIGHTS):
                    nd=(d[0]+a,d[1]+b,n)
                    if not lift.fits(nd,bound):
                        continue
                    v=lift.bracket(lift.letter(letter),row)
                    if v:
                        generated.setdefault(nd,[]).append(v)
        for d,vectors in sorted(generated.items()):
            spaces[d]=batch_space(vectors,d)
    return spaces


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--control-fixed',choices=['r','s'],required=True)
    args=ap.parse_args()
    fixed=args.control_fixed
    r,s=(4,6) if fixed=='r' else (6,4)
    filename=f'frontier-20261028-level6-{fixed}4-quotient-family-v1.json'
    raw=(ROOT/filename).read_bytes()
    C=json.loads(raw)
    spaces=ideal_bases((6,6,6),r,s)
    records=[]
    for e in C['records']:
        d=tuple(e['degree'])
        for label,dd in (('source',d),('target',(d[0],d[1],5))):
            rows=[{tuple(map(int,w)):Q(c) for w,c in v.items()} for v in e[f'{label}_ideal_rows']]
            old=lift.Span()
            for row in rows:
                old.add(row)
            native=spaces.get(dd,WordSpace())
            assert len(old)==len(native)==e[f'full_{label}_ideal_dimension']
            for row in old.rows.values():
                assert not native.reduce(row)
            for row in native.rows.values():
                assert not old.reduce(row)
            records.append({'degree':list(dd),'kind':label,'dimension':len(native),'both_directions_checked':True})
    out=ROOT/f'frontier-20261028-lyndon-native-ideal-control-{fixed}4-v2.json'
    with out.open('x') as stream:
        json.dump({'reference':filename,'reference_sha256':hashlib.sha256(raw).hexdigest(),
                   'records':records,'construction':LAST_TRACE,
                   'status':'PASS_ALL_FOURTEEN_FULL_IDEAL_SPACES_MATCH_PRIOR_WORD_CONSTRUCTION',
                   'scope':'exact one-seed ideal representation control; actual source interfaces and scientific acceptance remain separate'},stream,indent=2)
        stream.write('\n')
    print('PASS native Lyndon ideals match all14 source/target controls',fixed,out.name,flush=True)


if __name__=='__main__':
    main()
