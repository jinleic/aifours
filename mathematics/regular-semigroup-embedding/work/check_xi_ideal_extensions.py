"""Search for a counterexample to Problem 1 via the necessary condition 'xi is idempotent pure'.

Lemma 0' (proof.md): if a FINITE semigroup S embeds in B (.) C or B (.)* C (B a band, C completely
simple) then the least completely simple congruence xi of S is idempotent pure.
So a finite weakly E-unitary locally r-orthodox S with xi NOT idempotent pure would refute P1.

Family tested: S = K u {f}, K = M[H; I, L; P] completely simple (normalized P), f an idempotent
acting on K by a linked commuting bitranslation
     f(i,h,l) = (alpha(i), gamma_i h, l),     (i,h,l)f = (i, h delta_l, beta(l)),
with alpha, beta idempotent, gamma = 1 on Im alpha, delta = 1 on Im beta and the linking condition
p_{l alpha(j)} gamma_j = delta_l p_{beta(l) j}.   (Every such S is regular.)
For each random instance: verify S is a semigroup, regular, weakly E-unitary, locally r-orthodox,
record orthodoxy, and compute xi as the congruence generated by (x, x(yx)^omega).

Usage: python3 work/check_xi_ideal_extensions.py [num] [seed]
"""
from __future__ import annotations

import itertools
import random
import sys

from check_two_chain_theorem import GROUPS, group_identity, group_inverse


def omega_power(T, x):
    seen = []
    y = x
    while y not in seen:
        seen.append(y)
        y = T[y][x]
    # idempotent power
    for z in seen:
        if T[z][z] == z:
            return z
    raise AssertionError


def xi_classes(T):
    N = len(T)
    parent = list(range(N))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
            return True
        return False

    queue = []
    for x in range(N):
        for y in range(N):
            z = T[x][omega_power(T, T[y][x])]
            if union(x, z):
                queue.append((x, z))
    while queue:
        a, b = queue.pop()
        for g in range(N):
            for u, v in ((T[g][a], T[g][b]), (T[a][g], T[b][g])):
                if union(u, v):
                    queue.append((u, v))
    return [find(x) for x in range(N)]


def is_weakly_E_unitary(T):
    N = len(T)
    E = [x for x in range(N) if T[x][x] == x]
    Es = set(E)
    for a in range(N):
        if a in Es:
            continue
        for e in E:
            if any(T[g][a] == e for g in E) and any(T[a][g] == e for g in E):
                return False
    return True


def locally_r_orthodox(T):
    N = len(T)
    E = [x for x in range(N) if T[x][x] == x]
    for e in E:
        loc = sorted({T[T[e][x]][e] for x in range(N)})
        Eloc = [x for x in loc if T[x][x] == x]
        S = set(Eloc)
        if not all(T[a][b] in S for a in Eloc for b in Eloc):
            return False
        for a, x, y in itertools.product(Eloc, repeat=3):
            if T[T[T[a][x]][y]][a] != T[T[T[T[a][x]][a]][y]][a]:
                return False
    return True


def build(seed):
    random.seed(seed)
    gname = random.choice(["Z2", "Z3", "S3", "Z4"])
    Gt = GROUPS[gname]
    e = group_identity(Gt)
    ginv = group_inverse(Gt, e)
    nI, nL = random.randint(2, 3), random.randint(2, 3)
    n = len(Gt)
    # normalized sandwich matrix: p[l][i] with p[0][i] = p[l][0] = e
    p = [[e if (l == 0 or i == 0) else random.randrange(n) for i in range(nI)] for l in range(nL)]
    for _ in range(200):
        alpha = [random.randrange(nI) for _ in range(nI)]
        alpha = [alpha[alpha[i]] if alpha[alpha[i]] == alpha[alpha[alpha[i]]] else alpha[i] for i in range(nI)]
        if any(alpha[alpha[i]] != alpha[i] for i in range(nI)):
            continue
        beta = [random.randrange(nL) for _ in range(nL)]
        if any(beta[beta[l]] != beta[l] for l in range(nL)):
            continue
        # solve linking for gamma, delta by brute force
        sols = []
        for gamma in itertools.product(range(n), repeat=nI):
            if any(gamma[i] != e for i in range(nI) if alpha[i] == i):
                continue
            for delta in itertools.product(range(n), repeat=nL):
                if any(delta[l] != e for l in range(nL) if beta[l] == l):
                    continue
                if all(Gt[p[l][alpha[j]]][gamma[j]] == Gt[delta[l]][p[beta[l]][j]] for l in range(nL) for j in range(nI)):
                    sols.append((gamma, delta))
        if sols:
            gamma, delta = random.choice(sols)
            break
    else:
        return None
    K = [(i, h, l) for i in range(nI) for h in range(n) for l in range(nL)]
    idx = {x: k for k, x in enumerate(K)}
    F = len(K)
    N = F + 1

    def mul(x, y):
        if x == F and y == F:
            return F
        if x == F:
            i, h, l = K[y]
            return idx[(alpha[i], Gt[gamma[i]][h], l)]
        if y == F:
            i, h, l = K[x]
            return idx[(i, Gt[h][delta[l]], beta[l])]
        i, h, l = K[x]
        j, g, m = K[y]
        return idx[(i, Gt[Gt[h][p[l][j]]][g], m)]

    T = [[mul(x, y) for y in range(N)] for x in range(N)]
    return T, dict(G=gname, nI=nI, nL=nL, p=p, alpha=alpha, beta=beta, gamma=gamma, delta=delta)


def main() -> None:
    num = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    seed0 = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    tested = nonorth = 0
    for k in range(num):
        r = build(seed0 + k)
        if r is None:
            continue
        T, d = r
        N = len(T)
        assert all(T[T[x][y]][z] == T[x][T[y][z]] for x in range(N) for y in range(N) for z in range(N)), "not associative"
        assert all(any(T[T[x][y]][x] == x and T[T[y][x]][y] == y for y in range(N)) for x in range(N)), "not regular"
        if not (is_weakly_E_unitary(T) and locally_r_orthodox(T)):
            continue
        E = [x for x in range(N) if T[x][x] == x]
        orth = all(T[a][b] in set(E) for a in E for b in E)
        lab = xi_classes(T)
        pure = all(x in set(E) for x in range(N) if any(lab[x] == lab[e] for e in E))
        tested += 1
        nonorth += not orth
        if not pure:
            print("COUNTEREXAMPLE CANDIDATE: xi not idempotent pure", d)
            print(T)
            return
    print(f"tested {tested} weakly E-unitary locally r-orthodox ideal extensions K u {{f}} "
          f"({nonorth} non-orthodox): xi idempotent pure in all")


if __name__ == "__main__":
    main()
